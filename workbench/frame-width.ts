/**
 * Ширина кадра. Живёт в оболочке и НЕ едет в адрес КАДРА.
 *
 * Ширина кадра — это ширина его вьюпорта, и задаёт её тот, кто кадр держит.
 * Стоит сделать её параметром адреса кадра — она разойдётся с тем, что видит
 * `@media` и `vw`, и правда, ради которой заведён кадр, уедет. Санитар на
 * это — в shell-width.test.tsx.
 *
 * В адресе ОБОЛОЧКИ она с DS-345 есть (`w`), и это не отмена правила, а
 * его вторая половина: оболочка кадр держит и вьюпорт ему задаёт, так что поле
 * описывает то, чем она распорядится. Довод — у `buildShellUrl`.
 */
export const MIN_WIDTH = 240
export const MAX_WIDTH = 2560

/**
 * 360 — телефон, 768 — умолчание из макета, 1024 — планшет,
 * 1440 — рабочий стол. Последний шире типичного окна ноутбука НАМЕРЕННО:
 * поле умеет прокручиваться и не режет левый край (`justify-content: safe center`).
 */
export const WIDTH_PRESETS = [360, 768, 1024, 1440] as const

/**
 * Ширина, с которой оболочка открывается, когда в адресе `w` нет.
 *
 * Именем, а не литералом в двух местах: с DS-345 умолчание знают ДВОЕ —
 * начальное состояние оболочки и сборщик её адреса (`buildShellUrl` умолчание
 * в адрес не пишет). Разойдясь, они дали бы `?w=768` на пустом состоянии либо
 * ссылку, теряющую ширину, — и то и другое молча.
 */
export const DEFAULT_WIDTH: number = WIDTH_PRESETS[1]

export function clampWidth(px: number): number {
  if (!Number.isFinite(px)) return MIN_WIDTH
  return Math.min(MAX_WIDTH, Math.max(MIN_WIDTH, Math.round(px)))
}
