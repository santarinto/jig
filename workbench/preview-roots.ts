/**
 * Корни, по которым ходят слои кадра (DS-163).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ, а не строчка в каждом слое. Слоёв, ходящих от
 * `hostRef`, два — axe и таб-стопы, — и оба были слепы к порталам ОДИНАКОВО:
 * `.ds-modal__overlay` и `.ds-drawer__overlay` монтируются прямым ребёнком
 * `body` кадра, то есть вне поддерева хоста. Слой axe печатал при этом
 * «смотреть было нечего», слой стопов — ноль стопов; второе хуже, потому что
 * пустой список читается как «проверено, чисто», а прочерк хотя бы честно
 * говорит «не знаю». Одно определение корней на оба слоя — единственный
 * способ не чинить это по второму разу, когда появится третий слой.
 *
 * ПОЧЕМУ НЕ ВЕСЬ ДОКУМЕНТ, хотя кадр — отдельный документ и чужого в нём нет.
 * Корень прогона держит ГРАНИЦУ (см. шапку `axe-layer.ts`): при контексте-
 * ЭЛЕМЕНТЕ axe не задаёт правил уровня страницы вовсе, а при документе задал
 * бы — и `document-title`, `html-has-lang`, `region` приехали бы претензиями к
 * ОБОЛОЧКЕ КАДРА, которую человек не пишет и починить не может. Плюс служебная
 * разметка самого кадра: полоса неразмещённых начинок, номера таб-стопов,
 * контуры нарушений — они внутри `#root`, но вне хоста, и в отчёт им нельзя.
 * Список элементов сохраняет и границу, и порталы.
 *
 * ЧТО СЧИТАЕТСЯ ПОРТАЛОМ: любой ребёнок `body`, который не хост и не его
 * предок. Перечислять селекторы порталов (`.ds-modal__overlay`, …) нельзя —
 * следующий портал забудут добавить, и слой снова замолчит МОЛЧА. Отрицание
 * («всё, кроме своего») переживает добавление компонента, перечисление — нет.
 */

/**
 * Теги, которые ребёнком `body` бывают, а поддеревом для обхода — нет.
 * `vite-error-overlay` — оверлей ошибки сборки в dev: он не часть превью, и
 * его собственные претензии axe в отчёте о компоненте были бы ложным следом
 * ровно в тот момент, когда человек и так смотрит на сломанное.
 */
const NOT_A_PORTAL = new Set(['SCRIPT', 'STYLE', 'LINK', 'TEMPLATE', 'NOSCRIPT', 'VITE-ERROR-OVERLAY'])

/**
 * Хост плюс порталы. Хост ВСЕГДА первый: слои печатают списки в порядке
 * корней, и превью обязано идти раньше того, что всплыло поверх него.
 *
 * Корни не пересекаются по построению — портал живёт ребёнком `body`, а хост
 * лежит внутри `#root`, — поэтому ни один узел не приедет дважды.
 */
export function previewRoots(host: Element): Element[] {
  const body = host.ownerDocument.body
  if (!body) return [host]
  const portals = Array.from(body.children).filter(
    (el) => el !== host && !el.contains(host) && !NOT_A_PORTAL.has(el.tagName),
  )
  return [host, ...portals]
}
