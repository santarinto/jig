/**
 * Значение крутилки из АДРЕСА — в значение пропа (DS-265).
 *
 * ТРИ СОСТОЯНИЯ, А НЕ ДВА, и в этом весь смысл модуля. «Параметра нет» и
 * «параметр со значением, которого не бывает» — РАЗНЫЕ вещи, и первое обязано
 * оставлять умолчание случая. До этой задачи булева крутилка сравнивалась со
 * строкой `'true'`, то есть всё непонятое падало в ЛОЖЬ:
 * `?c=Timeline&case=base&p.groupByDay=xyzzy` рисовал кадр БЕЗ разделителей дня,
 * хотя у случая `base` умолчание — с ними.
 *
 * Это хуже, чем «падает в умолчание», которое верстак обещает для `mode` и
 * `text`: там опечатка даёт ОБЫЧНЫЙ кадр, а здесь давала ДРУГОЙ, законно
 * выглядящий, отличающийся от случая ровно одним признаком. Отличить его от
 * настоящего поведения компонента нельзя ничем, кроме как знать про ловушку.
 * Цена измерена: браузерный агент на приёмке потратил на это три хода и один
 * раз почти сдал замечание «компонент не реагирует на проп».
 *
 * ЖИВЁТ ОТДЕЛЬНЫМ МОДУЛЕМ, потому что читателей ДВА и они в разных документах:
 * кадр сводит пропы (`resolve-case.ts`), а док рисует состояние крутилки
 * (`dock.tsx`). Разойдись они — док показывал бы галочку там, где кадр её не
 * применил, то есть верстак врал бы про самого себя. Ровно этим кончается любая
 * вторая копия правила.
 *
 * ПОЧЕМУ НЕ В `parseFrameUrl`. Разбор адреса про фикстуру не знает и знать не
 * должен: там нет `controls`, а без них «значения, которого не бывает» не
 * существует как понятия.
 */
import type { ControlMeta } from './protocol.js'

/**
 * Пустая строка — ИСТИНА, а не ложь: `?p.dense` без `=` — обычная форма флага
 * в адресе, и `URLSearchParams` отдаёт для неё `''`. У `enum` пустая строка
 * может быть законным ЗНАЧЕНИЕМ (`tone` в фикстуре `Form` объявляет `''` как
 * «тона нет»), и туда это правило не заходит — там значение ищется в списке.
 */
const TRUE_WORDS = new Set(['true', '1', 'on', 'yes', ''])
const FALSE_WORDS = new Set(['false', '0', 'off', 'no'])

/** Понято (и во что), либо не понято вовсе. */
export type Coerced = { ok: true; value: unknown } | { ok: false }

const NOT_UNDERSTOOD: Coerced = { ok: false }

export function coerceControl(ctl: ControlMeta, raw: string): Coerced {
  switch (ctl.kind) {
    case 'bool':
      if (TRUE_WORDS.has(raw)) return { ok: true, value: true }
      if (FALSE_WORDS.has(raw)) return { ok: true, value: false }
      return NOT_UNDERSTOOD

    case 'number': {
      const n = Number(raw)
      // `Number('')` — это НОЛЬ, а не NaN, и пустое значение числовой крутилки
      // молча ставило бы 0 вместо умолчания случая. Отдельная проверка, а не
      // один `isFinite`.
      if (raw.trim() === '' || !Number.isFinite(n)) return NOT_UNDERSTOOD
      return { ok: true, value: n }
    }

    case 'enum':
      if (!ctl.values.includes(raw)) return NOT_UNDERSTOOD
      // ЧИСЛОВОЙ enum обязан доехать ЧИСЛОМ. До DS-265 он доезжал
      // строкой, а сниппет печатал его числом (`jsx-snippet.ts` читает
      // `numeric`) — то есть док утверждал `months={3}`, а компонент получал
      // `months="3"`. Сниппет врал не про мелочь: он и есть то, что копируют.
      return { ok: true, value: ctl.numeric === true ? Number(raw) : raw }

    case 'text':
      // Текст не бывает неверным: любая строка — законное значение.
      return { ok: true, value: raw }
  }
}

/**
 * То же для дока, которому нужна не типизованная величина, а СТРОКА для
 * отрисовки: понятое возвращается как есть, непонятое — `null`, и вызывающий
 * откатывается к значению случая. Без этого док рисовал бы мусор из адреса
 * рядом с кадром, который его не применил.
 */
export function displayValue(ctl: ControlMeta, raw: string): string | null {
  const c = coerceControl(ctl, raw)
  if (!c.ok) return null
  return ctl.kind === 'bool' ? String(c.value) : raw
}
