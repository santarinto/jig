/**
 * Полоса фактических тонов под копиями режима «Состояния» (Задача 31).
 *
 * Зачем вообще числа. Спека: «две одинаковые ячейки видно числом, а не
 * памятью». В CLAUDE.md записан живой случай — `:hover` и `:focus-visible` с
 * ОДИНАКОВЫМ фоном: правка доступности открыла клавиатуре путь туда, где его
 * не было, и подсветка фокуса оказалась неотличима от наведения. Четыре копии
 * в ряд эту пару показывают, но глаз на «чуть-чуть другое» не отвечает —
 * отвечает совпадение строк.
 *
 * ЧТО ИМЕННО МЕРИТСЯ: `background-color` выбранного узла, а если он прозрачен
 * — ПЕРВОГО НЕПРОЗРАЧНОГО ПРЕДКА, и тогда полоса говорит, чей это тон.
 *
 * Прозрачный узел мерить бессмысленно, и это выяснилось на живом DataTable:
 * прицел попадает в `td` (щелчок всегда достаётся самому глубокому узлу), фон
 * зебры и наведения живёт на `tr`, и полоса печатала четыре «прозрачно» с
 * «= покой» под наведённой копией, которая на экране явно другая. Числа
 * верные — и не о том, что человек видит. Видит он тон, ПРОСВЕЧИВАЮЩИЙ сквозь
 * прозрачный узел, то есть тон предка.
 *
 * Откуда взят тон, говорится вслух: подмена молча превратила бы «фон этого
 * узла» в «фон чего-то выше», и «= покой» под наведённой копией снова стало
 * бы загадкой.
 *
 * ЧЕГО ЭТО НЕ ЛОВИТ, и это записано, чтобы не выдавать за большее: состояния,
 * отличающиеся НЕ фоном — рамкой, тенью, цветом текста, — полоса покажет
 * одинаковыми, и «= покой» будет правдой про фон и неправдой про вид. Фон
 * взят потому, что им кодируется большинство интерактивных состояний системы
 * (`Button.css`: у всех вариантов `:hover` меняет именно `background`), а не
 * потому, что он исчерпывает вопрос.
 */

/** Тон копии: что намерено и чей он. */
export interface Tone {
  /** Вычисленный `background-color`. */
  value: string
  /** Узел, с которого он снят, — сам выбранный или предок. `null` — не искали. */
  from: Element | null
  /** Тон снят с самого выбранного узла, а не с предка. */
  own: boolean
}

/**
 * Фактический тон узла: он сам, а если прозрачен — первый непрозрачный предок
 * (не выше `root`).
 *
 * Чтение вынесено параметром, чтобы функция проверялась без раскладки: в
 * jsdom `getComputedStyle` наследование фона не считает, а вопрос здесь — про
 * ПОРЯДОК обхода, а не про то, как браузер вычисляет цвет.
 */
export function effectiveTone(
  el: Element,
  root: Element,
  read: (e: Element) => string,
): Tone {
  let cur: Element | null = el
  while (cur) {
    const value = read(cur)
    if (!isTransparent(value)) return { value, from: cur, own: cur === el }
    if (cur === root) break
    cur = cur.parentElement
  }
  // Ничего непрозрачного до самого корня копии: тон и правда прозрачный, и
  // говорить про него надо от имени выбранного узла, а не корня.
  return { value: read(el), from: el, own: true }
}

/** Прозрачный фон в вычисленном виде — то, что отдаёт браузер. */
const TRANSPARENT = new Set(['rgba(0, 0, 0, 0)', 'transparent', ''])

export function isTransparent(tone: string): boolean {
  return TRANSPARENT.has(tone.trim())
}

/** Человеческая подпись тона: «прозрачно» вместо `rgba(0, 0, 0, 0)`. */
export function toneLabel(tone: string): string {
  return isTransparent(tone) ? 'прозрачно' : tone
}

/**
 * Для каждой копии — подпись ПЕРВОЙ совпавшей с ней слева, или `null`.
 *
 * Сравнение с ПЕРВОЙ, а не с ближайшей: цепочка «покой = hover = focus» должна
 * читаться как три ссылки на один тон, а не как разговор соседей по кругу.
 * Первая копия ни с чем не сравнивается по построению — сравнивать не с чем.
 */
export function sameAsBefore(tones: string[], labels: string[]): (string | null)[] {
  return tones.map((tone, i) => {
    for (let j = 0; j < i; j++) {
      if (tones[j] === tone) return labels[j] ?? null
    }
    return null
  })
}
