/**
 * Прицел (Задача 32): выбор узла, на который вешается форс.
 *
 * Зачем. По умолчанию атрибут форса висит на корне превью, и дубликат правил
 * в форме «предок» красит ВСЁ внутри. Для одиночной кнопки это ровно то, что
 * нужно; для таблицы бессмысленно — подсветятся все строки разом, и вопрос
 * «как выглядит наведённая строка» останется без ответа.
 *
 * Здесь — только имя узла. Само наведение прицела живёт в кадре: узел
 * выбирается щелчком, а не селектором, потому что селектор пришлось бы
 * СНАЧАЛА написать, а прицеливаются как раз тогда, когда не знают, как
 * называется то, во что тыкают.
 */

import { SPOT_ATTR } from './canvas-plan.js'

/**
 * Имя узла для человека: `button.ds-btn.ds-btn--primary`.
 *
 * ЭТО ПОДПИСЬ, А НЕ АДРЕС. Она не обязана быть уникальным селектором и не
 * используется для поиска — узел уже выбран щелчком и держится ссылкой.
 * Попытка сделать её адресом (`:nth-child` до корня) дала бы нечитаемую
 * строку вида `div > div:nth-child(2) > table > tbody > tr:nth-child(7) > td`,
 * которую всё равно нельзя вставить в CSS системы: она про ЭТУ отрисовку,
 * а не про компонент.
 *
 * Служебные классы верстака (`wbf-*`) отброшены: они принадлежат инструменту,
 * а прицеливаются в компонент. Классы форса тем более — иначе имя менялось бы
 * от того, что мы сами же на узел и повесили.
 *
 * КЛАССЫ ПЕЧАТАЮТСЯ ВСЕ. До 30.08.2026 здесь стоял порог `MAX_CLASSES = 3` с
 * пометкой `+N`, и он резал ХВОСТ цепочки — а в BEM хвост это модификатор, то
 * есть ровно то единственное, что различает соседей. Порог воспроизводил
 * дефект, ради устранения которого написан шаг 6.
 *
 * Это не теория: `Avatar` с `presence` даёт ЧЕТЫРЕ класса
 * (`ds-avatar ds-avatar--md ds-avatar--neutral ds-avatar--presence-busy`,
 * Avatar.tsx:66), и четыре аватара в одном кадре получали ОДНО имя на всех;
 * `Button` с `tone` и `iconOnly` даёт ПЯТЬ (Button.tsx:84-88), и `+2` прятал
 * `ds-btn--tone-error` — единственное, чем опасная кнопка в колонке действий
 * отличается от соседней обычной.
 *
 * «Оставить первый и последний» не спасает: у пятиклассовой кнопки различает
 * предпоследний. Любой порог режет не то, потому что различающий класс не
 * стоит на фиксированном месте, — значит порога быть не должно вовсе.
 *
 * Длина здесь никогда и не была предметом. Строку обрезает ТУЛБАР
 * (`.wb__aim-node`, 18rem), и его обрезка ВОЗВРАТНА: целое имя лежит в `title`
 * и на бейдже над узлом, который не обрезается ничем. `+N` был необратим и
 * портил обе отдушины разом — в `title` уезжала та же обрезанная строка.
 *
 * НА КАНВАСЕ К ИМЕНИ ПРИПИСАНО МЕСТО (DS-128, шаг 6): `td в «table»`
 * вместо `td`. Без него имя перестаёт что-либо называть, как только на канвасе
 * две таблицы: `td.ds-table__lead` у обеих один и тот же.
 *
 * В ХВОСТЕ, А НЕ ВПЕРЕДИ, и это не порядок слов, а выбор жертвы. Строку
 * обрезает тулбар — `.wb__aim-node`, 18rem с многоточием, — то есть теряется
 * ХВОСТ, и вопрос стоит не «что важнее», а «что положить под нож». Пока место
 * стояло впереди, первым уходил модификатор в конце цепочки классов, и это
 * ровно то единственное, что отличает выбранный узел от девяти соседей с теми
 * же классами: замер владельца 30.08.2026 дал
 * `«pages» › button.ds-pager__btn.is-active` — 40 знаков из 40 доступных, то
 * есть впритык, а `«table» › th.ds-table__lead.ds-table__rowhead` уже терял
 * 4–5 знаков хвоста.
 *
 * Имя места в хвосте теряется БЕЗ ПОТЕРИ, и вот почему именно оно: тот же
 * текст целиком нарисован на бейдже над самим узлом (`.wbf-aim__label` не
 * обрезается ничем), а на канвасе к нему добавлена и метка выделенного места
 * в конце группы «канвас». Модификатор не продублирован нигде.
 *
 * ЧЕГО НЕ СДЕЛАНО И ПОЧЕМУ. Выбросить место из строки совсем (предложение
 * владельца: «метка группы его дублирует») — метка показывает ВЫДЕЛЕННОЕ
 * место, а прицел стоит на том, куда ткнули. Мышкой это одно и то же
 * (`pointerdown` выбирает место раньше, чем прицел гасит `mousedown`), но
 * приход табом двигает выделение и НЕ двигает прицел — и метка начинает
 * называть не тот узел, что обведён. Обрезка с середины отвергнута его же
 * доводом: у BEM-цепочки середина несёт корень.
 *
 * ИМЯ МЕСТА, А НЕ ИМЯ КОМПОНЕНТА, хотя спека говорит «называющий компонент».
 * Спека своим же примером это и опровергает: два места с `DataTable` дают
 * ОДИНАКОВОЕ имя компонента, и приписать его значило бы удлинить строку, ничего
 * не различив. Имя места на канвасе уникально (`parseSpots` выбрасывает
 * повторы) и это тот же адрес, которым пользуются док, тулбар и выгруженный
 * файл — то есть по нему можно ткнуть дальше, а не только прочитать.
 *
 * КАВЫЧКИ И `›` — ЧТОБЫ НЕ ПРОЧИТАЛОСЬ КАК СЕЛЕКТОР. Умолчание канваса зовёт
 * первое место `table`, и «table td.ds-table__lead» через пробел — валидный CSS
 * про совсем другое. Кавычки в хроме уже означают «это имя» (набор «экран»,
 * место «pages»), а `›` в CSS не значит ничего. Имя и так не селектор — см.
 * абзац выше, — но выглядеть селектором оно не должно тем более.
 */
export function describeNode(el: Element): string {
  const tag = el.tagName.toLowerCase()
  const id = el.getAttribute('id')
  const classes = Array.from(el.classList).filter((c) => !c.startsWith('wbf-'))
  // `closest`, а не проверка самого узла: прицеливаются в глубину компонента,
  // а место — его обёртка. Сам узел места тоже подходит и назовётся
  // `div в «id»`, и это правда: ткнули в коробку места, а не в компонент внутри.
  const spot = el.closest(`[${SPOT_ATTR}]`)?.getAttribute(SPOT_ATTR)
  return [
    tag,
    id ? `#${id}` : '',
    classes.map((c) => `.${c}`).join(''),
    spot ? ` в «${spot}»` : '',
  ].join('')
}

/**
 * КУДА САДИТСЯ ПРИЦЕЛ на самом деле (DS-128, находка [6] ручного QA).
 *
 * Щелчок отдаёт верхний узел под указателем, и у иконочной кнопки это
 * `<circle>` внутри `<svg aria-hidden="true">`. Прицел показывал `circle в
 * «table»` для кнопки «Изменить» И ТО ЖЕ САМОЕ для кнопки «Удалить» рядом:
 * одно имя на две разные кнопки, отличающиеся и классом тона, и `aria-label`.
 * Навесить `:hover` на кнопку действия было нельзя вовсе — а это главный
 * сценарий, ради которого иконочная кнопка вообще существует.
 *
 * ПРАВИЛО РОВНО ОДНО: не садиться на то, чего нет для диктора. Прицел заявлен
 * как «выбрать узел, на который вешается форс», а форс на `aria-hidden`
 * бессмысленен по определению: этого узла нет в дереве доступности, и
 * состояние, которое он изобразит, никому не адресовано.
 *
 * ПОЧЕМУ НЕ «ближайший интерактивный». Соблазн подниматься до кнопки или
 * ссылки понятен, но он сломал бы прицел по `td`, `dt` и `dd` — а по ним
 * целятся постоянно, и они не интерактивны. Правило про `aria-hidden`
 * решает ЗАЯВЛЕННЫЙ случай (у иконки скрыт весь `<svg>`, подъём даёт кнопку),
 * ничего больше не трогая. Догадка «человек наверняка хотел кнопку» — та же
 * порода, что печатать проп, которого нет.
 *
 * ЗНАЧЕНИЕ, А НЕ НАЛИЧИЕ АТРИБУТА: `aria-hidden="false"` означает «виден», и
 * `closest('[aria-hidden]')` увёл бы прицел с нормального узла.
 *
 * Всё дерево скрыто — `null`, и прицел не садится никуда. Сесть «куда-нибудь»
 * значило бы показать имя узла, которого для диктора нет, — то есть ответить
 * на вопрос, которого не задавали.
 */
export function aimTargetOf(el: Element): Element | null {
  let node: Element | null = el
  while (node !== null) {
    const hidden: Element | null = node.closest('[aria-hidden="true"]')
    if (hidden === null) return node
    node = hidden.parentElement
  }
  return null
}

/**
 * НА СКОЛЬКО СДВИНУТЬ БЕЙДЖ ВЛЕВО, чтобы он не вылезал за правый край кадра
 * (DS-128, находки [5] и [7] ручного QA).
 *
 * Одна правка на два дефекта, и это не совпадение — у них общая причина.
 *
 * [5] Бейдж — обычный узел в потоке документа кадра, и вылезая за правый край,
 * он УВЕЛИЧИВАЕТ ширину прокрутки: замер отчёта — `scrollWidth` 875 при
 * `clientWidth` 768 после щелчка по кнопке листалки у правого края. У кадра
 * появлялась горизонтальная полоса, которой до щелчка не было. Это прямо
 * ломает главный вопрос стенда — «лезет ли что-нибудь за 768?»: инструмент
 * отвечал на него собственным присутствием. Человек видит полосу и заводит
 * баг на вёрстку, которой нет, или привыкает к полосе и перестаёт замечать
 * настоящее переполнение.
 *
 * [7] Тот же вылезший хвост не читается: `button.ds-pager__btn.is-active в` —
 * и обрыв, пропало «pages», то есть ровно указание места. Добраться до хвоста
 * можно было только прокруткой, которую этот же бейдж и породил.
 *
 * ПРИЖАТЬ, А НЕ ОБРЕЗАТЬ. Многоточие на бейдже запрещено отдельным
 * инвариантом (`make measure`, «самое длинное имя системы целиком видно на
 * бейдже, а тулбар его режет»): тулбар — превью и режет, бейдж — ответ и не
 * режет НИКОГДА. Обрезав его здесь, мы бы закрыли [5] ценой того, что целого
 * имени не видно нигде, — то есть починили бы прокрутку, сломав то, ради чего
 * прокручивались.
 *
 * ВЛЕВО НЕ ДАЛЬШЕ КРАЯ: сдвиг ограничен собственным отступом бейджа слева.
 * Уехав за левый край, он вырастил бы ширину прокрутки с другой стороны — тот
 * же дефект зеркально (в RTL ровно он и был бы первым).
 *
 * Имя длиннее всего кадра прижатием не спасти, и здесь честно возвращается
 * максимум возможного: сдвиг до левого края. Остаток — забота `title`, ровно
 * как в тулбаре. Сегодня такого имени в системе нет (самое длинное измерено и
 * укладывается), но правило не должно зависеть от того, что верно сегодня.
 */
export function labelShiftOf(labelLeft: number, labelWidth: number, frameWidth: number): number {
  const overflow = labelLeft + labelWidth - frameWidth
  if (overflow <= 0) return 0
  // Сколько места есть слева. Отрицательный левый край (бейдж стоит на -2px от
  // рамки) двигать вправо не повод — это оторвало бы его от своего узла.
  const shift = Math.min(overflow, Math.max(labelLeft, 0))
  // ЯВНЫЙ НОЛЬ, А НЕ `-shift`. Унарный минус от нуля даёт `-0`, и он не равен
  // нулю по `Object.is` — то есть сравнение «сдвиг не изменился», которым
  // кадр гасит лишний рендер, на нём бы не сработало. Поймано тестом.
  return shift === 0 ? 0 : -shift
}

/**
 * ЦЕПОЧКА ПРЕДКОВ: узел и всё, что над ним, до корня компонента включительно
 * (DS-128, находка [12] ручного QA).
 *
 * ЗАЧЕМ. Щелчок отдаёт САМЫЙ ГЛУБОКИЙ узел под указателем — и потому целые
 * классы узлов недостижимы прицелом вовсе, сколько ни целься: `tr.is-clickable`
 * закрыт своими `td` целиком, корень компонента — всем своим содержимым,
 * `div.ds-tabs-layout` — вкладками. А это ровно те узлы, на которых состояние
 * и живёт: вопрос «как выглядит наведённая СТРОКА» задают про `tr`, а попасть
 * в него нечем. Отсюда подъём как отдельное действие (Alt+клик в кадре).
 *
 * ГРАНИЦА — УЗЛЫ ИНСТРУМЕНТА, и она не косметическая. Над корнем компонента
 * стоят коробка места (`.wbf-canvas__spot`) и хост кадра (`.wbf-canvas`,
 * `.wbf-host`); подъём в них увёл бы форс с предмета на инструмент — тот же
 * довод, по которому щелчок по служебному узлу прицел вообще не двигает.
 * Признак — класс `wbf-`, тот же, по которому `describeNode` выбрасывает свои
 * классы из имени: одно правило «это наше, а не системы» на оба места.
 *
 * ВВЕРХ, А НЕ ВНИЗ, и цепочка не циклическая. Дойдя до корня, подъём
 * ОСТАНАВЛИВАЕТСЯ: заворот к самому глубокому узлу выглядел бы как промах —
 * человек жмёт «выше» и оказывается ниже всего, где был. Про то, что выше
 * некуда, тулбар говорит ЗАРАНЕЕ (счётчик `↑0`), а не молчанием после нажатия.
 *
 * Первым элементом идёт САМ УЗЕЛ. Так длина цепочки сразу отвечает на вопрос
 * «сколько ступеней осталось» (`length - 1`), а вызывающему не приходится
 * помнить, включён ли текущий узел в счёт.
 */
export function aimChainOf(el: Element): Element[] {
  const isTool = (node: Element): boolean =>
    Array.from(node.classList).some((c) => c.startsWith('wbf-'))
  if (isTool(el)) return [el]
  const chain: Element[] = [el]
  let node = el.parentElement
  while (node !== null && !isTool(node)) {
    chain.push(node)
    node = node.parentElement
  }
  return chain
}
