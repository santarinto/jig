/**
 * Состав сетки (Задача 34): какие кадры показать и что не поместилось.
 *
 * ЛИМИТ ЖИВЁТ В КОДЕ, А НЕ В ДОГОВОРЁННОСТИ (нефункциональное требование
 * спеки). Шесть кадров с набором `rows-500` — это шесть документов, каждый со
 * своей копией листа системы, своей фикстурой и своими сотнями строк; седьмой
 * не «чуть медленнее», он в разы дороже, и решать это на глаз нельзя.
 *
 * СРЕЗАННОЕ НАЗЫВАЕТСЯ ВСЛУХ. Молчаливая обрезка читается как «показано всё»
 * — та же ловушка, что у обрезанного списка классов в `describeNode`: экран
 * выглядит полным ответом, а половины вопроса в нём нет.
 *
 * ТЕМЫ ПРИХОДЯТ В ПОРЯДКЕ «основная, добавленная», а не «светлая, тёмная»:
 * основная — та, что выбрана в тулбаре, и она обязана оставаться на своём
 * месте, когда рядом появляется вторая.
 *
 * ПОРЯДОК — ПАРАМИ ПО ШИРИНЕ: 360 в обеих темах, потом 768 в обеих и так
 * далее. Сравнивают всегда две вещи разом, и в сетке это либо «одна ширина в
 * двух темах», либо «две соседние ширины». Порядок «сначала все светлые,
 * потом все тёмные» разводит пару темы на противоположные концы, и лимит
 * отрезал бы у неё вторую половину, оставив первую притворяться целой.
 */
import type { Theme } from './protocol.js'

/** Кадров в сетке одновременно. Число из спеки, а не с потолка. */
export const GRID_LIMIT = 6

export interface GridCell {
  w: number
  theme: Theme
  /**
   * Место ячейки внутри своей ширины: 0 — основная тема, 1 — добавленная.
   *
   * По нему оболочка держит ТОЖДЕСТВО документа. Ключ по теме («360:dark»)
   * переименовывал бы ячейку при каждой смене темы, и требование спеки
   * «кадры переиспользуются при смене темы» превращалось бы в шесть
   * перезагрузок; ключ по месту это разводит: сменили тему — то же место,
   * тот же документ, патч внутрь; добавили вторую тему — новое место, новый
   * документ рядом, а первый остался жив.
   */
  slot: number
}

export interface GridPlan {
  cells: GridCell[]
  /** Сколько кадров не поместилось. Печатается человеку, а не глотается. */
  dropped: number
}

export function gridPlan(
  widths: readonly number[],
  themes: readonly Theme[],
  limit: number = GRID_LIMIT,
): GridPlan {
  const all: GridCell[] = []
  for (const w of widths) {
    themes.forEach((theme, slot) => all.push({ w, theme, slot }))
  }
  return { cells: all.slice(0, limit), dropped: Math.max(0, all.length - limit) }
}
