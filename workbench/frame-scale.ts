/**
 * Масштаб интерфейса в кадре.
 *
 * Ставится на `documentElement`, потому что метрические токены объявлены в
 * `:root` через `calc(rem * var(--ds-ui-scale))`: переменная, поставленная
 * ниже, до объявления не дотянется.
 */
import type { Theme } from './protocol.js'

/**
 * Шкалы, НА КОТОРЫХ ЖИВУТ ПОТРЕБИТЕЛИ (DS-164), а не круглый ряд.
 * 0.875 — плотный режим, 1 — умолчание, 1.15 — шкала потребителя, 1.5 — верхняя
 * граница, на которой ломается раскладка. Было `1 / 1.25 / 1.5`: 1.25 не
 * стоит ни у кого, а обе настоящие нестандартные шкалы в набор не входили.
 *
 * Шкала вне набора (из адреса) законна и применяется как есть — оболочка
 * показывает её пометкой «не из набора», а не гасит группу.
 */
export const SCALE_PRESETS = [0.875, 1, 1.15, 1.5] as const

/** Шкала входит в набор чипов. Сравнение числом: адрес разбирается `Number`. */
export const isPresetScale = (s: number): boolean =>
  (SCALE_PRESETS as readonly number[]).includes(s)

export function applyScale(doc: Document, scale: number): void {
  if (scale === 1) {
    doc.documentElement.style.removeProperty('--ds-ui-scale')
    return
  }
  doc.documentElement.style.setProperty('--ds-ui-scale', String(scale))
}

/**
 * Тема и масштаб — то, что кадр применяет к СВОЕМУ документу, прочитав адрес.
 *
 * Вынесено из `frame.tsx` не ради красоты: раньше вызов стоял внутри эффекта
 * компонента, который монтировался через `createRoot` на уровне модуля, и
 * проверить его в jsdom было нельзя. Здесь связка «адрес → документ» стала
 * обычной функцией, и мутация в ней краснеет — это не изменилось.
 *
 * ЧЕГО ЭТО НЕ ПРОВЕРЯЕТ (по состоянию на сегодня): что вызывающий код
 * действительно зовёт эту функцию. Раньше это было объявлено в принципе
 * непроверяемым в jsdom — но с разделением точки входа кадра (Ruling 6
 * задачи 3, DS-63) вызов переехал в `Frame` (`frame-app.tsx`), который
 * больше НЕ монтируется через `createRoot` на уровне модуля, а экспортируется
 * и рисуется как обычный компонент. То есть проверка «`Frame` зовёт
 * `applyFrameEnv` на патч темы/масштаба» технически СТАЛА возможной в jsdom
 * (смонтировать `Frame`, отправить патч, прочитать
 * `document.documentElement.dataset.theme`) — она просто ещё не написана,
 * это отдельная работа. До неё расхождение по-прежнему ловится глазами и
 * падением превью.
 */
export function applyFrameEnv(doc: Document, s: { theme: Theme; scale: number }): void {
  doc.documentElement.dataset.theme = s.theme
  applyScale(doc, s.scale)
}
