/**
 * Числовое поле раскладки канваса: колонка и ширина ([4] ручного QA,
 * DS-128).
 *
 * ДВА ВОПРОСА, А НЕ ОДИН, и в этом всё. «Что уехало на этом нажатии клавиши» и
 * «чем кончился набор» — разные вопросы с разными ответами, а поле отвечало на
 * оба одним выражением `Number(v) || 1`. Отсюда дефект отчёта: стираешь поле,
 * чтобы набрать заново, оно мгновенно становится единицей, и набранное
 * дописывается К НЕЙ — «12» даёт 112. Поле мешало набрать ровно то, ради чего
 * его и стирают.
 *
 * ЗДЕСЬ ЖЕ ЗАКРЫВАЕТСЯ ПУНКТ А КОДОВОГО РЕВЬЮ 30.08.2026. `min`/`max` у
 * `input type=number` ничего не запрещают НАБРАТЬ, а правка писала что дали:
 * место с `col: -3` уходило в раскладку, в хранилище и в файл — который
 * `parseFile` обратно уже НЕ читает, то есть ломалось первое смягчение спеки
 * («выгрузка даёт файл в формате, который читается обратно»). Ревью предлагало
 * провести правку через `parseSpots` и объяснять отказ словами; сделано иначе и
 * сильнее: негодное значение просто НЕ УЕЗЖАЕТ, и объяснять нечего. Диапазон
 * при этом не тайна — он объявлен на самом контроле (`min`/`max`), и молчание
 * тут не тишина, а отсутствие события.
 */

/**
 * Что уезжает в раскладку на ЭТОМ вводе. `null` — ничего.
 *
 * ГОДНОЕ УЕЗЖАЕТ СРАЗУ, не дожидаясь ухода из поля: раскладку двигают, глядя
 * на кадр, и отложи мы отклик до `blur` — человек набирал бы вслепую.
 *
 * НЕГОДНОЕ НЕ ПРИЖИМАЕТСЯ, а откладывается до конца набора. Прижимать на
 * каждой цифре — значит мешать набирать: «99» проходит через «9», и прижми его
 * сразу к 12, второй девятке уже некуда дописаться. Ровно та же болезнь, что
 * у единицы вместо пустого поля, только этажом выше.
 */
export function commitOf(raw: string, min: number, max: number): number | null {
  // `Number` вместо `parseInt`: второй читает «1.5» как 1 и «12abc» как 12, то
  // есть молча принимает то, чего человек не набирал.
  const n = Number(raw)
  if (raw.trim() === '' || !Number.isInteger(n)) return null
  return n >= min && n <= max ? n : null
}

/**
 * Чем кончился набор, когда из поля ушли. Всегда число: пустого места в сетке
 * не бывает.
 *
 * ВНЕ ДИАПАЗОНА ПРИЖИМАЕТСЯ К КРАЮ — человек видит, куда попало его намерение,
 * а не остаётся с полем, которое «не сработало».
 *
 * ПУСТОЕ ВОЗВРАЩАЕТ ТЕКУЩЕЕ, а не минимум, и это не мелочь: минимум подвинул бы
 * место, которое человек не трогал. Стёр поле и передумал — это «ничего не
 * менял», а не «поставь единицу».
 */
export function settleOf(raw: string, min: number, max: number, current: number): number {
  const n = Number(raw)
  if (raw.trim() === '' || !Number.isInteger(n)) return current
  return Math.min(max, Math.max(min, n))
}
