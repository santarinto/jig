/**
 * Высота дока. Живёт в оболочке, НЕ едет в адрес и хранится у человека.
 *
 * В DS-125 высота дока поднялась со 180 до 340, потому что док резал
 * собственную четвёртую колонку. Это было ЧИСЛО, а не решение: правильной
 * высоты у дока нет — она зависит от того, чем сейчас занят человек. Смотришь
 * раскладку — док мешает; крутишь пропсы и читаешь JSX — его мало.
 *
 * ПОЧЕМУ НЕ В АДРЕС, хотя `mirror-url` рядом и соблазн очевиден. Адрес в
 * верстаке описывает ПРЕДМЕТ: какой компонент, какой случай, какие данные,
 * какая тема кадра — то, что человек шлёт другому, чтобы тот увидел то же
 * самое. Высота дока к предмету не относится; уехав в адрес, она поедет вместе
 * со ссылкой и будет навязывать получателю чужую раскладку. Ровно то же
 * рассуждение, что у ширины кадра в `frame-width.ts`, но кончается оно в другом
 * месте: ширина не едет в адрес КАДРА и остаётся в оболочке, а высота дока не
 * едет и в адрес ОБОЛОЧКИ — она принадлежит рабочему месту, а не работе.
 */

/** Ключ `localStorage`. Пространство имён `ds-wb/` — чтобы соседи по origin не спорили. */
export const DOCK_H_KEY = 'ds-wb/dock-h'

/**
 * Умолчание из DS-125 — высота, при которой видны все четыре колонки.
 *
 * ПЕРЕСНЯТО на DS-141, когда хром стал на 15% крупнее. 340 было не
 * круглым числом, а худшим случаем плюс два пикселя, и старый вывод
 * ВОСПРОИЗВОДИТСЯ: порог, за которым колонка начинает прокручиваться, снят
 * делением пополам по ВСЕМ 41 компонентам каталога (1600×1000,
 * deviceScaleFactor 1), и при корне 100% максимум даёт PivotTable — ровно 338.
 *
 * При корне 115% самым голодным становится ДРУГОЙ компонент: DataTable, 393
 * против 308 у себя же на 100%. Рост в 1.28 против 1.15 у соседей означает
 * перенос — на большем кегле его колонка кладёт содержимое в лишнюю строку, а
 * не просто растёт. Поэтому число нельзя было домножить: пришлось бы взять
 * 340 × 1.15 = 391 и промахнуться мимо живого порога.
 *
 * 395 — тот же худший случай плюс те же два пикселя. Старые 340 при новом
 * масштабе режут колонку у пяти компонентов (DataTable, PivotTable, Combobox,
 * Pagination, Select) — то есть ровно то, ради чего число заводили в
 * DS-125.
 */
export const DOCK_H_DEFAULT = 395

/**
 * Ниже дока не бывает: 105 = 1 (граница дока) + 33.188 (полоса вкладок) +
 * 23 (заголовок колонки) + 47.64 (одна строка крутилки), округлённое вверх.
 *
 * ЗАМЕРЕНО ПО ВСЕМ 41 ФИКСТУРАМ КАТАЛОГА (1600×1000, deviceScaleFactor 1), а
 * не по одной: низ первой `.wb__ctl` берётся максимумом. Худший случай —
 * Badge (`tone`) и Button (`variant`), оба ровно 104.828. У остальных
 * тридцати девяти 87.078, и мерить надо было не их.
 *
 * ОТКУДА 47.64 ВМЕСТО 29.891 — строка крутилки ПЕРЕНОСИТ переключатель на
 * второй ряд чипов. У `.wb__ctl` не высота, а `min-block-size` (DS-128),
 * и перенос там объявлен правильным поведением: «ровный ряд там, где
 * содержимое умещается, и честный перенос там, где нет». Шесть значений тона
 * (`neutral accent success warning error info`) и пять вариантов кнопки в один
 * ряд не ложатся ни при какой ширине окна — замерено на 1600, 1728, 1920 и
 * 2405, число одно и то же. То есть переносится не от тесноты, а всегда.
 *
 * ПЕРЕНОС ЗДЕСЬ БЫЛ И ДО МАСШТАБА 115%, и это главное про историю числа. При
 * корне 100% те же два компонента требуют 91.969 — против пола 76, который
 * стоял со DS-125. Значит пол резал первую крутилку у Badge и Button с
 * того дня, как его завели, а не с DS-141: масштаб не создал дефект, он
 * его домножил (91.969 → 104.828).
 *
 * ОШИБКА БЫЛА В СПОСОБЕ ЗАМЕРА, а не в числе: и 76, и 88 сняли с ОДНОГО
 * компонента (DataTable), где первая крутилка однострочная, и приняли частный
 * случай за пол. Тот же промах в этой же задаче уже ловили у
 * `DOCK_H_DEFAULT` — 340 сняли по десяти компонентам, пришлось переснимать по
 * всем 41. Константа, названная «пол», обязана быть максимумом по каталогу;
 * замер по одному имени отвечает правдоподобным числом и молчит о том, что
 * оно не про пол. Гейт `dock-floor` держит это утверждение живым.
 *
 * Док, утянутый в ноль, — это «поломалось» сворачивание, отдельный разговор,
 * и у дока для него уже есть вкладки. На 104 первая крутилка подрезана, и док
 * читается как сломанный, а не как свёрнутый.
 *
 * Числа дробные, потому что все слагаемые, кроме границы, — rem, и при корне
 * 115% (DS-141) они перестали быть целыми пикселями. Кратности четырём
 * у пола больше нет и быть не может: сетка хрома — 0.25rem, то есть 4.6px.
 *
 * ЗАМЕРЯТЬ ОБЯЗАТЕЛЬНО ПРИ deviceScaleFactor 1. На дробном масштабе дисплея
 * хром браузера СНАПИТ хэйрлайны к целым устройственным пикселям и отдаёт
 * `1px` как `0.869565px` в `getComputedStyle` — то есть в стек попадает не та
 * величина, которая записана в CSS. Первый замер этой задачи шёл в браузере с
 * масштабом 1.15 и дал 86.81 вместо 87.078: разница ровно два хэйрлайна, и её
 * хватало, чтобы округление ушло на 87 и подрезало ту самую крутилку, ради
 * которой пол считают.
 */
export const DOCK_MIN_H = 105

/**
 * Столько остаётся полю кадра, когда док тянут вверх: 121 = 23 (поле поля) +
 * 6 (обвязка кадра) + 92 (самая высокая из однострочных фикстур).
 *
 * Из трёх слагаемых масштаб хрома двинул ровно одно, и это ровно то, чего от
 * границы и ждут: поле поля — хром (`.wb__field { padding: 1.25rem }`, замерено
 * 23px при корне 115%); обвязка кадра — 6px хэйрлайнов, физическая величина; а
 * 92 — высота ФИКСТУРЫ, то есть предмета, и она не едет за прибором вовсе.
 * Округления вверх до сетки больше нет: сетка хрома — 0.25rem, в пикселях 4.6,
 * и кратность четырём здесь ничего не означала бы.
 *
 * ЗАМЕРЕНО: содержимое кадра у простых компонентов — Badge 79, Money 78,
 * Avatar 88, OrgBadge 88, ProgressBar 86, Button 92. То есть на 120px поля
 * кадр ЦЕЛИКОМ показывает любой из них, а у высоких (DataTable, Tree) остаётся
 * шапка со строкой — этого хватает, чтобы кадр читался кадром, а не полоской.
 * Ниже 100 в поле обрезается и левый список компонентов: из тринадцати имён
 * видно четыре. Проверялось скриншотами на 1600×1000.
 */
export const FIELD_MIN_H = 121

/**
 * Шаг стрелок. Тянуть мышью можно попиксельно, клавишами — шагом.
 *
 * Четыре — целое число пикселей, а не «сетка хрома», как здесь было записано.
 * Сетка хрома — 0.25rem, и с масштабом 115% (DS-141) это 4.6px: дробным
 * шагом клавиатура двигать не может, а округлять его на каждом нажатии значило
 * бы копить ошибку. Четыре остаётся потому, что это удобный шаг, а не потому,
 * что оно чему-то кратно.
 */
export const DOCK_STEP = 4

/**
 * Потолок дока при известной высоте области «тело + док».
 *
 * Пол выигрывает у потолка: на окне, где не помещается ни то ни другое,
 * подрезанный док читается как поломка, а подрезанное поле — нет, оно
 * прокручивается (`.wb__field { overflow: auto }`).
 */
export function maxDockH(availH: number): number {
  if (!Number.isFinite(availH) || availH <= 0) return Number.POSITIVE_INFINITY
  return Math.max(DOCK_MIN_H, Math.round(availH) - FIELD_MIN_H)
}

/**
 * Загнать высоту в границы.
 *
 * `availH <= 0` — это «ещё не мерили» (первый кадр, до `useLayoutEffect`), а не
 * «места нет»: потолок тогда не применяется, иначе док на первом кадре мигал бы
 * с 395 до 105 и обратно.
 */
export function clampDockH(px: number, availH: number): number {
  if (!Number.isFinite(px)) return DOCK_H_DEFAULT
  return Math.min(maxDockH(availH), Math.max(DOCK_MIN_H, Math.round(px)))
}

type MaybeStorage = Pick<Storage, 'getItem' | 'setItem'> | null | undefined

/**
 * Чужое и испорченное значение отвечает умолчанием, а не нулевым доком.
 *
 * `winH` — высота окна, а не замеренная область: читать надо ДО первой
 * раскладки, иначе высота приезжает вторым кадром и видно моргание. Потолком
 * здесь работает всё окно: док выше окна не может быть ничьим выбором, это
 * мусор — и `«99999»` отвечает умолчанием, а не доком во весь экран.
 *
 * Значение, законно сохранённое на большом мониторе, на ноутбуке отвечает
 * умолчанием, а не подрезанным доком. Это НАМЕРЕННО: подрезанный чужой выбор
 * выглядит как выбор, сделанный здесь, и человек начинает искать, кто ему
 * задал такую раскладку. Записи при этом не происходит — вернувшись на
 * большой монитор, он получит свою высоту обратно.
 *
 * Доступ к хранилищу обёрнут: в приватном окне и при запрещённых данных сайта
 * сам `getItem` бросает, и оболочка не имеет права падать из-за настройки
 * браузера.
 */
export function readDockH(winH: number, storage?: MaybeStorage): number {
  const store = storage === undefined ? safeStorage() : storage
  if (!store) return DOCK_H_DEFAULT

  let raw: string | null = null
  try {
    raw = store.getItem(DOCK_H_KEY)
  } catch {
    return DOCK_H_DEFAULT
  }
  if (raw === null || raw.trim() === '') return DOCK_H_DEFAULT

  const px = Number(raw)
  if (!Number.isFinite(px)) return DOCK_H_DEFAULT
  if (px < DOCK_MIN_H) return DOCK_H_DEFAULT
  if (Number.isFinite(winH) && winH > 0 && px > winH) return DOCK_H_DEFAULT
  return Math.round(px)
}

/** Записать. Молча не пишет, если хранилище недоступно, — это не повод падать. */
export function writeDockH(px: number, storage?: MaybeStorage): void {
  const store = storage === undefined ? safeStorage() : storage
  if (!store) return
  try {
    store.setItem(DOCK_H_KEY, String(Math.round(px)))
  } catch {
    /* приватное окно, запрещённые данные сайта, переполненная квота */
  }
}

function safeStorage(): MaybeStorage {
  try {
    return typeof localStorage === 'undefined' ? null : localStorage
  } catch {
    return null
  }
}
