/**
 * Карта видов не врёт про НАСТОЯЩИЕ фикстуры репозитория (DS-67).
 *
 * Единственное место, где статическая карта сверяется с исполнением. Дальше по
 * коду это уже нечем поймать: разбор ошибся — панель просто предложит другой
 * набор начинок, и выглядеть это будет как решение `fitsSlot`, а не как враньё
 * карты. Ошибиться при этом легко ровно одним способом — взять чужое `kind:`
 * (у крутилок их в каждой фикстуре по пять-восемь).
 *
 * ЧЕГО ЭТОТ ГЕЙТ НЕ ЛОВИТ — измерено, а не предположено. Подмена разбора
 * наивной регуляркой «первое kind: в файле» оставляет его ЗЕЛЁНЫМ: сегодня во
 * всех тринадцати фикстурах `kind` объявлен ВЫШЕ блока `controls`, и первое
 * `kind:` файла случайно оказывается верхним. Проверка на этой мутации молчит
 * не потому, что мутация безвредна, а потому, что репозиторий сейчас на ней не
 * различается — ровно тот случай, ради которого различимость проверяют
 * мутацией, а не рассуждением. Тот класс держит `kinds-source.test.ts` («kind
 * крутилки ВЫШЕ по файлу»), где вход выбран так, что различает.
 *
 * Что красит ЗДЕСЬ: разбор, перестающий доставать шапку (`objectOf` вернул
 * `null` на `defineFixture(…)`) — все тринадцать уезжают `unread`; пропущенный
 * или лишний файл в обходе каталога; расхождение сортировки со списком слева.
 *
 * Мутацией самой фикстуры гейт не красится, и это не дыра: правка `kind:` в
 * исходнике меняет обе стороны сравнения разом. Предмет здесь — согласие двух
 * способов прочитать одно и то же, а не значение само по себе.
 */
/// <reference types="vite/client" />
import { describe, it, expect } from 'vitest'
import { fixtureKinds } from './registry.js'
import type { AnyFixture } from '../src/internal/fixture.js'

// eager: гейту нужен весь список сразу — тот же довод, что в
// src/__guards__/fixtures.test.ts.
const shipped = import.meta.glob<{ default: AnyFixture }>(['../src/components/*/*.fixture.tsx', '../src/icons/*.fixture.tsx'], {
  eager: true,
})

const runtime = new Map<string, AnyFixture>(
  Object.entries(shipped).map(([path, m]) => [
    path.split('/').pop()!.replace('.fixture.tsx', ''),
    m.default,
  ]),
)

describe('карта видов против импорта', () => {
  const rows = fixtureKinds()

  it('состав совпадает: ни одной лишней записи, ни одной пропавшей', () => {
    expect(rows.map((r) => r.name).sort()).toEqual([...runtime.keys()].sort())
  })

  it('вид каждой фикстуры прочитан из исходника ТОЧНО так же, как из импорта', () => {
    const fromSource = Object.fromEntries(rows.map((r) => [r.name, r.kind]))
    const fromImport = Object.fromEntries([...runtime].map(([n, f]) => [n, f.kind]))
    expect(fromSource).toEqual(fromImport)
  })

  it('ни у одной фикстуры репозитория вид не остался непрочитанным', () => {
    // «Не прочитан» — честный ответ разбора, панель его показывает словами, и
    // верстак от него не ломается. Но такая фикстура предлагается В ЛЮБУЮ
    // позицию, и в собственном дереве это чинится, а не терпится: `kind`
    // пишется строковым литералом, без констант и спредов.
    expect(rows.filter((r) => r.unread).map((r) => r.name)).toEqual([])
  })

  it('карта отсортирована по имени — список слева идёт из неё же', () => {
    expect(rows.map((r) => r.name)).toEqual([...rows.map((r) => r.name)].sort((a, b) => a.localeCompare(b)))
  })
})
