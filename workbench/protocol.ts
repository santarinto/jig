/**
 * Протокол «оболочка ↔ кадр».
 *
 * Единственный модуль, общий для двух половин верстака. Спека говорит «общего
 * кода — ноль» про React-деревья и стили; конверт общий намеренно — иначе две
 * половины разъедутся при первой же правке формата.
 *
 * Четыре проверки на входящем сообщении, и важно понимать, что делает каждая:
 *  - `origin` сам по себе почти ничего не отсекает: кадр у нас same-origin,
 *    и любой сосед в том же origin её пройдёт;
 *  - `ns` — настоящая защита. В страницу регулярно шлют `window.postMessage`
 *    расширения браузера (HMR Vite тут ни при чём: `postMessage` в его клиенте
 *    не встречается ни разу, он ходит по WebSocket);
 *  - `sid` — защита от гонок. Пользователь щёлкает DataTable → Drawer → Card,
 *    и сообщение от предыдущего кадра приходит, когда на экране уже следующий.
 *  - `source` — защита от ЧУЖОГО ОКНА с тем же `sid` (DS-148). Наверх
 *    кадр говорит широковещательно, `window.parent.postMessage`, поэтому в
 *    слушателя оболочки попадает КАЖДЫЙ кадр, заведённый на её странице, —
 *    в том числе скрытый зонд из CLAUDE.md, у которого в адресе тот же
 *    `sid=1`, что у первого настоящего кадра. Ни `origin`, ни `ns`, ни `sid`
 *    их не различают: зонд честно свой, честно того же протокола и честно
 *    той же сессии. Различает только окно-отправитель.
 */
export const NS = 'ds-wb' as const
export const V = 1 as const

export type Theme = 'light' | 'dark'

/**
 * Набор текста, которым говорит предмет в кадре (DS-139, приёмка).
 *
 * `ru` — как у потребителя: русское умолчание словаря, без провайдера вовсе.
 * `pseudo` — `DS_TEXT_PSEUDO`, где каждое значение называет свой ключ; всё,
 * что осталось русским, компонент сказал МИМО словаря.
 *
 * Это не «язык» и языком не станет: живого второго языка в системе нет, а
 * псевдолокаль — приёмочный инструмент. Поэтому значений ровно два, и третье
 * сюда не добавится без второго языка.
 */
export type TextMode = 'ru' | 'pseudo'

/** Случай фикстуры — то, что от него нужно оболочке. */
export interface CaseMeta {
  id: string
  title: string
  note?: string
  /** Значение каждой УПРАВЛЯЕМОЙ крутилки в этом случае, строкой. */
  values: Record<string, string>
  /**
   * Случай задаёт свой `render` — то, что видно на экране, не выводится из
   * пропсов. Панель на таком случае не имеет права строить JSX-сниппет: он
   * воспроизводил бы пропсы, а не нарисованное (см. `dock.tsx`).
   */
  ownRender?: true
  /**
   * ПРОПЫ ДО ЭТОГО СЛУЧАЯ НЕ ДОЕЗЖАЮТ ([3] ручного QA, DS-128): его
   * действующий `render` объявлен без параметров, то есть прочитать их нечем.
   * Значит мертвы ВСЕ крутилки разом, и панель вправе их погасить.
   *
   * ЭТО НЕ ТО ЖЕ, ЧТО `ownRender`, и разница видна на первой же фикстуре: у
   * `Badge` случай «Все тона» рисует себя сам, но берёт `p.dot` — своя
   * разметка есть, крутилка работает. Погасив её «по своей разметке», панель
   * отняла бы живой контрол.
   *
   * Отсутствие поля НЕ значит «пропы точно читаются»: `render` с параметром
   * может не тронуть ни одного. Поэтому про такой случай панель молчит —
   * ложное утверждение хуже молчания.
   */
  ignoresProps?: true
  /**
   * КРУТИЛКИ, КОТОРЫЕ СЛУЧАЙ ПЕРЕКРЫВАЕТ (DS-164): его действующий
   * `render` рисует одно и то же при любом их значении — `<Live {...p}
   * title="Парки" />`. Панель такие гасит, а оболочка не пишет их в адрес:
   * ссылка со значением, которое ничего не значит, врёт тому, кто её откроет.
   *
   * Выводится зондом (`case-overrides.ts`), а не объявляется. Отсутствие поля
   * — «перекрытых нет» ИЛИ «зонд не смог ответить»; оба значат «живые»,
   * потому что ошибка в эту сторону ничего не отнимает.
   */
  overrides?: string[]
  /**
   * Начинки, которые задал сам кейс, — в той же строковой форме `'Component:case'`,
   * которой пользуется адрес кадра (`s.<id>=`). Приведены к одной форме нарочно:
   * панель сравнивает выбранное с кейсовым как две строки, ровно как `values`
   * для крутилок, и «сброс к кейсу» получается тем же кодом.
   *
   * ЧЕГО ЗДЕСЬ НЕТ: начинки вида `{ text: '…' }`. `SlotFill` их допускает, в строку
   * `'Component:case'` они не приводятся, и в этой фазе их не рисует НИКТО — ни
   * панель, ни кадр. Чтобы это не обернулось молчаливой пустотой, объявление такой
   * начинки — ошибка валидатора (Task 8), то есть красный гейт в момент, когда её
   * пишут, а не тишина в кадре через полчаса.
   */
  slots: Record<string, string>
}

/**
 * Вид крутилки — в протоколе, а не импортом из `src/internal/fixture.ts`.
 * Протокол общий для двух половин верстака и намеренно ничего не знает про
 * формат фикстуры; здесь описана ФОРМА СООБЩЕНИЯ, которая совпадает с ней по
 * составу. Гейт `fixture-meta.test.ts` следит, чтобы они не разошлись.
 */
export type ControlMetaKind =
  | { kind: 'enum'; values: string[]; /** Значения — числа, а не строки. Форма повторяет `EnumControl.numeric`. */ numeric?: true }
  | { kind: 'bool' }
  | { kind: 'number'; min: number; max: number; step?: number }
  | { kind: 'text' }

/**
 * Чему крутилка соответствует у компонента: `true` — проп с тем же именем,
 * строка — проп под другим именем, `false` — пропа нет вовсе. Форма повторяет
 * `PropRef` из формата фикстуры; смысл и цена ошибки описаны там.
 *
 * Едет ЧЕРЕЗ ПРОТОКОЛ, а не выводится в оболочке: сниппет печатает оболочка, а
 * знает про пропы только фикстура. Не довезя это поле, оболочка снова осталась
 * бы гадать — то есть печатать все крутилки подряд, как до DS-128.
 */
export type PropRefMeta = true | string | false

export type ControlMeta = ControlMetaKind & { prop: PropRefMeta }

/**
 * Вид позиции/фикстуры — форма, повторяющая `SlotKind` из фикстуры (Задача 2).
 * Как и `ControlMeta`, объявлена здесь заново: протокол про формат фикстуры не
 * знает, а форма сообщения обязана с ним совпадать по составу.
 */
export type SlotKind = 'inline' | 'block' | 'any'

/**
 * Объявленная позиция — форма сообщения, повторяющая `Slot` из фикстуры.
 * Как и `ControlMeta`, объявлена здесь заново: протокол общий для двух половин
 * верстака и про формат фикстуры не знает. От расхождения страхует присваивание
 * в тесте, проверяемое компилятором.
 */
export interface SlotMeta {
  title: string
  accepts: SlotKind
  /** ПОДПИСЬ для панели. Ничего не адресует. */
  prop?: string
  note?: string
}

/**
 * Один пункт карты видов (Задача 5) — по записи на каждую фикстуру
 * репозитория, а не только на те, что годятся в конкретную позицию: карта
 * общая на всю сессию кадра, фильтрует уже панель через `fitsSlot`.
 *
 * `kind` не указан у фикстуры, которая сама его не объявила (`fitsSlot`
 * трактует это как «годится куда угодно»), И у той, чей вид НЕ ПРОЧИТАН — в
 * паре с `unread`. Различить эти два случая тут же, полем, панель не обязана:
 * `fitsSlot` одинаково пускает оба, а `unread` панель показывает отдельной
 * пометкой СВЕРХ совместимости, а не вместо неё.
 */
export interface KindRow {
  name: string
  /**
   * Группа из шапки фикстуры (DS-152) — ею список компонентов и
   * группируется. Необязательное поле, потому что разбор честно ломается:
   * непрочитанная группа даёт `undefined`, а не выдуманное имя.
   */
  group?: string
  kind?: SlotKind
  /**
   * Вид не прочитан (DS-67): карта собирается разбором ИСХОДНИКА, и
   * `kind: SOME_CONST`, спред чужой шапки или отсутствие `export default` в
   * строковый литерал не сводятся.
   *
   * Отдельным полем, а не пустым `kind`, потому что пустой `kind` — это
   * утверждение «вид не объявлен», и `fitsSlot(accepts, undefined)` по нему
   * пускает фикстуру КУДА УГОДНО. Выдать «не знаю» за «годится везде» значило
   * бы предлагать блочный компонент в строчную ячейку молча.
   *
   * Такая фикстура остаётся ВЫБИРАЕМОЙ, а не исчезает: исчезнувшая из списка
   * читается как «такой фикстуры нет», а она есть.
   */
  unread?: true
}

/**
 * Выжимка из фикстуры, которую кадр отдаёт оболочке.
 *
 * Оболочка НЕ импортирует фикстуры сама, и это не вкусовщина: импорт исполняет
 * модуль фикстуры, тянет в документ оболочки компонент, его CSS и его
 * стресс-данные. Фикстура сломанного компонента — а верстак существует ради
 * сломанных компонентов — уронила бы вместе с собой панель, которой этот
 * компонент чинят.
 *
 * `data` едет ИМЕНАМИ наборов, а не содержимым: набор вроде `rows-500` — это
 * сотни объектов, и структурное клонирование такого груза на каждый `ready`
 * стоит мегабайта. Содержимое запрашивается отдельно, когда набор выбран.
 */
export interface FixtureMeta {
  name: string
  group: string
  cases: CaseMeta[]
  controls: Record<string, ControlMeta>
  /**
   * Ключи `props` фикстуры, у которых НЕТ крутилки: значения, строкой не
   * выразимые — `rows`, `columns`, `tabs`, `nodes`. Сниппет называет их
   * отдельно от крутилок стенда: там человеку нечего искать, а здесь он
   * обязан подставить своё.
   */
  unexpressed: string[]
  data: string[]
  slots: Record<string, SlotMeta>
}

/**
 * Нарушение в сообщении наверх — форма, повторяющая `Violation` из
 * `axe-layer.ts`. Как `ControlMeta`, объявлена здесь заново: протокол про
 * устройство слоя не знает, а форма сообщения обязана с ним совпадать по
 * составу. От расхождения страхует присваивание, проверяемое компилятором
 * (`frame-axe.test.tsx`).
 *
 * `impact` едет, но НЕ ДЛЯ ЦВЕТА: серьёзность — упорядоченная величина, а
 * величину цвет не кодирует никогда (закон системы). Порядок в списке уже
 * задан отправителем, а поле остаётся подписью.
 */
export interface A11yViolation {
  id: string
  impact: 'critical' | 'serious' | 'moderate' | 'minor' | null
  help: string
  nodes: { node: string }[]
}

/**
 * Отчёт слоя целиком — то, что оболочка держит и отдаёт в док. Отдельным
 * типом, а не инлайном в `Up`: его же имя носит состояние оболочки, и два
 * описания одной формы разъехались бы при первой правке.
 */
export interface A11yReportMsg {
  violations: A11yViolation[]
  incomplete: string[]
  applied: number
  /**
   * Прогон НЕ СОСТОЯЛСЯ — axe бросил. Отдельное поле, а не пустой отчёт:
   * «ноль нарушений» и «посмотреть не удалось» это разные ответы, и второй,
   * поданный как первый, — зелёное враньё в чистом виде. Верстак существует
   * ради сломанных компонентов, а axe спотыкается как раз на них.
   */
  error?: string
  /**
   * Прогона НЕ БЫЛО — слой включён, а корня превью в кадре нет (DS-163).
   *
   * Третий разряд, а не второе значение `applied: 0`. Ноль применённых правил
   * — ответ ПРО РАЗМЕТКУ: она отрисовалась, и axe честно не нашёл в ней ничего
   * своего. Отсутствие корня — ответ ПРО КАДР, и чинить его надо в другом
   * месте. До этой задачи оба факта печатались одним текстом («пустое превью
   * или фикстура не отрисовалась»), то есть вкладка предлагала гадать, какая
   * из двух бед случилась, ровно там, где сама и знала ответ.
   */
  noRoot?: true
}

/** Кадр → оболочка. */
export type Up =
  | { type: 'ready'; meta: FixtureMeta | null }
  /**
   * `w`×`h` — сколько заняла фикстура; `cw` — сколько места кадр ей отдал
   * (ширина содержимого хоста), `bar` — полоса прокрутки документа кадра, на
   * которую `cw` меньше ожидаемого (DS-314, `frame-size.ts`).
   */
  | { type: 'size'; w: number; h: number; cw: number; bar: number }
  | { type: 'error'; message: string; stack?: string }
  /**
   * Слой таб-стопов (Задача 33). Едет СПИСКОМ, а не числом: «стопов 12» не
   * отвечает на вопрос, ради которого слой заведён, — какие именно и в каком
   * порядке. Число выводится из длины списка, второго источника правды для
   * него не заводим.
   */
  | { type: 'tabstops'; stops: { node: string; label: string }[] }
  /**
   * Слой axe (DS-78). Спека обещала это сообщение ещё когда сам слой
   * был кандидатом на снятие — форма та же.
   *
   * ТРИ РАЗРЯДА, а не один список нарушений. `incomplete` — правила, которые
   * axe не смог решить (контраст поверх картинки), `applied` — сколько правил
   * вообще применилось к этой разметке. Без них «0 нарушений» читается как
   * «доступность проверена», хотя axe ловит меньше трети.
   *
   * Узлы едут ОПИСАНИЯМИ (`node`), а не элементами: элементы через
   * `postMessage` не проходят, и оверлей рисует их кадр у себя.
   */
  | ({ type: 'a11y' } & A11yReportMsg)
  | { type: 'force-stats'; ms: number; skipped: number }
  /**
   * Прицел: имя выбранного узла и ЦЕПОЧКА ЕГО ПРЕДКОВ до корня компонента,
   * снизу вверх (`up`), — DS-128, находка [12].
   *
   * `up` ОБЯЗАТЕЛЬНОЕ, а не необязательное с умолчанием `[]`. Пустой массив
   * значит «выше некуда», и это содержательный ответ, который тулбар печатает
   * счётчиком `↑0`; необязательное поле сделало бы «сообщение старой формы»
   * неотличимым от него — то есть сломанный кадр выглядел бы как компонент без
   * предков.
   *
   * СТРОКАМИ, а не элементами: узлы через `postMessage` не проходят, и
   * оболочка своих узлов в документе кадра не имеет. Тем же приёмом, что
   * `A11yReportMsg`.
   */
  | { type: 'aim'; selector: string | null; up: string[] }
  /** Ответ на `ask-kinds` (Задача 5). Уходит В ЛЮБОМ случае и СРАЗУ: с
   * DS-67 карта приезжает в кадр виртуальным модулем (`registry.ts`),
   * то есть готова к моменту запроса и ничего не грузит. Запрос остаётся
   * запросом, потому что кадр к нему может быть ещё не поднят — молчание
   * теперь означает только это. */
  | { type: 'kinds'; list: KindRow[] }
  /**
   * Ткнули в место на канвасе (DS-128) — оболочке пора показать в доке
   * ЕГО крутилки. Решение владельца: выделенная позиция управляет доком.
   *
   * Едет ВВЕРХ, потому что тычут внутри кадра, а док живёт в оболочке. Само
   * выделение при этом хранит ОБОЛОЧКА и присылает обратно патчем: держи кадр
   * источником правды о выделении — и док с канвасом разъедутся при первом же
   * пересоздании `<iframe>`, когда кадр забудет, а оболочка нет.
   */
  | { type: 'canvas-pick'; id: string }
  /**
   * Состав случаев и крутилок ОДНОГО места канваса. Едет вверх потому, что
   * фикстуры исполняет только кадр — оболочка их не импортирует и посчитать
   * это сама не может; ровно тот же довод, по которому `ready` возит `meta`
   * одиночного компонента.
   *
   * Шлётся на КАЖДОЕ место, как только его фикстура загрузилась, а не только
   * на выделенное. Иначе переключение выделения упиралось бы в круговой обмен
   * (оболочка спросила — кадр ответил), и док на долю секунды показывал бы
   * пустоту или, того хуже, крутилки ПРЕЖНЕГО места поверх нового имени.
   */
  | { type: 'canvas-meta'; id: string; meta: FixtureMeta | null }

/**
 * Колонок в сетке канваса (DS-128). Двенадцать — не круглое число, а
 * делимое: 12 даёт пополам, на треть, на четверть и на шесть без остатка, и
 * ровно поэтому на нём стоят вёрстки, ради сходства с которыми канвас и
 * существует. Живёт в протоколе, а не в раскладке: и кадр, и оболочка судят о
 * допустимом `col`/`span` по одному числу, а два числа разъехались бы молча.
 */
export const CANVAS_COLS = 12

/**
 * Место на канвасе — компонент, случай и координаты в сетке (DS-128).
 *
 * «Место», а не «позиция», хотя спека говорит «позиция»: слово «позиция» в
 * верстаке занято начинками фикстуры (`FrameState.slots`, `.wbf-slot-error`),
 * и два смысла одного слова в одном файле — будущий дефект, а не неудобство
 * чтения. Довод целиком — в шапке `canvas-plan.ts`.
 *
 * Живёт В ПРОТОКОЛЕ, потому что ездит по нему: раскладка приходит в кадр
 * патчем, а не адресом. Адрес описывает ПРЕДМЕТ и им делятся ссылкой; десять
 * мест в него по-хорошему не помещаются (решение спеки), и потому раскладки в
 * `FrameState` нет и не будет — иначе зеркало адреса начало бы врать о том,
 * что ссылка восстанавливает.
 */
export interface CanvasSpot {
  /**
   * Тождество места. Ключ React, адрес крутилок выделенного места и то, чем
   * место называет себя в разметке (`data-wb-spot`).
   */
  id: string
  /**
   * Имя компонента. СЛОВОМ, а не буквой `c`, хотя в адресе кадра параметр
   * зовётся `c` (замечание владельца 30.08.2026).
   *
   * Расхождение с адресом намеренное и стоит дешевле совпадения: адрес
   * набирают руками и делятся ссылкой — там каждая буква видна и `c=DataTable`
   * читается целиком; место же уезжает в ФАЙЛ, который кладут в репозиторий и
   * смотрят диффом, а `"c": "DataTable"` в диффе не читается никак. Байты в
   * `postMessage` и `localStorage` при этом никого не волнуют.
   *
   * Имя одно на все три двери — провод, хранилище и файл, — потому что разбор
   * у них один (`parseSpots`). Дай файлу своё имя поля, и в этой двери станет
   * два формата, которые разойдутся молча.
   */
  component: string
  /**
   * Случай. Пустая строка — «первый случай фикстуры», как и в адресе;
   * НАЗВАННЫЙ и не найденный — отказ, а не откат к первому.
   */
  caseId: string
  /** Начальная колонка, 1..CANVAS_COLS. */
  col: number
  /** Ширина в колонках, 1..CANVAS_COLS; `col + span` не больше CANVAS_COLS+1. */
  span: number
  /**
   * Покрученные пропсы ЭТОГО места. Значения строками — типизует их фикстура,
   * ровно как `FrameState.props` у одиночного кадра.
   *
   * Живут В МЕСТЕ, а не отдельным патчем «крутилки выделенного», и это решение
   * с последствием на шаге 5: раскладка сохраняется именованным набором, и
   * набор, потерявший покрученные значения, воспроизводит ПОЛОВИНУ собранного
   * экрана. Человек, сохранивший «таблицу в состоянии загрузки рядом с пустой
   * листалкой», обязан получить обратно её же, а не два умолчания.
   */
  props: Record<string, string>
  /**
   * Набор данных места (`fixture.data`), `null` — свой набор кейса.
   *
   * Есть по той же причине, что и `props`: набор — половина того, что человек
   * собрал («пустая таблица рядом с полной листалкой»), и раскладка, которая
   * его теряет, воспроизводит не тот экран. Плюс без него блок наборов в доке
   * оказался бы кнопками, которые нажимаются и ничего не делают, — а молчащая
   * кнопка хуже отсутствующей.
   */
  data: string | null
}

/**
 * Вид, который умеет САМ ДОКУМЕНТ КАДРА.
 *
 * `grid` сюда не входит, и это не забывчивость: сетка — несколько ДОКУМЕНТОВ,
 * и держит их оболочка (см. шапку `FrameMode` в frame-url.ts). `canvas`,
 * наоборот, целиком внутри одного документа — несколько компонентов в одном
 * хосте, — и потому едет вниз наравне с `frame` и `states`.
 *
 * Отдельным ИМЕНЕМ, а не перечислением по месту: правило «grid до кадра не
 * доезжает» иначе живёт в трёх местах списком строк и расходится молча —
 * достаточно дописать вид в одном из них.
 */
export type FrameDocMode = 'frame' | 'states' | 'canvas'

/** Оболочка → кадр: патч состояния. */
export interface Patch {
  type: 'patch'
  props?: Record<string, string>
  data?: string | null
  force?: string | null
  theme?: Theme
  scale?: number
  /**
   * Набор текста. Патчем, а не перезагрузкой, ровно тем же доводом, что тема и
   * `mode`: щёлкать «ru ↔ pseudo» будут часто и ПАРАМИ («что тут русское? а
   * какой у него ключ?»), а перезагрузка роняет живое состояние компонента —
   * то есть ровно то развёрнутое меню или открытую строку, текст которых и
   * разглядывают.
   */
  text?: TextMode
  /**
   * Вид кадра. Патчем, а не перезагрузкой: щёлкать «Кадр ↔ Состояния» будут
   * часто, а перезагрузка документа роняет и живое состояние компонента, и
   * тёплый лист форса. Канвасу это нужно ровно так же: он держит НЕСКОЛЬКО
   * компонентов, и перезагрузка роняет живое состояние каждого из них.
   */
  mode?: FrameDocMode
  /**
   * Начинки позиций. `null` у ключа — СНЯТЬ начинку, а не «начинка по имени
   * null»: без этого позицию, которую кейс не задавал, можно было заполнить
   * и уже никогда не опустошить — патч умел только заменять значение, и
   * единственным путём назад была перезагрузка кадра.
   */
  slots?: Record<string, string | null>
  layers?: string[]
  aim?: boolean
  /**
   * Раскладка канваса ЦЕЛИКОМ, а не дельтой — в отличие от `props` и `slots`
   * выше, которые дополняют. Место можно не только добавить и переставить, но
   * и УДАЛИТЬ, а дельта, умеющая удалять, — это `null` на ключе, то есть
   * второй язык поверх списка; список же отвечает на «что сейчас на канвасе»
   * одним значением и не расходится с собой.
   *
   * `unknown`, а не `CanvasSpot[]`, НАМЕРЕННО: значение приезжает через
   * `postMessage` и на шаге 5 придёт ещё и из `localStorage`, то есть из мест,
   * где типов нет вовсе. Объявить его типизованным значило бы поверить чужой
   * строке на слово; разбирает его `parseSpots` (`canvas-plan.ts`), и он же
   * называет вслух то, что не прочиталось.
   */
  canvas?: unknown
  /**
   * Выделенное место. `null` — снять выделение (канвас опустел), и потому это
   * поле различает `undefined` и `null`, как `data` и `force` выше.
   *
   * Именем, а не индексом: индекс сдвигается при удалении соседа, и выделение
   * молча переезжало бы на другое место — а вместе с ним и весь док.
   */
  canvasSelected?: string | null
}

