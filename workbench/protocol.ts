/** Оболочка → кадр. Размеченное объединение — новый вид добавляется членом,
 * а не необязательным полем: необязательное поле позволяло бы собрать
 * бессмысленный набор («патч и запрос карты видов разом»), член — нет. */
export type Down = Patch | AskKinds

export interface Envelope<T> {
  ns: typeof NS
  v: typeof V
  sid: number
  body: T
}

export function pack<T>(sid: number, body: T): Envelope<T> {
  return { ns: NS, v: V, sid, body }
}

/**
 * Разобрать входящее сообщение или вернуть `null`.
 *
 * `from` — окно, от которого сообщение ждут: у оболочки это `contentWindow`
 * её собственного `<iframe>`, у кадра — `window.parent`. Параметр
 * ОБЯЗАТЕЛЬНЫЙ, а не необязательный с умолчанием «не проверять»: проверка,
 * которую можно не передать, — это проверка, которую забудут на третьем
 * слушателе, и забудут молча. Обязательный параметр делает такой пропуск
 * ошибкой компиляции.
 *
 * `null` в `from` — «окна ещё нет» (кадр не смонтирован). Это не «пропустить
 * всё»: сообщение от неизвестно кого в такой момент и есть то, что режется.
 */
export function unpack<T>(e: MessageEvent, sid: number, from: Window | null): T | null {
  if (e.origin !== window.location.origin) return null
  if (!from || e.source !== from) return null
  const d = e.data as Partial<Envelope<T>> | null | undefined
  if (!d || typeof d !== 'object') return null
  if (d.ns !== NS || d.v !== V) return null
  if (d.sid !== sid) return null
  return (d.body ?? null) as T | null
}
