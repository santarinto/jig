/**
 * JSX текущего состояния — то, что копируют в свой код.
 *
 * Печатаются только УПРАВЛЯЕМЫЕ пропы: `rows`, `columns`, рендереры ячеек
 * строкой не выразить, и попытка их напечатать дала бы сниппет, который не
 * компилируется. Набор данных уходит комментарием: `data` — понятие верстака,
 * а не проп компонента.
 */
import { layoutIssueOf } from './canvas-plan.js'
import { CANVAS_COLS, type CanvasSpot, type ControlMeta, type FixtureMeta } from './protocol.js'

/**
 * Строковое значение как атрибут JSX. Двойные кавычки JSX-строка не умеет
 * экранировать бэкслешем (это не JS-строка) — печатать `raw` прямо между `"`
 * при значении вроде `нет "данных"` даёт сниппет, который не парсится
 * скопировавшим. Одинарные кавычки в атрибуте JSX ломаются симметрично.
 * Если в значении есть и те, и другие, единственный надёжный путь —
 * настоящая JS-строка в фигурных скобках: там `JSON.stringify` экранирует
 * честно.
 */
function jsxStringLiteral(raw: string): string {
  if (!raw.includes('"')) return `"${raw}"`
  if (!raw.includes("'")) return `'${raw}'`
  return `{${JSON.stringify(raw)}}`
}

/**
 * Текст, безопасный внутри JSX-комментария.
 *
 * Закрывающая пара «звёздочка-слэш» внутри строки ЗАКРЫВАЕТ комментарий
 * раньше времени, и хвост остаётся голым
 * внутри фигурных скобок — вставленное не компилируется. Строки сюда приезжают
 * снаружи: `parseSpots` пропускает любую строку в `component` и `caseId`
 * (проверяется только `typeof === 'string'`), а файл раскладки правят руками в
 * репозитории — это заявленная форма ввода, а не выдуманный случай.
 *
 * Тот же класс, что у `jsxStringLiteral` этажом выше, и та же цена ошибки: у
 * кавычек в атрибутах был докблок и три юнита, у комментариев — ничего.
 *
 * (Эта самая шапка на первой редакции закрылась на собственном примере и
 * сломала сборку — писать пару буквами здесь не педантизм.)
 *
 * ПРОБЕЛ, А НЕ ВЫРЕЗАНИЕ. Имя остаётся читаемым и остаётся собой; выкинуть
 * звёздочку значило бы показать в комментарии не то имя, которое стоит в
 * раскладке, — то есть соврать в объяснении, которое для того и печатается.
 */
function commentSafe(text: string): string {
  return text.replace(/\*\//g, '* /')
}

/**
 * Текст как СОДЕРЖИМОЕ тега. В JSX между тегами `{`, `}` и `<` — синтаксис, а
 * не буквы: `<Alert>цена {5}</Alert>` вставит выражение, а не строку, которую
 * человек видел на экране. Надёжный путь тот же, что у атрибутов, — настоящая
 * JS-строка в фигурных скобках.
 */
function jsxChildren(raw: string): string {
  return /[{}<>]/.test(raw) ? `{${JSON.stringify(raw)}}` : raw
}

/**
 * Что в сниппет НЕ ПОПАЛО — и почему. Печатается комментарием над тегом.
 *
 * Две причины различаются, потому что человеку они стоят разного. Крутилка
 * стенда (`prop: false`) означает «такого пропа у компонента нет, я собрал это
 * сам» — искать в API бесполезно. Значение фикстуры без крутилки означает
 * «проп есть, но его значение — данные, строкой не выразимые»: `rows`,
 * `columns`, `tabs`. Второе человек обязан подставить своё, первое — забыть.
 *
 * ПУСТО — КОММЕНТАРИЯ НЕТ ВОВСЕ. Комментарий «потеряно: ничего» над каждым
 * тегом за неделю становится шумом, который перестают читать, — и тогда он не
 * сработает в тот единственный раз, когда потеряно было что-то.
 */
function lossComment(lostKnobs: string[], unexpressed: readonly string[]): string | null {
  const parts: string[] = []
  if (unexpressed.length > 0) {
    parts.push(`значения фикстуры, строкой не выразимые: ${unexpressed.join(', ')}`)
  }
  if (lostKnobs.length > 0) {
    parts.push(`крутилки стенда, у компонента таких пропов нет: ${lostKnobs.join(', ')}`)
  }
  return parts.length > 0 ? `{/* в сниппет не попало — ${commentSafe(parts.join('; '))} */}` : null
}

export function snippetOf(
  name: string,
  values: Record<string, string>,
  controls: Record<string, ControlMeta>,
  data: string | null,
  unexpressed: readonly string[],
): string {
  const parts: string[] = []
  const lostKnobs: string[] = []
  let children: string | null = null
  for (const [key, control] of Object.entries(controls)) {
    const raw = values[key]
    if (raw === undefined || raw === '') continue
    // Крутилка, которой у компонента не соответствует ничего. Печатать её
    // пропом — выдумывать API; печатать молча ничего — терять молча. Называем.
    if (control.prop === false) {
      lostKnobs.push(key)
      continue
    }
    // Имя пропа, а не имя крутилки: `emptyText` у фикстуры `DataTable` — это
    // `emptyContent` у компонента, и сниппет обязан печатать второе.
    const prop = control.prop === true ? key : control.prop
    if (control.kind === 'bool') {
      // `false` не печатается: в JSX отсутствие пропа И ЕСТЬ false, а `dense={false}`
      // в скопированном коде выглядит как осознанное решение, которым не было.
      if (raw === 'true') parts.push(prop)
      continue
    }
    if (control.kind === 'number') {
      const n = Number(raw)
      // Крутилка number может держать нечисловой промежуточный ввод —
      // `Number('abc')` даёт NaN. `count={NaN}` синтаксически валиден (NaN —
      // глобал), но это не то значение, что видно на экране; печатать его
      // как факт о компоненте нельзя. Пропускаем проп целиком.
      if (!Number.isNaN(n)) parts.push(`${prop}={${n}}`)
      continue
    }
    // `children` — обычное имя пропа, но единственное, которое в JSX живёт не
    // атрибутом. Отдельной формы в `PropRef` для него нет намеренно: строковая
    // форма уже значит «проп зовётся так», и этого достаточно.
    if (prop === 'children') {
      children = jsxChildren(raw)
      continue
    }
    // Числовой enum: `columns` у `KeyValueList` объявлен `1 | 2`, и
    // `columns="1"` у потребителя не присваивается. Проверяется ОБЪЯВЛЕНИЕ, а
    // не вид значения — см. `EnumControl.numeric`. Нечисловое значение под
    // такой пометкой пропускается по той же причине, что NaN у крутилки
    // number: печатать его фактом о компоненте нельзя.
    if (control.kind === 'enum' && control.numeric === true) {
      const n = Number(raw)
      if (!Number.isNaN(n)) parts.push(`${prop}={${n}}`)
      continue
    }
    parts.push(`${prop}=${jsxStringLiteral(raw)}`)
  }
  const attrs = parts.length > 0 ? ` ${parts.join(' ')}` : ''
  const tag = children === null ? `<${name}${attrs} />` : `<${name}${attrs}>${children}</${name}>`
  const head = [lossComment(lostKnobs, unexpressed), data ? `{/* набор данных: ${commentSafe(data)} */}` : null]
  return [...head.filter((l): l is string => l !== null), tag].join('\n')
}

/**
 * JSX ВСЕГО НАБОРА канваса (DS-128, шаг 7).
 *
 * Спека требует именно набор целиком, а не выделенное место: «это
 * единственный ответ, при котором скопированное можно вставить и получить то
 * же самое». Одно место из десяти воспроизводит компонент, а канвас собирают
 * ради ОТНОШЕНИЙ между компонентами — они-то и живут в сетке, а не в тегах.
 *
 * КОНТЕЙНЕР — ИНЛАЙНОВЫМ СТИЛЕМ, А НЕ КЛАССОМ. Класс `.wbf-canvas` живёт в
 * `frame.css`, то есть в верстаке; вставленный к потребителю он не значит
 * ничего, и раскладка развалилась бы молча — все места встали бы друг под
 * друга, что на двенадцати колонках выглядит как «так и было задумано».
 * Инлайн уродлив и переживает копирование; это и есть предмет.
 *
 * ЧТО ИЗ CSS КАНВАСА СЮДА ПОПАЛО И ПОЧЕМУ ИМЕННО ЭТО:
 * - `display`, `gridTemplateColumns`, `alignItems`, `gap` — раскладка. Без
 *   `alignItems: start` соседи в одной строке растянулись бы по самому
 *   высокому, то есть вставка дала бы другую картинку.
 * - `minWidth: 0` на месте — та же страховка, что `minmax(0, 1fr)`: без неё
 *   несжимаемый компонент раздвигает СЕТКУ и утаскивает соседей. В
 *   `frame.css` она названа страховкой, которая сегодня ничего не чинит;
 *   выбросить её здесь значило бы, что сниппет разойдётся с канвасом ровно на
 *   первом компоненте, ради которого она поставлена.
 * - `padding: 30px` НЕ ПОПАЛО. Это воздух вокруг канваса в верстаке, хром
 *   инструмента; у потребителя набор встаёт в его собственную страницу, и
 *   чужой отступ там — не воспроизведение, а мусор.
 *
 * `gap` уходит токеном `var(--ds-space-4)`, а не числом: потребитель ставит
 * дизайн-систему, токен у него есть, и раскладка обязана поехать вместе с
 * системой, а не застыть на значении, каким оно было в день копирования.
 *
 * НИ ОДНО МЕСТО НЕ УНОСИТ С СОБОЙ НАБОР. Место, про которое печатать нечего
 * (своя разметка у случая, не загрузившаяся фикстура, названный и не
 * найденный случай), объясняется комментарием в СВОЕЙ клетке — тем же
 * правилом, по которому `parseSpots` называет выброшенное место поимённо, а
 * не отказывается от раскладки целиком. Пустая клетка при этом не молчит:
 * человек вставит набор, увидит дыру и прочтёт рядом, отчего она.
 */
export function canvasSnippetOf(
  spots: readonly CanvasSpot[],
  metaById: Record<string, FixtureMeta | null>,
): string {
  // Пусто — пустая строка, а не контейнер с дырой внутри. Контейнер без мест
  // копируется и вставляется успешно, не делая ничего: галочка на кнопке
  // подтвердила бы работу, которой не было.
  if (spots.length === 0) return ''

  // Имена НАПЕЧАТАННЫХ компонентов, в порядке первого появления. Место с
  // отказом (своя разметка, нет фикстуры, битая раскладка) сюда не попадает:
  // в `import` оно дало бы неиспользуемый символ и вопрос «а где же он» у
  // того, кто вставил. `Set` — потому что два места одного компонента
  // (сравнить плотную таблицу с обычной) обычное дело, а
  // `import { DataTable, DataTable }` не компилируется.
  const printed = new Set<string>()
  const lines: string[] = [
    `<div style={{ display: 'grid', gridTemplateColumns: 'repeat(${CANVAS_COLS}, minmax(0, 1fr))',` +
      ` alignItems: 'start', gap: 'var(--ds-space-4)' }}>`,
  ]
  for (const [i, spot] of spots.entries()) {
    // РАСКЛАДКА ПРОВЕРЯЕТСЯ ДО СОДЕРЖИМОГО, и место с плохой раскладкой не
    // получает клетки вовсе: клетка И ЕСТЬ дефект. Напечатать
    // `gridColumn: '99 / span 99'` с объяснением рядом значило бы отдать
    // сломанный CSS вместе с запиской о том, что он сломан, — скопировавший
    // вставит и то, и другое.
    //
    // Слова берутся у `canvas-plan.ts`, а не пишутся здесь: кадр печатает их
    // же, и разойдясь, два источника читались бы как два разных дефекта.
    const issue = layoutIssueOf(spot, `место №${i + 1}`)
    if (issue !== null) {
      lines.push(`  {/* ${commentSafe(issue)} — раскладка не годится, место не скопировано */}`)
      continue
    }
    lines.push(`  <div style={{ gridColumn: '${spot.col} / span ${spot.span}', minWidth: 0 }}>`)
    const body = spotBody(spot, metaById[spot.id] ?? null)
    if (body.printed !== null) printed.add(body.printed)
    for (const line of body.lines) lines.push(`    ${line}`)
    lines.push('  </div>')
  }
  lines.push('</div>')
  // ВВОЗ ПЕРВОЙ СТРОКОЙ, и его нет, когда печатать нечего: пустой
  // `import {} from …` хуже отсутствия — он выглядит как обрезанный вывод.
  // Форма ровно та, которой пользуется потребитель (`consumption.md`):
  // именованный ввоз из корня пакета. Подпутей к компонентам в `exports` нет,
  // и `@santarinto/jig/dist/…` ответил бы `ERR_PACKAGE_PATH_NOT_EXPORTED`.
  const head = printed.size > 0 ? [`import { ${[...printed].join(', ')} } from '@santarinto/jig'`, ''] : []
  return [...head, ...lines].join('\n')
}

/**
 * Содержимое одной клетки: тег с пропами либо строка о том, почему тега нет.
 *
 * `printed` — имя компонента, ЕСЛИ тег напечатан. Возвращается отсюда, а не
 * вылавливается регуляркой из готовых строк наверху: здесь про отказ известно
 * прямо, а разбор собственного вывода обратно — та же догадка, от которой
 * уводит весь этот модуль.
 */
function spotBody(spot: CanvasSpot, meta: FixtureMeta | null): { lines: string[]; printed: string | null } {
  // Фикстуры нет или она упала — кадр в этом месте показывает те же слова.
  // Напечатать `<Nowhere />` было бы догадкой: про пропы компонента без
  // фикстуры верстак не знает НИЧЕГО, и сниппет утверждал бы состав, который
  // никто не проверял.
  if (!meta) return { lines: [`{/* ${commentSafe(spot.component)}: фикстура не загрузилась, печатать нечего */}`], printed: null }
  // Пустой `caseId` — «первый случай», ровно как в адресе кадра; названный и
  // не найденный — отказ, а не откат к первому (`resolve-case.ts`, то же
  // правило). Откат напечатал бы значения ЧУЖОГО случая под именем своего.
  const kase = spot.caseId ? meta.cases.find((k) => k.id === spot.caseId) : meta.cases[0]
  if (!kase) return { lines: [`{/* ${commentSafe(meta.name)}: случая «${commentSafe(spot.caseId)}» нет, печатать нечего */}`], printed: null }
  // Своя разметка у случая — тот же отказ, что у одиночного дока: сниппет
  // показал бы пропсы вместо нарисованного. Разница лишь в том, что здесь он
  // отказывается ЗА МЕСТО, а не за весь набор.
  if (kase.ownRender) {
    return { lines: [`{/* ${commentSafe(meta.name)}, случай «${commentSafe(kase.title)}»: своя разметка, пропсами не выражается */}`], printed: null }
  }
  // Действующее состояние места: значения случая, поверх них покрученное, —
  // тот же порядок, что в доке одиночного кадра.
  const lines = snippetOf(meta.name, { ...kase.values, ...spot.props }, meta.controls, spot.data, meta.unexpressed).split('\n')
  return { lines, printed: meta.name }
}

/**
 * Есть ли в сниппете хоть один настоящий тег компонента.
 *
 * Кнопка копирования гаснет на ПУСТОМ канвасе — но набор, где ни одно место не
 * печатается (ни одна фикстура не загрузилась), даёт непустую строку из
 * контейнера и одних объяснений. Клик по ней копировал бы сетку без единого
 * компонента и показывал галочку — успех, которого не было, то есть ровно то,
 * что запрещено двумя экранами выше в `dock.tsx`.
 *
 * Отдельной функцией, а не регуляркой в разметке: это утверждение о ФОРМАТЕ
 * сниппета, и жить оно обязано рядом с тем, кто формат печатает.
 */
export function hasPrintableSpot(snippet: string): boolean {
  return /^\s*<[A-Z]/m.test(snippet)
}
