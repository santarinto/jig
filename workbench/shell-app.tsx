/**
 * Что оболочка говорит про последнее действие с хранением (DS-128, шаг 5).
 *
 * ПОЧЕМУ ГОВОРИТЬ ОБЯЗАНА ИМЕННО ОБОЛОЧКА, хотя полоса про непрочитанные места
 * в кадре уже есть (`.wbf-slot-unplaced`, `frame-app.tsx`). Кадр объясняет
 * раскладку, которую ЕМУ ДАЛИ; оболочка — ту, которую она ПРОЧИТАЛА. Вниз
 * уезжают уже отобранные места, значит кадру нечего сообщить о выброшенных, и
 * молчание получилось бы полное: человек нажал на набор, увидел два места
 * вместо десяти и не узнал бы почему. Спека требует прямо: разбор чужого и
 * испорченного значения отвечает пустым канвасом С ОБЪЯСНЕНИЕМ.
 *
 * `undo` есть только у ЗАГРУЗКИ, и только у неё. Загрузка — единственное
 * действие шага, которое одним щелчком стирает собранный экран, а щелчок этот
 * стоит в ряду похожих чипов рядом с «+ DataTable». Сохранение и выгрузка
 * канвас не трогают, «забыть» требует сначала набрать имя в поле — это уже два
 * действия, а не одно, и обратный ход им не нужен.
 */
interface CanvasNote {
  /** Строка про то, что произошло. Есть всегда — молчания у действия нет. */
  head: string
  /**
   * Подробности, каждая отдельной строкой и цветом внимания: выброшенные места
   * из разбора, причина отказа хранилища. Пусто — значит всё прошло.
   *
   * НЕ СЧЁТЧИКОМ И НЕ ПОДСКАЗКОЙ В `title`. Строки называют место поимённо
   * («место №4 («pages»): колонка вне 1..12»), и по ним правят файл, который
   * лежит в репозитории; счётчик отправил бы искать заново, а `title` — это
   * объяснение, которое надо найти.
   */
  lines: string[]
  /**
   * Раскладка, к которой полоса предлагает вернуться, и слова этого хода.
   *
   * СЛОВА ЛЕЖАТ РЯДОМ С РАСКЛАДКОЙ, а не зашиты в кнопку. Ходов теперь два, и
   * они ведут в разные стороны: у загрузки это «вернуть прежнюю» (была работа,
   * её стёрли одним щелчком), у восстановления — «вернуть умолчание» (работы
   * не было, её принесли). Одна подпись на оба назвала бы умолчание «прежней
   * раскладкой», которой человек не собирал.
   */
  undo?: { spots: CanvasSpot[]; picked: string | null; label: string; done: string }
}

/**
 * Числовое поле раскладки: колонка или ширина выделенного места ([4] ручного
 * QA, DS-128).
 *
 * СВОЙ ЧЕРНОВИК ТЕКСТА, а не одно только число из раскладки. Пока поле правят,
 * в нём законно стоит то, что числом ещё не стало — пустая строка, «-», начало
 * «1» будущей «12». Раскладка таких значений не знает и знать не должна:
 * место без колонки не бывает. Черновик и есть та щель, в которой набор живёт
 * до того, как станет числом; без неё поле обязано было подставлять хоть
 * что-то на каждый ввод — и подставляло единицу.
 *
 * `draft === null` значит «показываем раскладку», а не «черновик пустой»:
 * пустая строка — законный черновик, и различить их обязательно.
 *
 * СБРОС ЧЕРНОВИКА ПРИ СМЕНЕ МЕСТА сделан `key` у вызывающего, а не эффектом:
 * поле принадлежит МЕСТУ, и другое место — это другое поле. Эффект на смену
 * `value` пришлось бы писать так, чтобы он не спорил с собственным вводом, и
 * первая же правка ввела бы его в спор.
 */
function SpotNumber({
  id,
  label,
  value,
  min,
  max,
  onCommit,
}: {
  id: string
  label: string
  value: number
  min: number
  max: number
  onCommit: (n: number) => void
}) {
  const [draft, setDraft] = useState<string | null>(null)
  return (
    <>
      <label className="wb__group-label" htmlFor={id}>
        {label}
      </label>
      <input
        id={id}
        type="number"
        className="wb__ctl-input"
        /* `min`/`max` НИЧЕГО НЕ ЗАПРЕЩАЮТ НАБРАТЬ — это подпись диапазона, не
           барьер (пункт А кодового ревью). Барьер — `commitOf`/`settleOf`.
           Атрибуты остаются: они рисуют стрелки в нужных пределах и говорят
           диапазон вслух, а это единственное место, где он вообще написан. */
        min={min}
        max={max}
        value={draft ?? String(value)}
        onChange={(e) => {
          const raw = e.target.value
          setDraft(raw)
          const n = commitOf(raw, min, max)
          if (n !== null) onCommit(n)
        }}
        onBlur={() => {
          const n = settleOf(draft ?? String(value), min, max, value)
          setDraft(null)
          if (n !== value) onCommit(n)
        }}
      />
    </>
  )
}

