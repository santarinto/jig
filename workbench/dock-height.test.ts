/**
 * Границы высоты дока и защита хранилища.
 *
 * Санитар написан на ДВА разных утверждения, и их нельзя мешать. Первое —
 * «границы держат»: док не уезжает ни в ноль, ни на весь экран. Второе —
 * «чужое значение отвечает умолчанием»: в `localStorage` лежит строка, которую
 * писал не обязательно верстак, и разбор обязан пережить что угодно.
 *
 * Числа границ проверяются ОТ КОНСТАНТ, а не литералами 76 и 120: литерал здесь
 * согласился бы сам с собой, потому что и код, и тест читали бы одно и то же
 * измерение. Литералы стоят только там, где утверждается САМО измерение
 * (первый тест) — иначе замер, потерянный при правке, ушёл бы незамеченным.
 */
import { describe, it, expect } from 'vitest'
import {
  clampDockH,
  maxDockH,
  readDockH,
  writeDockH,
  DOCK_H_DEFAULT,
  DOCK_H_KEY,
  DOCK_MIN_H,
  FIELD_MIN_H,
} from './dock-height.js'

/** Хранилище-заглушка: тесту нужен предсказуемый ящик, а не браузерный. */
const box = (start: Record<string, string> = {}) => {
  const map = new Map(Object.entries(start))
  return {
    map,
    getItem: (k: string) => map.get(k) ?? null,
    setItem: (k: string, v: string) => void map.set(k, v),
  }
}

/** Хранилище, которое БРОСАЕТ: приватное окно, запрещённые данные сайта. */
const angryBox = () => ({
  getItem: (): string => {
    throw new DOMException('denied', 'SecurityError')
  },
  setItem: (): void => {
    throw new DOMException('denied', 'SecurityError')
  },
})

describe('замеренные числа', () => {
  // Замер, а не вкус, и здесь он ПЕРЕСОБИРАЕТСЯ ИЗ СЛАГАЕМЫХ, а не сверяется с
  // литералом. Прежняя редакция держала `toBe(76)` плюс `% 4 === 0`; вторая
  // половина после DS-141 стала ложью (сетка хрома — 0.25rem, при корне
  // 115% это 4.6px), а первая ловила только «число сползло», но не «число
  // сползло вместе с тем, из чего оно сложено». Складывая части здесь, тест
  // краснеет и тогда, когда правку внесли в константу, минуя замер.
  it('пол дока — одна строка крутилки под заголовком колонки', () => {
    // Снято при корне 115% и deviceScaleFactor 1 по ВСЕМ 41 фикстурам каталога
    // (1600×1000), максимумом: граница дока, полоса вкладок, заголовок колонки,
    // строка крутилки. Худший случай — Badge (`tone`) и Button (`variant`), у
    // них низ первой `.wb__ctl` приходится на 104.828 от верха дока.
    //
    // Слагаемое 47.64, а не 29.891, потому что переключатель из пяти-шести
    // значений переносится на второй ряд чипов — при любой ширине окна, а не от
    // тесноты. У остальных тридцати девяти компонентов строка однострочная и
    // требует 87.078; пол, снятый по любому из них, был бы правдоподобен и
    // подрезал бы Badge с Button.
    //
    // Целая единица у границы — не округление, а признак верного замера: на
    // дробном масштабе дисплея хром браузера снапит хэйрлайн и отдаёт его как
    // 0.869565px. Первый замер этой задачи шёл именно так и дал 86.81, то есть
    // пол на пиксель ниже нужного.
    const parts = [1, 33.188, 23, 47.64]
    expect(DOCK_MIN_H).toBe(Math.ceil(parts.reduce((a, b) => a + b)))
  })

  it('полю кадра остаётся целая простая фикстура', () => {
    // Поле поля (хром, 1.25rem = 23px при корне 115%), обвязка кадра (6px
    // хэйрлайнов, не едет), Button — самая высокая из однострочных фикстур
    // (предмет, не едет).
    const parts = [23, 6, 92]
    expect(FIELD_MIN_H).toBe(parts.reduce((a, b) => a + b))
  })

  // Умолчание — худший случай плюс два пикселя, а не круглое число. Порог
  // (высота, ниже которой колонка начинает прокручиваться) снят делением
  // пополам по всем 41 компоненту каталога, 1600×1000, deviceScaleFactor 1.
  // При корне 100% максимум даёт PivotTable — ровно 338, и прежнее умолчание
  // 340 из этого и складывалось. При корне 115% самый голодный уже DataTable:
  // 393 против своих же 308 на 100%, то есть рост от переноса, а не от кегля —
  // домножить старое число на 1.15 значило бы промахнуться мимо живого порога.
  it('умолчание закрывает самый голодный компонент', () => {
    expect(DOCK_H_DEFAULT).toBe(393 + 2)
    expect(DOCK_H_DEFAULT).toBeGreaterThan(DOCK_MIN_H)
  })
})

describe('границы', () => {
  it('док не уезжает в ноль', () => {
    expect(clampDockH(0, 1000)).toBe(DOCK_MIN_H)
    expect(clampDockH(-500, 1000)).toBe(DOCK_MIN_H)
    expect(clampDockH(DOCK_MIN_H - 1, 1000)).toBe(DOCK_MIN_H)
  })

  it('док не съедает поле кадра', () => {
    expect(clampDockH(99999, 1000)).toBe(1000 - FIELD_MIN_H)
    expect(maxDockH(1000)).toBe(1000 - FIELD_MIN_H)
  })

  it('в промежутке высота не трогается, только округляется', () => {
    expect(clampDockH(340, 1000)).toBe(340)
    expect(clampDockH(340.4, 1000)).toBe(340)
  })

  /**
   * Окно, где не помещается ни док, ни поле. Пол выигрывает: подрезанный док
   * читается как поломка, подрезанное поле — нет, оно прокручивается.
   *
   * Утверждение именно о ПОРЯДКЕ границ, а не о числе: наивный
   * `Math.min(max, Math.max(min, px))` при `max < min` вернул бы `max`, то есть
   * док НИЖЕ пола, и внешне это выглядело бы как «границы работают».
   */
  it('на низком окне пол выигрывает у потолка', () => {
    expect(maxDockH(150)).toBe(DOCK_MIN_H)
    expect(clampDockH(340, 150)).toBe(DOCK_MIN_H)
  })

  it('«ещё не мерили» — не «места нет»: потолок не применяется', () => {
    expect(maxDockH(0)).toBe(Number.POSITIVE_INFINITY)
    expect(clampDockH(340, 0)).toBe(340)
  })

  it('не-число отвечает умолчанием, а не NaN-ом в стиле', () => {
    expect(clampDockH(Number.NaN, 1000)).toBe(DOCK_H_DEFAULT)
  })
})

describe('чтение хранилища', () => {
  it('своё значение возвращается как есть', () => {
    expect(readDockH(1000, box({ [DOCK_H_KEY]: '420' }))).toBe(420)
  })

  it.each([
    ['мусор', 'abc'],
    ['отрицательное', '-500'],
    ['выше окна', '99999'],
    ['ниже пола', '40'],
    ['пусто', ''],
    ['пробелы', '   '],
  ])('%s отвечает умолчанием, а не нулевым доком', (_, raw) => {
    expect(readDockH(1000, box({ [DOCK_H_KEY]: raw }))).toBe(DOCK_H_DEFAULT)
  })

  it('ключа нет — умолчание', () => {
    expect(readDockH(1000, box())).toBe(DOCK_H_DEFAULT)
  })

  /**
   * Хранилище, которое бросает, — это НАСТРОЙКА БРАУЗЕРА, а не поломка
   * верстака. Оболочка обязана открыться.
   */
  it('бросающее хранилище не роняет оболочку', () => {
    expect(readDockH(1000, angryBox())).toBe(DOCK_H_DEFAULT)
    expect(() => writeDockH(400, angryBox())).not.toThrow()
  })

  it('хранилища нет вовсе — умолчание', () => {
    expect(readDockH(1000, null)).toBe(DOCK_H_DEFAULT)
    expect(() => writeDockH(400, null)).not.toThrow()
  })
})

describe('запись', () => {
  it('пишет целое число под своим ключом', () => {
    const b = box()
    writeDockH(340.7, b)
    expect(b.map.get(DOCK_H_KEY)).toBe('341')
  })

  /**
   * Записанное читается обратно тем же числом. Пара, а не два теста по
   * отдельности: разъехавшийся ключ или формат прошёл бы оба — запись писала
   * бы своё, чтение отвечало бы умолчанием, и оба остались бы зелёными.
   */
  it('записанное читается обратно', () => {
    const b = box()
    writeDockH(512, b)
    expect(readDockH(1000, b)).toBe(512)
  })
})
