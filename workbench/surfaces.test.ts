/**
 * Стена оболочки и фон кадра — разные поверхности в ОБЕИХ темах.
 *
 * Дефект, ради которого это написано (фаза 1): документ кадра красится
 * --ds-bg-app, и поле оболочки красилось им же — в светлой теме обе
 * поверхности оказались буквально одного пикселя (#F0F0F0 против #F0F0F0).
 * Никакая рамка этого не лечит: глаз видит не контур, а сплошное поле
 * с царапиной.
 *
 * ЧЕГО ЭТОТ ГЕЙТ НЕ ДЕЛАЕТ, и это надо знать: он не утверждает, что ступень
 * между поверхностями ДОСТАТОЧНА. Два разных, но соседних оттенка он пропустит.
 * Достаточность — вопрос к глазу, и он остаётся за владельцем. Здесь ловится
 * только совпадение — то есть ровно тот дефект, который случился.
 *
 * Вторая граница: сравнивается ТЕКСТ объявления токена, а не вычисленный цвет.
 * Два разных токена с одинаковым цветом, записанным по-разному (`#FFF` против
 * `#FFFFFF`, или литерал против `var(--другой-токен)`), гейт пропустит — они
 * различны как строки, хотя красят одним и тем же. Сегодня оба токена (стены
 * и кадра) — литеральные хексы, так что это утверждение непусто.
 *
 * ПОСЛЕ DS-124 ЭТОТ ГЕЙТ НУЖНЕЕ, А НЕ МЕНЬШЕ. Раньше обе поверхности жили
 * в одном файле и расходились потому, что их развела система. Теперь стена —
 * `--wb-*` из `shell.css`, кадр — `--ds-*` из `tokens.css`: два файла, которые
 * никто не держит вместе, и совпасть они могут от правки любого из них. Поэтому
 * значение токена ищется в ТОМ файле, который его объявляет, а не в одном
 * заранее известном — иначе гейт падал бы с «токена нет», что читается как
 * поломка гейта, а не как разъехавшиеся поверхности.
 *
 * ПОСЛЕ DS-125 РАЗВОРАЧИВАЕТСЯ ССЫЛКА НА СТУПЕНЬ. Роли хрома больше не
 * хранят цвет — они указывают на ступень лестницы (`--wb-wall: var(--wb-4)`).
 * Сравнение строк без разворота вернуло бы «различны» ВСЕГДА: `var(--wb-4)` не
 * равно `#1A1A1A` как текст, даже если ступень покрашена ровно в него. Гейт,
 * который не может упасть, — это не гейт, а комментарий.
 *
 * У хрома при этом больше НЕТ тем: стена одна на всё. Кадр темы сохраняет, и
 * стена обязана отличаться от обеих — светлая стена сливалась бы со светлым
 * компонентом, тёмная с тёмным. Отсюда и средняя ступень.
 */
import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const read = (p: string): string =>
  readFileSync(resolve(__dirname, '..', p), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')

const SHELL = read('workbench/shell.css')
const TOKENS = read('tokens/tokens.css')

/** Тело правила по селектору. Комментарии уже вырезаны, вложенных фигурных нет. */
const body = (css: string, selector: string): string => {
  const m = css.match(new RegExp(`(^|\\})\\s*${selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*\\{([^}]*)\\}`))
  if (!m) throw new Error(`в CSS нет правила ${selector}`)
  return m[2]!
}

/** Токен, которым правило красит фон: background: var(--X). */
const bgToken = (css: string, selector: string): string => {
  const m = body(css, selector).match(/background:\s*var\((--[a-z0-9-]+)\)/)
  if (!m) throw new Error(`${selector} не красит фон через var(--*)`)
  return m[1]!
}

/**
 * Слои тени по запятым ВЕРХНЕГО уровня.
 *
 * Наивный `split(',')` здесь врёт и врёт тихо: первый слой — `rgba(138, 138,
 * 138, .95)`, и обычное деление даёт шесть кусков вместо трёх. Проверено на
 * живом файле: `слоёв 6, средний: 138`.
 */
const splitLayers = (decl: string): string[] => {
  const out: string[] = []
  let depth = 0
  let cur = ''
  for (const ch of decl) {
    if (ch === '(') depth += 1
    if (ch === ')') depth -= 1
    if (ch === ',' && depth === 0) {
      out.push(cur.trim())
      cur = ''
    } else {
      cur += ch
    }
  }
  out.push(cur.trim())
  return out
}

/**
 * Где объявлен токен: `--wb-*` — палитра хрома в `shell.css`, `--ds-*` — система
 * в `tokens.css` (DS-124). Развилка по префиксу, а не поиск по обоим
 * файлам: токен, случайно объявленный в обоих, обязан быть заметен, а не
 * молча разрешён первым попавшимся совпадением.
 */
const declaringSheet = (token: string): string =>
  token.startsWith('--wb-') ? SHELL : TOKENS

/** Объявление токена в области. Без разворота ссылок — это делает `value`. */
const declared = (token: string, scopeSel: string): string => {
  const scope = body(declaringSheet(token), scopeSel)
  const m = scope.match(new RegExp(`${token}:\\s*([^;]+);`))
  if (!m) throw new Error(`токена ${token} нет в области ${scopeSel}`)
  return m[1]!.trim()
}

/**
 * Значение токена в теме КАДРА. У хрома тем нет: `--wb-*` всегда из `:root`, и
 * аргумент `theme` их не касается — он про `--ds-*`.
 *
 * Ссылка на ступень разворачивается ровно на один уровень: сегодня лестница
 * плоская (`--wb-4: #444`), а цепочка длиннее одного звена означала бы, что
 * лестница перестала быть лестницей, — это надо увидеть, а не обойти.
 */
const value = (token: string, theme: 'light' | 'dark'): string => {
  const scope = token.startsWith('--wb-') ? ':root' : theme === 'light' ? ':root' : '[data-theme="dark"]'
  const raw = declared(token, scope)
  const ref = raw.match(/^var\((--wb-[a-z0-9-]+)\)$/)
  if (!ref) return raw
  const step = declared(ref[1]!, ':root')
  if (/^var\(/.test(step)) throw new Error(`ступень ${ref[1]} сама ссылка (${step}) — лестница не плоская`)
  return step
}

describe('поверхности верстака', () => {
  const wall = bgToken(SHELL, '.wb__field')
  const frame = bgToken(TOKENS, 'body')

  it('стена и кадр красятся разными токенами', () => {
    expect(wall).not.toBe(frame)
  })

  it.each(['light', 'dark'] as const)('в теме %s значения токенов различаются', (theme) => {
    const a = value(wall, theme)
    const b = value(frame, theme)
    expect(a, `стена ${wall}=${a}, кадр ${frame}=${b}`).not.toBe(b)
  })

  /**
   * Второй слой тени — «поля» вокруг кадра. Он обязан совпадать с цветом того,
   * на чём кадр лежит: разъедутся — вокруг кадра появится полоса третьего
   * цвета, которую никто не заказывал и которая читается как часть компонента.
   */
  it('средний слой границы кадра красится цветом стены', () => {
    const shadow = body(SHELL, '.wb__frame').match(/box-shadow:([^;]+);/)
    expect(shadow, 'у .wb__frame нет box-shadow').not.toBeNull()
    const layers = splitLayers(shadow![1]!)
    expect(layers, `слоёв ${layers.length}: ${layers.join(' | ')}`).toHaveLength(3)
    expect(layers[1]).toContain(`var(${wall})`)
  })
})
