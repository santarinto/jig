/**
 * Тема — свойство ПРЕДМЕТА. У инструмента её нет.
 *
 * Было два переключателя, и проверялась их различимость: один, красящий обе
 * поверхности, прошёл бы любую проверку вида «после щелчка стало темно».
 *
 * С DS-125 переключатель темы оболочки снят совсем, и предмет проверки
 * сместился, а не исчез. Светлый хром вокруг светлого компонента сливается с ним
 * в одно поле — ровно тот дефект, ради которого хром оторвали от системы
 * (DS-124). Переключатель, умеющий его воссоздать, — не удобство, а
 * заряженное ружьё, и его отсутствие приходится УТВЕРЖДАТЬ: снятый контрол
 * возвращается одной строкой JSX, и заметит это не автор.
 */
import { describe, it, expect, afterEach } from 'vitest'
import { render, screen, cleanup, fireEvent, within } from '@testing-library/react'
import { Shell } from './shell-app.js'
import { downSpy, frameQuery, frameSid, sendUp } from './test-kit.js'
import type { Envelope } from './protocol.js'

afterEach(() => {
  cleanup()
  delete document.documentElement.dataset.theme
})

const group = (name: string) => within(screen.getByRole('group', { name }))

describe('темы оболочки и кадра', () => {
  // Было: адрес кадра нёс тему и обновлялся при щелчке — предмет проверялся
  // через `frameQuery().get('theme')`. С патчем вниз (DS-62) адрес
  // замирает на монтировании (см. shell-frame.tsx), и тема в него больше не
  // попадает вовсе. Предмет — «тема кадра не красит оболочку» — не изменился,
  // только его наблюдаемый след: теперь тема едет ВНИЗ патчем, а не в адресе.
  it('тёмная тема кадра не трогает оболочку', () => {
    render(<Shell />)
    sendUp(frameSid(), { type: 'ready', meta: null })
    const spy = downSpy()

    fireEvent.click(group('Тема кадра').getByRole('button', { name: 'тьма' }))

    const sent = spy.mock.calls.map(([m]) => m as Envelope<{ type: string; theme?: string }>)
    expect(sent.some((m) => m.body.type === 'patch' && m.body.theme === 'dark')).toBe(true)
    // Оболочка не ставит `data-theme` вовсе — ни до щелчка, ни после. Раньше
    // здесь стояло `toBe('light')`, и это утверждение пережило бы возврат
    // переключателя в положении «свет».
    expect(document.documentElement.dataset.theme).toBeUndefined()
    spy.mockRestore()
  })

  // Было: «смена темы кадра заводит новую сессию» — это утверждение и было
  // ЦЕЛЬЮ задачи 3: патч заменил перезагрузку именно там, где раньше ехала
  // новая сессия. Форма развернулась на противоположную, предмет («смена темы
  // кадра — что происходит с сессией») остался тем же самым вопросом. Что
  // патч при этом действительно уходит — проверяет shell-patch.test.tsx.
  it('смена темы кадра не заводит новую сессию', () => {
    render(<Shell />)
    const before = Number(frameQuery().get('sid'))

    fireEvent.click(group('Тема кадра').getByRole('button', { name: 'тьма' }))

    expect(Number(frameQuery().get('sid'))).toBe(before)
  })

  /**
   * Обратное утверждение, и без него две проверки выше зелены при вернувшемся
   * переключателе: они смотрят на группу «Тема кадра», а вторая группа рядом им
   * не мешает. Проверяется ИМЕННО отсутствие, а не «единственность»: групп в
   * полосе девять, и счётчик по ним ловил бы любую правку тулбара, то есть
   * краснел бы не про то.
   */
  it('переключателя темы оболочки нет — инструмент тёмный всегда', () => {
    render(<Shell />)

    expect(screen.queryByRole('group', { name: 'Тема оболочки' })).toBeNull()
    // И предмет остался на месте: отсутствие проверяется рядом с наличием,
    // иначе опечатка в имени группы дала бы зелёный на пустом месте.
    expect(screen.getByRole('group', { name: 'Тема кадра' })).toBeTruthy()
  })
})
