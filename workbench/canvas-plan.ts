/**
 * Раскладка канваса: что стоит на нём по умолчанию и как читается чужая
 * (DS-128).
 *
 * ПОЧЕМУ «МЕСТО», А НЕ «ПОЗИЦИЯ», хотя спека говорит «позиция». Слово
 * «позиция» в верстаке уже занято, и занято прочно: `FrameState.slots` — это
 * начинки ПОЗИЦИЙ фикстуры (`?s.actions=Button:danger`), по ним же назван
 * `.wbf-slot-error` и вокруг них написана половина `frame-app.tsx`. Два разных
 * смысла одного слова в одном файле — это не неудобство чтения, это будущий
 * дефект: «позиция» канваса и «позиция» фикстуры встретятся в одном
 * `resolveCase`, и различать их будут по контексту. В спеке
 * (`docs/superpowers/specs/2026-08-29-workbench-canvas-design.md` — удалена из
 * дерева на DS-351, берётся из истории через `git log --diff-filter=D`)
 * слово одно и
 * путать его там не с чем — расхождение намеренное и стоит дешевле совпадения.
 *
 * САМ ТИП `CanvasSpot` живёт в `protocol.ts`, а не здесь: раскладка ездит
 * ПАТЧЕМ, то есть по протоколу. Здесь — умолчание и разбор.
 */
import { CANVAS_COLS, type CanvasSpot } from './protocol.js'

/**
 * Имя места В РАЗМЕТКЕ кадра. Кадр его пишет, прицел и таб-стопы читают.
 *
 * Константа, а не строка в трёх местах, по тому же доводу, что у `FORCE_ATTR`:
 * атрибут читают ДРУГИЕ модули, и разъехавшийся литерал не сломает сборку — он
 * просто перестанет находить места, и прицел молча вернётся к именам без
 * адреса. Отказ выглядел бы как «на канвасе прицел работает по-старому».
 */
export const SPOT_ATTR = 'data-wb-spot'

/**
 * Раскладка по умолчанию — та, что видно, пока никакой другой не прислали.
 *
 * ПАРА ВЫБРАНА НЕ СЛУЧАЙНО И НЕ ПО КРАСОТЕ.
 *
 * - У ОБОИХ мест таб-стопы непустые: `DataTable` в случае «Открытие строки»
 *   ведёт Tab по именам водителей, `Pagination` — по кнопкам страниц. Пара, где
 *   у второго компонента стопов нет вовсе, давала бы РОВНО ТОТ ЖЕ список, что и
 *   фокус, застрявший в первом, — и замеру нечего было бы утверждать. Проверка
 *   обязана утверждать ПОРЯДОК, а количество на такой паре не различает работу
 *   и поломку.
 * - Оба `kind: 'block'` — встают в свои клетки без обёрток.
 * - Друг под другом во всю ширину: таблица с листалкой под ней — настоящий
 *   кусок экрана, а канвас существует ради вопроса «как это будет выглядеть у
 *   потребителя». Проверять сквозной таб-порядок на паре, которая рядом не
 *   встречается, значит проверять его на выдумке.
 */
export const CANVAS_SPOTS: readonly CanvasSpot[] = [
  { id: 'table', component: 'DataTable', caseId: 'row-open', col: 1, span: CANVAS_COLS, props: {}, data: null },
  { id: 'pages', component: 'Pagination', caseId: 'base', col: 1, span: CANVAS_COLS, props: {}, data: null },
]

/** Что вышло из разбора: годные места и поимённо названные потери. */
export interface ParsedSpots {
  spots: CanvasSpot[]
  /**
   * Что не прочиталось — СТРОКАМИ ДЛЯ ЧЕЛОВЕКА, а не счётчиком.
   *
   * Спека требует прямо: разбор чужого и испорченного значения отвечает пустым
   * канвасом С ОБЪЯСНЕНИЕМ, а не белым экраном (то же правило, что у высоты
   * дока в `dock-height.ts`). Молчаливая потеря половины мест выглядит как
   * «раскладка не сохранилась», и искать будут в хранилище, а не в данных.
   */
  dropped: string[]
}

const isObj = (v: unknown): v is Record<string, unknown> =>
  typeof v === 'object' && v !== null && !Array.isArray(v)

const str = (v: unknown): string | null => (typeof v === 'string' ? v : null)

/**
 * Целое в диапазоне. `undefined` — поля НЕ БЫЛО, это законное умолчание;
 * всё остальное непрочитанное — порча, и она называется вслух.
 *
 * Разница несущая: место без `col` — это «поставь куда сам знаешь», а место с
 * `col: -1` — это испорченные данные, и молчаливое выправление их в 1
 * показало бы раскладку, которой никто не задавал. Тот же довод, по которому
 * названный и не найденный случай — отказ, а не откат к первому.
 */
function intIn(v: unknown, lo: number, hi: number): number | null | undefined {
  if (v === undefined) return undefined
  if (typeof v !== 'number' || !Number.isInteger(v) || v < lo || v > hi) return null
  return v
}

/**
 * Разбор чужой раскладки: из патча сегодня, из `localStorage` и файла на шаге 5.
 *
 * НЕ БРОСАЕТ И НЕ ОТКАЗЫВАЕТ ЦЕЛИКОМ ИЗ-ЗА ОДНОГО МЕСТА. Раскладка — это
 * работа человека; выбросить девять годных мест из-за десятого испорченного
 * значило бы наказать его за то, чего он не делал. Но и промолчать нельзя,
 * поэтому каждое выброшенное место названо.
 *
 * ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО: проверки, что компонент существует в каталоге.
 * Реестр ленивый, и знание об этом живёт в кадре, а не в чистой функции; кадр
 * и отвечает на это словами в самом месте («у компонента ещё не написан
 * `.fixture.tsx`»). Спека прямо ждёт такого случая: канвас переживёт удаление
 * компонента, и «раскладка ссылается на снесённое» — нормальный ход событий,
 * а не исключение.
 */
/**
 * Тексты отказов раскладки — ОДНОЙ ФУНКЦИЕЙ НА ТЕКСТ, а не шаблоном по месту
 * употребления (DS-128).
 *
 * Читателей у этих строк трое: `parseSpots` (разбор файла и хранилища), кадр
 * (печатает их в самом месте) и сниппет (объясняет, почему место не
 * скопировалось). Написанные шаблоном в каждом, они разошлись бы на первой же
 * правке формулировки — и разошлись бы МОЛЧА: два источника, отвечающие на
 * один вопрос по-разному, читаются как два разных дефекта.
 *
 * Ручной QA канваса отдельно отметил, что три источника имени узла в прицеле
 * отдают дословно одну строку, и это ровно то свойство, которое здесь
 * защищается механизмом, а не аккуратностью.
 */
export const LAYOUT_MSG = {
  col: (at: string, id: string): string => `${at} («${id}»): колонка вне 1..${CANVAS_COLS}`,
  span: (at: string, id: string): string => `${at} («${id}»): ширина вне 1..${CANVAS_COLS}`,
  overflow: (at: string, id: string, col: number, span: number): string =>
    `${at} («${id}»): ${col}+${span} не помещается в ${CANVAS_COLS} колонок`,
}

/**
 * Что не так с раскладкой ОДНОГО уже разобранного места, или `null`.
 *
 * Отдельно от `parseSpots`, потому что вопрос другой. `parseSpots` разбирает
 * ЧУЖОЙ вход (файл, хранилище) и отвечает «что удалось прочитать»; здесь вход
 * уже типизован, и вопрос — «годится ли то, что человек накрутил прямо
 * сейчас». Живая раскладка в оболочке через `parseSpots` не проходит вовсе:
 * `col` там меняет поле ввода, и 99 попадает в состояние без разбора.
 *
 * ИМЕННО ЭТОГО НЕ ХВАТАЛО СНИППЕТУ. Кадр показывал «колонка вне 1..12», а
 * кнопка «скопировать» рядом отдавала `gridColumn: '99 / span 99'` без единого
 * слова — то есть стенд копировал раскладку, которую сам же только что назвал
 * невалидной, и у коллеги компонент вылезал за сетку без намёка на причину.
 */
export function layoutIssueOf(spot: CanvasSpot, at: string): string | null {
  const inRange = (n: number): boolean => Number.isInteger(n) && n >= 1 && n <= CANVAS_COLS
  if (!inRange(spot.col)) return LAYOUT_MSG.col(at, spot.id)
  if (!inRange(spot.span)) return LAYOUT_MSG.span(at, spot.id)
  if (spot.col + spot.span > CANVAS_COLS + 1) return LAYOUT_MSG.overflow(at, spot.id, spot.col, spot.span)
  return null
}

export function parseSpots(raw: unknown): ParsedSpots {
  if (!Array.isArray(raw)) {
    return { spots: [], dropped: ['раскладка не список'] }
  }

  const spots: CanvasSpot[] = []
  const dropped: string[] = []
  const seen = new Set<string>()

  raw.forEach((item, i) => {
    const at = `место №${i + 1}`
    if (!isObj(item)) {
      dropped.push(`${at}: не объект`)
      return
    }
    const id = str(item.id)
    if (!id) {
      dropped.push(`${at}: нет имени (id)`)
      return
    }
    if (seen.has(id)) {
      // Повтор — не косметика: `id` служит ключом React и адресом крутилок
      // выделенного места, и два места с одним именем получили бы одни
      // крутилки на двоих.
      dropped.push(`${at}: имя «${id}» уже занято`)
      return
    }
    const component = str(item.component)
    if (!component) {
      // СТАРОЕ ИМЯ ПОЛЯ НАЗЫВАЕТСЯ ВМЕСТЕ С ПОЧИНКОЙ. До 30.08.2026 поле звалось
      // `c`, и выгрузки с ним у людей на диске уже лежат. «Нет компонента»
      // отправило бы искать пропажу там, где поле на месте и просто зовётся
      // по-старому, — то есть ровно тот молчаливый отказ, от которого уводит
      // весь этот разбор.
      dropped.push(
        typeof item.c === 'string'
          ? `${at} («${id}»): поле «c» больше не читается — переименуй его в «component»`
          : `${at} («${id}»): нет компонента (component)`,
      )
      return
    }
    const caseId = item.caseId === undefined ? '' : str(item.caseId)
    if (caseId === null) {
      dropped.push(`${at} («${id}»): случай задан не строкой`)
      return
    }
    const col = intIn(item.col, 1, CANVAS_COLS)
    if (col === null) {
      dropped.push(LAYOUT_MSG.col(at, id))
      return
    }
    const span = intIn(item.span, 1, CANVAS_COLS)
    if (span === null) {
      dropped.push(LAYOUT_MSG.span(at, id))
      return
    }
    const c0 = col ?? 1
    const s0 = span ?? CANVAS_COLS
    if (c0 + s0 > CANVAS_COLS + 1) {
      // Место, вылезающее за правый край, сетка бы ПЕРЕНЕСЛА на строку ниже
      // молча — и раскладка на экране разошлась бы с раскладкой в данных.
      // Молчаливый перенос хуже потери: его принимают за свою же ошибку в
      // расстановке и двигают соседей, которые ни при чём.
      dropped.push(LAYOUT_MSG.overflow(at, id, c0, s0))
      return
    }
    // КРУТИЛКИ ЧИСТЯТСЯ ПОШТУЧНО, а не отвергают место целиком. Значение
    // крутилки — строка, которую типизует фикстура; чужое значение там уже
    // сегодня просто не применяется (`resolveCase` молча пропускает крутилку,
    // которой в фикстуре нет). Выбросить из-за него всё место значило бы
    // потерять раскладку из-за пропа, который и так ни на что не влияет.
    const props: Record<string, string> = {}
    if (item.props !== undefined) {
      if (!isObj(item.props)) {
        dropped.push(`${at} («${id}»): крутилки заданы не объектом`)
        return
      }
      for (const [k, v] of Object.entries(item.props)) {
        const val = str(v)
        if (val === null) dropped.push(`${at} («${id}»): крутилка «${k}» задана не строкой`)
        // `defineProperty`, А НЕ ПРИСВАИВАНИЕ. Для ключа `__proto__`
        // присваивание — это вызов сеттера: строка ему не годится, поле
        // молча исчезает, и `dropped` о нём НЕ ГОВОРИТ — единственное
        // исключение из «каждое выброшенное названо», ради которого весь
        // разбор и написан. Дыры в безопасности тут нет и не было: сам
        // `JSON.parse` кладёт такой ключ обычным собственным полем и прототип
        // не трогает; терялась крутилка из файла, который правят руками.
        else Object.defineProperty(props, k, { value: val, writable: true, enumerable: true, configurable: true })
      }
    }
    // Набор данных: `null` и отсутствие поля — одно и то же «свой набор
    // кейса»; строка — имя набора. Чужой тип отвергает МЕСТО, а не чистится
    // поштучно, в отличие от крутилок: набор задаёт данные целиком, и место с
    // потерянным набором показало бы совсем не тот экран, молча.
    const dataRaw = item.data
    if (dataRaw !== undefined && dataRaw !== null && typeof dataRaw !== 'string') {
      dropped.push(`${at} («${id}»): набор данных задан не строкой`)
      return
    }
    seen.add(id)
    spots.push({ id, component, caseId, col: c0, span: s0, props, data: dataRaw ?? null })
  })

  return { spots, dropped }
}
