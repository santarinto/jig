/**
 * Хранение раскладок канваса: именованные наборы в `localStorage` плюс
 * выгрузка и загрузка файла (DS-128, шаг 5).
 *
 * ХРАНИЛИЩЕ ВЫБРАЛ ВЛАДЕЛЕЦ, ПРОТИВ МОЕЙ РЕКОМЕНДАЦИИ (я предлагал файл в
 * репозитории). Основание принято, цена записана в спеке отдельным разделом и
 * повторяется здесь, потому что читать её будут тут:
 *
 *  - раскладка НЕ ПЕРЕЖИВАЕТ чистку данных сайта и не ездит между машинами.
 *    Собранный экран — это работа, а работа, живущая в одном браузере,
 *    теряется молча;
 *  - двое разойдутся версиями одного имени, и узнать об этом можно только
 *    сравнив картинки;
 *  - ревью раскладки нет: она не попадает в git и не проходит через diff.
 *
 * Три смягчения из спеки ОБЯЗАНЫ быть сделаны, а не подразумеваться, и вот где
 * они здесь:
 *
 *  1. выгрузка даёт файл В ФОРМАТЕ, КОТОРЫЙ ЧИТАЕТСЯ ОБРАТНО, — `toFile`
 *     и `parseFile` ниже, и второй принимает то, что написал первый, плюс
 *     голый список, набранный руками;
 *  2. ключ ИМЕНОВАННЫЙ (`ds-wb/canvas/<имя>`), а не один общий: иначе второй
 *     канвас затирает первый, и это выглядит как «не сохранилось»;
 *  3. разбор чужого и испорченного значения отвечает ПУСТЫМ канвасом с
 *     объяснением — этим занят `parseSpots` (`canvas-plan.ts`), и обе двери
 *     сюда, хранилище и файл, ведут через него. Второго разбора нет намеренно:
 *     два разбора одного формата расходятся молча, и тогда файл, загруженный
 *     из репозитория, показывал бы не то, что показывает сохранённый набор.
 */
import { parseSpots, type ParsedSpots } from './canvas-plan.js'
import type { CanvasSpot } from './protocol.js'

/**
 * Пространство имён то же, что у высоты дока (`ds-wb/`), — чтобы соседи по
 * origin не спорили за ключи. Косая черта в конце несущая: без неё набор с
 * именем `-h` попал бы в ключ `ds-wb/canvas-h`, а это уже другое пространство.
 */
export const CANVAS_KEY_PREFIX = 'ds-wb/canvas/'

/** Ключ набора по имени. */
export const canvasKey = (name: string): string => `${CANVAS_KEY_PREFIX}${name}`

/**
 * Имя набора: непустое, без ведущих и хвостовых пробелов.
 *
 * ПОЧЕМУ ИМЯ ВООБЩЕ ПРОВЕРЯЕТСЯ. Пустое имя даёт ключ `ds-wb/canvas/`, то есть
 * ровно тот единственный общий ключ, от которого уводит смягчение №2: все
 * безымянные наборы затирали бы друг друга, и выглядело бы это как «не
 * сохранилось». Имя из одних пробелов делает то же самое, только незаметнее —
 * в списке оно выглядит пустой строкой, и два разных набора неразличимы.
 */
export const isValidName = (name: string): boolean => name.trim() === name && name.length > 0

type MaybeStorage = Pick<Storage, 'getItem' | 'setItem' | 'removeItem' | 'key' | 'length'> | null

function safeStorage(): MaybeStorage {
  try {
    return typeof localStorage === 'undefined' ? null : localStorage
  } catch {
    return null
  }
}

const pick = (storage?: MaybeStorage): MaybeStorage =>
  storage === undefined ? safeStorage() : storage

/**
 * Имена сохранённых наборов, по алфавиту.
 *
 * ИСПОРЧЕННЫЙ НАБОР ИЗ СПИСКА НЕ ПРОПАДАЕТ. Соблазн проверять содержимое здесь
 * и не показывать нечитаемое — ложная забота: набор ЕСТЬ, он занимает имя, и
 * пропав из списка он оставил бы человека с «я же сохранял» и без способа
 * это имя освободить. Про негодность отвечает `loadSet`, словами.
 */
export function listSets(storage?: MaybeStorage): string[] {
  const store = pick(storage)
  if (!store) return []
  const names: string[] = []
  try {
    for (let i = 0; i < store.length; i++) {
      const key = store.key(i)
      if (key && key.startsWith(CANVAS_KEY_PREFIX)) names.push(key.slice(CANVAS_KEY_PREFIX.length))
    }
  } catch {
    return []
  }
  return names.sort((a, b) => a.localeCompare(b, 'ru'))
}

/**
 * Записать набор. Отвечает, получилось ли, — и это не педантизм.
 *
 * Квота `localStorage` кончается (пять мегабайт на origin, и делит их весь
 * верстак), приватное окно бросает на самой записи, данные сайта могут быть
 * запрещены. Молча проглотить отказ здесь значило бы сказать человеку
 * «сохранено» и потерять его работу — ровно то, чего цена выбранного хранения
 * и так стоит дорого. Пусть скажет.
 */
export function saveSet(name: string, spots: readonly CanvasSpot[], storage?: MaybeStorage): boolean {
  if (!isValidName(name)) return false
  const store = pick(storage)
  if (!store) return false
  try {
    store.setItem(canvasKey(name), JSON.stringify(toFile(name, spots)))
    return true
  } catch {
    return false
  }
}

/**
 * Совпадает ли раскладка на канвасе с той, что лежит под именем (шаг 5,
 * дополнено по замечанию владельца 30.08.2026).
 *
 * ЗАЧЕМ. «Сохранить» есть, «вернуть прежнюю» есть, а «то, что на экране, уже
 * не то, что сохранено» не говорил никто: полоса показывала «набор сохранён,
 * мест 3» и после того, как места подвинули. Работа, разошедшаяся с
 * сохранённой молча, — это ровно та потеря, которой цена выбранного хранения
 * и так велика (см. шапку файла).
 *
 * СРАВНЕНИЕ ПОЛЕЙ, А НЕ ТЕКСТА. `JSON.stringify` был бы одной строкой и не
 * мог бы разойтись с путём записи, но он зависит от ПОРЯДКА КЛЮЧЕЙ в `props`:
 * набор, загруженный из файла и покрученный обратно к тем же значениям, дал бы
 * «расходится» на раскладке, которая не изменилась. Ложное расхождение хуже
 * молчания — его видят каждый раз и перестают верить признаку.
 *
 * ПОРЯДОК МЕСТ ЗНАЧИМ, а порядок крутилок — нет, и разница не произвольна:
 * порядок мест — это порядок обхода табом, то есть половина того, ради чего
 * канвас собирают; порядок ключей в `props` не виден нигде.
 */
export function sameSpots(a: readonly CanvasSpot[], b: readonly CanvasSpot[]): boolean {
  if (a.length !== b.length) return false
  return a.every((x, i) => {
    const y = b[i]!
    if (x.id !== y.id || x.component !== y.component || x.caseId !== y.caseId) return false
    if (x.col !== y.col || x.span !== y.span || x.data !== y.data) return false
    const xk = Object.keys(x.props)
    if (xk.length !== Object.keys(y.props).length) return false
    return xk.every((k) => x.props[k] === y.props[k])
  })
}

/** Забыть набор. `false` — хранилища нет или оно отказало. */
export function removeSet(name: string, storage?: MaybeStorage): boolean {
  const store = pick(storage)
  if (!store) return false
  try {
    store.removeItem(canvasKey(name))
    return true
  } catch {
    return false
  }
}

/**
 * Прочитать набор. Всегда `ParsedSpots` — то есть всегда есть что показать и
 * что сказать, даже когда показать нечего.
 *
 * Отсутствие набора и негодный набор различены СЛОВАМИ, а не пустотой: первое
 * значит «такого имени нет», второе — «имя есть, содержимое не читается», и
 * второе требует от человека совсем других действий (пересохранить, а не
 * искать опечатку в имени).
 */
export function loadSet(name: string, storage?: MaybeStorage): ParsedSpots {
  const store = pick(storage)
  if (!store) return { spots: [], dropped: ['хранилище недоступно'] }
  let raw: string | null = null
  try {
    raw = store.getItem(canvasKey(name))
  } catch {
    return { spots: [], dropped: ['хранилище недоступно'] }
  }
  if (raw === null) return { spots: [], dropped: [`набора «${name}» нет`] }
  return parseFile(raw)
}

/**
 * Содержимое файла выгрузки.
 *
 * ОБЁРТКА С ИМЕНЕМ, а не голый список, — чтобы загруженный файл возвращал и
 * имя набора: без него загрузка из файла давала бы безымянный канвас, и
 * человек, отправивший коллеге `order-screen.json`, получал бы обратно вопрос
 * «а как он назывался». Голый список при этом ЧИТАЕТСЯ ТОЖЕ (см. `parseFile`):
 * файл кладут в репозиторий и правят руками, и требовать от руки обёртку
 * значит требовать церемонию там, где нужен список.
 */
/**
 * Версия формата обёртки (замечание владельца 30.08.2026).
 *
 * ЗАЧЕМ ОДНО ПОЛЕ. Файл ложится в репозиторий и живёт дольше той раскладки,
 * ради которой написан. Без версии будущая смена схемы въезжает МОЛЧА: поля,
 * которых разбор не знает, он пропускает, и на экране встаёт кривая раскладка
 * без единого слова о причине. С версией это громкий отказ в тот момент, когда
 * файл открыли, — то же правило, по которому названо каждое выброшенное место.
 *
 * ОБЕЩАНИЕ ДАНО ОБЁРТКЕ, А НЕ ГОЛОМУ СПИСКУ. Обёртку пишет инструмент, и
 * требовать от неё версию ничего не стоит; голый список пишут РУКОЙ в
 * репозитории, и `"v": 1` там — та самая церемония, от которой голый список и
 * заведён. Список без версии читается как текущий формат, и это его честная
 * граница: он не переживёт смену схемы молча — он её просто не заметит, и
 * тогда отвечать будет разбор места, поимённо.
 */
export const CANVAS_FILE_V = 1

export interface CanvasFile {
  v: typeof CANVAS_FILE_V
  name: string
  spots: CanvasSpot[]
}

export function toFile(name: string, spots: readonly CanvasSpot[]): CanvasFile {
  // `v` ПЕРВЫМ ключом, а не последним: `JSON.stringify` пишет в порядке
  // вставки, и версия обязана быть первой строкой файла — её читают глазами,
  // открыв файл, а не долистав до конца списка мест.
  return { v: CANVAS_FILE_V, name, spots: spots.map((s) => ({ ...s })) }
}

/**
 * Текст файла — С ПЕРЕВОДАМИ СТРОК И ОТСТУПОМ. Файл кладут в репозиторий, и
 * однострочный JSON там даёт diff «изменилась одна строка» на любую правку, то
 * есть ревью раскладки — то немногое, что при этом хранении вообще возможно, —
 * перестало бы работать.
 */
export function toFileText(name: string, spots: readonly CanvasSpot[]): string {
  return `${JSON.stringify(toFile(name, spots), null, 2)}\n`
}

/** Имя файла выгрузки: имя набора плюс расширение, а не `canvas.json`. */
export function fileNameOf(name: string): string {
  // Всё, что не буква/цифра/дефис, — в дефис: имя набора человеческое («экран
  // заказа»), а имя файла ездит через файловые системы и архивы.
  const safe = name.replace(/[^\p{L}\p{N}-]+/gu, '-').replace(/^-+|-+$/g, '')
  return `${safe || 'canvas'}.json`
}

/**
 * Разбор файла или значения из хранилища. Одна дверь на оба источника — иначе
 * два разбора одного формата разойдутся молча.
 *
 * Принимает три формы, и это НЕ снисходительность ради снисходительности:
 * обёртку (её пишет `toFile`), голый список (его пишут руками в репозитории) и
 * ничего не принимает молча — всё прочее объясняется словами.
 */
export function parseFile(text: string): ParsedSpots {
  let json: unknown
  try {
    json = JSON.parse(text)
  } catch {
    // Текст ошибки JSON.parse человеку не поможет («Unexpected token < in JSON
    // at position 0»), а вот «это не JSON» — уже направление поиска.
    return { spots: [], dropped: ['файл не читается как JSON'] }
  }
  if (Array.isArray(json)) return parseSpots(json)
  if (json && typeof json === 'object' && 'spots' in json) {
    // ВЕРСИЯ ПРОВЕРЯЕТСЯ ДО МЕСТ. Разобрать места чужой схемы и отчитаться
    // «отброшено 7» значило бы обвинить данные там, где не совпал формат:
    // человек пошёл бы чинить раскладку вместо того, чтобы взять другой файл.
    const v = (json as { v?: unknown }).v
    if (v !== CANVAS_FILE_V) {
      return {
        spots: [],
        dropped: [
          v === undefined
            ? `файл без версии — формат до v${CANVAS_FILE_V}; выгрузи раскладку заново`
            : `файл версии ${String(v)}, а читается только v${CANVAS_FILE_V}`,
        ],
      }
    }
    return parseSpots((json as { spots: unknown }).spots)
  }
  return { spots: [], dropped: ['в файле нет списка мест'] }
}

/** Имя набора из файла, если оно там есть. `null` — голый список без имени. */
export function nameFromFile(text: string): string | null {
  try {
    const json: unknown = JSON.parse(text)
    if (json && typeof json === 'object' && !Array.isArray(json)) {
      const raw = (json as { name?: unknown }).name
      if (typeof raw === 'string' && isValidName(raw)) return raw
    }
  } catch {
    /* про негодный файл отвечает parseFile — здесь молчание уместно */
  }
  return null
}

/**
 * Ключ РАБОЧЕГО канваса — того, что на экране сейчас ([1] ручного QA).
 *
 * МИМО ПРОСТРАНСТВА ИМЁН НАБОРОВ, и это не косметика ключа. Лежи он под
 * `ds-wb/canvas/…`, `listSets` показал бы его отдельным набором с придуманным
 * именем, «забыть» предлагало бы его забыть, а загрузка — открыть. Рабочий
 * канвас не набор: у него нет имени, его никто не называл, и в списке имён ему
 * места нет. Отсюда дефис вместо косой черты.
 *
 * ЗАЧЕМ ОН ВООБЩЕ. До него в хранилище лежали ТОЛЬКО именованные наборы, то
 * есть механизм сохранения был, а к текущей работе приложен не был: собранный
 * экран из десяти мест жил до первой перезагрузки — а дев-сервер перезагружает
 * вкладку сам, без спроса и часто.
 *
 * `beforeunload` РАССМОТРЕН И ОТВЕРГНУТ. Модалка «точно уйти?» на каждый
 * релоад дев-сервера стоит дороже потери, которую предотвращает: её нажимают
 * не читая через день, и тогда она не предотвращает уже ничего.
 */
export const CANVAS_DRAFT_KEY = 'ds-wb/canvas-draft'

/**
 * Записать рабочий канвас. Имя НЕ ПРОВЕРЯЕТСЯ — в отличие от `saveSet`.
 *
 * Проверка имени у набора защищает ключ: пустое имя дало бы общий ключ, и
 * безымянные наборы затирали бы друг друга. Здесь ключ один и постоянный, а
 * имя — просто содержимое поля в тулбаре, которое человек мог не набрать
 * вовсе. Требовать его значило бы не сохранять работу до тех пор, пока её не
 * назвали, то есть ровно в тот период, когда она теряется чаще всего.
 *
 * Ответ `false` нужен по тому же доводу, что у `saveSet`: молчаливо отказавшее
 * автосохранение хуже отсутствующего — оно создаёт уверенность, которой не
 * соответствует.
 */
export function saveDraft(
  name: string,
  spots: readonly CanvasSpot[],
  storage?: MaybeStorage,
): boolean {
  const store = pick(storage)
  if (!store) return false
  try {
    store.setItem(CANVAS_DRAFT_KEY, JSON.stringify(toFile(name, spots)))
    return true
  } catch {
    return false
  }
}

/**
 * Прочитать рабочий канвас. `null` — ЧЕРНОВИКА НЕТ, и это не пустой канвас.
 *
 * Разница несущая и видна на экране. «Нет» — первый запуск (или чистка данных
 * сайта), и тогда встаёт умолчание из `CANVAS_SPOTS`. «Пусто» — человек убрал
 * все места сам, и подсовывать ему обратно две штуки умолчания значило бы
 * отменить его действие через перезагрузку. Та же пара, что у `loadSet`:
 * «имени нет» против «имя есть, содержимое не читается».
 *
 * Имя едет вместе с раскладкой: черновик пишется той же обёрткой `toFile`, что
 * и файл, поэтому поле набора после перезагрузки возвращается само. Второго
 * формата и второго разбора здесь нет намеренно — довод в шапке файла.
 */
export function loadDraft(storage?: MaybeStorage): (ParsedSpots & { name: string | null }) | null {
  const store = pick(storage)
  if (!store) return null
  let raw: string | null = null
  try {
    raw = store.getItem(CANVAS_DRAFT_KEY)
  } catch {
    return null
  }
  if (raw === null) return null
  return { ...parseFile(raw), name: nameFromFile(raw) }
}
