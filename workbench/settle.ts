/**
 * ОТСТАИВАНИЕ КАДРА ПО СВОЕМУ ПРЕДМЕТУ (DS-177).
 *
 * Строка матрицы меряет кадр, который часть компонентов раскладывает замером
 * (`ResizeObserver` → состояние → рендер): первый кадр после монтирования
 * законно не тот, что установится. Ждать надо ТОГО, что строка затем меряет, —
 * иначе ответ зависит от соседа. Строка цели клика до этого ждала предмета
 * строки переполнения («пока документ шире вьюпорта»), и компонент, который
 * раскладывается JS-ом и режет содержимое в своём контейнере, документ не
 * переполняет вовсе: цикл выходил через два кадра, а в полном обходе ту же
 * ячейку перед этим отстаивала проба переполнения — `--row targets` и
 * `npm run matrix` видели разные коробки.
 *
 * Правило: снять подпись, дальше по кадру анимации, пока ДВА КАДРА ПОДРЯД не
 * дадут одну подпись. Окно ограничено: не отстоялось за `windowMs` —
 * `settled: false`, и решать, что это значит, вызывающему (строка цели клика
 * называет такую ячейку «не измерено»: мерить ускользающее значит дать ответ,
 * зависящий от момента). Ответ от того, что исполнялось раньше, не зависит:
 * исходы — «установилось» (то же состояние, куда бы ни пришли) либо красное.
 *
 * Чистая функция от четырёх зависимостей — ради юнитов: в браузере её зовут с
 * `requestAnimationFrame` и `performance.now`, в тестах — с поддельными.
 */
export interface Settled {
  settled: boolean
  /** Сколько кадров анимации прождано. */
  frames: number
}

export async function settle(
  sample: () => string,
  nextFrame: () => Promise<void>,
  windowMs: number,
  now: () => number,
): Promise<Settled> {
  const deadline = now() + windowMs
  let prev = sample()
  let frames = 0
  while (now() < deadline) {
    await nextFrame()
    frames++
    const cur = sample()
    if (cur === prev) return { settled: true, frames }
    prev = cur
  }
  return { settled: false, frames }
}
