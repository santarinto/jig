/**
 * Начинка позиции — чужая фикстура, нарисованная внутри нашей.
 *
 * Грузит её КАДР, а не оболочка: кадр и так единственный, кому разрешено
 * исполнять модули фикстур, и начинка — ровно вторая фикстура.
 *
 * ДВА ИСТОЧНИКА, и порядок между ними тот же, что у пропсов
 * (`resolve-case.ts`: шапка → кейс → набор → адрес):
 *   1. `case.slots` — связка, объявленная ДАННЫМИ; работает без адреса;
 *   2. `state.slots` (`s.<id>=` в адресе) — перекрывает кейс.
 * Без первого слоя случай «колонка действий» показывал бы пустую колонку,
 * а гейт при этом оставался бы зелёным: он проверяет ссылки, а не рендер.
 *
 * ТЕКСТОВЫХ НАЧИНОК ЗДЕСЬ НЕТ. `fillsOf` возвращает строки `'Component:case'`, и
 * `{ text: '…' }` в эту форму не приводится: `fillToString` даёт на неё `null`,
 * и такая начинка СЕГОДНЯ молча выпадает из результата — так же, как выпадают
 * пустые значения `undefined` в `fixture-meta.ts` (см. комментарий там же).
 * Это честная тишина, не дыра: `{ text }` может прийти ТОЛЬКО из `case.slots`
 * — адрес возит строки, и строка никогда не разберётся в текстовую начинку —
 * а гейт (Task 8) запрещает объявлять `{ text }` в фикстуре вообще. После него
 * состояние «кадр увидел текстовую начинку» недостижимо, и заводить под него
 * шестой отказ здесь было бы кодом, до которого не дотянется ни один честный
 * тест — неопровержимая ветка, а их этот проект запрещает так же, как
 * неопровержимый тест. Если гейт Task 8 когда-нибудь ослабят — тишина
 * вернётся, и вот тогда шестой отказ станет нужен.
 *
 * РЕКУРСИЯ ЗАПРЕЩЕНА: начинка рисуется со `slots={{}}` всегда. `DataTable`
 * может оказаться начинкой самого себя, и это бесконечный цикл; а связка
 * «компонент в компоненте в компоненте» — не то, ради чего заводился слот.
 * Ради чего заводился, видно на одном уровне: портальный `<a><button>` даёт
 * два таб-стопа на пункт, а колонка действий рисует многоточие рядом с
 * кнопками (DS-57). Само рисование начинки (`loadFills`) живёт в
 * `frame-app.tsx` — там нужна JSX-разметка отказов, а этот файл её не несёт.
 *
 * Модуль общий для кадра и панели: `fitsSlot` — ссылка на ОДНУ функцию
 * валидатора (не копия), иначе гейт может пройти, пока кадр и валидатор
 * судят по-разному.
 */
import { fillToString } from './fixture-meta.js'
import type { AnyFixture } from '../src/internal/fixture.js'
import type { FrameState } from './frame-url.js'

export { fitsSlot } from '../src/internal/fixture-validate.js'

/**
 * Разбор ссылки на начинку: `'Badge:dot'` → `{ c: 'Badge', case: 'dot' }`,
 * `'Badge'` → `{ c: 'Badge' }`. Пустая строка и мусор вида `':dot'` (кейс без
 * имени компонента) отвергаются `null`ом, а не угадываются — молчаливая
 * догадка тут страшнее явного отказа.
 */
export function parseFill(raw: string): { c: string; case?: string } | null {
  if (!raw) return null
  const i = raw.indexOf(':')
  if (i === -1) return { c: raw }
  const c = raw.slice(0, i)
  const kase = raw.slice(i + 1)
  if (!c) return null
  return kase ? { c, case: kase } : { c }
}

/**
 * Слоистость начинок позиций: кейс → адрес (см. шапку файла). `fillToString`
 * — та же функция, которой `fixture-meta.ts` приводит начинку кейса к строке
 * для чипа панели; звать собственное приведение здесь нельзя — иначе панель и
 * кадр рано или поздно разойдутся в том, что считается одной и той же начинкой.
 */
export function fillsOf(fx: AnyFixture, s: FrameState): Record<string, string> {
  const kase = fx.cases.find((x) => x.id === s.caseId) ?? fx.cases[0]
  const fromCase: Record<string, string> = {}
  for (const [slotId, fill] of Object.entries(kase?.slots ?? {})) {
    const str = fillToString(fill)
    if (str !== null) fromCase[slotId] = str
  }
  // Адрес — после кейса и целиком поверх: позиция, которую адрес не трогал,
  // остаётся кейсовой, а та, что трогал, перекрывается, а не сливается по
  // символам.
  return { ...fromCase, ...s.slots }
}
