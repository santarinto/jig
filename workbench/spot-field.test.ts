/**
 * Числовые поля раскладки канваса ([4] ручного QA, DS-128).
 *
 * Два вопроса, и они РАЗНЫЕ: «что уехало на этом нажатии клавиши» и «чем
 * кончился набор». Слив их в один, получаем то, что и было: `Number(v) || 1` на
 * каждый ввод, пустое поле мгновенно становится единицей, и набранное
 * дописывается к ней.
 */
import { describe, it, expect } from 'vitest'
import { commitOf, settleOf } from './spot-field.js'

describe('что уезжает на вводе', () => {
  it('годное число уезжает сразу — раскладку двигают, глядя на кадр', () => {
    expect(commitOf('6', 1, 12)).toBe(6)
  })

  it('пустое поле не уезжает ничем: его стёрли, чтобы набрать заново', () => {
    expect(commitOf('', 1, 12)).toBe(null)
  })

  it('вне диапазона не уезжает — прижимать на каждой цифре значит мешать набирать', () => {
    // «12» при потолке 12 набирается через «1», а «1» годна. А вот «99»
    // проходит через «9», и прижми мы его сразу — второй девятке уже некуда
    // было бы дописаться.
    expect(commitOf('99', 1, 12)).toBe(null)
    expect(commitOf('0', 1, 12)).toBe(null)
    expect(commitOf('-3', 1, 12)).toBe(null)
  })

  it('мусор не уезжает и не превращается в ноль', () => {
    expect(commitOf('e', 1, 12)).toBe(null)
    expect(commitOf('1.5', 1, 12)).toBe(null)
  })
})

describe('чем кончился набор', () => {
  it('годное остаётся собой', () => {
    expect(settleOf('6', 1, 12, 3)).toBe(6)
  })

  it('вне диапазона прижимается к краю — человек видит, куда попало намерение', () => {
    expect(settleOf('99', 1, 12, 3)).toBe(12)
    expect(settleOf('-3', 1, 12, 3)).toBe(1)
  })

  it('пустое возвращает то, что на канвасе, а не минимум', () => {
    // Минимум подвинул бы место, которое человек не трогал: он передумал
    // набирать, а не попросил единицу.
    expect(settleOf('', 1, 12, 3)).toBe(3)
    expect(settleOf('e', 1, 12, 3)).toBe(3)
  })

  it('дробное — тоже не число для сетки, и возвращается прежнее', () => {
    expect(settleOf('1.5', 1, 12, 3)).toBe(3)
  })
})
