/**
 * Фактический размер превью — снизу вверх.
 *
 * Мерится ОБЪЕДИНЕНИЕ БОКСОВ ДЕТЕЙ корня превью, а не сам корень. `.wbf-host` —
 * блочный div, его ширина ВСЕГДА равна ширине вьюпорта кадра, то есть
 * заданной, — число, снятое с него самого, не может с ней разойтись и потому
 * ничего не измеряет (ревью раунд 1, DS-61). Интересно то, что реально
 * нарисовала фикстура: узкий бейдж, карточка, блочная таблица во всю ширину —
 * различимо только по боксам детей хоста.
 *
 * Если детей нет (фикстура вернула голый текстовый узел) — измеряется бокс
 * самого хоста: редкий, но законный случай.
 *
 * `render` фикстуры вправе вернуть фрагмент из нескольких узлов, поэтому
 * берётся ОБЪЕДИНЕНИЕ всех детей, а не первый: измерение по первому занизило
 * бы бокс, если следом идёт более широкий или более высокий сосед.
 *
 * Боксы с нулевой площадью (`display: none`, например скрытый форс-слой)
 * отфильтрованы: `left`/`top` у такого ребёнка — `0,0`, и `Math.min` тянул бы
 * объединение в ноль, раздувая итоговый размер каждым скрытым соседом. В
 * фазе 2 этого не происходит, но фаза 3 патчей может добавить рядом со
 * старым результатом рендера новый скрытый узел — и раздутое число читалось
 * бы как «фактическое больше нарисованного», то есть как ложный диагноз
 * дефекта компонента (ревью раунд 2, DS-61). Если после фильтра детей
 * не осталось (все скрыты или их не было) — прежний откат на бокс хоста.
 *
 * Берётся `getBoundingClientRect`, а не `contentRect` наблюдателя: второй не
 * считает рамку с падингом, а вопрос здесь про место, которое занято.
 */
/**
 * Место, которое кадр ОТДАЛ компоненту, — второй вопрос рядом с «сколько он
 * занял» (DS-314). `cw` — ширина содержимого хоста: `clientWidth` минус
 * паддинги, то есть ширина, от которой считает `width: 100%` компонента.
 * `bar` — ширина вертикальной полосы прокрутки документа кадра.
 *
 * Зачем. Хост отдаёт компоненту «ширина кадра − 60», пока документ не выше
 * кадра. Когда выше, у документа появляется полоса (~15 px), и контейнер молча
 * становится 285 вместо 300 на кадре 360. Гейты ставят хост ровно в кадр без
 * полосы, так что числа приёмки и гейта расходились на ширину полосы — и
 * выглядели дефектом компонента. Приёмка DS-310 поймала это только
 * потому, что агент печатал своё окружение рядом с каждым числом.
 *
 * Полосу НЕ прячем (`scrollbar-width: none`): на рабочем столе она в потоке и
 * настоящая, и кадр без неё солгал бы о раскладке. Показываем правду.
 *
 * Паддинг читается вычисленным стилем, а не литералом 30: он живёт в
 * `frame.css`, и число, зашитое здесь, разошлось бы с ним молча.
 */
export interface Room {
  cw: number
  bar: number
}

export function roomOf(target: Element): Room {
  const doc = target.ownerDocument
  const view = doc.defaultView
  const cs = view ? view.getComputedStyle(target) : null
  const pad = cs ? (parseFloat(cs.paddingLeft) || 0) + (parseFloat(cs.paddingRight) || 0) : 0
  const cw = Math.round(target.clientWidth - pad)
  const bar = view ? Math.max(0, Math.round(view.innerWidth - doc.documentElement.clientWidth)) : 0
  return { cw, bar }
}

export function reportSize(target: Element, send: (w: number, h: number, room: Room) => void): () => void {
  const emit = (): void => {
    const kids = Array.from(target.children)
    const kidBoxes = kids.map((el) => el.getBoundingClientRect()).filter((b) => b.width > 0 && b.height > 0)
    const boxes = kidBoxes.length > 0 ? kidBoxes : [target.getBoundingClientRect()]
    const left = Math.min(...boxes.map((b) => b.left))
    const top = Math.min(...boxes.map((b) => b.top))
    const right = Math.max(...boxes.map((b) => b.right))
    const bottom = Math.max(...boxes.map((b) => b.bottom))
    send(Math.round(right - left), Math.round(bottom - top), roomOf(target))
  }
  const ro = new ResizeObserver(emit)
  // Хост наблюдается ради смены СОСТАВА детей (их стало больше или меньше),
  // каждый ребёнок — ради смены СВОЕГО размера: у блочного хоста своя ширина
  // не следует за содержимым, и наблюдение одного хоста промолчало бы, когда
  // содержимое сжалось или выросло внутри него.
  //
  // ГРАНИЦА: список детей читается ОДИН РАЗ, при подключении. Если фикстура
  // заменит корневые узлы уже после первого рендера, наблюдение за старыми
  // узлами не переедет на новые. В фазе 2 это не происходит — кадр рендерится
  // один раз, патчей вниз нет; пересмотреть в фазе 3 вместе с патчами.
  // Появление полосы сужает сам хост, поэтому его наблюдение ловит и `cw`, и
  // `bar`: отдельного слушателя на документ не нужно.
  ro.observe(target)
  for (const el of target.children) ro.observe(el)
  return () => ro.disconnect()
}
