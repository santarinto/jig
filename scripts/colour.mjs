/**
 * Альфа цвета, 0–1. Разбирается ЯВНО, теми же двумя записями, что и каналы:
 * современной через `/` и старой четвёртой через запятую. Незнакомый формат
 * бросает — валидация делегирована `channelsOf`, чтобы правило «не гадать
 * молча» было ОДНО, а не два разошедшихся.
 *
 * Раньше альфа отбрасывалась везде и намеренно (см. шапку файла): цвета
 * приходили с `getComputedStyle`, где `backgroundColor` уже сложен каскадом.
 * Для ТЕКСТА это неверно — `color: rgba(…, .6)` каскад не складывает ни с чем,
 * он смешивается только при отрисовке, — и ровно на этом стоял DS-209.
 * Отбрасывание сохранено в `channelsOf`, чтобы ни одно зелёное число не
 * поехало; кто хочет видимый цвет, зовёт `blend`.
 */
export function alphaOf(css) {
  const s = String(css).trim()
  channelsOf(s) // единственная точка отказа на незнакомом формате
  const body = /^(?:rgba?|color)\(([^)]*)\)$/i.exec(s)[1]
  const num = (t) => {
    const pct = t.endsWith('%')
    const n = Number(pct ? t.slice(0, -1) : t)
    if (!Number.isFinite(n)) throw new Error(`colour: альфа «${t}» в «${s}» не число`)
    return Math.min(1, Math.max(0, pct ? n / 100 : n))
  }
  const slash = body.split('/')
  if (slash.length === 2) return num(slash[1].trim())
  const parts = body.trim().split(/[\s,]+/).filter(Boolean)
  if (parts.length === 4 && body.includes(',')) return num(parts[3])
  return 1
}

/**
 * `fg` поверх `bg` с прозрачностью `alpha` — то, что глаз видит на экране.
 * Собственная альфа `fg` УМНОЖАЕТСЯ на `alpha`: и то и другое — слой
 * прозрачности, разницы между «цвет полупрозрачен» и «предок приглушён» при
 * отрисовке нет.
 *
 * Подложка обязана быть НЕПРОЗРАЧНОЙ. Полупрозрачная означает, что вопрос задан
 * не до конца («а что под ней?»), и молчаливый ответ здесь был бы ровно тем
 * правдоподобным числом, против которого написан весь модуль.
 *
 * Результат НЕ округляется до целых каналов: слоёв бывает несколько, и
 * округление на каждом копило бы ошибку в ту сторону, которую никто не считал.
 */
export function blend(fg, bg, alpha = 1) {
  if (!(alpha >= 0 && alpha <= 1)) throw new Error(`colour: прозрачность «${alpha}» вне 0–1`)
  if (alphaOf(bg) < 1) throw new Error(`colour: подложка «${bg}» полупрозрачна — под ней не видно`)
  const a = alphaOf(fg) * alpha
  const f = channelsOf(fg)
  const b = channelsOf(bg)
  const mix = f.map((v, i) => +(v * a + b[i] * (1 - a)).toFixed(2))
  return `rgb(${mix.join(', ')})`
}
