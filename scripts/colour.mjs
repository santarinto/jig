/**
 * Разбор цвета для гейтов, которые считают контраст и ΔE.
 *
 * До DS-216 обе считающие функции брали из строки первые три числа
 * регекспом `/[\d.]+/g` и делили их на 255. На `rgb(221, 237, 237)` это
 * работает, а на `color(srgb 0.867686 0.928078 0.928078)` — том, что chromium
 * отдаёт за `color-mix()`, — читает доли как каналы: почти белый становится
 * почти чёрным. Ошибка не падает и не предупреждает, она отдаёт правдоподобное
 * число, и направление промаха зависит от пары: светлый текст на «почерневшем»
 * фоне даёт ЗАВЫШЕННОЕ отношение, то есть зелёный гейт на непроходящей паре —
 * проверка, которая прошла, не проверив.
 *
 * Отсюда два решения.
 *
 * 1. Форматы разбираются ЯВНО, по имени функции, а не по цифрам в строке.
 * 2. Незнакомый формат — ИСКЛЮЧЕНИЕ, а не «первые три числа». Сериализация
 *    computed-значения выбирается браузером, а не нами: сегодня это
 *    `color(srgb …)`, завтра обновление chromium может дать `oklch(…)`, и
 *    молчаливый разбор превратит один тихий промах в массовый за один
 *    `npm update`. Упавший гейт видно, посчитанное наугад число — нет.
 *
 * Альтернатива — нормализация канвасом внутри `page.evaluate` — нормализует всё,
 * но требует DOM в момент замера, а эти функции живут в node и вызываются уже
 * над снятыми строками. Явный разбор с отказом даёт то же свойство «не врать
 * молча» там, где браузера под рукой нет.
 *
 * Альфа НЕ учитывается в `channelsOf`/`contrastOf`/`deltaE76` — как и раньше:
 * цвета туда приходят с `getComputedStyle`, где `backgroundColor` уже сложен
 * каскадом. Полупрозрачный цвет там означал бы, что замер снят не с той
 * стороны, и молчаливое «использовать как есть» сохранено намеренно, чтобы
 * правка 216 не меняла ни одного зелёного числа.
 *
 * Для ТЕКСТА это оказалось неверно (DS-209): `opacity` предка и альфа
 * самого `color` каскадом не складываются ни с чем — они смешиваются только при
 * отрисовке, и номинальный контраст `.ds-cal__day--out` 5.33 был на экране 2.64.
 * Отсюда `alphaOf` и `blend` в конце файла: отдельные функции, а не изменение
 * поведения старых.
 */

const SUPPORTED = 'rgb() / rgba() / color(srgb …)'

/** Один компонент: число или проценты, приведённые к 0–255. */
function channel(token, full, css) {
  const pct = token.endsWith('%')
  const n = Number(pct ? token.slice(0, -1) : token)
  if (!Number.isFinite(n)) {
    throw new Error(`colour: компонент «${token}» в «${css}» не число`)
  }
  const v = pct ? (n / 100) * 255 : (n / full) * 255
  return Math.min(255, Math.max(0, v))
}

/**
 * Три компонента из тела функции. Альфа отбрасывается в обеих её записях:
 * современной, после `/`, и старой четвёртой через запятую (`rgba(r, g, b, a)`)
 * — chromium отдаёт именно её на всём, что прозрачно.
 */
function channels(body, full, css) {
  const head = body.split('/')[0].trim()
  const parts = head.split(/[\s,]+/).filter(Boolean)
  if (parts.length === 4 && head.includes(',')) parts.pop()
  if (parts.length !== 3) {
    throw new Error(`colour: в «${css}» ${parts.length} компонент(ов), а нужно 3`)
  }
  return parts.map((p) => channel(p, full, css))
}

/**
 * Каналы 0–255 из строки цвета. На незнакомом формате БРОСАЕТ — это и есть
 * предмет DS-216, а не защитное программирование.
 */
export function channelsOf(css) {
  const s = String(css).trim()
  const rgb = /^rgba?\(([^)]*)\)$/i.exec(s)
  if (rgb) return channels(rgb[1], 255, s)
  const srgb = /^color\(\s*srgb\s+([^)]*)\)$/i.exec(s)
  if (srgb) return channels(srgb[1], 1, s)
  throw new Error(`colour: не понимаю формат «${s}» — разбираются только ${SUPPORTED}`)
}

/** Контраст двух цветов по WCAG. */
export function contrastOf(a, b) {
  const lum = (c) =>
    c
      .map((v) => {
        const x = v / 255
        return x <= 0.03928 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4
      })
      .reduce((acc, v, i) => acc + v * [0.2126, 0.7152, 0.0722][i], 0)
  const [hi, lo] = [lum(channelsOf(a)), lum(channelsOf(b))].sort((x, y) => y - x)
  return (hi + 0.05) / (lo + 0.05)
}

/**
 * ΔE (CIE76) двух цветов — расстояние в Lab, а не разность каналов. Порог
 * различения соседних заливок ≈2.3: ниже него человек два цвета рядом не
 * разделяет. Тот же вопрос, что у contrastOf, но про заливки, а не про текст.
 */
export function deltaE76(a, b) {
  const lab = (css) => {
    const [r0, g0, b0] = channelsOf(css)
    const f = (c) => { const s = c / 255; return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4 }
    const [r, g, bl] = [f(r0), f(g0), f(b0)]
    const X = (0.4124 * r + 0.3576 * g + 0.1805 * bl) / 0.95047
    const Y = 0.2126 * r + 0.7152 * g + 0.0722 * bl
    const Z = (0.0193 * r + 0.1192 * g + 0.9505 * bl) / 1.08883
    const k = (t) => (t > 0.008856 ? Math.cbrt(t) : 7.787 * t + 16 / 116)
    const [x, y, z] = [k(X), k(Y), k(Z)]
    return [116 * y - 16, 500 * (x - y), 200 * (y - z)]
  }
  const [la, lb] = [lab(a), lab(b)]
  return Math.hypot(la[0] - lb[0], la[1] - lb[1], la[2] - lb[2])
}

