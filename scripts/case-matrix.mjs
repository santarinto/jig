#!/usr/bin/env node
/**
 * МАТРИЦА ОБЩИХ ПРИЁМОЧНЫХ СВОЙСТВ — одна точка входа (DS-177).
 *
 * Строки матрицы (`case-overflow.mjs`, `case-targets.mjs`) — МОДУЛИ: каждая
 * экспортирует объект строки (проба, санитар, вердикт, отчёт) и сама ничего не
 * поднимает. Поднимает здесь: один дев-сервер, один пул браузеров, один обход
 * `walk` (`case-walk.mjs`), где каждая ячейка (случай × шкала) грузится ОДИН
 * раз и обслуживает все строки, которые её судят. Решение владельца 18.09.2026:
 * первая редакция плана заводила строке 1 свой файл, свой порт и свою цель, то
 * есть два дев-сервера и два полных обхода тех же ячеек — это отменяло довод,
 * ради которого обвязка вообще вынесена в ходок.
 *
 * ПОРЯДОК СТРОК НЕСЁТ СМЫСЛ. Сперва те, кто только читает (переполнение,
 * ширина поля), и лишь потом цель клика: её проба листает окно и контейнеры
 * (`scrollIntoView`), и хотя возвращает их сама (`scanTargets`, `finally`),
 * ходок сверяет состояние кадра только для судей ПОСЛЕ портящего. Читающая
 * строка стоит раньше — её число не зависит ни от чьей аккуратности.
 *
 * ОСИ ОБХОДА — объединение шкал ВЫБРАННЫХ строк: строка переполнения судит
 * 0.875, 1 и 1.5, цель клика и ширина поля — ещё и 1.15. `--row overflow` грузит ровно три шкалы своей строки, а
 * не четыре ради соседки, которую не спрашивали.
 *
 * Usage: npm run matrix                  — все строки (это зовёт `check-full`)
 *        npm run matrix -- --row <ключ>  — одна строка: только её ячейки и её отчёт
 * Неизвестный ключ или лишний аргумент — список ключей и код 2, ДО подъёма
 * дев-сервера: опечатка в ключе не должна стоить минуты обхода.
 */
import { walk } from './case-walk.mjs'
import { overflowRow } from './case-overflow.mjs'
import { targetsRow } from './case-targets.mjs'
import { fieldsRow } from './case-fields.mjs'
import { WIDTH_FLOOR } from './width-surface.mjs'

/**
 * СВОЙ порт и `--strictPort` (его ставит `walk`) — тем же доводом, что у
 * `case-states.mjs`: прогон, молча подключившийся к службе на 5274, проверял бы
 * чужое дерево. Список портов держит `dev-server-ports`, и он читает этот
 * ЛИТЕРАЛ из файла регуляркой — переменная ослепила бы гейт молча. Порт у
 * матрицы один: строки своих серверов не поднимают.
 */
const PORT = 5280

// Ширина — объявленный пол поддерживаемой ширины (DS-380), литерала
// здесь больше нет намеренно: гейт `width-surface.test.ts` держит и то, что
// матрица берёт число из `WIDTH_FLOOR`, и то, что оно совпадает с CLAUDE.md.
const VIEWPORT = { width: WIDTH_FLOOR, height: 640 }

/** Ключ для `--row` → строка. Порядок вставки — порядок строк в обходе. */
const ROWS = new Map([
  ['overflow', overflowRow],
  ['fields', fieldsRow],
  ['targets', targetsRow],
])

const args = process.argv.slice(2)
let keys
if (args.length === 0) keys = [...ROWS.keys()]
else if (args.length === 2 && args[0] === '--row' && ROWS.has(args[1])) keys = [args[1]]
else {
  console.error(
    `case-matrix: не понял аргументы «${args.join(' ')}». `
    + `Строки: ${[...ROWS.keys()].join(', ')}; без аргумента — все.\n`
    + 'Usage: npm run matrix [-- --row <ключ>]',
  )
  process.exit(2)
}

const rows = keys.map((k) => ROWS.get(k))
const scales = [...new Set(rows.flatMap((r) => r.scales))].sort((a, b) => a - b)

await walk({ port: PORT, viewport: VIEWPORT, scales, rows })
