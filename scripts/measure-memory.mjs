#!/usr/bin/env node
/**
 * Память вкладки верстака, два разных предмета в одном прогоне.
 *
 * СЕТКА — уборка ДОКУМЕНТОВ: до входа / шесть кадров / после выхода.
 * КАНВАС — уборка КОМПОНЕНТОВ в одном документе: цикл добавления и уборки
 * десяти мест по 500 строк. Это разные механизмы, и зелёный один ничего не
 * говорит про другой; почему так — в шапке раздела канваса ниже.
 *
 * ОТДЕЛЬНЫЙ ПРОГОН, А НЕ ГЕЙТ, и это решение, а не лень. `performance.memory`
 * квантована, зависит от того, когда сборщик мусора сочтёт нужным поработать,
 * и от чужой нагрузки на машине; порог на таком числе краснел бы через раз и
 * учил бы перезапускать проверку. Здесь он отвечает на вопрос, который иначе
 * не задаётся вовсе: ВОЗВРАЩАЕТСЯ ли память после выхода из сетки. Невозврат
 * значит, что уборка кадров не работает, и шесть документов с `rows-500`
 * остаются висеть.
 *
 * Порог грубый (полтора раза от исходного) — он ловит не «стало на мегабайт
 * больше», а «шесть кадров никуда не делись».
 *
 * Usage: npm run measure:memory
 */
import { chromium } from 'playwright'
import { spawn } from 'node:child_process'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
/**
 * СВОЙ порт и `--strictPort`, а не общий 5274. Разработчик держит верстак
 * поднятым, и прогон, молча подключившийся к ЕГО серверу, проверял бы чужое
 * дерево — в лучшем случае устаревшее. Занятый порт валит запуск, а не
 * подменяет предмет проверки.
 */
const PORT = 5276
const MB = (n) => `${(n / 1024 / 1024).toFixed(1)} МБ`

/** Дев-сервер верстака: фикстуры и JSX без него не собрать. */
const vite = spawn('npm', ['run', 'wb', '--', '--port', String(PORT), '--strictPort'], {
  cwd: ROOT,
  stdio: 'ignore',
})
const stop = () => {
  try {
    vite.kill('SIGTERM')
  } catch {
    /* уже мёртв */
  }
}
process.on('exit', stop)

async function waitForServer(url, tries = 60) {
  for (let i = 0; i < tries; i++) {
    try {
      const res = await fetch(url)
      if (res.ok) return
    } catch {
      /* ещё поднимается */
    }
    await new Promise((r) => setTimeout(r, 250))
  }
  throw new Error(`дев-сервер не поднялся: ${url}`)
}

await waitForServer(`http://localhost:${PORT}/`)

const browser = await chromium.launch({
  args: ['--js-flags=--expose-gc', '--enable-precise-memory-info'],
})
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errs = []
page.on('pageerror', (e) => errs.push(String(e.message)))

/**
 * Сборка мусора и замер — МИНИМУМ из нескольких проб.
 *
 * Одной сборки мало, и это измерено: тот же код на том же дереве давал то
 * ×1.01, то ×1.32 между заходами. Отсоединённый документ живёт до сборки,
 * которая до него дойдёт, а `usedJSHeapSize` показывает занятое, а не живое.
 * Минимум из проб с паузами — то, что вкладка ДЕРЖИТ, а не то, что сборщик
 * ещё не успел отпустить.
 */
const heapOf = async (target, label) => {
  let best = Infinity
  for (let i = 0; i < 6; i++) {
    await target.evaluate(() => globalThis.gc?.())
    await target.waitForTimeout(400)
    const used = await target.evaluate(() => performance.memory?.usedJSHeapSize ?? 0)
    if (used < best) best = used
  }
  console.log(`  ${label.padEnd(28)} ${MB(best)}`)
  return best
}

/** Вкладка сетки — та, ради которой замер и заводился. */
const heap = (label) => heapOf(page, label)

// Пилотная фикстура с самым тяжёлым набором: 500 строк на каждый кадр.
await page.goto(`http://localhost:${PORT}/?c=DataTable&data=rows-500`, { waitUntil: 'networkidle' })
await page.waitForTimeout(1500)

console.log('Память вкладки (rows-500):')
const before = await heap('до входа в сетку')

const view = (name) => page.getByRole('group', { name: 'Вид' }).getByRole('button', { name })

const cycle = async (n) => {
  await view('сетка').click()
  if (n === 1) await page.getByRole('button', { name: 'обе темы' }).click()
  await page.waitForTimeout(4000)
  const frames = await page.locator('iframe.wb__frame').count()
  const during = await heap(`заход ${n}: в сетке (${frames} кадров)`)
  await view('кадр').click()
  await page.waitForTimeout(2000)
  const after = await heap(`заход ${n}: после выхода`)
  return { frames, during, after }
}

/**
 * ПЯТЬ ЗАХОДОВ: первый прогревает вкладку (лист системы, модуль фикстуры, шесть
 * документов — всё впервые), дальше две ПАРЫ — ранняя и поздняя.
 *
 * ПАРАМИ, А НЕ ПООДИНОЧКЕ, И ЭТО ПОЧИНКА ФЛАКА, а не аккуратность. Было три
 * захода, и накопление считалось как «третий / второй» — отношение двух СЫРЫХ
 * чисел. А одиночное число здесь врёт: выброс примерно в +9 МБ появляется
 * случайно и гуляет по заходам. Четыре прогона одного и того же дерева 29.08:
 * 17.0/25.4/17.1, 17.0/17.0/17.1, 17.0/17.0/17.1, 17.0/26.9/17.1 — выброс в
 * двух прогонах из четырёх, оба раза во втором заходе. Оба раза это дало
 * ЗЕЛЁНОЕ по случайности (делить на большое число безопасно); упади он на
 * третий — вышло бы ×1.5 при пороге 1.25, то есть красное на заведомо здоровом
 * коде. Такое ровно один раз и наблюдалось.
 *
 * Довод для починки был уже написан в этом файле, у соседней величины:
 * неустоявшийся замер число только ЗАВЫШАЕТ (сборщик не успел), занизить его
 * нечему — поэтому `settled` и берёт ПОЛ. К отношению этот довод применялся
 * ровно наполовину: пол с одной стороны, сырое число с другой. Теперь пол с
 * обеих, и порог сравнивает две устоявшиеся величины, а не две пробы.
 *
 * ЦЕНА — два лишних захода, около тридцати секунд. Замер ручной, вне `check` и
 * `check-full`; привычка перезапускать красное убивает гейт вернее, чем эти
 * тридцать секунд.
 *
 * ПОСЛЕ ПОЧИНКИ, пять прогонов подряд: выбросы легли на заходы 1 и 3, потом на
 * 5, потом на 1, 2 и 5, потом на 1 и 4, потом на 5 — накопление вышло ×1.00,
 * ×1.01, ×1.00, ×1.01, ×1.00. Первый из них на старой формуле дал бы
 * 27.0/17.0 = ×1.59, то есть красное на здоровом коде. Самый наглядный —
 * последний: выброс 47.0 МБ в пятом заходе при 17.2 в четвёртом, и пол пары
 * его просто не заметил.
 *
 * ЧЕГО ПОЛ НЕ ЛЕЧИТ И НЕ ДОЛЖЕН. Один прогон из этих шести пришёл красным с
 * числами 35.2/43.6/61.9/50.5/58.8 — подняты ВСЕ пять заходов, а не один. Это
 * не выброс, это вкладка, которая под нагрузкой машины (load average 20 на
 * чужих процессах) действительно не отдаёт память вовремя. Усреднением такое
 * не чинится, и чинить не надо: «держит на каждом заходе» — ровно тот ответ,
 * ради которого замер написан. Мерить надо на спокойной машине, и это уже
 * сказано в шапке файла.
 *
 * ЧТО ЭТА ВЕЛИЧИНА ЛОВИТ ОДНА, А ЧТО НЕТ — ИЗМЕРЕНО. Мутация «каждое
 * монтирование кадра оставляет за собой мегабайт» даёт накопление ×1.74, но
 * первым краснеет ВОЗВРАТ (×4.82): у утечки, растущей заметно, оба утверждения
 * срабатывают, и порядок проверок решает, чьё сообщение увидят. Полоса, где
 * накопление краснеет ОДНО, узкая и посчитана: утечка от `before`/6 до
 * `before`/4 за заход, то есть меньше чем в полтора раза шириной. Попасть в неё
 * мутацией при разбросе в ±9 МБ не вышло — ближайшая попытка дала возврат ×2.14
 * при накоплении ×1.24, обе величины на границе своих порогов. Значит держать
 * накопление стоит как раннее предупреждение, а не как самостоятельный гейт, и
 * ссылаться на него в одиночку не надо.
 */
const passes = []
for (let n = 1; n <= 5; n++) passes.push(await cycle(n))
const frames = passes[0].frames
const during = passes[0].during

/**
 * КАНВАС (DS-128) — ОТДЕЛЬНЫЙ раздел, а не наследование от сетки, и
 * спека требует именно этого. Сетка — это несколько ДОКУМЕНТОВ, и уборка там
 * про снятие `<iframe>`; канвас — несколько КОМПОНЕНТОВ в ОДНОМ документе, и
 * уборка там про размонтирование поддерева React. Зелёная сетка ничего не
 * говорит про канвас, и наоборот.
 *
 * ЕДЕТ ПО ДОКУМЕНТУ КАДРА, а не через оболочку, в отличие от сетки выше.
 * Кнопка «канвас» в оболочке с шага 4 есть, и щёлкать по ней замер МОГ БЫ —
 * но не должен: десять щелчков по «+ DataTable» добавили бы к предмету саму
 * оболочку, её состояние и её перерисовки. Кадр не знает, откуда пришёл патч,
 * и тулбар, загрузка набора и эта строка шлют ему одно и то же сообщение.
 *
 * ЦИКЛ — ПАТЧЕМ, а не переходом по адресу. Переход сносит документ целиком, и
 * вкладка вернулась бы к исходному независимо от того, отпускает ли канвас свои
 * компоненты: замер был бы зелёным всегда и не проверял бы ничего.
 */
/**
 * СВОЯ ВКЛАДКА, а не та, в которой мерили сетку. Первая редакция мерила в той
 * же и напечатала «до входа 16.0 МБ, в канвасе 8.0» — память УПАЛА вдвое от
 * добавления двух компонентов. Врал не канвас, врало «до»: `page.goto` на
 * `frame.html` бросает документ оболочки с шестью кадрами, а `usedJSHeapSize`
 * показывает занятое, а не живое, — исходным числом стали чужие несобранные
 * останки. Дальше всё считалось от них, `canvasRetained` выходил 0.51 и
 * проходил порог ВСЕГДА, чем бы канвас ни занимался. Ровно тот случай, когда
 * проверка зелёная и не проверяет ничего.
 *
 * Лечится вкладкой, а не паузой подлиннее: у новой вкладки свой heap, и мерить
 * в ней нечего, кроме предмета.
 */
const cpage = await browser.newPage({ viewport: { width: 1440, height: 900 } })
cpage.on('pageerror', (e) => errs.push(String(e.message)))
await cpage.goto(`http://localhost:${PORT}/frame.html?c=DataTable`, { waitUntil: 'networkidle' })
await cpage.waitForTimeout(1500)

console.log('\nПамять вкладки КАДРА (канвас):')
const canvasBefore = await heapOf(cpage, 'до входа в канвас')

/**
 * ТЯЖЁЛАЯ РАСКЛАДКА: десять мест `DataTable` с набором `rows-500`.
 *
 * ВЕС — ЕДИНСТВЕННОЕ, ЧЕГО НЕ ХВАТАЛО ЗАМЕРУ, и это измерено. На двух лёгких
 * местах из умолчания вход в канвас стоил 0.9 МБ на фоне 5.5, и одно
 * неубранное поддерево там тонуло в шуме `usedJSHeapSize`: мутация «канвас
 * прячется, а не снимается» замер ПЕРЕЖИЛА (здоровый ×1.19/×1.02, с мутацией
 * ×1.21/×1.02). Сетка не зря мерится на `rows-500` — там вход стоит вчетверо
 * от вкладки.
 *
 * `span: 12` у всех — места встают друг под другом. Раскладка здесь не
 * предмет: мерится уборка, а не сетка колонок.
 */
const SPOTS = 10
const heavy = () =>
  Array.from({ length: SPOTS }, (_, i) => ({
    id: `t${i + 1}`,
    c: 'DataTable',
    caseId: 'row-open',
    col: 1,
    span: 12,
    props: {},
    data: 'rows-500',
  }))

const patch = async (body, settle) => {
  await cpage.evaluate(
    (b) => window.postMessage({ ns: 'ds-wb', v: 1, sid: 0, body: { type: 'patch', ...b } }, window.location.origin),
    body,
  )
  await cpage.waitForTimeout(settle)
}

/**
 * ПРЕДМЕТ ЗАМЕРА — ЦИКЛ ДОБАВЛЕНИЯ И УДАЛЕНИЯ МЕСТ, А НЕ ВХОД И ВЫХОД ИЗ
 * РЕЖИМА. Спека называет риском ровно это: «позиции добавляют и убирают
 * руками, десятками за сессию». Выход из режима — другое событие, и уборку
 * там делает та же ветка, что и в сетке; вход-выход стоял здесь до шага 3
 * только потому, что механизма добавления не существовало.
 *
 * ЕДЕТ ПАТЧЕМ В ДОКУМЕНТ КАДРА, а не щелчками по оболочке, и это не обход
 * интерфейса. Кадр не знает, откуда пришёл патч: «+ DataTable» в тулбаре,
 * загрузка набора и эта строка шлют ему одно и то же сообщение. А вот десять
 * щелчков по кнопке в оболочке добавили бы к предмету замера саму оболочку,
 * её состояние и её перерисовки — то есть мерили бы не то, что названо.
 *
 * ЗАМЕР ПОСЛЕ УБОРКИ ДЕЛАЕТСЯ В РЕЖИМЕ КАНВАСА, с нулём мест. Выйди сначала в
 * `frame` — и цифра говорила бы про выход из режима, то есть про ту самую
 * уборку, которую здесь не проверяют.
 */
let full = 0
let empty = 0
const canvasAfter = {}
await patch({ mode: 'canvas', canvas: heavy() }, 4000)
full = await cpage.locator('[data-wb-spot]').count()
await heapOf(cpage, `мест ${full}, по 500 строк`)

/**
 * ЗАМЕР ПОСЛЕ КАЖДОГО ЦИКЛА, КРОМЕ ЧЕТВЁРТОГО. Пары, а не одиночные пробы, и
 * по той же причине, что у сетки выше: сырое число врёт случайным выбросом, а
 * пол из пары — нет. Ранняя пара — циклы 2 и 3, поздняя — 5 и 6; первый цикл
 * печатается ради прогрева и в счёт не идёт, четвёртый не нужен никому и
 * пропущен — это единственная экономия здесь, которая ничего не стоит.
 */
for (let i = 1; i <= 6; i++) {
  await patch({ canvas: [] }, 2000)
  if (i === 1) empty = await cpage.locator('[data-wb-spot]').count()
  if (i !== 4) canvasAfter[i] = await heapOf(cpage, `цикл ${i}: места убраны`)
  await patch({ canvas: heavy() }, 3000)
}

await cpage.close()
await browser.close()
stop()

/**
 * ДВА УТВЕРЖДЕНИЯ, потому что уборка ломается двумя разными способами, и одно
 * другое не покрывает — проверено мутацией на обоих.
 *
 * 1. ВОЗВРАТ. Пол установившихся заходов сравнивается с полом ПУСТОЙ вкладки.
 *    Ловит постоянное удержание: кадры, которые не размонтируются вовсе (в
 *    мутации «ячейки прячутся, а не снимаются» вкладка держала 47 МБ вместо
 *    12.8 — ×4.6). Порог 2.0, а не 1.1: после первого захода вкладка честно
 *    держит прогретый лист системы, модуль фикстуры и свежий одиночный кадр,
 *    и требовать возврата к пустой значит требовать невозможного (измерено:
 *    здоровый прогон даёт ×1.23–1.25).
 *
 * 2. НАКОПЛЕНИЕ. Поздняя пара заходов сравнивается с ранней. Ловит утечку,
 *    растущую с каждым разом, — ту, где вкладка после выхода выглядит
 *    прилично, но каждый следующий заход оставляет ещё немного. Первое
 *    утверждение её заметит только тогда, когда станет поздно.
 *
 * ПОЛ С ОБЕИХ СТОРОН, а не последнее число и не одиночная проба: не
 * устоявшийся замер число только ЗАВЫШАЕТ (сборщик не успел), занизить его
 * нечему. Почему это пришлось чинить и какими числами — в шапке пяти заходов
 * выше.
 */
const early = Math.min(passes[1].after, passes[2].after)
const settled = Math.min(passes[3].after, passes[4].after)
const retained = settled / before
const growth = settled / early
console.log(`\n  рост на сетке      ×${(during / before).toFixed(2)}`)
passes.forEach((p, i) => console.log(`  после ${i + 1}-го захода  ${MB(p.after)}`))
console.log(`  осталось от пустой ×${retained.toFixed(2)}  (пол ${MB(settled)} против ${MB(before)})`)
console.log(`  накопление ×${growth.toFixed(2)}  (поздний пол ${MB(settled)} против раннего ${MB(early)})`)
if (errs.length) console.log(`  ошибки страницы: ${errs.join('; ')}`)

if (frames !== 6) {
  console.log(`\nFAIL: в сетке ${frames} кадров, а замер обещает шесть`)
  process.exit(1)
}
if (retained > 2) {
  console.log('\nFAIL: память не вернулась — кадры сетки остались висеть')
  console.log('      вместе со своими стресс-данными.')
  process.exit(1)
}
if (growth > 1.25) {
  console.log('\nFAIL: каждый заход оставляет память за собой — уборка')
  console.log('      отпускает не всё, и это накапливается.')
  process.exit(1)
}

/**
 * КАНВАС: те же два утверждения и по тем же доводам, что у сетки, — возврат и
 * накопление. Пороги те же намеренно: другое число здесь было бы вторым мнением
 * о том, что считать утечкой.
 *
 * ДВА САНИТАРА НА ПРЕДМЕТ, и они разные.
 *
 * 1. МЕСТ НЕ МЕНЬШЕ ДЕСЯТИ, когда раскладка полна. Смысл канваса в НЕСКОЛЬКИХ
 *    компонентах, и на одном он неотличим от обычного кадра; пустой канвас без
 *    этой строки дал бы идеальные числа и зелёный результат.
 * 2. НОЛЬ МЕСТ, когда раскладку убрали. Ловит `display: none` вместо
 *    размонтирования БЫСТРО И ГРОМКО, не дожидаясь сборщика мусора, — а это
 *    главный ожидаемый способ сломать уборку, и до шага 3 он замер переживал.
 *    Числа и разметка отвечают на разные вопросы: разметка говорит «узла нет»,
 *    память — «за ним ничего не осталось». Утечка бывает и при снятом узле
 *    (ссылка в модульном кэше, живой слушатель), и второй санитар её не видит
 *    вовсе — поэтому оба, а не один вместо другого.
 */
const canvasEarly = Math.min(canvasAfter[2], canvasAfter[3])
const canvasSettled = Math.min(canvasAfter[5], canvasAfter[6])
