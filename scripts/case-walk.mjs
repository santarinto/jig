/**
 * ОБЩИЙ ХОДОК СЛУЧАЕВ: один обход, много проб (DS-177).
 *
 * Обвязка обхода — поднять верстак на своём порту, взять план случаев, свериться
 * с диском, обойти пары (случай, шкала) пулом браузеров — одна и та же у любой
 * строки матрицы общих приёмочных свойств. До этого модуля она жила внутри
 * `case-overflow.mjs`, и вторая строка стоила бы второй полный обход: ещё минуту
 * на те же загрузки ради другого вопроса к тому же кадру.
 *
 * СТРОКА — это проба в странице плюс формат отчёта. Ячейка (случай × шкала)
 * грузится ОДИН раз и обслуживает все строки, которые её судят; `scales` строки
 * — подмножество осей обхода, потому что `KNOWN` и объявления фикстур
 * откалиброваны каждой строкой на своих шкалах, и загруженная ячейка никого не
 * обязывает её судить.
 *
 * ЧТО ХОДОК УТВЕРЖДАЕТ САМ — семь вещей, и они держат ЛЮБУЮ строку:
 *
 * 1. ПЛОЩАДЬ — с ДИСКА, а не из плана (ловушка 7, `docs/writing-checks.md`):
 *    компоненты плана сверяются с каталогами `src/components/*` плюс
 *    `src/icons/*.fixture.tsx`, и у каждого обязан быть хотя бы один случай.
 *    План, собранный тем же glob-ом, согласен сам с собой и тогда, когда
 *    потерял половину каталога.
 * 2. САНИТАР НА ЖИВОМ КАДРЕ (ловушка 5). Перед обходом каждая строка обязана
 *    подложить в кадр то, что её проба обязана увидеть, и назвать это. Проба,
 *    разучившаяся видеть свой предмет, иначе дала бы ровный зелёный по всему
 *    каталогу. Строки без санитара ходок не берёт вовсе — см. проверку в начале
 *    `walk`.
 * 3. ПОЛНОТА. `done !== jobs.length` — красное: оборвавшийся обход и обход без
 *    находок печатают одно и то же.
 * 4. У КАЖДОЙ СТРОКИ — ВСЕ ЕЁ ЯЧЕЙКИ, ПО СЧЁТУ. `scales` строки обязаны быть
 *    ПОДМНОЖЕСТВОМ осей обхода (проверка на входе, до `spawn`), а после обхода
 *    `measured` плюс `unmeasured` обязаны дать РОВНО `(plan.length +
 *    touchPlan.length) × row.scales.length` — не «хоть что-то», иначе пропажа
 *    одной ячейки молчит (`touchPlan` — случаи сенсорной площади, пункт 7).
 *    Дыру открыло само разделение осей и суждения: пока это была одна
 *    константа, разойтись им было негде, а опечатка в цифре давала полный обход
 *    с зелёным отчётом ни о чём.
 * 5. ИСКЛЮЧЕНИЕ ВНУТРИ ЯЧЕЙКИ — НЕ БЕДА ОБХОДА, и это держит ФОРМА, а не
 *    внимательность автора. Разбор ячейки живёт в `measureCell` на уровне
 *    модуля, `page` туда не попадает вовсе: спросить страницу можно только у
 *    `frame` (см. `cellFrame`), а он переводит любой отказ в «не измерено» с
 *    адресом ячейки. Проба и вердикт каждой строки идут вдобавок в своём
 *    `try/catch` — чтобы назвать ВИНОВНУЮ строку; всё остальное, включая ещё
 *    не написанное, ловит внешний перехват на весь разбор. «Не измерено» —
 *    красное, а не проглоченное: локализуется адрес, не глохнет ошибка.
 * 6. И СОСТОЯНИЕ КАДРА — ТОЖЕ. Прокрутка документа и число узлов в хосте — и
 *    только они — сверяются между судьями: строка, вернувшая кадр не таким, как
 *    взяла, названа поимённо, а судьи, идущие ПОСЛЕ неё, получают «не
 *    измерено». Защищены именно последующие; после последнего судьи сверки нет,
 *    портить некому. Без этого порча соседки была бы ЕДИНСТВЕННЫМ исходом, не
 *    краснеющим вовсе.
 * 7. СЕНСОРНАЯ ОСЬ (DS-336). Случаи компонентов, чьи листы несут ветку
 *    `@media` по `hover`/`pointer`/`any-*`, грузятся ВТОРОЙ РАЗ контекстом с
 *    `hasTouch` — ключ ячейки `Компонент/случай ×шкала касание` — и судятся
 *    теми же строками на тех же шкалах. Остальные — только мышью: их сенсорная
 *    ячейка равна мышиной по построению. Площадь — с ДИСКА
 *    (`touch-surface.mjs`), сверенная с CSSOM страницы в обе стороны;
 *    эмуляция сверяется `matchMedia` на каждой ячейке площади; компонент, чей
 *    сенсорный кадр ни в одной паре (случай, шкала) не отличился от мышиного,
 *    — красный, если не объявлен в `TOUCH_SAME` с доводом. Почему `hasTouch`, а
 *    не `isMobile` или CDP, — замер в шапке `touch-surface.mjs`.
 *
 * 8. ОСЬ ШИРИНЫ (DS-347, база — DS-380). Случаи компонентов, чьи
 *    листы несут `@container` по ШИРИНЕ, грузятся ВТОРОЙ РАЗ на вьюпорте
 *    `WIDTH_SECOND` (768) — ключ ячейки `Компонент/случай ×шкала 768` — и
 *    судятся теми же строками на тех же шкалах. Первый раз — на базовом
 *    вьюпорте обхода, `WIDTH_FLOOR` (440), объявленном полу поддерживаемой
 *    ширины. Вьюпорт у ячейки СВОЙ, а не общий на обход: `frameWhy` каждой
 *    строки сверяет с ним `clientWidth`, так что кадр 768, нарисованный на
 *    440, назовётся «не тот вьюпорт», а не зазеленеет. Площадь — с ДИСКА
 *    (`width-surface.mjs`), сверенная с CSSOM; компонент, чья ветка ни в одной
 *    паре не переключилась, — красный, если не объявлен в `WIDTH_SAME` с
 *    доводом. Почему 768 — замер в шапке `width-surface.mjs`.
 *
 * «НЕ ИЗМЕРЕН» — КРАСНОЕ, и считает его строка. `pageerror`, упавшая фикстура,
 * пустой кадр, не доехавшая шкала или не появившийся в DOM узел из `shows` дают
 * пустой либо не тот кадр, а пустой кадр не нарушает никогда. Зелёный на нём —
 * ровно тот вид зелёного, ради которого пишутся такие гейты. Повторов (retry)
 * здесь нет намеренно. Но и чужого «не измерено» тоже: отказ страницы в ячейке
 * меняет страницу до следующей (`freshPage`, DS-319), иначе недогруженная
 * навигация роняет всех соседей по партии `recycle` с одинаковой причиной.
 *
 * `shows` ЗДЕСЬ — СИГНАЛ ГОТОВНОСТИ, А НЕ УТВЕРЖДЕНИЕ О ВИДИМОСТИ: ждём
 * `attached`, потому что видимость объявлена под кадр 900 и её держит `states`,
 * а на узком кадре узел законно прячется (выключенная кнопка
 * `CommandBar/disabled` уходит в «Ещё» и там `visibility: hidden`).
 *
 * Порт остаётся ЛИТЕРАЛОМ в файле точки входа (`case-matrix.mjs`) и приходит
 * сюда параметром: гейт `dev-server-ports` читает его регуляркой из ИСХОДНИКА
 * скрипта, и переменная или поиск свободного порта сломали бы ровно то, что он
 * заведён запрещать (vite при занятом порте молча берёт следующий, и прогон
 * начинает проверять чужое дерево). Строки — модули и порта не имеют.
 */
