    await page.close()
    // Не `if (why)`, а `!== null`: `undefined` от санитара, вывалившегося без
    // `return`, неотличим от «доволен» — а это ровно та проверка, снятие
    // которой зеленит весь каталог. Тем же доводом, что и вердикт `report`.
