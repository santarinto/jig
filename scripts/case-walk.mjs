/**
 * ОТКАЗ, ЛОКАЛИЗОВАННЫЙ ДО ЯЧЕЙКИ: несёт уже написанный текст «почему не
 * измерено». Отдельный класс, а не просто строка в `message`, потому что
 * внешний перехват обязан различать две вещи: отказ страницы, у которого текст
 * для человека уже составлен (`загрузка не состоялась — …`), и всё прочее,
 * чему текст ещё только предстоит составить из `message`.
 */
class CellFailure extends Error {
  constructor(why) {
    super(why)
    this.why = why
  }
}

/** Playwright пишет в `message` абзац с подсказками; в отчёт идёт первая строка. */
const firstLine = (e) => String(e?.message ?? e).split('\n')[0]

/**
 * ЕДИНСТВЕННАЯ ДВЕРЬ К СТРАНИЦЕ ВНУТРИ ЯЧЕЙКИ.
 *
 * Три круга правок подряд закрывали ОДИН класс дефекта поштучно: сперва голым
 * оказался `evaluate` пробы, потом чтение вердикта, потом снимок состояния. И
 * каждый раз падение одной строки на одной ячейке уносило ВЕСЬ обход — без
 * имени строки и без адреса. Четвёртая обёртка привела бы сюда же на пятом
 * круге: следующий, кто допишет обращение к странице, снова его не обернёт.
 *
 * Поэтому лечится не место, а доступ. `measureCell` объявлен НА УРОВНЕ МОДУЛЯ и
 * получает только `frame`; переменной `page` в его области видимости нет ни
 * одной, так что «дописать обращение мимо помощника» — это либо вызов отсюда,
 * либо `ReferenceError`. И то и другое остаётся внутри внешнего перехвата
 * ячейки, то есть даёт «не измерено» с адресом, а не мёртвый обход.
 *
 * Свой `frame` НА КАЖДУЮ ЯЧЕЙКУ, хотя страница живёт `recycle` ячеек: `errs`
 * копит `pageerror`, и накопитель, общий на сорок ячеек, приписал бы исключение
 * первой всем тридцати девяти следующим. Это СОХРАНЁННОЕ свойство, а не
 * починка: `errs` и `onErr` жили внутри `measureCell` и снимались в `finally`
 * ещё до помощника (`c412c53`), дефекта тут никогда не было. Сказано потому,
 * что наивный вынос помощника наружу ломает его молча — слушатель естественно
 * ложится на страницу, то есть на её жизнь, и никакой отчёт об этом не скажет:
 * ячейки просто начнут наследовать чужие исключения.
 */
function cellFrame(page) {
  const errs = []
  const onErr = (e) => errs.push(String(e.message))
  page.on('pageerror', onErr)
  // `why` строкой — «что не вышло», сообщение страницы дописывается; функцией —
  // когда текст считается в момент отказа (счёт `errs`, имя селектора).
  const frame = {
    errs,
    /**
     * Отказал ли хоть один вызов к странице. Тогда исполнитель меняет страницу
     * до следующей ячейки: иначе недогруженная навигация роняет и её (см.
     * `freshPage` в `walk`, DS-319). Ставит `through`, то есть любой
     * отказ, прошедший через дверь, — а мимо двери к странице не ходят.
     */
    broken: false,
    goto: (url) => through('загрузка не состоялась', () => page.goto(url, { waitUntil: 'load' })),
    attached: (sel, timeout, why) =>
      through(why, () => page.waitForSelector(sel, { state: 'attached', timeout })),
    evaluate: (fn, arg, why = 'замер не состоялся') => through(why, () => page.evaluate(fn, arg)),
    // Слушатель с умершей страницы снимается молча: `release` зовётся из
    // `finally`, и новое исключение там затёрло бы уже составленный вердикт
    // ячейки — ровно тот обмен, ради отмены которого всё это и написано.
    release: () => {
      try {
        page.off('pageerror', onErr)
      } catch {
        /* страницы уже нет — снимать не с чего */
      }
    },
  }
  const through = async (why, fn) => {
    try {
      return await fn()
    } catch (e) {
      frame.broken = true
      throw new CellFailure(typeof why === 'function' ? why(e) : `${why} — ${firstLine(e)}`)
    }
  }
  return frame
}

