/**
 * СЕНСОРНАЯ ОСЬ МАТРИЦЫ: площадь с диска и три её суждения (DS-336).
 *
 * Обход матрицы (`case-walk.mjs`) грузил каждую ячейку МЫШИНЫМ контекстом, то
 * есть на 360 рисовалась мышиная раскладка, и всё, что компонент показывает
 * только пальцу (`@media (hover: none)`, `(pointer: coarse)`, `any-*`), гейтом
 * не было видано ни разу. Ось «касание» догружает ТЕ ЖЕ случаи контекстом с
 * `hasTouch`, но только у компонентов, чьи листы такую ветку несут: дублировать
 * весь каталог ради двух компонентов — ×2 к обходу ради ячеек, отличие которых
 * от мышиных равно нулю по построению.
 *
 * ЗДЕСЬ ТОЛЬКО ЧИСТОЕ — без браузера, без дев-сервера, чтение файла через
 * переданный `read`. Поэтому всё суждение оси держат юниты
 * (`src/__guards__/touch-surface.test.ts`) на синтетическом дереве, а ходок
 * лишь снимает числа и зовёт эти функции.
 *
 * ОБЩАЯ МЕХАНИКА ОСИ — в `scripts/axis-surface.mjs` (DS-347): площадь с
 * диска, сверка с CSSOM, отпечаток и вердикт у сенсорной оси и у оси ширины
 * одни и те же, различаются они ат-правилом и условием. Здесь остаётся ровно
 * то, что про ПАЛЕЦ: какое условие делит мышь и палец, кто объявлен «кадр тот
 * же» и как читается доехавшая эмуляция. Копия вместо общего модуля разошлась
 * бы при первой же правке площади — молча и в ту сторону, где обход меньше.
 *
 * ПОЧЕМУ `hasTouch` И ТОЛЬКО ОН — замер 19.09.2026, chromium 149.0.7827.55,
 * `matchMedia` в кадре `FormTabs/base`, вьюпорт 360×640, dpr 1:
 *  - `hasTouch` — `hover: none`, `pointer: coarse`, `any-hover: none`,
 *    `any-pointer: coarse`, `innerWidth` 360, крестики вкладок `1,1,1`
 *    (мышиный контекст — `1,0,0`);
 *  - `hasTouch` + `isMobile` — те же медиа, но `innerWidth` 980: у
 *    `frame.html` нет `<meta name="viewport">`, и мобильный контекст рисует
 *    кадр на запасной ширине вьюпорта. `frameWhy` назвал бы это «не тот
 *    вьюпорт» на каждой ячейке, но ось была бы мертва;
 *  - CDP `Emulation.setEmulatedMedia` с `features` `hover`/`pointer`/`any-*` —
 *    НЕ ДЕЙСТВУЕТ вовсе, матчи остаются мышиными. Документация обещает иное;
 *  - CDP `Emulation.setTouchEmulationEnabled` — касание, 360, но это второй
 *    путь к тому же, что даёт опция контекста.
 */
import { axisSurface, axisVerdict, crossCheckSurface } from './axis-surface.mjs'

export { crossCheckSurface }

/**
 * Условие медиа, делящее мышь и палец. `any-` тоже: `any-pointer: coarse`
 * включён у ноутбука с сенсорным экраном, и ветка по нему — та же развилка.
 * Одна регулярка на диск и на CSSOM страницы: браузер нормализует запись
 * (`(hover:none)` → `(hover: none)`), и пробел после двоеточия необязателен.
 */
export const TOUCH_MEDIA = /\((?:any-)?(?:hover|pointer)\s*:/

/**
 * КОМПОНЕНТЫ, ЧЬЯ СЕНСОРНАЯ ВЕТКА В СТАТИЧНОМ КАДРЕ НЕ МЕНЯЕТ НИЧЕГО, — с
 * доводом. Проверяется НАОБОРОТ (`touchVerdict`): разошлась хоть одна пара —
 * довод протух, красное. Ячейки такого компонента ось всё равно обходит: иначе
 * протухание, то есть новое правило в той же ветке, меняющее раскладку, не
 * увидел бы никто.
 */
export const TOUCH_SAME = new Map([
  ['BarChart', 'ветка снимает залипший после тапа :hover столбца; без наведения кадр тот же по построению'],
])

/**
 * Площадь сенсорной оси с диска — общим `axisSurface`: прелюдии `@media`, где
 * стоит `TOUCH_MEDIA`.
 *
 * @param {{ root: string, entry: string, read: (abs: string) => string }} o
 */
export const touchSurface = (o) => axisSurface({ ...o, at: 'media', cond: TOUCH_MEDIA })

/**
 * ОПИСАНИЕ ОСИ ДЛЯ СТРАНИЦЫ: что искать (`src`) и в каком ат-правиле (`kind`).
 * Это АРГУМЕНТ `page.evaluate(cssomAxisRules | axisPrint, TOUCH_AXIS)`, а не
 * обёртка вокруг них: обёртка сериализуется в страницу без своего импорта и
 * падает там `ReferenceError`, причём только в живом прогоне — юниты, зовущие
 * её в node, остаются зелёными. Поймано на DS-347.
 */
export const TOUCH_AXIS = { src: TOUCH_MEDIA.source, kind: 'CSSMediaRule' }

/** В СТРАНИЦЕ: какие указатели видит кадр. Уходит в `page.evaluate` целиком. */
export const pointerFacts = () => ({
  hoverNone: matchMedia('(hover: none)').matches,
  coarse: matchMedia('(pointer: coarse)').matches,
})

/**
 * Эмуляция доехала до кадра? `null` — да, иначе причина «не измерено». Ячейка
 * оси «касание», нарисованная мышиным контекстом, отвечает на мышиный вопрос
 * под сенсорным ключом, и зелёный на ней — ложь ровно про предмет оси.
 */
export function pointerWhy(facts, pointer) {
  const want = pointer === 'touch'
  if (facts.hoverNone === want && facts.coarse === want) return null
  return `эмуляция указателя не доехала: ось «${pointer === 'touch' ? 'касание' : 'мышь'}», `
    + `а кадр видит (hover: none) ${facts.hoverNone}, (pointer: coarse) ${facts.coarse}`
}

/**
 * РАЗНИЦА ПО КОМПОНЕНТУ — вердикт оси.
 *
 *  - компонент площади, у которого НИ ОДНА пара (случай, шкала) не разошлась, —
 *    красный: ось его обошла и ничего не увидела; зелёный по его сенсорным
 *    ячейкам — зелёный на пустом множестве;
 *  - кроме объявленных в `same` с доводом (ветка действует только под
 *    состоянием, которого в статичном кадре нет, — `:hover` после тапа). Их
 *    объявление проверяется НАОБОРОТ: разошлась хоть одна пара — довод протух,
 *    красное, как устаревшее исключение `KNOWN`;
 *  - объявление на компоненте вне площади — красное: довод ни о чём;
 *  - пара без одного из отпечатков — не сравнена, и компонент, у которого не
 *    сравнена ни одна, судится как «не увидела» — отсутствие данных не
 *    превращается в «разницы нет, значит, объявлено верно».
 *
 * @param {{ surface: string[], prints: Map<string, { c: string, mouse?: string, touch?: string }>, same: Map<string, string> }} o
 * @returns {{ lines: string[], bad: string[] }}
 */
export const touchVerdict = ({ surface, prints, same }) => axisVerdict({
  surface, prints, same, sides: ['mouse', 'touch'], from: 'мыши', what: 'сенсорная ветка',
})
