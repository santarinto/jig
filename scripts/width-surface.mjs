/**
 * ОСЬ ШИРИНЫ МАТРИЦЫ: площадь с диска и её суждение (DS-347).
 *
 * Обход матрицы грузил каждую ячейку на ОДНОМ вьюпорте 360, то есть всё, что
 * компонент показывает чуть шире телефона, гейтом не было видано ни разу. А
 * показывает он там другое: замер 19.09.2026 (DS-336) нашёл 19 ячеек, где
 * вычисленные значения правил `@container` на 360 и на 440 РАЗОШЛИСЬ —
 * `LedgerList` все шесть случаев на шкалах 0.875 и 1 (порог 28.4em: запись
 * стопкой против грида), `Pagination` все шесть на 0.875, `Tabs/position` на
 * 1.5. Переключение измерено, поэтому ось и заводится: по плану 336 она
 * вводилась только при измеренном переключении, а не «на всякий случай».
 *
 * БАЗА ОСИ ПЕРЕЕХАЛА НА ОБЪЯВЛЕННЫЙ ПОЛ — 440 (DS-380, решение владельца
 * 22.09.2026, см. докблок `WIDTH_FLOOR`). Он же теперь и базовый вьюпорт
 * обхода матрицы (`case-matrix.mjs`, `VIEWPORT.width`) — прежний литерал 360
 * там снят целиком, не только для этой оси.
 *
 * ВТОРАЯ СТОРОНА — 768, А НЕ 440 (ПРЕЖНЕЕ ЗНАЧЕНИЕ). Довод, который раньше
 * стоял здесь про 440 («ближайшая ширина, на которой РЕАЛЬНО переключается
 * больше одного компонента»), ОТМЕНЁН НЕ ОШИБКОЙ, А ПЕРЕЕЗДОМ БАЗЫ: это был
 * довод о ВТОРОЙ стороне оси, а с переездом базы 440 стал ПЕРВОЙ, и сравнивать
 * её саму с собой (`WIDTH_SECOND === WIDTH_FLOOR`) ось не может по построению
 * (юнит в `width-surface.test.ts`). 768 — ширина УСТРОЙСТВА (CSS-вьюпорт iPad в
 * портрете), а не счёт по порогам листа; живой прогон 22.09.2026 нашёл флип
 * ветки у ВСЕХ ШЕСТИ компонентов площади — числа в докблоке `WIDTH_SECOND`.
 *
 * ПЛОЩАДЬ — ТОЛЬКО КОМПОНЕНТЫ С `@container` ПО ШИРИНЕ, по тому же доводу, что
 * у сенсорной оси: догружать весь каталог ради шести компонентов — это ×2 к
 * обходу ради ячеек, отличие которых от базы равно нулю по построению.
 *
 * ОСЬ ДВИГАЕТ КАДР, А НЕ КОНТЕЙНЕР — и это не всё, чего она не видит. Она
 * отвечает на вопрос «что между полом и планшетом», меняя ШИРИНУ ВЬЮПОРТА;
 * контейнеру внутри достаётся кадр минус паддинг верстака, а у потребителя
 * контейнер может быть уже кадра (боковая панель, сплит, вложенная колонка) —
 * этого ось не воспроизводит вовсе. Отсюда прямое следствие, которое НЕЛЬЗЯ
 * читать в обратную сторону: по ширине КАДРА нельзя арифметикой предсказать,
 * включится ли ветка, — контейнер бывает уже кадра, и порог, посчитанный от
 * ширины хоста, срабатывает раньше, чем счёт обещал. Ровно так был написан и
 * тут же протух (см. `WIDTH_SAME`) довод про `Tabs`: 22.09.2026 казалось, что
 * порог 17em лежит ниже контейнера пола и ветка не включается ни на одной
 * ширине оси, — а живой прогон нашёл 8 из 28 разошедшихся пар. Объявление
 * покупается ЗАМЕРОМ узла в браузере, а не счётом по листу.
 *
 * ЧЕГО ОСЬ НЕ ВИДИТ, и это названо, а не замолчано. Компонент, который считает
 * раскладку САМ (`ResizeObserver` → состояние → рендер: хвост `CommandBar` в
 * «Ещё», `useVirtualList`), в площадь не попадает — у него нет прелюдии в
 * листе, искать её нечем, а гадать по имени хука значило бы завести список,
 * который отстаёт молча. `@media` по ширине в `src/` нет вовсе (проверено на
 * 20.09.2026), поэтому площадь ищет только `@container`; появится `@media` —
 * появится и вторая прелюдия здесь.
 *
 * ЗДЕСЬ ТОЛЬКО ЧИСТОЕ — общая механика оси в `scripts/axis-surface.mjs`, здесь
 * ровно то, что про ШИРИНУ. Юниты — `src/__guards__/width-surface.test.ts`.
 */
import { axisSurface, axisVerdict } from './axis-surface.mjs'

/**
 * Условие `@container`, говорящее о ШИРИНЕ контейнера. Одна регулярка на диск и
 * на CSSOM страницы: браузер нормализует запись (`(max-width:28.4em)` →
 * `(max-width: 28.4em)`), и пробел после двоеточия необязателен.
 *
 * `\b(width|inline-size)\b` покрывает все четыре формы разом — `max-width`,
 * `min-width`, диапазон `(width > 30em)` и `(inline-size > 30em)`: дефис не
 * словесный знак, поэтому `\bwidth\b` находится и внутри `max-width`. Запрос по
 * ВЫСОТЕ (`max-height`) сюда не попадает намеренно: вторая ширина кадра его не
 * переключает, и ось судила бы ячейки, равные исходным по построению.
 */
export const WIDTH_COND = /\b(?:width|inline-size)\b/

/**
 * ОБЪЯВЛЕННЫЙ ПОЛ ПОДДЕРЖИВАЕМОЙ ШИРИНЫ (DS-380, решение владельца
 * 22.09.2026) — CSS-вьюпорт iPhone 17 Pro Max, 440×956 при dpr 3. Он же
 * БАЗОВЫЙ ВЬЮПОРТ ОБХОДА МАТРИЦЫ (`case-matrix.mjs`, `VIEWPORT.width`):
 * литерала там больше нет намеренно, число берётся отсюда. Число ещё раз
 * записано словами в CLAUDE.md, раздел «System law: пол поддерживаемой
 * ширины», и гейт `width-surface.test.ts` сверяет одно с другим — разойдись
 * они, разошедшееся молчало бы до первого спора.
 */
export const WIDTH_FLOOR = 440

/**
 * ВЬЮПОРТ ВТОРОЙ СТОРОНЫ ОСИ. Литерал здесь, а не в точке входа: число —
 * предмет этой оси (см. шапку), а не настройка обхода.
 *
 * 768, А НЕ 440. Число выбрано не круглостью: это ШИРИНА УСТРОЙСТВА
 * (CSS-вьюпорт iPad в портрете). 440 не годится второй стороной с DS-380:
 * это теперь `WIDTH_FLOOR`, база оси, а вторая сторона обязана быть ШИРЕ базы,
 * иначе ось сравнивала бы кадр сам с собой (юнит в `width-surface.test.ts`).
 *
 * Живой прогон 22.09.2026 (`npm run matrix`) нашёл флип ветки у ВСЕХ ШЕСТИ
 * компонентов площади между 440 и 768 — DataTable 30 из 40 пар, EventCalendar
 * 4 из 24, Form 9 из 40, LedgerList 18 из 24, Pagination 18 из 28, Tabs 8 из
 * 28 (это и есть падение `Tabs` — см. `WIDTH_SAME`, теперь пустой).
 *
 * ЧТО НЕ УТВЕРЖДАЕТСЯ. Что 768 — САМАЯ УЗКАЯ такая ширина, — НЕ ПРОВЕРЕНО.
 * Порядок величины ниже даёт оценку по порогам листа, СЧИТАННУЮ ОТ ШИРИНЫ
 * ХОСТА (пороги при кегле 14: Form 18.6em на шкале 1.5, LedgerList/Pagination
 * 28.4em и 29em на 1/1.15/1.5, DataTable 40em на 0.875/1/1.15, EventCalendar
 * 40rem с запасом 53 px даже с полосой прокрутки — контейнеру достаётся кадр
 * минус 60, минус ещё 15 с полосой: 440 → 380/365, 768 → 708/693). Это ОЦЕНКА,
 * не довод: контейнер компонента бывает уже хоста, и тогда порог достигается
 * РАНЬШЕ, чем счёт по листу обещал, — ровно так 22.09.2026 разошёлся счёт по
 * `Tabs` (см. предупреждение в `WIDTH_SAME`). Минимальность 768 из этой
 * арифметики не выводится.
 */
export const WIDTH_SECOND = 768

/**
 * КОМПОНЕНТЫ, ЧЬЯ ВЕТКА ШИРИНЫ МЕЖДУ ПОЛОМ И ВТОРОЙ СТОРОНОЙ ОСИ НЕ МЕНЯЕТ
 * НИЧЕГО, — с доводом. Проверяется НАОБОРОТ (`widthVerdict`): разошлась хоть
 * одна пара — довод протух, красное. Ячейки такого компонента ось всё равно
 * обходит: иначе новое правило в той же ветке, меняющее раскладку, не увидел
 * бы никто.
 *
 * Довод здесь бывает ДВУХ видов по смыслу, и оба называются числом, чтобы
 * сдвиг порога было видно по протуханию объявления:
 * — порог ветки лежит ВНЕ промежутка между двумя ширинами оси, но ВЫШЕ обеих;
 * — порог ветки лежит НИЖЕ ОБЕИХ ширин оси — контейнер пола уже перерос его
 *   до старта, и ось эту ветку не проверяет вовсе (см. шапку файла, абзац
 *   «ОСЬ ДВИГАЕТ КАДР, А НЕ КОНТЕЙНЕР»).
 *
 * НА 22.09.2026 ОБЪЯВЛЕНИЙ НЕТ НИ ОДНОГО. Живой прогон `npm run matrix` дал
 * флип ветки у ВСЕХ ШЕСТИ компонентов площади на новой оси (пол 440 против
 * 768): DataTable 30 из 40 пар, EventCalendar 4 из 24, Form 9 из 40,
 * LedgerList 18 из 24, Pagination 18 из 28, Tabs 8 из 28. Прежние объявления
 * `DataTable` и `EventCalendar` (порог вне промежутка 440–768) сняты не как
 * ошибочные — на паре 360/440 их пороги действительно лежали вне промежутка —
 * а потому, что переезд базы (DS-380) подвинул промежуток и оба порога
 * оказались ВНУТРИ него. Запись `Tabs`, написанная тем же прогоном 22.09.2026,
 * протухла на первом же живом прогоне, и это САМ УРОК, а не только пример:
 * подробности ниже.
 *
 * ДОВОД ОБЪЯВЛЕНИЯ НЕЛЬЗЯ ВЫВОДИТЬ АРИФМЕТИКОЙ ПО ШИРИНЕ КАДРА. Именно так был
 * написан — и тут же протух на живом прогоне — довод про `Tabs`: порог 17em
 * (238 px при кегле 14, максимум 357 px на шкале 1.5) сочли ниже контейнера
 * пола, посчитав контейнер РАВНЫМ ХОСТУ (380 px на кадре 440); контейнер
 * `Tabs` на деле УЖЕ хоста, порог достигается раньше счёта, и ветка внутри оси
 * включается — 8 из 28 пар разошлись. Объявление покупается ЗАМЕРОМ узла в
 * браузере, а не счётом по листу.
 */
export const WIDTH_SAME = new Map([])

/**
 * Площадь оси ширины с диска — общим `axisSurface`: прелюдии `@container`, где
 * стоит `WIDTH_COND`.
 *
 * @param {{ root: string, entry: string, read: (abs: string) => string }} o
 */
export const widthSurface = (o) => axisSurface({ ...o, at: 'container', cond: WIDTH_COND })

/**
 * ОПИСАНИЕ ОСИ ДЛЯ СТРАНИЦЫ — аргумент `page.evaluate`, а не обёртка: довод
 * тот же, что у `TOUCH_AXIS`.
 */
export const WIDTH_AXIS = { src: WIDTH_COND.source, kind: 'CSSContainerRule' }

/**
 * РАЗНИЦА ПО КОМПОНЕНТУ — вердикт оси. Стороны — `wFloor` и `wSecond`, база
 * первая: отчёт читается «N из M пар отличаются от кадра ${WIDTH_FLOOR}».
 */
export const widthVerdict = ({ surface, prints, same }) => axisVerdict({
  surface, prints, same, sides: ['wFloor', 'wSecond'], from: `кадра ${WIDTH_FLOOR}`, what: 'ветка ширины',
})
