#!/usr/bin/perl
#
# Поля без атрибута `label=` — те, что диктор прочитает как «поле ввода»
# (DS-131). Отдаётся ПОТРЕБИТЕЛЮ вместе с выпуском: он сохраняет этот
# файл у себя и запускает
#
#   git grep -lz -E '<(TextField|Textarea|Select|NumberField|Combobox|SearchBar)' -- '*.tsx' \
#     | xargs -0 perl -0777 -n find-unlabeled-fields.pl
#
# От корня своего репозитория и без пути (DS-166): `src/` у потребителя
# может оказаться не фронтом вовсе, а `git grep` не заглядывает в `node_modules`,
# где лежит и сам этот пакет.
#
# Набор тегов, искомый атрибут и сторона вопроса задаются окружением:
# `FIND_TAGS`, `FIND_ATTR`, `FIND_MODE` (`without` — теги без атрибута, `with` —
# с ним).
#
# ПРЕФИКС НЕ УКРАШЕНИЕ. Сначала переменная звалась `MODE` — и немедленно поймала
# чужое значение: `vitest` ставит `MODE=test` всему процессу, скрипт умер на
# проверке, и это ЛУЧШИЙ исход из возможных. Не будь проверки значения, он
# молча отработал бы режимом по умолчанию, то есть ответил бы на
# ПРОТИВОПОЛОЖНЫЙ вопрос списком, который выглядит правдоподобно.
#
# Здесь он лежит не для нас, а чтобы ПРОВЕРЯЛСЯ: команду, которая уехала в
# CHANGELOG текстом, никто больше не запускает, и разъезжается она молча.
# Гейт `changelog-search-command` гоняет ровно этот файл.
#
# ПОЧЕМУ НЕ ОДНОСТРОЧНЫЙ ГРЕП. В 4.0.1 команда была `grep … | grep -v "label="`,
# то есть меряла СТРОКУ. JSX у потребителя многострочный, `label=` уходит на
# следующую строку — и поле с подписью считается безымянным. У потребителя:
# 45 попаданий сырой командой, 19 разбором тега, 7 реально безымянных.
# Завышение в шесть раз. Пункт с такой командой хуже пункта без команды: он
# выглядит работой.
#
# `-0777` обязателен — он и делает разбор поФАЙЛОВЫМ, а не построчным.
#
# ГРАНИЦЫ, И О НИХ СКАЗАНО ПРЯМО. Греп меряет этот класс ПРИБЛИЗИТЕЛЬНО и
# сверху: поле, названное внешним `<label htmlFor>`, отсюда неотличимо от
# безымянного, и таких у потребителя было двенадцать из девятнадцати. Число
# на выходе — верхняя оценка, список мест для просмотра глазами, а не диагноз.

# Скобочный блок пропса: `{...}` с вложенностью до трёх уровней. Он же
# единственная причина, по которой тег нельзя искать как `[^<>]*`: стрелка в
# `onChange={() => …}` содержит `>`, и наивный класс режет тег ПОПОЛАМ ровно
# перед `label=`. Первая версия этого регекса на том и попалась — а по числу
# попаданий выглядела правдоподобно, потому что смотрели на вывод, а не на то,
# различает ли команда два состояния.
my $B = qr/\{(?:[^{}]|\{(?:[^{}]|\{[^{}]*\})*\})*\}/;

my $tags = $ENV{FIND_TAGS} || 'TextField|Textarea|Select|NumberField|Combobox|SearchBar';
my $attr = $ENV{FIND_ATTR} || 'label';
# `without` (по умолчанию) — теги БЕЗ атрибута, `with` — теги С НИМ. Второй режим
# нужен ровно так же часто: «где у меня выключенное поле» — это тот же вопрос,
# заданный с другой стороны, и решать его вторым скриптом значило бы завести
# вторую копию разбора тега, которая разойдётся с первой.
my $mode = $ENV{FIND_MODE} || 'without';
die "FIND_MODE должен быть with или without, а не «$mode»\n" unless $mode =~ /^(with|without)$/;

while (/<(?:$tags)\b(?:[^<>{]|$B|"[^"]*"|'[^']*')*\/?>/gs) {
  my $m = $&;
  # СМЕЩЕНИЕ СНИМАЕТСЯ ДО ЛЮБОГО ДРУГОГО СОПОСТАВЛЕНИЯ. `$-[0]` принадлежит
  # ПОСЛЕДНЕМУ УДАВШЕМУСЯ матчу, и проверка атрибута ниже его затирает — номер
  # строки тогда указывает внутрь тега, а не на его начало. В режиме `without`
  # это не всплывало: там внутренний матч у напечатанных тегов не удаётся, а
  # неудачный `@-` не трогает. То есть ошибка ждала ровно того дня, когда
  # появится режим `with`.
  my $off = $-[0];
  # БУЛЕВ АТРИБУТ БЕЗ `=` СЧИТАЕТСЯ ТОЖЕ. `<FileDrop disabled />` — самая частая
  # запись выключенного поля, а `\battr=` её не видит: команда отвечала бы «таких
  # мест нет» на дереве, где они есть. Границы `(?<![-\w])…(?![-\w])` держат два
  # соседних промаха: `aria-disabled` не считается за `disabled`, а `disabledFoo`
  # не считается ни за что.
  my $has = $m =~ /(?<![-\w])\Q$attr\E(?![-\w])/ ? 1 : 0;
  next if $has == ($mode eq 'without' ? 1 : 0);
  my $l = 1 + (substr($_, 0, $off) =~ tr/\n//);
  (my $one = $m) =~ s/\s+/ /g;
  print "$ARGV:$l: $one\n";
}
