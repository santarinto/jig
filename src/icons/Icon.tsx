import type { HTMLAttributes, ReactNode } from 'react'
import '../styles/icon.css'

/**
 * Контракт значка: ЛЮБОЙ переданный SVG приводится к системному виду
 * (DS-145).
 *
 * ЧТО БЫЛО СЛОМАНО. Доступность иконок проблемой не была — у обоих потребителей
 * tabler уже стоит, и берут они его сами. Сломано было другое: НИЧТО не держало
 * переданную иконку в общем виде. Двенадцать компонентов принимают `icon` как
 * голый `ReactNode`, и что бы туда ни положили, толщина штриха, размер, посадка
 * и цвет оставались чужими. Рядом с нашим шевроном это два разных знака, и
 * разница видна.
 *
 * ПОЧЕМУ НЕ ПАК ИКОНОК, хотя владелец предлагал именно его. Пак этого не чинит:
 * он добавляет свои глифы РЯДОМ с чужими, а чужие никуда не деваются —
 * потребитель всё равно положит в `icon` то, чего у нас нет. Плюс три цены:
 * таксономия навсегда («какие двести из пяти тысяч» — выбор не разовый, каждое
 * «нужной иконки нет» становится релизом системы), имена как публичный API
 * (периода совместимости в проекте нет, и каждое переименование — пункт
 * CHANGELOG с командой поиска), и бандл (N компонентов-глифов требуют, чтобы
 * tree-shaking держался у бандлера потребителя, а `dist/` — голый вывод `tsc`, и
 * ничто в репозитории не утверждает `sideEffects: false`).
 *
 * Единственный сильный довод ЗА пак — «наши глифы нарисованы под сетку tabler
 * 24×24, и если у потребителя tabler уедет по версии, они разойдутся». Контракт
 * закрывает ровно это: `<Icon>` навязывает толщину штриха, поэтому дрейф чужой
 * библиотеки до экрана не доезжает. Лучший довод за пак обслуживается дешевле
 * без пака.
 *
 * КАК ЭТО РАБОТАЕТ, и это проверено в браузере, а не предположено: CSS бьёт
 * презентационные атрибуты SVG. На разметке в точности как у tabler
 * (`width="24" stroke-width="1.5" stroke="currentColor"`) правило
 * `.probe svg { width:14px; stroke-width:2; color:… }` дало `13.99px`,
 * `stroke-width: 2px` и наш цвет. То есть чужой глиф нормализуется без права
 * его перерисовывать.
 *
 * РАЗМЕР — ТОЛЬКО СТИЛЕМ, и это не вкус. `Glyph` (`icons/glyphs.tsx`) отдаёт
 * размер атрибутом `width`, то есть голыми CSS-пикселями мимо `--ds-ui-scale`:
 * при шкале 1.5 текст растёт, а значок нет. Та же ловушка описана в
 * `styles/caret.css`, и публичный `<Icon>`, повторивший проп `size`, унёс бы её
 * в API потребителя. Поэтому пропа `size` здесь НЕТ; величина живёт в
 * `--ds-size-icon`, а место, которому нужен свой размер, ставит модификатор.
 */
export interface IconProps extends HTMLAttributes<HTMLSpanElement> {
  /**
   * Сам глиф: наш экспортированный, чужой из библиотеки потребителя или голый
   * `<svg>`. Обёртка не перерисовывает его и не заглядывает внутрь.
   */
  children?: ReactNode
}

export function Icon({ children, className, ...rest }: IconProps) {
  return (
    <span className={['ds-icon', className].filter(Boolean).join(' ')} {...rest}>
      {children}
    </span>
  )
}
