import { describe, it, expect } from 'vitest'
import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

/**
 * Превью, которое СОБИРАЕТСЯ из компонента, лежит на диске собранным
 * (DS-156).
 *
 * `preview-classes` держит слабое утверждение: каждый `ds-*` класс страницы
 * существует в CSS. Оно ловит опечатку и переименование, но НЕ ловит
 * расхождение по числам и структуре — а именно оно дважды случалось молча.
 * Свежий пример из этой же задачи: полосе `allDay` в рукописном превью стояло
 * `height:24px` прямым числом, а компонент считает её как
 * `calc(1.5rem * var(--ds-ui-scale))`. Все классы существовали, `measure` был
 * зелёный, и при этом страница показывала пол цели, которого у компонента не
 * было: 21px на рабочей шкале 0.875. Замер честно мерил разметку, к которой
 * никто не имеет отношения.
 *
 * Поэтому у страниц, чью геометрию мерят числом, есть источник —
 * `scripts/render-preview.mjs --page <имя>`, — и этот гейт требует, чтобы на
 * диске лежал ровно его вывод. Правка превью руками краснеет; лечится
 * перерисовкой, а не подгонкой.
 *
 * Охват ПОИМЁННЫЙ, и это не недоделка. Из 51 превью здесь одно: три страницы
 * вообще не про один компонент, а `measure` держится в бюджете `check` тем,
 * что грузит плоский HTML (решение DS-224, оно в силе). Страница
 * попадает в список тогда, когда её разметку начинают мерить числом.
 *
 * Гейт зовёт САМ СКРИПТ подпроцессом, а не повторяет его работу здесь.
 * Повтор — это второй конвейер, который расходится с первым так же молча, как
 * расходилось превью: собирает бандл иначе, режет `--strip` иначе, склеивает
 * шапку иначе. Цена вызова — 0.5s на один бандл react на все блоки страницы.
 */
const ROOT = resolve(__dirname, '../..')

/** Страницы, собираемые из компонента. Имя = `previews/<имя>.html`. */
const GENERATED = ['eventcalendar']

describe('превью, собираемое из компонента, лежит собранным (DS-156)', () => {
  it.each(GENERATED)('previews/%s.html совпадает с рендером фикстуры', (name) => {
    let out = ''
    try {
      out = execFileSync('node', ['scripts/render-preview.mjs', '--page', name, '--check'], {
        cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'],
      })
    } catch (e) {
      const err = e as { stderr?: string; stdout?: string }
      throw new Error(`${err.stderr ?? ''}${err.stdout ?? ''}`.trim() || String(e))
    }
    expect(out).toMatch(/^ok:/)
  })

  /**
   * Санитар: гейт обязан УМЕТЬ покраснеть. Без этого утверждения он зеленеет и
   * тогда, когда скрипт разучился находить расхождение вовсе — например
   * сравнивает файл сам с собой. Подсовываем заведомо чужое имя страницы и
   * требуем ненулевого кода: механизм отказа живой.
   */
  it('механизм отказа живой: неизвестная страница — это красный, а не тишина', () => {
    expect(() =>
      execFileSync('node', ['scripts/render-preview.mjs', '--page', 'нет-такой', '--check'], {
        cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'],
      })).toThrow()
  })

  /**
   * Санитар охвата: имя из списка обязано указывать на существующий файл,
   * который И ЕСТЬ вывод скрипта для ЭТОГО имени. Опечатка в имени иначе
   * прошла бы как «нечего проверять».
   *
   * Держится на самоназвании страницы: сборка вписывает в шапку команду
   * перерисовки со своим именем, и рукописное превью такой строки не несёт.
   * До DS-225 здесь стояла проверка на шапку `<!-- @dsCard`, и она
   * различала ровно ничего: маркер лежал в 51 превью из 51, то есть на любое
   * подставленное имя отвечал «да». Читателя у него не нашлось нигде —
   * ни в гейтах, ни в `.design-sync/`, ни у потребителей, — и он снят.
   */
  it.each(GENERATED)('previews/%s.html — это вывод скрипта для ЭТОГО имени', (name) => {
    const src = readFileSync(resolve(ROOT, 'previews', `${name}.html`), 'utf8')
    expect(src).toContain(`node scripts/render-preview.mjs --page ${name}`)
  })
})
