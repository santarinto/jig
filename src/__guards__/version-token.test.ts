import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { resolve, join } from 'node:path'

/**
 * `--ds-version` — единственный способ узнать версию системы СО СТРАНИЦЫ
 * потребителя (DS-215). Ни `styles.bundle.css`, ни `tokens.css`, ни
 * `window` версии не несли, а `package.json` до рантайма страницы не доезжает:
 * в `exports` только типы, `index.js` и четыре css.
 *
 * Вопрос не праздный. Потребитель ставит ПРИБИТЫЙ тег и сам не обновляется,
 * так что «а он вообще на свежем?» — первое, что нужно знать перед разговором
 * о дефекте: половина замечаний к чужой странице может оказаться починенной
 * три версии назад, и разбирать их — потерянный день с обеих сторон.
 *
 * ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ И ЧТО НЕТ. Здесь — только ФОРМА ЗАПИСИ в исходнике:
 * шаг идёт ДО сборки, и о собранном пакете утверждать ему нечем (DS-238).
 * Доезд до сборки — `make dist-version`, совпадение всех пяти версионных файлов
 * — `doc-version`, а чтение НАСТОЯЩИМ `getComputedStyle` в настоящем браузере —
 * случай `версия читается со страницы` в `scripts/measure-invariants.mjs`:
 * jsdom кавычки в значении переменной разбирает по-своему, и утверждать по нему
 * «страница ответит» значило бы проверять jsdom, а не браузер.
 */
const ROOT = resolve(__dirname, '../..')
const version = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version as string

/** Объявление токена в тексте листа. Кавычки — часть утверждения. */
const QUOTED = /--ds-version:\s*"(\d+\.\d+\.\d+)"\s*;/

describe('--ds-version', () => {
  it('объявлен в :root СТРОКОЙ В КАВЫЧКАХ, а не голым числом', () => {
    const css = readFileSync(join(ROOT, 'tokens/tokens.css'), 'utf8')
    const m = QUOTED.exec(css)
    expect(m, 'токен --ds-version не объявлен или записан без кавычек').not.toBeNull()
    expect(m![1]).toBe(version)
    // `4.2.0` не значение CSS: без кавычек объявление невалидно, браузер
    // выбрасывает его при разборе, и `getPropertyValue` возвращает ПУСТУЮ
    // строку — молча, ровно тем способом, каким этот класс дефектов и живёт.
    // Утверждение про кавычки поэтому отдельное и своими словами: регексп выше
    // мог бы совпасть по случайности внутри комментария.
    const bare = /--ds-version:\s*\d+\.\d+\.\d+\s*;/.test(css)
    expect(bare, 'где-то объявлен --ds-version без кавычек — он вернётся пустым').toBe(false)
  })

  it('объявлен в :root, а не в теме — иначе на тёмной странице его нет', () => {
    const css = readFileSync(join(ROOT, 'tokens/tokens.css'), 'utf8')
    const root = /:root\s*\{([\s\S]*?)\n\}/.exec(css)
    expect(root, 'блок :root в tokens.css не найден').not.toBeNull()
    expect(root![1], '--ds-version объявлен вне :root').toMatch(QUOTED)
  })

  // Доезд до СОБРАННОГО пакета проверяет `scripts/check-dist-version.mjs` —
  // шаг `make dist-version`, стоящий сразу за `build` (DS-238). Здесь
  // его быть не может: guards идут ДО сборки, и на релизе — `prepare` бампит
  // пять версионных файлов, `check-full` идёт следом — утверждение читало
  // артефакт ПРОШЛОЙ версии и отвечало «не доехала» там, где не доехала ЕЩЁ.
  // `skipIf` тот случай не закрывает: артефакт есть, он протух. Порядок держит
  // `dist-freshness`, он же запрещает завести такую проверку в guards заново.
})
