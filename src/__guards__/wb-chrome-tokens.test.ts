import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

/**
 * Прибор не имеет права ехать вместе с предметом (DS-124).
 *
 * Компонентов системы в оболочке верстака нет и не было — из `src/` она тянет
 * только `import type`. А вот покрашена оболочка была токенами системы: 108
 * обращений к шестнадцати `--ds-*` в `shell.css`. Цена: правка `--ds-surface`
 * или `--ds-fs-base` сдвигала ИНСТРУМЕНТ вместе с компонентом, и человек не
 * отличал «сдвинулся предмет» от «сдвинулся прибор». Тот же класс, что
 * DS-122 с палитрой серий, только прибор меряет сам себя. Отказ тихий:
 * картинка правдоподобна в обоих случаях.
 *
 * ГРАНИЦА ИДЁТ ПО ГРАНИЦЕ IFRAME, А НЕ ПО КАТАЛОГУ `workbench/`. Кадр —
 * предмет измерения, он обязан краситься системой и меняться вместе с ней.
 * Поэтому гейт держит утверждение в ОБЕ стороны: `--ds-` в оболочке — дефект, и
 * его отсутствие в кадре — тоже дефект. Без второй половины «починка» свелась бы
 * к тому, чтобы вычистить `--ds-` отовсюду, и верстак перестал бы показывать
 * систему вообще — зелено и бессмысленно.
 *
 * Комментарии вырезаются, как в `no-raw-hex`: предмет гейта — ЗНАЧЕНИЕ, а не
 * текст. Объяснить в комментарии, от чего именно оторвана палитра, можно только
 * назвав `--ds-*` по имени; запрет на упоминание запрещал бы ровно то, ради чего
 * комментарий пишут.
 */
const ROOT = resolve(__dirname, '../..')
const stripComments = (src: string) => src.replace(/\/\*[\s\S]*?\*\//g, ' ')

const read = (rel: string) => stripComments(readFileSync(resolve(ROOT, rel), 'utf8'))
const hits = (src: string, needle: RegExp) => src.match(needle) ?? []

describe('хром верстака покрашен своими токенами', () => {
  it('оболочка не обращается ни к одному --ds-*', () => {
    const shell = read('workbench/shell.css')
    const offenders = [...new Set(hits(shell, /--ds-[a-z0-9-]+/g))]

    // Обратные мутации. Пустой или укоротившийся файл дал бы такой же зелёный
    // результат: пришлось бы «починить» связь удалением стилей.
    expect(shell.length, 'shell.css подозрительно короток — гейту нечего смотреть').toBeGreaterThan(
      8000,
    )
    expect(
      hits(shell, /--wb-[a-z0-9-]+/g).length,
      'в shell.css нет обращений к --wb-* — палитра не своя, а никакая',
    ).toBeGreaterThan(100)
    expect(offenders, `оболочка держится за систему: ${offenders.join(', ')}`).toEqual([])
  })

  it('палитра — лестница: каждая роль ссылается на ступень, а не хранит цвет', () => {
    const shell = read('workbench/shell.css')
    const root = shell.match(/:root\s*\{([\s\S]*?)\n\}/)?.[1] ?? ''

    const steps = new Map<string, string>()
    const roles = new Map<string, string>()
    for (const m of root.matchAll(/(--wb-[a-z0-9-]+):\s*([^;]+);/g)) {
      const [, name, raw] = m as unknown as [string, string, string]
      if (/^--wb-[0-9a-f]$/.test(name)) steps.set(name, raw.trim())
      else roles.set(name, raw.trim())
    }

    // Шестнадцать ступеней, все разные. Ровно та проверка, которой нет у
    // системной палитры: там оттенок выбирают, здесь его берут с полки, и полка
    // обязана быть полной — дыра в ней читается как «этой ступени не бывает».
    expect(steps.size, 'лестница не из шестнадцати ступеней').toBe(16)
    expect(new Set(steps.values()).size, 'две ступени одного цвета — лестница не различает').toBe(16)

    /**
     * Единственный цветной в хроме, и потому единственное исключение. Цвет тут
     * значит ровно одно — внимание; ступенью его не выразить, лестница
     * нейтральная по построению. Разрешение выдано ИМЕНИ, а не «любому
     * литералу»: второй такой токен обязан пройти через это место и через
     * разговор, а не просочиться.
     */
    const COLOURED = ['--wb-warning-fg']

    const literals = [...roles]
      .filter(([n]) => !COLOURED.includes(n))
      .filter(([, v]) => /#|rgb|hsl|oklch/.test(v))
      .map(([n, v]) => `${n}: ${v}`)

    expect(roles.size, 'ролей в :root нет — гейту нечего смотреть').toBeGreaterThan(8)
    expect(
      literals,
      `роль хранит цвет вместо ступени — это оттенок мимо лестницы:\n${literals.join('\n')}`,
    ).toEqual([])

    // Ссылки ведут на существующие ступени: `var(--wb-g)` — опечатка, которая
    // в браузере даёт прозрачный фон и выглядит как «правило не применилось».
    const dangling = [...roles]
      .map(([n, v]) => [n, v.match(/^var\((--wb-[a-z0-9-]+)\)$/)?.[1]] as const)
      .filter(([, ref]) => ref && !steps.has(ref))
      .map(([n, ref]) => `${n} → ${ref}`)
    expect(dangling, `ссылка на несуществующую ступень: ${dangling.join(', ')}`).toEqual([])
  })

  it('у хрома нет тем — светлый инструмент вернуть нечем', () => {
    const shell = read('workbench/shell.css')
    // Тема оболочки умела воссоздать ровно тот дефект, ради которого хром
    // оторвали от системы: светлый хром вокруг светлого компонента. Снятый
    // контрол возвращается одной строкой JSX (это держит shell-theme.test.tsx),
    // а блок в CSS — одним селектором; утверждать надо оба.
    const themed = [...shell.matchAll(/\[data-theme[^\]]*\]/g)].map((m) => m[0])
    expect(themed, `в хроме появился блок темы: ${themed.join(', ')}`).toEqual([])
  })

  it('кадр, наоборот, остаётся на токенах системы — он предмет измерения', () => {
    const frame = read('workbench/frame.css')
    expect(
      hits(frame, /--ds-[a-z0-9-]+/g).length,
      'в frame.css не осталось --ds-*: кадр перестал показывать систему',
    ).toBeGreaterThan(5)
  })
})
