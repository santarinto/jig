import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

/**
 * `.ds-scale` — масштаб поддерева: класс объявляет метрические токены заново, на
 * самом элементе, поэтому `var(--ds-ui-scale)` в них резолвится там, а не в
 * `:root` (подстановка внутри кастомного свойства происходит на элементе, где
 * свойство объявлено — свойство каскада, пропом не чинится).
 *
 * Правило способа — «полностью или никак»: частичный набор ХУЖЕ, чем ничего.
 * Дизайн-агент переобъявил три токена из восемнадцати, и `RouteBar` разошёлся по
 * швам — высота и шрифт выросли, горизонтальный padding и кегль счётчика нет.
 *
 * Держится оно не обещанием, а общим селектором: набор физически один. Этот гейт
 * стережёт две вещи, которые общий селектор сам по себе не запрещает:
 *   1) метрический токен, объявленный где-то ещё мимо `.ds-scale` — он и будет
 *      тем самым «одним из восемнадцати», который не поехал;
 *   2) НЕметрический токен, заехавший в общий блок. Цвет там — не лишняя строка,
 *      а дефект: `.ds-scale` внутри тёмной темы переобъявил бы светлый цвет на
 *      себе, и поддерево посветлело бы вместе с масштабом.
 */
/**
 * Семейства метрик: кегль, высота контрола, отступ, ширина, сторона квадрата.
 * `w` заведено на DS-137 вместе с `--ds-w-col-min` — пол ширины колонки
 * таблицы; `size` на DS-143 вместе с `--ds-size-caret`. Не исключение
 * поимённо, а семейство: имя, названное в гейте буквально, пришлось бы
 * дописывать при каждой новой метрике, и первая недописанная объявила бы себя
 * цветом в общем блоке.
 *
 * `size` — метрика, ОДИНАКОВАЯ по обеим осям: у знака раскрытия ширина и высота
 * это одно число, и разложить его на `--ds-w-*` и `--ds-h-*` значило бы завести
 * два имени, которым запрещено расходиться. `h` сюда не годится: там высоты
 * контролов по плотности, а не сторона квадрата.
 */
const METRIC = /^--ds-(?:fs|h|space|w|size)-[a-z0-9-]+$/

/** Блоки верхнего уровня: [селекторы, тело]. Комментарии уже вырезаны. */
function blocks(css: string): [string, string][] {
  const out: [string, string][] = []
  const clean = css.replace(/\/\*[\s\S]*?\*\//g, '')
  for (const m of clean.matchAll(/([^{}]+)\{([^{}]*)\}/g)) out.push([m[1]!.trim(), m[2]!])
  return out
}

function declared(body: string): string[] {
  return [...body.matchAll(/(--ds-[a-z0-9-]+)\s*:/gi)].map((m) => m[1]!)
}

describe('масштаб поддерева (.ds-scale)', () => {
  const css = readFileSync(resolve(__dirname, '../../tokens/tokens.css'), 'utf8')
  const all = blocks(css)
  const shared = all.filter(([sel]) => sel.includes('.ds-scale'))

  it('общий блок с :root существует ровно один', () => {
    expect(shared.map(([sel]) => sel.replace(/\s+/g, ' '))).toEqual([':root, .ds-scale'])
  })

  it('каждый метрический токен объявлен только в нём', () => {
    const outside = all
      .filter(([sel]) => !sel.includes('.ds-scale'))
      .flatMap(([sel, body]) => declared(body).filter((t) => METRIC.test(t)).map((t) => `${sel}: ${t}`))
    expect(
      outside,
      'метрический токен мимо .ds-scale — поддерево масштабируется частично:\n' + outside.join('\n'),
    ).toEqual([])
  })

  it('в нём объявлены ТОЛЬКО метрические — цвет там перекрасил бы тёмную тему', () => {
    const foreign = declared(shared[0]![1]).filter((t) => !METRIC.test(t))
    expect(foreign, 'не размеры в общем блоке:\n' + foreign.join('\n')).toEqual([])
  })

  it('набор непустой — иначе предыдущие два утверждения не о чем', () => {
    expect(declared(shared[0]![1]).length).toBeGreaterThanOrEqual(18)
  })
})
