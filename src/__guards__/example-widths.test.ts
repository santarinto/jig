import { describe, it, expect } from 'vitest'
import { readFileSync, readdirSync } from 'node:fs'
import { resolve, join, relative } from 'node:path'

/**
 * Ширина колонки в ПРИМЕРАХ системы записывается числом, а не абсолютной
 * строкой (DS-87).
 *
 * Строка законна и остаётся законной: доля `'20%'`, `'max-content'`,
 * `minmax(…)`, готовый `calc(… * var(--ds-ui-scale, 1))` числом не
 * записываются. Но `'90px'` и `'5.5rem'` — записываются, и означают ровно то,
 * от чего дважды чинили систему: величина, выпавшая из `--ds-ui-scale`, при
 * том что высота строки едет всегда (`--ds-h-compact`). Под `.ds-scale` строки
 * растут, колонки стоят — сетка расходится там, где её фиксировали
 * (DS-82 в `DataTable`, DS-83 в `Tree`).
 *
 * **Почему охват — примеры, а не весь репозиторий.** Обе задачи были не про
 * строку в коде, а про то, что так показывало ПРЕВЬЮ дизайн-агента: пример
 * сильнее документации, документацию читают единицы, пример копируют все.
 * `.design-sync/previews/Tree.tsx` учил `width: '90px'`, `demo/constraints-lab`
 * — `'5.5rem'`; оба починены руками, и удержать их починенными было нечем.
 *
 * Три зелёные проверки, и ни одна не об этом:
 * - `js-px-scale` ловит ИНТЕРПОЛЯЦИЮ (`${n}px`) и только в `src/` — примеры вне
 *   охвата дважды;
 * - `rem-units` читает стили, а тут значение приходит пропом из TSX;
 * - тайпчек превью видит тип `number | string` — обе формы законны, и должны
 *   оставаться законными: запрет живёт в примерах, не в типах.
 */
const ROOT = resolve(__dirname, '../..')

/**
 * Каталоги примеров. Охват по КАТАЛОГАМ, а не по расширению: дефект в том, что
 * пример оказался вне зоны проверки, и повторится он на следующем каталоге
 * примеров, а не на следующем расширении.
 */
const EXAMPLE_DIRS = [join('.design-sync', 'previews'), 'demo']

/**
 * Якоря охвата — файлы, а не каталоги, и это разница между проверкой и
 * тавтологией. Цикл `for (const d of EXAMPLE_DIRS) expect(scanned.some(…))`
 * упасть не может: он спрашивает про то, что сам же перечислил, и молча
 * зеленеет, когда каталог из списка ВЫПАДАЕТ (проверено мутацией — удаление
 * `'demo'` не уронило ни одного утверждения).
 *
 * Оба файла названы поимённо потому, что именно они дважды показывали промах:
 * превью `Tree` учило `'90px'`, лаборатория констрейнтов — `'5.5rem'`.
 */
const ANCHORS = [
  join('previews', 'Tree.tsx'),
  join('demo', 'constraints-lab.tsx'),
]

/**
 * Абсолютная длина, которую можно записать числом. `%`, `max-content`, `auto`,
 * `minmax()`, `calc()` сюда не попадают намеренно — числом они не выражаются,
 * и запрет на них означал бы запрет на то, ради чего строковая форма и есть.
 */
const ABSOLUTE = /^\d+(\.\d+)?(px|rem|em)$/

/**
 * Объявление ширины строкой — ВСЕ три вида кавычек.
 *
 * Найдено ревью собственного гейта: первая редакция читала только одинарные, и
 * `width: "90px"` вместе с `` width: `90px` `` проходили мимо (проверено — обе
 * мутации выживали). Стиль репозитория тут не довод: гейт пишется против того,
 * что кто-то напишет завтра, а не против того, что принято сегодня, — и
 * скопированный из чужого примера фрагмент приезжает ровно в двойных.
 *
 * Инлайновые стили (`style={{ width: 320 }}`) под тем же именем живут в тех же
 * файлах — их отсекает требование кавычек и `(?<![\w.])` перед `width`:
 * `maxWidth`, `minWidth`, `strokeWidth`, `box.width` не считаются.
 */
const QUOTED_WIDTH = /(?<![\w.])width:\s*(['"`])([^'"`]+)\1/

function files(dir: string): string[] {
  const out: string[] = []
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name)
    if (e.isDirectory()) out.push(...files(p))
    else if (/\.tsx?$/.test(e.name)) out.push(p)
  }
  return out
}

describe('ширина колонки в примерах', () => {
  it('записана числом, а не абсолютной строкой', () => {
    const scanned = EXAMPLE_DIRS.flatMap((d) => files(join(ROOT, d)))
    const offenders: string[] = []
    for (const file of scanned) {
      const source = readFileSync(file, 'utf8')
      source.split('\n').forEach((line, i) => {
        // Только объявление ширины колонки: `width: '90px'`. Инлайновые стили
        // (`style={{ width: 320 }}`) под тем же именем живут в тех же файлах и
        // к колонкам отношения не имеют — там число значит другое.
        const m = QUOTED_WIDTH.exec(line)
        if (m && ABSOLUTE.test(m[2]!)) {
          offenders.push(`${relative(ROOT, file)}:${i + 1}: width: ${m[1]}${m[2]}${m[1]}`)
        }
      })
    }
    expect(
      offenders,
      'абсолютная ширина строкой в примере — пример учит величине, выпавшей из --ds-ui-scale:\n'
      + offenders.join('\n'),
    ).toEqual([])

    // Счётчик — не украшение: обход, вернувший пусто (переименовали каталог,
    // сузили расширение), даёт зелёный тест, который ничего не читал.
    expect(scanned.length, 'обход не нашёл примеров — охват сломан').toBeGreaterThan(20)
    // Якоря — по одному из КАЖДОГО каталога. Выпадение каталога из списка
    // роняет утверждение, а не проходит незамеченным (см. комментарий к
    // ANCHORS: цикл по самому списку этого не ловит).
    for (const a of ANCHORS) {
      expect(
        scanned.some((f) => f.endsWith(a)),
        `${a} вне охвата — каталог примеров выпал из списка`,
      ).toBe(true)
    }
  })

  /**
   * Обратная сторона: строковая форма в ТЕСТАХ законна и обязана остаться
   * зелёной. Там проверяется, что строка форвардится дословно, — гейт,
   * ловящий заодно и её, охранял бы не тот контракт и запрещал бы то, ради
   * чего строка существует.
   */
  it('не трогает src: там строковая ширина — предмет проверки, а не промах', () => {
    // Читается ВЕСЬ набор кейсов компонента, а не один файл: после разрезания
    // `DataTable.test.tsx` на пять (DS-116) строковые ширины уехали в
    // `DataTable.columns.test.tsx`, и утверждение по одному имени тут же
    // покраснело — правильно покраснело, предмет из наблюдаемого файла исчез.
    // По каталогу оно переживёт и следующее разрезание.
    const dir = join(ROOT, 'src/components/DataTable')
    const test = readdirSync(dir)
      .filter((f) => f.endsWith('.test.tsx'))
      .map((f) => readFileSync(join(dir, f), 'utf8'))
      .join('\n')
    const literals = [...test.matchAll(new RegExp(QUOTED_WIDTH.source, 'g'))].map((m) => m[2]!)
    expect(
      literals.filter((v) => ABSOLUTE.test(v)).length,
      'в тестах DataTable больше нет строковых ширин — проверка форвардинга исчезла,'
      + ' и этот случай перестал что-либо утверждать',
    ).toBeGreaterThan(0)
    // Каталог `src` в охват гейта не входит — утверждается прямо, а не
    // подразумевается: иначе завтрашнее расширение охвата уронит тесты
    // DataTable и повод будет искать некому.
    expect(EXAMPLE_DIRS.some((d) => d === 'src')).toBe(false)
  })
})
