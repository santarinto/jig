import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { resolve, join } from 'node:path'

/**
 * Число, которое меняется каждой задачей, не живёт в ПРАВИЛЕ (DS-230).
 *
 * В CLAUDE.md рядом с описанием `make check` стояло «`measure` 146 из 146».
 * Оно устарело в тот же день, когда было записано: за одну ночь прогон вырос
 * на тринадцать случаев, и правило продолжало читаться как факт — а читают его
 * ровно затем, чтобы узнать, что считать нормой. Прочитавший «146 из 146» и
 * увидевший «166 из 166» решает не «файл устарел», а «что-то не так с
 * прогоном»: устаревшее число хуже отсутствующего, потому что ему верят.
 *
 * Настоящий счёт печатает сам прогон последней строкой, и он всегда свежий.
 * Правилу от него нужно ровно одно: «все держатся», а не сколько их.
 *
 * ЧТО ЗАПРЕЩЕНО И ЧТО НЕТ. Запрещён СЧЁТ СЛУЧАЕВ `measure` — величина, которую
 * двигает каждая вторая задача. Числа, которые двигает решение (пол контраста
 * 4.5, порог ΔE 25), остаются: они и есть содержание правил, и стареют они
 * по-другому — вместе с решением, а не сами собой.
 *
 * ДЛИТЕЛЬНОСТЬ ЦЕЛОЙ ЦЕЛИ — туда же (DS-342). Прежняя редакция этого
 * докблока разрешала её «с датой замера», и именно она показала, почему дата
 * не спасает: `make check ~65s` устарело от добавленных шагов, а перезамер
 * требовал холостой машины, которой три захода подряд не дождались. Число
 * ждало условия вместо того, чтобы быть фактом. Теперь его печатает последняя
 * строка `check` и `check-full` вместе с нагрузкой на старте. Цена ОТДЕЛЬНОГО
 * шага (`states` 3s, `matrix` ~60 s) остаётся: это довод, по которому шаг
 * положен в свою цель, то есть число решения.
 *
 * Грепом класс ловится не весь, и это сказано прямо: пойманы две формы, в
 * которых число жило и в которые его вернёт копипаста, — в скобках заголовка
 * цели и в фразе «check занимает/измерен N s». Перефразированное мимо них
 * гейт не увидит.
 */
const ROOT = resolve(__dirname, '../..')

/** «measure 146 из 146», «146 из 147», «measure: 151/151» — все формы счёта. */
const PINNED = [
  /`?measure`?[^\n]{0,60}\b\d{2,4}\s+из\s+\d{2,4}\b/gi,
  /`?measure`?[^\n]{0,60}\b\d{2,4}\s*\/\s*\d{2,4}\s+инвариант/gi,
]

/** Длительность ЦЕЛОЙ цели: «`make check` (guards, …, ~65s)», «check was measured … (61s, 69s)». */
const DURATION = [
  /`make check(?:-full)?`\s*\([^)]*?~?\d+(?:[.,]\d+)?\s?(?:s|m|min|с|мин)\)/gi,
  /`?\bcheck(?:-full)?`?\s+(?:was measured|was re-measured|takes|занимает|идёт|измерен)[^\n]{0,60}?\b\d+(?:[.,]\d+)?\s?(?:s|m|min|с|мин)\b/gi,
]

/**
 * `docs/checks.md` вошёл сюда на DS-351 вместе со своим появлением: из
 * CLAUDE.md туда уехали цены шагов, а с ними и соблазн дописать рядом цену
 * целой цели — в файле, который ровно про то, сколько что стоит. Гейт,
 * стерегущий опустевшее место и не смотрящий на новое, зелен оттого, что слеп.
 */
const DOCS = [
  'CLAUDE.md', 'docs/guards.md', 'docs/writing-checks.md', 'AGENTS.md', 'docs/checks.md',
]

describe('счёт случаев measure не прибит в документации', () => {
  it.each(DOCS)(
    '%s не называет, сколько случаев в прогоне',
    (rel) => {
      const text = readFileSync(join(ROOT, rel), 'utf8')
      const hits = PINNED.flatMap((re) => [...text.matchAll(re)].map((m) => m[0].trim()))
      expect(
        hits,
        `${rel}: счёт случаев прибит числом — он двигается каждой второй задачей и устареет молча. `
        + 'Свежий счёт печатает последняя строка `make measure`; правилу достаточно «все держатся»',
      ).toEqual([])
    },
  )
})

describe('длительность make check / check-full не прибита в документации', () => {
  it.each(DOCS)('%s не называет, сколько идёт целая цель', (rel) => {
    const text = readFileSync(join(ROOT, rel), 'utf8')
    const hits = DURATION.flatMap((re) => [...text.matchAll(re)].map((m) => m[0].trim()))
    expect(
      hits,
      `${rel}: длительность целой цели прибита числом — она устаревает от каждого добавленного шага, `
      + 'а перезамер требует холостой машины. Её печатает последняя строка `make check` / `check-full` '
      + 'вместе с нагрузкой на старте; цена отдельного шага, на которой держится решение, остаётся',
    ).toEqual([])
  })

  // Узор обязан узнавать ровно те формы, в которых число жило до DS-342,
  // и не трогать цену шага: иначе гейт зелёный оттого, что слеп.
  it.each([
    ['`make check` (guards, test, measure, states, dock-floor,\n  ~65s). Is the source', true],
    ['`make check-full` (adds matrix, smoke, wb-smoke, ~3m). Does it', true],
    ['`check` was measured twice on 30.08 (61s, 69s)', true],
    ['`states` was added on DS-134 and costs 3s', false],
    ['owner\'s decision on cost (16.09.2026, ~60 s, measured when', false],
  ])('узор: %s → %s', (sample, expected) => {
    expect(DURATION.some((re) => new RegExp(re.source, re.flags).test(sample))).toBe(expected)
  })
})
