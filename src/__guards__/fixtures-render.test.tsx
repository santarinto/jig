/**
 * Гейт рендера фикстур: каждый случай каждой фикстуры рисуется без броска.
 *
 * Отдельно от `fixtures.test.ts` намеренно — тот проверяет СОСТАВ (имена
 * уникальны, ссылки слотов разрешимы, `accepts` × `kind` совместимы) и сам
 * оговаривает, что рендера не касается. Разница не теоретическая: фикстура с
 * обращением к несуществующему полю в `render` проходит гейт состава зелёной
 * (проверено мутацией — 10/10), а здесь валит свои случаи.
 *
 * Чего этот гейт НЕ ловит, чтобы следующий не принял его за проверку вида:
 *  - невидимый рендер. Узел с нулевой высотой, `display: none` у родителя,
 *    белое по белому — всё это «отрисовалось». На такое есть `make measure` и
 *    глаза в верстаке;
 *  - СОСТОЯНИЕ. Случай, который сам приводит себя в него (раскрывает список,
 *    открывает поповер), здесь неотличим от схлопнувшегося: замер DS-134
 *    — снятый сторож `opened` в `Combobox.fixture.tsx` оставляет 218/218
 *    зелёными, а в chromium список не раскрывается. Это спрашивает `shows`
 *    (`src/internal/fixture.ts`) и гейт `scripts/case-states.mjs`, в браузере.
 *    ОБОРАЧИВАТЬ ЭТОТ РЕНДЕР В `StrictMode` НЕ НАДО: проверено на той же
 *    задаче — все случаи остаются зелёными, потому что схлопнувшийся список не
 *    бросает и в консоль не пишет. Утверждать новое `StrictMode` здесь не
 *    начинает, а выглядит усилением;
 *  - осмысленность случая. Что случай утверждает различимость состояний —
 *    предмет ревью, не автоматической проверки;
 *  - начинки позиций. Слоты передаются ПУСТЫМИ: позиция без начинки —
 *    законное состояние компонента, и рендер обязан его пережить. Связки
 *    «кто в кого вставлен» разрешает гейт состава.
 */
/// <reference types="vite/client" />
import { describe, it, expect, vi } from 'vitest'
import { render, cleanup } from '@testing-library/react'
import type { AnyFixture } from '../internal/fixture.js'

const shipped = import.meta.glob<{ default: AnyFixture }>(['../components/*/*.fixture.tsx', '../icons/*.fixture.tsx'], {
  eager: true,
})

const all = Object.values(shipped).map((m) => m.default)

/** Пары «фикстура × случай» — то, что обходится. Считаются заранее, чтобы было
 *  что утверждать про сам обход: цикл, не выполнившийся ни разу, даёт ноль
 *  тестов и молча зелёный файл. */
const pairs = all.flatMap((fx) => fx.cases.map((c) => [fx, c] as const))

describe('рендер фикстур', () => {
  it('обход непустой: каждая фикстура дала хотя бы один случай', () => {
    expect(all.length).toBeGreaterThan(0)
    expect(pairs.length).toBeGreaterThanOrEqual(all.length)
  })

  it.each(pairs.map(([fx, c]) => [`${fx.name}/${c.id}`, fx, c] as const))(
    '%s',
    (_label, fx, c) => {
      // `case.render` сильнее общего: он и заводится ради случая, у которого
      // отличается СТРУКТУРА, а не пропсы (Modal «открыт»).
      const draw = c.render ?? fx.render
      expect(draw, `у случая нет ни своего render, ни общего у фикстуры`).toBeTruthy()

      /**
       * React ругается В КОНСОЛЬ, а не броском, и это не мелочь: повторяющийся
       * `key`, неизвестный DOM-атрибут, `<div>` внутри `<p>` — всё это рисуется,
       * проходит гейт и остаётся жить. Поймано на DS-127: случай со
       * шкалой промежутков давал три пустых ключа подряд, гейт был зелёным, и
       * увидели это только глазами в консоли живого браузера.
       *
       * Перехват СВОЙ на каждый случай, а не общий на файл: общий свалил бы
       * все жалобы в один тест, и по красному было бы не понять, какая
       * фикстура их принесла.
       */
      const complaints: string[] = []
      const spy = vi.spyOn(console, 'error').mockImplementation((...args: unknown[]) => {
        complaints.push(args.map((a) => String(a)).join(' '))
      })
      try {
        const { container } = render(<>{draw!({ ...fx.props, ...c.props }, {})}</>)
        // Узел появился. Не «выглядит правильно» — см. границы в шапке файла.
        expect(container).toBeTruthy()
      } finally {
        spy.mockRestore()
        cleanup()
      }
      expect(complaints, `React жалуется на разметку случая:\n${complaints.join('\n')}`).toEqual([])
    },
  )
})
