import { describe, it, expect } from 'vitest'
import { readdirSync, existsSync } from 'node:fs'
import { resolve, join } from 'node:path'

/**
 * Обход превью — ВЫБОРКА, и этот гейт существует, чтобы она не притворялась
 * полнотой.
 *
 * Кейс `make measure` «Цель клика» ходит по `previews/*.html` и меряет всё
 * интерактивное. Его собственное обоснование говорит, что список имён «закрыл
 * бы найденные девять и пропустил десятый», — и ровно этим списком набор превью
 * и оказался. На ревью выяснилось, что семь компонентов не встречались НИ В
 * ОДНОМ превью, и каждый из них вёз цель ниже пола: крестик `Alert` 18×18,
 * крестик `Tabs` 18×18, очистка `SearchBar` 18×18, ползунок `Slider` 900×4.
 * Замер при этом был зелёный, а `AGENTS.md`, `conventions.md` и `CHANGELOG`
 * втроём утверждали, что пол держится.
 *
 * Написать превью всем 66 компонентам — не решение: часть из них нечего
 * показывать в отрыве (layout-примитивы), часть живёт только внутри других.
 * Решение — СПИСОК, как у `NOT_CATALOGUED`: пробел, названный поимённо, кто-то
 * читает; пробел, которого нет в коде, не читает никто.
 *
 * **Список ниже — ДОЛГ, а не разрешение.** Каждое имя в нём означает: цели
 * клика этого компонента замером НЕ ПРОВЕРЯЮТСЯ. Добавлять сюда новое имя
 * можно, но это решение, а не формальность; убирать — написав превью.
 */
const NO_PREVIEW = new Set([
  // Раскладочные примитивы и обёртки: показывать в отрыве нечего, своих целей
  // клика не несут вовсе.
  'Box', 'Grid', 'Stack', 'Split', 'PageShell', 'Prose', 'Skeleton',
  // Категория «живут внутри других экранов» ЗАКРЫТА (DS-120): все
  // одиннадцать имён из неё получили превью. Оставшиеся ниже — обоснованные
  // исключения, а не долг.
  // Отображение без интерактива: цифры, значки, полосы.
  'AsOf', 'Avatar', 'CodeBlock', 'EmptyState', 'EstimateMark', 'KeyValueList',
  'LedgerList', 'MetricStrip', 'Money', 'OrgBadge', 'ProgressBar', 'Stat',
  // Графики: цели внутри — легенда и подсказка, они же есть у соседей с превью.
  'BarChart', 'DonutChart', 'LineChart', 'EdgeBundling',
])

const ROOT = resolve(__dirname, '../..')

describe('покрытие превью', () => {
  const components = readdirSync(join(ROOT, 'src/components'), { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)

  it('у каждого компонента есть превью либо имя в списке долга', () => {
    const missing = components.filter(
      (c) => !NO_PREVIEW.has(c) && !existsSync(join(ROOT, 'previews', `${c.toLowerCase()}.html`)),
    )
    expect(
      missing,
      'нет превью и нет записи в NO_PREVIEW — значит цели клика этих компонентов '
      + `замер не видит, и об этом никто не знает: ${missing.join(', ')}`,
    ).toEqual([])
  })

  /**
   * Обратная сторона: имя, оставшееся в списке после того, как превью написали,
   * — это ложь наоборот. Список читают как «сюда замер не смотрит», и лишнее
   * имя заставит писать превью, которое уже есть.
   */
  it('в списке долга нет имён, у которых превью уже написано', () => {
    const stale = [...NO_PREVIEW].filter((c) => existsSync(join(ROOT, 'previews', `${c.toLowerCase()}.html`)))
    expect(stale, `превью есть, а имя всё ещё в NO_PREVIEW: ${stale.join(', ')}`).toEqual([])
  })

  it('в списке долга нет имён несуществующих компонентов', () => {
    const ghosts = [...NO_PREVIEW].filter((c) => !components.includes(c))
    expect(ghosts, `в NO_PREVIEW имя, которого нет в src/components: ${ghosts.join(', ')}`).toEqual([])
  })

  /**
   * Санитар: сам список компонентов обязан быть непустым и правдоподобным.
   * Переедет каталог — три утверждения выше станут утверждениями о пустоте и
   * позеленеют.
   */
  it('каталог компонентов прочитан — иначе всё выше ни о чём', () => {
    expect(components.length).toBeGreaterThan(50)
  })
})
