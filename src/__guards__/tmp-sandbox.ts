import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { resolve } from 'node:path'
import { onTestFinished } from 'vitest'

/**
 * Единственная разрешённая точка создания временного каталога в тестовом коде.
 *
 * До DS-165 каждый гейт звал `mkdtempSync(resolve(tmpdir(), '<префикс>'))`
 * сам, и три из них не сносили созданное вообще: в `/tmp` накопилось 6503
 * каталога, в каждом инициализированный git-репозиторий, то есть счёт шёл на
 * inode (53% на tmpfs), а не на байты. Утечку заметил не гейт, а сосед по
 * машине, у которого от этого кончались inode.
 *
 * Слоёв защиты три, и каждый ловит то, что предыдущий пропускает:
 *
 * 1. `vitest.globalSetup.ts` уводит `TMPDIR` в песочницу прогона и сносит её
 *    целиком — даже забытый снос не покидает пределов одного прогона.
 * 2. Тот же teardown ПАДАЕТ, если песочница на выходе не пуста, и называет
 *    остатки: без этого слоя первый молча поглощал бы каждую будущую утечку.
 * 3. Гейт `tmp-hygiene` требует, чтобы всё создание шло через этот файл, и
 *    отдельно проверяет, что подмена `TMPDIR` вообще доехала до воркера.
 *
 * Почему подмена `TMPDIR`, а не переписывание каждого вызова на явный корень:
 * `os.tmpdir()` в Node читает `process.env.TMPDIR` НА КАЖДОМ вызове, кеша нет.
 * Поэтому дочерние процессы (`git`, `node scripts/release.mjs`), которые пишут
 * во временный каталог сами и о песочнице ничего не знают, уезжают в неё вместе
 * со всеми. Проверять это приходится (слой 3): в PHP тот же приём — no-op, там
 * `sys_get_temp_dir()` кеширует результат на процесс, и потребитель на этом
 * наступил дважды. Разница между языками здесь не теория, а причина гейта.
 */

/** Каталог с авто-сносом по окончании ТЕКУЩЕГО теста. */
export function tempRoot(prefix: string): string {
  const { dir, remove } = tempRootManual(prefix)
  // Вне теста `onTestFinished` бросает — и это правильное поведение: каталог,
  // заведённый в `beforeAll`, живёт дольше теста, и его сносить должен
  // `afterAll` того же файла. Для этого случая есть `tempRootManual`.
  onTestFinished(remove)
  return dir
}

/** Каталог со сносом вручную — для `beforeAll`/`afterAll`, где нет контекста теста. */
export function tempRootManual(prefix: string): { dir: string; remove: () => void } {
  const dir = mkdtempSync(resolve(tmpdir(), prefix))
  return { dir, remove: () => rmSync(dir, { recursive: true, force: true }) }
}

/**
 * Куда Node В ЭТОМ ВОРКЕРЕ на самом деле кладёт временные файлы.
 *
 * Существует ради гейта: `tmp-hygiene` запрещает звать `tmpdir()` в тестовом
 * коде, а проверить доставку `TMPDIR` можно только настоящим вызовом — сравнение
 * `process.env.TMPDIR` с самим собой доказывало бы лишь то, что переменная
 * присвоена, но не то, что Node её видит.
 */
export const effectiveTmpdir = (): string => tmpdir()
