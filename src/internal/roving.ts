/**
 * Roving-навигация по полосе: куда ведёт клавиша и какой сосед не выключен.
 *
 * До 1.42.0 это стояло тремя копиями. `Tabs` умел пропускать `disabled`,
 * `SectionPanel` и `FormTabs` — нет, и совпадали они вплоть до сентинела
 * `ni = -1`. Дефекта в этом не было ровно потому, что у их элементов не было и
 * поля `disabled`: спящая копия, которая проснулась бы в тот день, когда его
 * заведут. Здесь его заводят — и математика одна на всех.
 *
 * Различать два «никуда» обязательно, и это не педантизм: «клавиша не наша» —
 * значит не трогать событие вовсе (иначе полоса съест Tab и ввод текста),
 * «идти некуда» — значит событие наше, `preventDefault` нужен, но выбор не
 * меняется. Один сентинел на оба случая и был бы той самой тихой ошибкой.
 *
 * КРАЙ ЗДЕСЬ НЕ ЗАВОРАЧИВАЕТСЯ, И ЭТО РЕШЕНИЕ, А НЕ УПУЩЕНИЕ. В системе живут
 * обе модели, и делит их не компонент, а ЦЕНА СЛУЧАЙНОГО НАЖАТИЯ:
 *
 * - стрелка ТОЛЬКО двигает фокус — заворачивает. `CommandBar` и `Accordion`,
 *   оба катят свой `% length` и этот модуль не зовут. Промахнулся — фокус
 *   перескочил, отменять нечего.
 * - стрелка ЗАОДНО ВЫБИРАЕТ — упирается в край. Все четверо, кто зовёт этот
 *   модуль: `Tabs`, `FormTabs`, `ToggleGroup`, `SectionPanel` — у каждого сразу
 *   за `rovingTarget` стоит `onSelect`/`onChange`. Заворот с последней формы на
 *   первую переключил бы открытый документ, и цена промаха там другая.
 *
 * Правило проверено по всем шести (DS-127, приёмка волны 4) и исключений
 * не имеет. Записано потому, что снаружи выглядит расхождением: приёмка
 * принесла это как замечание «выровнять», и выравнивание сломало бы полосу
 * форм. Меняешь модель у кого-то одного — сначала посмотри, что делает его
 * стрелка.
 */
export interface RovingItem { disabled?: boolean }

/** Ближайший не-выключенный сосед в направлении `dir`; -1, если такого нет. */
export function nextEnabled(items: readonly RovingItem[], from: number, dir: 1 | -1): number {
  for (let i = from + dir; i >= 0 && i < items.length; i += dir) {
    if (!items[i]?.disabled) return i
  }
  return -1
}

/** Первый (`dir: 1`) или последний (`dir: -1`) не-выключенный; -1, если выключены все. */
export function firstEnabled(items: readonly RovingItem[], dir: 1 | -1): number {
  const start = dir === 1 ? 0 : items.length - 1
  return items[start]?.disabled ? nextEnabled(items, start, dir) : start
}

/**
 * ВХОД В РОУМИНГ: какой элемент полосы получает `tabIndex 0` (DS-221).
 *
 * Правило одно на все полосы с роумингом, и оно записано ЗДЕСЬ, а не в
 * компоненте, потому что расходились компоненты именно в нём:
 *
 * **`tabIndex 0` получает активный элемент — ВЫКЛЮЧЕН ОН ИЛИ НЕТ. Активного
 * нет — первый доступный. Доступных нет — первый.**
 *
 * У `Tabs` формула была `active && !disabled ? 0 : -1`, и выключенная активная
 * вкладка оставляла полосу БЕЗ ВХОДА: `tabIndex 0` не доставался никому, `Tab`
 * перепрыгивал полосу на панель, и человек не узнавал, что вкладки вообще
 * есть. Замер `?c=Tabs&case=closable&data=all-disabled`: четыре вкладки, ноль
 * таб-стопов. То же по смыслу у `SectionPanel` (DS-197).
 *
 * ВЫКЛЮЧЕННОСТЬ УПРАВЛЯЕТ ВЫБОРОМ, А НЕ ДОСТИЖИМОСТЬЮ, и это содержательное
 * различие, а не поблажка. Выключенная вкладка — не выключенная ПОЛОСА:
 * человек обязан дойти до неё, прочитать, что там, и понять, почему ничего не
 * нажимается. Так это и описано в практике ARIA для составных виджетов.
 * Обратная половина обязательна и проверяется отдельно: достижимая
 * выключенная вкладка НЕ становится выбираемой — `aria-disabled` на месте,
 * `Enter`/`Space` выбор не меняют. Без неё правка меняет «недостижимо» на
 * «нажимается и молчит», а это хуже.
 *
 * РОВНО ОДИН вход, никогда ноль и никогда два. Два таб-стопа вместо нуля —
 * это другая поломка, выглядящая как починка.
 *
 * ПОКА ЗОВЁТ ОДИН `Tabs`. `SectionPanel` (DS-197) и `ToggleGroup` (у
 * него свой `anchor`, третья формула того же) переводятся отдельными задачами
 * — правило записано здесь заранее ровно затем, чтобы они не изобрели
 * четвёртую.
 */
export function rovingEntry(items: readonly RovingItem[], active: number): number {
  if (items.length === 0) return -1
  if (active >= 0 && active < items.length) return active
  const first = firstEnabled(items, 1)
  return first >= 0 ? first : 0
}

/**
 * Индекс, на который ведёт клавиша.
 *
 * `null` — клавиша не наша, событие не трогать. `-1` — клавиша наша, но идти
 * некуда (край полосы или все соседи выключены).
 */
export function rovingTarget(
  items: readonly RovingItem[],
  from: number,
  key: string,
  orientation: 'vertical' | 'horizontal' = 'horizontal',
): number | null {
  const next = orientation === 'vertical' ? 'ArrowDown' : 'ArrowRight'
  const prev = orientation === 'vertical' ? 'ArrowUp' : 'ArrowLeft'
  if (key === next) return nextEnabled(items, from, 1)
  if (key === prev) return nextEnabled(items, from, -1)
  if (key === 'Home') return firstEnabled(items, 1)
  if (key === 'End') return firstEnabled(items, -1)
  return null
}
