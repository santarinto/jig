import { describe, it, expect } from 'vitest'
import { heatLevel, HEAT_LEVELS, assertHeatThresholds } from './heatLevel.js'

/**
 * Границы порогов таблицей. Через рендер календаря они проверялись косвенно и
 * не полностью: чтобы увидеть «значение ровно на пороге», надо было подобрать
 * дату, отрисовать месяц и вычитать уровень из имени класса (DS-117).
 */

/** Дефолт компонента — он же самый интересный набор границ. */
const T = [1, 3, 6, 10]

describe('heatLevel: пороги', () => {
  const cases: Array<[string, number, number]> = [
    ['ноль — нулевая ступень', 0, 0],
    ['ниже первого порога дробным', 0.9, 0],
    ['РОВНО первый порог — уже первая ступень', 1, 1],
    ['между первым и вторым', 2, 1],
    ['ровно второй', 3, 2],
    ['ровно третий', 6, 3],
    ['ровно четвёртый', 10, 4],
    ['выше последнего', 1000, 4],
    ['отрицательное — нулевая ступень', -5, 0],
  ]
  for (const [name, value, want] of cases) {
    it(name, () => expect(heatLevel(value, T)).toBe(want))
  }

  it('порог ВКЛЮЧИТЕЛЬНЫЙ, и это не вкусовщина', () => {
    // На исключительном пороге день с одной поездкой красился бы как день без
    // поездок — то есть «есть данные» стало бы неотличимо от «данных нет».
    expect(heatLevel(1, [1])).toBe(1)
    expect(heatLevel(0.999, [1])).toBe(0)
  })
})

describe('heatLevel: края набора порогов', () => {
  it('пустые пороги — всегда нулевая ступень', () => {
    // Текущее поведение, зафиксировано до мутаций: считать нечего, ступень одна.
    expect(heatLevel(0, [])).toBe(0)
    expect(heatLevel(1_000_000, [])).toBe(0)
  })

  it('порогов больше, чем ступеней рампа, — уровень кламплен сверху', () => {
    // Иначе получился бы класс `ds-heat__swatch--7`, которому не соответствует
    // ни один токен `--ds-heat-*`, и ячейка осталась бы вовсе без цвета.
    //
    // Кламп проверяется как свойство ЧИСТОЙ функции, а не как ответ компонента
    // на ошибку потребителя: с DS-208 такой ряд до `Heatmap` не доходит —
    // он не компилируется (`HeatThresholds`) и бросает
    // (`assertHeatThresholds`). Здесь остаётся прямой вызов из системы, и
    // функция обязана быть тотальной.
    const many = [1, 2, 3, 4, 5, 6, 7]
    expect(heatLevel(100, many)).toBe(HEAT_LEVELS - 1)
    expect(heatLevel(7, many)).toBe(HEAT_LEVELS - 1)
    // Сосед с известным значением: до клампа ряд обязан расти как обычно.
    expect(heatLevel(3, many)).toBe(3)
  })

  it('ряд не убывает: каждое следующее значение не ниже предыдущего', () => {
    // Монотонность — то, ради чего рампу и дан ровный шаг в L*. Проверяется
    // тут напрямую, а не вычитанием чисел из имён классов.
    let prev = -1
    for (let v = -3; v <= 15; v++) {
      const lv = heatLevel(v, T)
      expect(lv, `уровень упал на значении ${v}`).toBeGreaterThanOrEqual(prev)
      prev = lv
    }
    expect(prev).toBe(HEAT_LEVELS - 1)
  })

  it('пороги ниже нуля работают: клампа снизу нет', () => {
    // Компонент отрицательные пороги не запрещает — «дельта к прошлой неделе»
    // законный ряд. Ступень ноль тогда достаётся значениям ниже -5.
    expect(heatLevel(-6, [-5, 0])).toBe(0)
    expect(heatLevel(-5, [-5, 0])).toBe(1)
    expect(heatLevel(0, [-5, 0])).toBe(2)
  })
})

/**
 * Граница без типа (DS-208). Тип держит вызов у потребителя, а сюда
 * приходит всё, что типа не имеет: `any`, JS, пороги из конфига.
 *
 * Проверяется РАЗЛИЧЕНИЕМ, а не одним броском: «бросает на пяти» верно и у
 * функции, которая бросает всегда, — поэтому рядом стоят четыре и ноль, где
 * молчание обязательно.
 */
describe('assertHeatThresholds: порогов не больше четырёх', () => {
  it('пять и больше — бросок, и он называет ЧИСЛО, а не «слишком много»', () => {
    expect(() => assertHeatThresholds([1, 2, 3, 4, 5])).toThrow(/порогов 5/)
    expect(() => assertHeatThresholds([1, 2, 3, 4, 5, 6, 7])).toThrow(/порогов 7/)
  })

  it('четыре и меньше — молча', () => {
    expect(() => assertHeatThresholds([1, 2, 3, 4])).not.toThrow()
    expect(() => assertHeatThresholds([-5, 0])).not.toThrow()
    expect(() => assertHeatThresholds([])).not.toThrow()
  })
})
