/**
 * Повёрнутый ряд подписей оси: −45°, якорь `end` у своей точки.
 *
 * Жил в `BarChart` (категории вертикального графика, DS-280). Общим стал
 * на DS-296: ось X `LineChart` на узком холсте вырождалась в ОДНУ подпись,
 * и ответ тот же — повернуть ряд целиком. Один вопрос «подписи не помещаются по
 * ширине» — один ответ в системе: тот же угол, тот же зазор, та же высота
 * строки, иначе два графика на одном дашборде поворачивали бы подписи по-разному.
 *
 * Геометрия. Подпись с якорем `end` повёрнута вокруг своей опорной точки, конец
 * текста остаётся на точке, хвост уходит вниз-влево. От опорной точки коробка
 * текста тянется влево и вниз на `sin45 × (ширина + строка)` — строка берётся
 * целиком, а не высотой глифа над базовой линией: запас, а не точность, и
 * именно так поле считал `BarChart` с 280.
 */

/** Угол поворота, градусы; в разметке — `rotate(-ROT_DEG …)`. */
export const ROT_DEG = 45
/** sin 45° = cos 45°: и снос вниз, и вылет влево у −45° считаются им одним. */
export const ROT_SIN = Math.SQRT1_2
/** Зазор от низа поля данных до опорной точки повёрнутой подписи, px при шкале 1. */
export const ROT_GAP = 10
/** Высота строки подписи в долях её размера — поперечник повёрнутой коробки. */
export const ROT_LINE_EM = 1.2

/** Насколько повёрнутая подпись уходит от опорной точки влево (и вниз). */
export function rotatedReach(width: number, lineH: number): number {
  return ROT_SIN * (width + lineH)
}

/** Нижнее поле под повёрнутым рядом: зазор до опоры плюс самая длинная подпись. */
export function rotatedGutter(longest: number, lineH: number, k: number): number {
  return ROT_GAP * k + rotatedReach(longest, lineH)
}
