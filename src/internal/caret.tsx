import { ChevronDown, ChevronRight } from '../icons/glyphs.js'
import '../styles/caret.css'

/**
 * Знак «это раскрывается» — один на систему.
 *
 * До DS-144 один смысл был исполнен восемью способами: четыре размера,
 * три цвета и две РАЗНЫЕ ФИГУРЫ — залитый треугольник `▸` против штрихового
 * шеврона. Рядом на одном экране (таблица внутри аккордеона) это читалось как
 * два разных знака для одной мысли.
 *
 * Разошлись они не по небрежности: `▸` рисует ШРИФТ, а не мы. Вес, посадка по
 * базовой линии и оптический центр приходят со шрифтом, поэтому держать
 * внешний вид знака, который ты не рисуешь, нельзя в принципе. Отсюда SVG —
 * и отсюда же гейт `inline-icons`, запрещающий текстовый знак раскрытия.
 *
 * Размера здесь нет НАМЕРЕННО. `Glyph` отдаёт его атрибутом `width`, то есть
 * голыми CSS-пикселями мимо `--ds-ui-scale`: при шкале 1.5 текст растёт, а
 * шеврон нет. Размер живёт в `styles/caret.css` и задаётся стилем, который
 * атрибут перебивает.
 */
export type CaretKind = 'branch' | 'panel' | 'menu'

/**
 * `'native'` — состояние раскрытия держит DOM, а не React: `LedgerList` строит
 * раскрытие на `<details>` и вообще без JS, поэтому момента поставить `is-open`
 * у него нет. Поворот в этом случае описывает сам компонент, от `[open]`.
 * Значение названо, а не выведено из отсутствия пропа: забытый `open` иначе
 * молча дал бы неподвижный знак, и гейт такого не поймает.
 */
export type CaretOpen = boolean | 'native'

export type CaretProps =
  /** Раскрывается ВЕТКА или СТРОКА: `Tree`, `DataTable`, `PivotTable`,
   *  `AgentTranscript`, `LogViewer`, `SideNav`, `LedgerList`. Растёт вправо-вниз
   *  от своего узла — знак смотрит вправо и поворачивается на 90°. */
  | { kind: 'branch'; open: CaretOpen; className?: string }
  /** Раскрывается ПАНЕЛЬ или секция на всю ширину: `Accordion`. Отличие от
   *  ветки настоящее — не «вправо от узла», а «вниз под заголовком», — поэтому
   *  знак смотрит вниз и переворачивается на 180°.
   *
   *  СТОИТ В НАЧАЛЕ заголовка, а не в конце (DS-262), и это не про вкус.
   *  Глиф у `panel` и у `menu` ОДИН И ТОТ ЖЕ — `ChevronDown`; пока `panel`
   *  стоял справа, свёрнутая секция в покое была байт в байт селектом: тот же
   *  знак, то же место, а заливка и радиус у `.ds-accordion` и `.ds-input` и
   *  так одни и те же токены. Потребитель сообщил об этом с
   *  живой страницы, и человек на СЛЕПОМ взгляде назвал блок «контролом»
   *  раньше, чем словом «раскрыть».
   *
   *  Различать их обязано ПОЛОЖЕНИЕ, потому что различать нечем больше:
   *  заливками системы это не берётся (`--ds-section-bar` к `--ds-surface` —
   *  1.19 в светлой, 1.17 в тёмной), а рамка не берёт порога и сама по себе
   *  (DS-267). Положение — признак КАТЕГОРИИ, а не величины, и потому
   *  здесь единственный честный носитель.
   *
   *  С `branch` при этом не сливается, хотя оба теперь слева: у ветки знак
   *  смотрит вправо и поворачивается на 90°, у панели вниз и на 180°. */
  | { kind: 'panel'; open: CaretOpen; className?: string }
  /** Есть ВЫПАДАЮЩИЙ СПИСОК: `Select`, `Combobox`. Знак означает не состояние,
   *  а «тут есть меню»: раскрытие уже объявлено и поповером, и `aria-expanded`,
   *  поэтому поворота НЕТ — движение не несло бы сведений. */
  | { kind: 'menu'; open?: never; className?: string }

export function Caret(props: CaretProps) {
  const { kind, className } = props
  const Glyph = kind === 'branch' ? ChevronRight : ChevronDown
  const cls = [
    'ds-caret',
    kind !== 'menu' && `ds-caret--${kind}`,
    kind !== 'menu' && props.open === true && 'is-open',
    className,
  ].filter(Boolean).join(' ')
  return <Glyph className={cls} aria-hidden="true" />
}
