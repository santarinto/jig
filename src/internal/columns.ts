/**
 * Модель колонок таблиц: типы `Column<T>` и helper'ы раскладки, общие для
 * `DataTable` и `LedgerList`. Вынесены сюда, чтобы `LedgerList` не тянул за собой
 * `DataTable.tsx` (и не ловил цикл), а helper'ы оставались чистыми — без
 * зависимости от состояния/пропсов/JSX конкретного компонента.
 *
 * `Tree` живёт на своём типе колонок (`TreeColumn`: заголовок — `ReactNode`,
 * выравнивание — `start`/`end`, ключа строки нет) и берёт отсюда только
 * `colWidth`. Разбор ширины общий не ради экономии строк, а потому что разъехался
 * он уже дважды: `Column.width` (DS-82) и `TreeColumn.width` (DS-83)
 * чинились по отдельности, хотя закон один.
 *
 * `DataTable/index.ts` реэкспортирует типы через `DataTable.tsx` — публичный путь
 * импорта у потребителей пакета не меняется.
 */
import type * as React from 'react'
import type { RowAction } from './action.js'

/** Ступени скрытия колонки. Две, потому что третьей ни у кого нет. */
export type HideBelow = 'sm' | 'md'

/**
 * `RowAction` живёт в `action.ts` с 4.3.x (DS-358): это одно из четырёх
 * сужений общего `ActionBase`, а не собственный тип таблицы. Реэкспорт оставлен
 * здесь, чтобы путь импорта у потребителя (`DataTable/index.ts`,
 * `LedgerList/index.ts`) не менялся.
 */
export type { RowAction } from './action.js'

/**
 * Край, к которому прижато содержимое колонки.
 *
 * Словарь ЛОГИЧЕСКИЙ, а не физический (DS-86): число прижимается к концу
 * СТРОКИ, а не к правому краю монитора, и в RTL `right` означал бы не то. То же
 * говорит и CSS — `text-align` понимает `start`/`end` нативно, так что
 * физический словарь ещё и переводился в логический по дороге.
 *
 * `Tree` жил на этом словаре с самого начала (`TreeColumn.align`), таблицы — на
 * физическом, и один признак колонки в одной системе назывался двумя словами:
 * потребитель, ставящий рядом `DataTable` и `Tree`, обязан был помнить, какое
 * слово где. Победил не старший, а верный.
 */
export type ColAlign = 'start' | 'end'

interface ColumnBase<T> {
  header: string
  /**
   * Подпись есть, глазами не нужна: колонка иконок состояния, аватаров,
   * кнопок — та, чей смысл виден по содержимому.
   *
   * Заведено потому, что до DS-80 сказать это было НЕЧЕМ: `header`
   * обязателен, и «подписи не надо» выражалось единственным доступным
   * способом — пустой строкой. То есть пустой `<th>`, на котором горел axe,
   * производил не потребитель, а форма пропа. Проп, вынуждающий писать
   * неправильное, чинится добавлением правильного, а не запретом.
   *
   * Заголовок при этом остаётся ОБЯЗАТЕЛЬНЫМ текстом: скрывается показ, а не
   * имя. Пустой `header` бросает и с `headerHidden`, и без него — скрывать
   * пустоту незачем, а колонка без имени для диктора остаётся безымянным
   * столбцом ровно так же.
   */
  headerHidden?: boolean
  align?: ColAlign
  numeric?: boolean
  sortable?: boolean
  /** Различитель с `ActionColumn`: у колонки данных/дисплея действий нет. */
  actions?: never
  render?: (row: T) => React.ReactNode
  /**
   * Спрятать колонку, когда таблице тесно.
   *
   * Порог считается от **ширины таблицы**, а не вьюпорта: таблица может стоять
   * в узкой панели на широком мониторе, и медиазапрос там не спрятал бы ничего.
   *
   * Прячется и заголовок, и все ячейки колонки — врозь они разъехались бы по
   * столбцам, и это выглядело бы как испорченные данные, а не как скрытая
   * колонка.
   */
  hideBelow?: HideBelow
  /**
   * Ширина колонки: число (пиксели интерфейса) или любое CSS-значение
   * (`'12rem'`, `'20%'`, `'calc(…)'`).
   *
   * Число едет по `--ds-ui-scale`, как `height` у BarChart, `size` у
   * DonutChart и `width` у SideNav и Skeleton. Голое `'9rem'` — не едет, и это
   * заметно не сразу: высота строки задана `--ds-h-compact`, то есть
   * `calc(rem * var(--ds-ui-scale))`, и под `.ds-scale` строки вырастают, а
   * колонки стоят. В ту же ширину влезает меньше текста при большей высоте
   * строки — ровно тот разъезд сетки, ради которого ширины и задавали
   * (DS-82).
   *
   * Строка форвардится дословно: потребитель, которому нужна ширина, НЕ
   * зависящая от масштаба (доля `'20%'`, `'max-content'`), просит её строкой —
   * как в Skeleton.
   *
   * Задание ширины **хотя бы одной** колонке переводит таблицу в
   * `table-layout: fixed`. Отдельного пропа на режим раскладки нет намеренно:
   * задать ширины и забыть включить режим — значит получить пропсы, которые
   * заданы и молча ничего не делают (`auto` считает колонки по содержимому и
   * ширины игнорирует). Один проп сделать наполовину нельзя.
   *
   * Зачем это вообще: у `auto`-раскладки текстовая колонка забирает место у
   * числовых — «Продукты» растягивается, суммы жмутся. Это поведение по
   * умолчанию, а не особенность данных, поэтому колонка с суммами есть у
   * любого потребителя таблиц.
   *
   * Ширина едет на `<col>`, а не на `<th>`: в `fixed`-раскладке ширины берутся
   * из первой строки таблицы, и `<colgroup>` — единственное место, где они
   * заданы для колонки целиком, а не для конкретной ячейки. Колонку без
   * `width` браузер делит между собой поровну из остатка — то есть `auto`
   * внутри `fixed` выражается отсутствием значения, а не словом `'auto'`.
   */
  width?: number | string
  /**
   * Разрешить содержимому колонки переноситься.
   *
   * Значим только в `fixed`-раскладке (то есть когда хоть у одной колонки
   * задана `width`). В `auto` переносится и так — там проп ничего не меняет,
   * потому что менять нечего.
   *
   * Умолчание `fixed`-раскладки — однострочные ячейки с многоточием: задание
   * ширины и есть заявка на ровную сетку, а строка, выросшая вдвое от одного
   * длинного значения, эту сетку и ломает. `wrap` — оговорка к умолчанию для
   * колонки, где важнее прочитать значение целиком, чем удержать высоту:
   * название, комментарий, статус словами.
   *
   * Снимает вместе с `nowrap` и многоточие. Иначе колонка обещала бы показать
   * значение целиком и сокращала бы его: `white-space: normal` многоточие не
   * отменяет — оно рисуется на неразрывном слове, вылезшем за ячейку (измерено
   * сравнением пикселей). Такое слово вместо этого разрывается по буквам,
   * иначе оно наедет на соседнюю колонку.
   */
  wrap?: boolean
}

/** Колонка, за которой стоит поле строки. Форма, существовавшая до 1.18.0. */
export interface DataColumn<T> extends ColumnBase<T> {
  key: keyof T & string
  id?: never
  rowHeader?: never
  /** Здесь форматируют `render`-ом: две формы для одного — молчаливый выбор одной. */
  format?: never
}

/**
 * Колонка, НАЗЫВАЮЩАЯ строку: код документа, наименование, имя сотрудника.
 * Её ячейка — `<th scope="row">`, а не `<td>`: диктор объявляет её при переходе
 * по ячейкам строки, и это верно само по себе, без всякой кликабельности.
 *
 * Она же — место клавиатурного пути строки. При `onRowClick` содержимое такой
 * ячейки заворачивается в кнопку, и доступным именем становится само значение
 * строки. Придумывать `aria-label` не нужно и НЕЛЬЗЯ: соседний чекбокс выбора
 * показывает, чем это кончается — он читает диктору `id` строки, потому что
 * человеческого имени у компонента нет, а взять его неоткуда, пока потребитель
 * не сказал, какая колонка его несёт.
 *
 * **`render` здесь запрещён типом, и это главное решение формы.** Содержимое
 * назначенной ячейки уходит внутрь `<button>`, а `render` отдаёт произвольный
 * узел — то есть ссылку или свою кнопку. Это ровно шов `SideNav.renderItem`,
 * который в этой же системе дал `<a><button>` в боевой навигации потребителя и
 * прожил сломанным столько, сколько существовала навигация: мышью кликается,
 * страница открывается, визуально всё цело, а таб-стопов вдвое больше. На нём
 * родился гейт `no-nested-interactive`, и его вывод записан там же — без шва,
 * отдающего чужой узел внутрь, вложенности не может быть ПО ПОСТРОЕНИЮ, и
 * проверять нечего. Здесь выбрано построение, а не проверка.
 *
 * Следствие, которое надо принять целиком: назначить можно только колонку,
 * печатающую поле строки. Нужен бейдж или моноширинность в ячейке кода — это
 * класс на колонке, а не `render`.
 */
export interface RowHeaderColumn<T> extends Omit<ColumnBase<T>, 'render'> {
  key: keyof T & string
  id?: never
  rowHeader: true
  render?: never
  /**
   * Напечатать поле НЕ КАК ЕСТЬ: дата, номер с префиксом, единицы.
   *
   * Это `render`, у которого сужен возвращаемый тип, — подпись та же, `(row: T)`.
   * Запрет на `render` держался ровно на одном: он отдаёт ПРОИЗВОЛЬНЫЙ УЗЕЛ, то
   * есть чужую ссылку или кнопку внутрь `<button>` строки. Сузив возврат до
   * строки, причину запрета убираешь по построению — вложенности нет, потому что
   * вкладывать нечего, а не потому, что это кто-то проверяет.
   *
   * Заведено по факту от потребителя: в журнале
   * веса ВСЕ четыре колонки шли через `render` — формат даты, бейдж «не верить»,
   * единицы, — и назначить строке имя было НЕЧЕМ. Пришлось завести второе поле
   * `dateLabel` в модели строк. То есть рядом с верным запретом стояла пустота:
   * колонка, называющая строку, у потребителя чаще всего форматированная, а не
   * голое поле.
   *
   * Сортировка `format` не видит и видеть не должна: она идёт по `row[key]`, то
   * есть по ISO-дате, а не по «25 авг». Это и есть причина, по которой формат —
   * отдельная функция, а не второе поле в модели: второе поле пришлось бы ещё и
   * сортировать правильно.
   *
   * При `onRowClick` напечатанное становится доступным ИМЕНЕМ строки — как и
   * раньше, только теперь это «25.08.2026», а не `2026-08-25T00:00:00Z`.
   */
  format?: (row: T) => string
}

/**
 * Колонка без поля в строке: прогресс из двух чисел, кнопки действий, иконка
 * состояния.
 *
 * **Имя свойства другое (`id`, не `key`) намеренно** — это то, что делает союз
 * различимым. Ослабь мы `key` до `string`, и опечатка в настоящем ключе
 * (`nmae`) перестала бы быть ошибкой типов: она стала бы валидной
 * display-колонкой, рисующей пустоту.
 *
 * `render` обязателен: без него колонке нечего показать, а проп, который задан
 * и молча ничего не делает, — худший вид дефекта, чем ошибка компиляции.
 */
export interface DisplayColumn<T> extends ColumnBase<T> {
  id: string
  key?: never
  render: (row: T) => React.ReactNode
  /** Назвать строку может только колонка с полем строки — см. `RowHeaderColumn`. */
  rowHeader?: never
  /** См. `DataColumn.format`: здесь для этого есть `render`. */
  format?: never
}

/**
 * Колонка действий: ряд кнопок над строкой (изменить, удалить). Данных в строке
 * ей не нужно — `actions` получает строку целиком, поэтому фиктивное поле в
 * модели строк (`actions: row.id` только ради типа) больше не требуется.
 *
 * Отдельная от `DisplayColumn` не ради синтаксиса, а ради поведения, которое
 * `render` руками не даёт бесплатно: ячейка сама гасит всплытие клика и
 * клавиатурного Enter, чтобы клик по «удалить» не открыл строку. Кто уходит на
 * `render` — берёт это гашение на себя; `actions` его встраивает.
 *
 * `render` здесь `never`: колонка либо декларативная (`actions`), либо ручная
 * (`DisplayColumn` с `render`). Задать оба — противоречие, и пусть это будет
 * ошибкой типов, а не молчаливым выбором одного из двух.
 */
export interface ActionColumn<T> {
  id: string
  key?: never
  render?: never
  numeric?: never
  sortable?: never
  actions: (row: T) => RowAction[]
  /** Колонка действий строку не называет: в ней кнопки, а не её имя. */
  rowHeader?: never
  /** Печатать нечего: в ячейке кнопки. */
  format?: never
  /**
   * Подпись есть, глазами не нужна — как у прочих колонок.
   *
   * Был запрещён типом («скрывать нечего: подпись невидима по умолчанию»), и
   * ровно это оказалось дырой (DS-137, повод — потребитель). Умолчание
   * невидимо, но оно РУССКОЕ: `Действия` зашито в компоненте. Заданный `header`
   * делает подпись видимой — то есть сказать «моё имя, по-прежнему невидимое»
   * было нечем, и на `?_locale=en` колонка объявлялась диктору по-русски на
   * шести маршрутах потребителя. Обхода не было ни одного.
   *
   * Проп, вынуждающий писать неправильное, чинится добавлением правильного, а
   * не запретом — тот же довод, которым `headerHidden` заведён на DS-80.
   * Умолчание не тронуто: без `header` колонка по-прежнему называет себя сама.
   *
   * Это шов ПОД ОДНУ колонку, а не локализация пакета. Русских строк, которые
   * компонент говорит от себя, в системе около тридцати (`Выбор` в этой же
   * таблице, `Закрыть`, `Найти`, `Загрузка`); словарь на пакет — отдельное
   * решение, и проп-однодневка под него был бы удалён в том же релизе, в
   * котором словарь появится.
   */
  headerHidden?: boolean
  /** По умолчанию пустой — колонку действий обычно не подписывают. */
  header?: string
  /** По умолчанию `'end'`. */
  align?: ColAlign
  hideBelow?: HideBelow
  /**
   * Переносов тут не бывает: внутри кнопки, а не текст. Запрещено явно, а не
   * опущено, — иначе проп молча ничего не делал бы. По той же причине у
   * колонки действий отключено и многоточие (`text-overflow: clip`).
   */
  wrap?: never
  /**
   * Ширина колонки — см. `width` у колонок данных. Колонке действий она нужна
   * чаще прочих: ряд кнопок имеет свою естественную ширину, и отдавать ему
   * долю по содержимому заголовка (у колонки действий он обычно пустой) —
   * значит получить то узкую, то разъезжающуюся колонку.
   */
  width?: number | string
}

export type Column<T> = DataColumn<T> | RowHeaderColumn<T> | DisplayColumn<T> | ActionColumn<T>

/** Колонка действий против колонки данных/дисплея: только у первой есть `actions`. */
export function isActionColumn<T>(c: Column<T>): c is ActionColumn<T> {
  return typeof (c as ActionColumn<T>).actions === 'function'
}

/**
 * Текст ячейки, называющей строку: `format`, если задан, иначе поле как есть.
 *
 * Функцией, а не двумя ветками по месту: имя строки печатается в ДВУХ местах —
 * внутри кнопки при `onRowClick` и без неё, — и разошедшиеся копии дали бы
 * форматирование в одном режиме и голое поле в другом. Ровно тот класс дефекта,
 * который не видно, пока не переключишь режим.
 */
export function rowHeaderText<T>(c: RowHeaderColumn<T>, row: T): string {
  return c.format ? c.format(row) : String(row[c.key])
}

/** Колонка, называющая строку: её ячейка — `<th scope="row">`. */
export function isRowHeader<T>(c: Column<T>): c is RowHeaderColumn<T> {
  return c.rowHeader === true
}

/**
 * Ключ колонки для React и для сверки с `sortKey`. `id === undefined` сужает
 * союз к `DataColumn`, потому что у `DisplayColumn` и `ActionColumn` он `string`
 * и отсутствовать не может.
 */
export function colId<T>(c: Column<T>): string {
  return c.id === undefined ? c.key : c.id
}

/**
 * Класс скрытия по тесноте. Отдельно от `colClass`, потому что носителей ТРИ, а
 * не два: `<th>`, `<td>` и `<col>` (DS-138). Прочие классы колонки
 * (`__end`, `__num`, `__wrap`) — про содержимое ячейки, и на `<col>` им делать
 * нечего: в `table-layout: fixed` браузер берёт с колонки только ширину,
 * фон и границу.
 *
 * Функция, а не строка по месту: имя класса обязано совпасть у трёх носителей
 * до символа. Разойдись оно — колонка спрячет ячейки и оставит трек (ровно
 * DS-138) либо уберёт трек и оставит ячейки, а обе половины по
 * отдельности выглядят как «скрытие почти работает».
 */
export function colHideClass<T>(block: string, c: Column<T>): string | undefined {
  return c.hideBelow ? `${block}__hide-${c.hideBelow}` : undefined
}

/**
 * Классы выравнивания/скрытия колонки, общие для `<th>`/`<td>` (они обязаны
 * совпадать). Первый аргумент — блок-владелец (`'ds-table'`, `'ds-ledger'`):
 * классы префиксуются им, чтобы каждый компонент эмитил только свои
 * (гейт block-ownership), а логика оставалась одна.
 */
export function colClass<T>(block: string, c: Column<T>, ...extra: (string | false | undefined)[]): string | undefined {
  assertAlign(c.align)
  assertHeader(c)
  // Колонка действий тяготеет к концу строки по умолчанию (`align: 'start'`
  // возвращает к началу), как её и держали руками во всех потребителях.
  const atEnd = c.numeric || c.align === 'end' || (isActionColumn(c) && c.align !== 'start')
  return [
    ...extra,
    // ДВА класса, а не один. `__num` раньше означал сразу край и цифровую
    // типографику (`tnum`), то есть ставился при `align: 'end'` на текстовой
    // колонке и включал ей то, чего никто не просил. Класс, означающий две
    // вещи, — та же болезнь, что `width`, кодировавший три решения
    // (DS-88): её нельзя чинить в соседнем месте и оставлять здесь.
    atEnd && `${block}__end`,
    c.numeric && `${block}__num`,
    colHideClass(block, c),
  ].filter(Boolean).join(' ') || undefined
}

/**
 * Физический словарь выравнивания удалён без периода совместимости
 * (CLAUDE.md), и типы это ловят — но только там, где они есть. У потребителя
 * колонки часто собираются динамически и проходят через `any`, и тогда
 * `'right'` просто не равно `'end'`: колонка молча уехала бы к началу строки,
 * то есть проп остался бы заданным и перестал действовать. Это худший исход
 * из возможных — хуже и ошибки компиляции, и падения.
 *
 * Поэтому проверка в рантайме, и именно бросок: вернуть «как было» нельзя (мы
 * ровно от этого уходим), а тихо выбрать сторону — значит соврать.
 */
/**
 * Пустой заголовок у колонки, которую компоненту назвать нечем.
 *
 * Колонка действий сюда не попадает намеренно: её имя следует из типа
 * (`actions` гарантирует, что это действия), и пустой `header` там означает
 * «возьми умолчание», а не «имени нет». Схлопни эти два случая — и либо
 * колонка действий начнёт бросать на ровном месте, либо обычная перестанет.
 *
 * Бросок, а не молчание: пустой `<th>` — это `empty-table-header` у axe и
 * безымянный столбец у диктора, то есть дефект, который на экране не виден
 * вовсе. Тихо оставить его значило бы оставить навсегда: смотреть на такую
 * колонку глазами бесполезно, она выглядит правильно.
 */
function assertHeader<T>(c: Column<T>): void {
  if (isActionColumn(c)) return
  if (c.header.trim()) return
  throw new Error(
    `jig: DataTable — у колонки "${colId(c)}" пустой header. Пустой <th> `
    + 'диктор объявляет безымянным столбцом (axe: empty-table-header). Напишите '
    + 'подпись и добавьте headerHidden: true, если её не должно быть видно '
    + '(DS-80).',
  )
}

function assertAlign(align: unknown): void {
  if (align === undefined || align === 'start' || align === 'end') return
  throw new Error(
    `jig: align="${String(align)}" — физического словаря выравнивания больше нет. `
    + `'left' → 'start', 'right' → 'end' (DS-86).`,
  )
}

/**
 * Переносится ли содержимое колонки в `fixed`-раскладке.
 *
 * **Умолчание выводится из ЗАДАННОСТИ ширины, а не из режима таблицы**
 * (DS-88). Раньше однострочность включалась режимом: ширины у одной
 * колонки хватало, чтобы перестали переноситься все — включая ту, у которой
 * ширины нет. Счёт по потребителям показал, что правило применялось наоборот:
 * ширину задают КОРОТКОМУ (код, статус, badge, кнопки), а длинный текст
 * оставляют делить остаток. В собственном демо системы
 * (`demo/constraints-lab.tsx`) ширины стояли у badge и у кнопок, а
 * однострочность досталась колонкам «Правило» и «Условие» — прозе.
 *
 * Явное значение побеждает вывод в обе стороны: `wrap: true` возвращает
 * перенос колонке с шириной, `wrap: false` — однострочность колонке без неё.
 * Поэтому `??`, а не `||`: на `||` значение `false` схлопывалось бы с
 * незаданным, и вторая половина пропа молча перестала бы существовать.
 *
 * Колонка действий не переносится никогда: внутри кнопки, а не текст.
 * `wrap?: never` в её типе запрещает проп потребителю, но компоненту навесить
 * класс не мешает — поэтому исключение живёт здесь, а не только в типах.
 *
 * **Числовая колонка из умолчания тоже исключена, и это найдено замером, а не
 * рассуждением.** Разряды в системе разделены обычным пробелом (`'12 400,00'`
 * в фикстуре, `toLocaleString` даёт неразрывный не везде), и в узкой колонке
 * сумма разрывается: замерено 34px против эталонных 32px в той же колонке без
 * переноса. Разорванное по разрядам число читается как ДВА числа — ошибка,
 * которая себя не показывает, тогда как многоточие показывает. Тем же доводом
 * выбрано и само умолчание, так что исключение из него — не оговорка, а то же
 * правило: перенос уместен там, где содержимое — текст.
 *
 * Исключён только ВЫВОД: явный `wrap: true` на числовой колонке работает —
 * потребитель, у которого в ней не сумма, а что-то читаемое, вправе сказать
 * это словом.
 *
 * Функция НЕ спрашивает, включена ли раскладка: правило переноса живёт в листе
 * под `.ds-table--fixed`, а класс вне `fixed` был бы мусором в разметке каждой
 * колонки у каждого потребителя без ширин. Это решает вызывающий — он же
 * считает `fixedLayout`.
 */
export function colWraps<T>(c: Column<T>): boolean {
  if (isActionColumn(c)) return false
  return c.wrap ?? (!hasWidth(c) && !c.numeric)
}

/**
 * Ширина колонки в CSS-значение.
 *
 * Число — размер интерфейса и потому едет по `--ds-ui-scale`; строка уходит
 * дословно. Тот же разбор, что у `Skeleton`, и та же причина: числовой размер,
 * отданный React'у как есть, превращается в голые пиксели и молча выпадает из
 * масштаба, пока всё вокруг него масштабируется.
 *
 * Результат годится и как ширина `<col>` (`DataTable`, `LedgerList`), и как трек
 * `grid-template-columns` (`Tree`): `calc()` законен в обоих местах.
 */
export function colWidth(w: number | string): string {
  return typeof w === 'number' ? `calc(${w}px * var(--ds-ui-scale, 1))` : w
}

/**
 * Задана ли ширина. Именно ЗАДАНА, а не истинна: `width: 0` — законное
 * значение (колонка-нитка под маркер состояния), и на `!!c.width` оно
 * оказывалось неотличимо от незаданной ширины. Раскладка тогда не включалась,
 * а ширины прочих колонок молча переставали действовать — то есть проп был
 * задан и ничего не делал у ВСЕЙ таблицы, а не только у своей колонки.
 */
export function hasWidth<T>(c: Column<T>): boolean {
  return c.width !== undefined
}

/**
 * Пол ширины колонки в `fixed`-раскладке — как `min-width` ТАБЛИЦЫ.
 *
 * Колонка без `width` получает ОСТАТОК, и пола у остатка нет: при контейнере
 * 342px и заданных 192+80+64 четвёртая колонка приходила 6px (DS-137,
 * замер потребителя — «Note» показывал 0 символов из 30, ячейка «Review» 20 из
 * 89). Столбец при этом объявлен диктору и подписан в шапке: данные невидимы, а
 * отсутствия их ничто не сообщает.
 *
 * **Место правки выбрано замером, а не вкусом — остальные три не работают.**
 * - `min-width` на ЯЧЕЙКЕ первой строки в `fixed`-раскладке игнорируется:
 *   колонка так и приходит 6px.
 * - Пропорциональная уступка (`min(192px, calc((100% - 96px) * .57))` на
 *   `<col>`) не работает НИКАК: Chrome оставляет значение в `style.width`, а
 *   раскладке отдаёт `auto`. На `<col>` живут только голая длина и голый
 *   процент — всё, что содержит процент внутри `calc()`/`min()`/`max()`, а
 *   также `max-content`, `min-content`, `fit-content()`, отбрасывается молча.
 * - Прокрутка обёртки воскрешает DS-97: `overflow-x: auto` вычисляет
 *   `overflow-y` в `auto`, обёртка становится клипующим контекстом, и меню
 *   строки режется — замерено 1px видимой высоты из 90.
 *
 * Что происходит, когда пол не помещается: таблица становится ШИРЕ обёртки.
 * Это не новое состояние — компонент производит его и сегодня, стоит заданным
 * ширинам в сумме перерасти контейнер (замерено: таблица 456px в обёртке
 * 342px). Ново то, что состояние стало ВИДНЫМ вместо колонки в 0px. Лечится
 * оно уменьшением заданных ширин либо `hideBelow`: с DS-138 скрытая
 * колонка теряет трек и отдаёт ширину соседкам (до неё трек продолжал
 * числиться, и на месте таблицы оставалась мёртвая полоса — 100px из 400).
 *
 * Ширина колонки выбора приходит параметром: её `<col>` пуст, а размер задан
 * ячейкой (`.ds-table__sel`), то есть снаружи этого модуля.
 *
 * **Возвращается ТРИ слагаемых, а не готовая сумма** (DS-138). Скрытая по
 * тесноте колонка теряет трек, но пол про тесноту не знает: одним числом он
 * продолжал держать таблицу широкой за колонку, которой на экране нет. Замер:
 * обёртка 342px, ширины 192+80+64 и колонка-остаток, вторая с `hideBelow: 'sm'`
 * — таблица оставалась 400px (переросла обёртку на 58), а остаток получал свои
 * 64px пола. То есть `hideBelow` не лечил тесноту даже после того, как научился
 * возвращать место: пол забирал его обратно.
 *
 * Считать это в JS нечем: тесноту знает только container-запрос, а ширину
 * обёртки компонент не меряет. Поэтому слагаемые уходят в разметку по
 * группам — видимые всегда, `sm` и `md` порознь, — а обнуляет ненужные лист
 * теми же порогами, что прячут колонки. Сумма собирается в `.ds-table--fixed`:
 * она константна и в компоненте ей делать нечего.
 *
 * Порядок носителей важен и он обратный привычному: слагаемые ставятся на
 * ОБЁРТКУ, а обнуляются на `.ds-table`. Инлайн бьёт лист, и объяви компонент
 * `--ds-table-min-sm` на самой таблице — правило `@container` из листа до него
 * бы не дотянулось. Наследование от обёртки, наоборот, слабее собственного
 * объявления элемента, и запрос выигрывает.
 */
export function tableMinWidth<T>(columns: Column<T>[], selectionWidth?: string): Record<'base' | 'sm' | 'md', string> {
  const bag: Record<'base' | 'sm' | 'md', string[]> = { base: [], sm: [], md: [] }
  if (selectionWidth) bag.base.push(selectionWidth)
  for (const c of columns) {
    bag[c.hideBelow ?? 'base'].push(hasWidth(c) ? assertColWidth(c) : 'var(--ds-w-col-min)')
  }
  // Пустая группа — `0px`, а не пустая строка: `calc()` с пустым членом
  // невалиден целиком, то есть пол исчез бы у ВСЕЙ таблицы (та же причина, по
  // которой нерастворимая ширина бросает, а не пропускается).
  const sum = (parts: string[]) => (parts.length ? `calc(${parts.join(' + ')})` : '0px')
  return { base: sum(bag.base), sm: sum(bag.sm), md: sum(bag.md) }
}

/** Длина или процент — единственное, что `<col>` понимает (замерено). */
const CSS_LENGTH = /^-?(?:\d+\.?\d*|\.\d+)(?:px|rem|em|ch|ex|vw|vh|vmin|vmax|cm|mm|in|pt|pc|%)$|^0$/

/**
 * Ширина колонки ТАБЛИЦЫ — длина или процент, и ничего больше.
 *
 * Бросок, а не пропуск слагаемого: `calc()` с невалидным членом отбрасывается
 * целиком, то есть пол молча исчез бы у ВСЕЙ таблицы, а не у одной колонки.
 * Тихо выкинуть слагаемое не лучше — пол стал бы меньше настоящего ровно на
 * ширину этой колонки, и колонка-остаток снова уехала бы под него.
 *
 * Запрет ничего не отнимает: `max-content` на `<col>` не работал и до правки —
 * Chrome отбрасывает его в пользу `auto`, то есть проп был задан и молча ничего
 * не делал. `minmax()`/`max-content` остаются законными у `Tree` и
 * `LedgerList`: там ширина — трек грида, и разбор общий (`colWidth`), а этот
 * запрет живёт в табличной ветке.
 */
function assertColWidth<T>(c: Column<T>): string {
  const w = c.width!
  if (typeof w === 'number' || CSS_LENGTH.test(w.trim())) return colWidth(w)
  throw new Error(
    `jig: DataTable — ширина колонки "${colId(c)}" задана как "${String(w)}". `
    + 'В `table-layout: fixed` браузер понимает у колонки только длину и процент: '
    + '`max-content`, `min-content`, `fit-content()` и любой `calc()` с процентом '
    + 'внутри он отбрасывает, оставляя колонку auto (DS-137).',
  )
}

/** Индекс первой колонки, у которой есть значение в cells; columns.length, если ни у одной. */
export function firstProjected<T>(columns: Column<T>[], cells: Partial<Record<string, React.ReactNode>>): number {
  const i = columns.findIndex((c) => cells[colId(c)] !== undefined)
  return i === -1 ? columns.length : i
}
