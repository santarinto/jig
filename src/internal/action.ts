/**
 * Одна сущность «действие» на всю систему: ядро `ActionBase` и сужения под
 * каждое место, где действие живёт (DS-358, ревизия слоя 1 по
 * JIG-17).
 *
 * ЗАЧЕМ. До 4.3.x одно и то же — «кнопка с иконкой, подписью и обработчиком» —
 * было объявлено ЧЕТЫРЬМЯ независимыми наборами полей: `RowAction`
 * (`columns.ts`), `CardTool` (`Form.tsx`), `CommandAction` (`CommandBar.tsx`),
 * `DropdownAction` (`DropdownMenu.tsx`). Подпись звалась `label` у трёх и
 * `ariaLabel` у четвёртого; обработчик — `onClick` у двух и `onSelect` у двух;
 * `id` был у двоих. Потребитель, переносящий действие из строки таблицы в меню,
 * переписывал объект целиком, а не перекладывал.
 *
 * ПОЧЕМУ ЯДРО ПЛЮС СУЖЕНИЯ, А НЕ ОДИН ОБЩИЙ ТИП с необязательными полями
 * (решение владельца 20.09.2026). Общий тип принял бы `href` у `CardTool` и
 * `group` у `RowAction` — и молча не сделал бы ничего. Это ровно класс дефектов
 * эпика DS-248 («молчаливая деградация API»): вызов компилируется,
 * выглядит осмысленным и не работает. Сужение делает такое поле ошибкой
 * компиляции, а это единственная форма отказа, которую потребитель не может не
 * заметить.
 *
 * ПОЧЕМУ НЕ ПАПКА В `src/components`. Каталог компонентов детектится как
 * `git ls-tree -d src/components` (довод — `src/index.ts`), то есть новая папка
 * подняла бы выпуск до minor, хотя каталог не меняется. Тип — не компонент.
 *
 * НАРУЖУ типы уезжают реэкспортом из `index.ts` своего компонента — как
 * `columns.ts` → `DataTable/index.ts`; `ActionBase` и `ActionTone` не
 * принадлежат ни одному компоненту и названы прямо в `src/index.ts`. Через
 * `export *` каждого barrel-а их пускать нельзя: два `export *` с одним именем
 * ES-модули роняют МОЛЧА, без ошибки сборки.
 */
import type * as React from 'react'

/**
 * Тон действия. Два значения, а не шесть из `BadgeTone`: действие либо обычное,
 * либо разрушительное. `success` у кнопки в строке не значит ничего — состояние
 * несёт строка, а не команда над ней.
 *
 * Цвет здесь ПОДТВЕРЖДАЕТ, а не несёт: `error`-действие остаётся подписанным
 * словом и иконкой (закон системы, CLAUDE.md «System law: colour and magnitude»).
 *
 * `neutral` — ИМЯ ОТСУТСТВИЯ тона, а не значение: у `Button` словарь `ButtonTone
 * = 'error'`, и компоненты переводят `neutral` в `tone={undefined}`. Имя нужно
 * потому, что «по умолчанию» приходится уметь написать явно — например, когда
 * тон вычисляется выражением.
 */
export type ActionTone = 'neutral' | 'error'

/**
 * Ядро действия — то, что верно про команду в ЛЮБОМ месте системы.
 *
 * `id` обязателен: им действие различается при свёртке полосы в «Ещё», им же
 * оно остаётся собой между рендерами. Индекс массива этого не умеет — он
 * меняется, когда действие скрыли по правам.
 *
 * `onSelect`, а не `onClick`: половина мест зовёт его не мышью (пункт меню с
 * клавиатуры, свёрнутое действие полосы), и `onClick` там называл бы устройство
 * ввода вместо события.
 *
 * `onSelect` НЕОБЯЗАТЕЛЕН намеренно: у `CommandAction` есть `href`, и
 * навигационное действие без обработчика законно. Обязательность, нужная одному
 * месту, живёт в его сужении, а не в ядре.
 */
export interface ActionBase {
  /** Ключ действия: различает его при свёртке, в меню и между рендерами. */
  id: string
  /** Подпись. Она же — доступное имя там, где кнопка `iconOnly`. */
  label: React.ReactNode
  /** Значок. Декоративен: смысл несёт подпись. */
  icon?: React.ReactNode
  /** Тон. `neutral` по умолчанию. */
  tone?: ActionTone
  disabled?: boolean
  /** Выбор действия — мышью, с клавиатуры, из свёрнутого меню. */
  onSelect?: () => void
}

/**
 * Действие над строкой в колонке действий (`ActionColumn` у `DataTable` и
 * `LedgerList`).
 *
 * Рисуется как `ghost`-`iconOnly`-кнопка размера `sm` — форма, к которой
 * потребители всё равно сходились руками. Значения, которые не менялись ни в
 * одной таблице (прозрачный ghost, размер, iconOnly, зазор, nowrap,
 * выравнивание вправо), заданы колонкой и в проп не вынесены.
 *
 * ТРИ СУЖЕНИЯ, и все три обязательны по построению кнопки:
 * - `icon` обязателен — рисовать в `iconOnly`-кнопке больше нечего;
 * - `label` сужен до `string` — подпись уходит в `aria-label`, куда `ReactNode`
 *   не кладётся. Ослабить его до ядра значит разрешить `<b>Удалить</b>` там, где
 *   в DOM уедет `[object Object]`;
 * - `onSelect` обязателен. В 4.2.6 поле звалось `onClick` и было обязательным;
 *   переименование не повод ослаблять — действие строки без обработчика это
 *   кнопка, которая рисуется и ничего не делает.
 */
export type RowAction = Omit<ActionBase, 'label'> & {
  label: string
  icon: React.ReactNode
  onSelect: () => void
}

/**
 * Инструмент в шапке карточки-панели (`Card tools`).
 *
 * СУЖЕНИЯ те же, что у `RowAction`, и по той же причине: инструмент рисуется
 * одной иконкой (`icon` обязателен), а подпись уходит в `aria-label`, куда
 * `ReactNode` не кладётся (`label` сужен до `string`).
 *
 * Тело DS-358 сужения подписи здесь не называло — оно называло только
 * переименование `ariaLabel` → `label`. Но довод, записанный там же для
 * `RowAction`, действует на `CardTool` дословно: в коде до правки поле так и
 * звалось `ariaLabel: string` и уезжало прямо в атрибут. Ослабить его до ядра
 * значит разрешить `<b>Обновить</b>` там, где в DOM уедет `[object Object]`, —
 * то есть завести ровно тот тихий дефект, против которого вся задача.
 *
 * `tone` ОТРЕЗАН от ядра, и это решение, а не недосмотр. Шапка карточки — не
 * место разрушительному действию: «Удалить» живёт в меню строки или в полосе
 * команд, где у него есть слово. Инструмент же рисуется ОДНОЙ ИКОНКОЙ, и
 * красная иконка без подписи — цвет как единственный носитель смысла, что
 * система запрещает прямо (CLAUDE.md, «System law: colour and magnitude»).
 * Унаследовать `tone` из ядра значило бы дать полю компилироваться и молча
 * ничего не делать — класс дефектов эпика DS-248.
 *
 * `onSelect` ОБЯЗАТЕЛЕН, в отличие от ядра: у инструмента нет второго способа
 * что-нибудь сделать (`href` сюда тоже не взят), и кнопка без обработчика —
 * мёртвая кнопка в шапке. В 4.2.6 поле звалось `onClick` и было обязательным;
 * ослабить его при переименовании значило бы разрешить регресс заодно.
 */
export type CardTool = Omit<ActionBase, 'label' | 'tone'> & {
  label: string
  icon: React.ReactNode
  onSelect: () => void
}

/**
 * Пункт меню `DropdownMenu`. Ядро без единого сужения — меню и есть то место,
 * где действие живёт в самом общем виде.
 *
 * Разделитель остаётся отдельным членом союза (`DropdownItem`), а не полем:
 * разделитель не действие, у него нет ни подписи, ни обработчика.
 */
export type DropdownAction = ActionBase

/**
 * Действие полосы команд (`CommandBar`) и шапки (`AppBar`).
 *
 * Три поля сверх ядра — и все три есть ровно здесь, потому что полоса умеет то,
 * чего не умеет ни строка таблицы, ни пункт меню: сворачивать хвост в «Ещё»
 * (`group`), нести главное действие заливкой (`variant`) и быть ссылкой
 * (`href`).
 *
 * `href` в ядро НЕ взят намеренно: он есть у одного места из четырёх, а `href` у
 * `CardTool` обязан быть ошибкой компиляции, а не тихим ничем.
 */
export type CommandAction = ActionBase & {
  /**
   * Вид кнопки В ПОЛОСЕ. В меню не значит ничего — пункт меню есть пункт меню,
   * и заливка внутри списка означала бы вторую иерархию поверх порядка.
   * Потери вида при свёртке нет: сворачивается хвост, а главное действие стоит
   * первым и уходит последним.
   */
  variant?: 'primary' | 'secondary' | 'ghost'
  /**
   * Имя группы. РАЗДЕЛИТЕЛЬ ВЫВОДИТСЯ ИЗ СМЕНЫ ГРУППЫ, а не ставится руками:
   * так он не может ни осиротеть при свёртке, ни встать через один и перестать
   * что-либо означать. У первого действия имя группы законно и разделителя
   * перед собой не даёт.
   */
  group?: string
  /**
   * Навигационное действие: рисуется `<a href>`, а не кнопкой. У потребителя
   * без гидрации переход обязан оставаться ссылкой.
   *
   * СВЁРНУТОЕ в меню теряет форму ссылки и уходит через `location.assign` —
   * меню без JS не открывается вовсе, так что терять там нечего. Роутеру это
   * даёт полную перезагрузку: действие, которое обязано остаться под роутером,
   * держат `onSelect` и его собственный `navigate`.
   */
  href?: string
}

/**
 * Старая форма действия под `any` — то, что осталось от вызова до DS-358.
 *
 * Отдельный тип, а не `as any` по месту: каждый компонент спрашивает об одном и
 * том же, и вопрос должен быть записан один раз.
 */
type LegacyAction = {
  id?: unknown
  ariaLabel?: unknown
  onClick?: unknown
}

/**
 * Бросок на старой форме действия, для потребителя с `any` на пути.
 *
 * ПОЧЕМУ БРОСОК, А НЕ ДЕГРАДАЦИЯ. Без него `tools={[{ ariaLabel, onClick }]}`
 * под `any` нарисовал бы безымянные кнопки, которые ничего не делают, — и ни
 * одной ошибки. Правило CLAUDE.md («Deprecated API»): старый вызов обязан
 * БРОСАТЬ там, где типа уже нет. Тот же приём, что у `AppBar.actions`
 * (DS-306).
 *
 * Проверяется ТРИ следа, и все три — текстовые, то есть находимые `git grep` у
 * потребителя: `ariaLabel` вместо `label`, `onClick` вместо `onSelect`,
 * отсутствие `id`.
 *
 * @param where имя пропа в сообщении — потребитель обязан узнать своё место
 *   вызова, а не «где-то в дизайн-системе».
 */
export function assertAction(a: unknown, where: string): void {
  if (a == null || typeof a !== 'object') {
    throw new TypeError(
      `${where}: действие — объект \`{ id, label, onSelect }\` (тип \`ActionBase\`), а не ${typeof a}.`,
    )
  }
  const legacy = a as LegacyAction
  if ('ariaLabel' in legacy) {
    throw new TypeError(
      `${where}: поле \`ariaLabel\` у действия отменено (DS-358) — подпись зовётся \`label\`, `
      + 'как у действий полосы, меню и строки таблицы. Переименуйте `ariaLabel` в `label`.',
    )
  }
  if ('onClick' in legacy) {
    throw new TypeError(
      `${where}: поле \`onClick\` у действия отменено (DS-358) — обработчик зовётся \`onSelect\`: `
      + 'пункт меню и свёрнутое действие выбирают с клавиатуры, а не мышью. Переименуйте `onClick` в `onSelect`.',
    )
  }
  if (typeof legacy.id !== 'string') {
    throw new TypeError(
      `${where}: у действия обязателен \`id: string\` (DS-358) — им действие различается при свёртке `
      + 'в «Ещё» и остаётся собой между рендерами, чего индекс массива не умеет.',
    )
  }
}
