import { useCallback, useLayoutEffect, useRef, useState } from 'react'

/**
 * Сторона якоря, у которой встаёт плавающий узел. `left`/`right` появились на
 * DS-242 ради подменю свёрнутой `SideNav`: рейка шириной 40px растёт
 * вниз, и всплывающее у неё обязано выходить ВБОК — вертикальной пары сторон
 * для этого не хватает в принципе, а не «неудобно».
 */
export type AnchorSide = 'top' | 'bottom' | 'left' | 'right'
/**
 * Выравнивание по ПОПЕРЕЧНОЙ оси, а не «по горизонтали»: у вертикальных сторон
 * это left, у горизонтальных — top. Названия осей не в терминах экрана
 * намеренно — иначе `align: 'start'` у стороны `right` пришлось бы читать как
 * «слева», хотя означает оно «верхние края совмещены».
 */
export type AnchorAlign = 'start' | 'center' | 'end'

export interface AnchoredPosition {
  /**
   * Инлайновый стиль плавающего узла. `position: fixed` здесь — ЧАСТЬ
   * КОНТРАКТА, а не оформление: именно она уносит пузырёк из-под клипа
   * прокручиваемого предка, и лист её продублировать не может, потому что
   * координаты считаются здесь.
   */
  style: {
    position: 'fixed'
    left: number
    top: number
    /**
     * Противоположные стороны ГАСЯТСЯ здесь, а не в листе потребителя
     * (DS-287). Лист держит статический фолбэк для вёрстки без JS, и у
     * `Tooltip` это `bottom: calc(100% + gap)`: `fixed`-бокс с `top` И `bottom`
     * при `height: auto` берёт высоту из остатка, остаток отрицательный —
     * подложка схлопывалась до падингов, текст вытекал вниз. Хук ставит
     * `fixed` — хук и отвечает за то, что остальные стороны не участвуют;
     * гашение в каждом компоненте уже разошлось: у `Popover` и `DropdownMenu`
     * оно было, у `Tooltip` — нет.
     */
    right: 'auto'
    bottom: 'auto'
    /** До первого замера узел ещё не поставлен — показывать его нельзя. */
    visibility?: 'hidden'
  }
  /** Сторона ПОСЛЕ переворота, а не заказанная. */
  side: AnchorSide
}

export interface UseAnchoredPositionOptions {
  /** Слушатели и пересчёт живут только пока true (обычно — open). */
  enabled: boolean
  /** Узел, от которого считаются координаты. */
  anchorRef: React.RefObject<HTMLElement | null>
  /**
   * Узел, от края которого отсчитывается СТОРОНА, если он не тот же
   * (DS-243). Поперечная ось при этом по-прежнему считается от
   * `anchorRef`.
   *
   * Нужно там, где всплывающее выходит ИЗ ПАНЕЛИ, но выравнивается ПО СТРОКЕ:
   * подменю свёрнутой `SideNav`. Плашка пункта утоплена внутрь панели на её
   * падинг, и это ещё не беда — беда в том, что величина эта НЕ ПОСТОЯННА:
   * стоит рейке прокрутиться, полоса прокрутки съедает ещё пятнадцать
   * пикселей. Замерено: на шкале 1.5 в кадре 380px плашка 29.35 при рейке 60,
   * и подменю, отсчитанное от плашки, уезжает на 9.66px ВНУТРЬ панели. Зазор,
   * выведенный из падинга, эту разницу не покрывает и покрыть не может: он
   * константа, а полоса появляется и исчезает.
   */
  sideAnchorRef?: React.RefObject<HTMLElement | null>
  /** Сам плавающий узел; обязан быть в DOM, чтобы его можно было померить. */
  floatingRef: React.RefObject<HTMLElement | null>
  /** Предпочитаемая сторона; переворачивается, если не помещается. */
  side?: AnchorSide
  /** Выравнивание по ПОПЕРЕЧНОЙ оси относительно `anchorRef`. */
  align?: AnchorAlign
  /**
   * Звать, когда узел ЛОВИТСЯ предком-containing block. Аргумент — насколько
   * начало коробки предка отстоит от начала вьюпорта, то есть на сколько узел
   * уехал БЫ без компенсации. Один раз на показ.
   *
   * Положение к этому моменту УЖЕ исправлено (DS-367): колбэк сообщает
   * не дефект, а то, что осталось за пределами починки — обрезка ловушкой и
   * ширина, посчитанная от её коробки. См. «ловушка containing block» ниже.
   */
  onTrapped?: (offBy: number) => void
}

/**
 * Число из CSS-переменной плавающего узла; токен остаётся в листе.
 *
 * РАБОТАЕТ ТОЛЬКО ПОТОМУ, ЧТО ОБЕ ПЕРЕМЕННЫЕ ЗАРЕГИСТРИРОВАНЫ `@property` в
 * `tokens/tokens.css` (DS-243). Без регистрации вычисленное значение —
 * не длина, а `"calc(0.125rem * 1)"`, и `parseFloat` даёт NaN. Прежняя
 * редакция молча возвращала на этом ноль, и зазор с поджимом были нулевыми у
 * всех четырёх компонентов с самого DS-240.
 *
 * Поэтому ноль здесь больше не безмолвный. Ошибка этого разряда не ломает
 * ничего видимого — панель просто липнет к триггеру, что легко принять за
 * замысел, — и единственное, что отличает её от замысла, это предупреждение.
 * Тот же довод, по которому не замалчивается ловушка containing block.
 *
 * Один раз на имя, и БЕЗ проверки `NODE_ENV`: в `src` нет ни одного
 * `process.env`, и заводить его здесь значило бы потребовать от потребителя
 * сборщика, который его подставляет. Цена и так нулевая — предупреждение
 * печатается только когда значение действительно нечитаемо, то есть когда
 * что-то сломано.
 *
 * Пустая строка молчит намеренно: узел, НЕ объявивший зазор, — это не поломка,
 * а обычный случай, и ноль для него верный ответ.
 */
const cssPxWarned = new Set<string>()
function cssPx(cs: CSSStyleDeclaration, name: string): number {
  const raw = cs.getPropertyValue(name)
  const v = parseFloat(raw)
  if (Number.isFinite(v)) return v
  if (raw.trim() && !cssPxWarned.has(name)) {
    cssPxWarned.add(name)
    console.warn(
      `[jig] ${name} не читается как длина: ${JSON.stringify(raw)}. `
      + 'Зазор от якоря и поджим от края экрана считаются нулём. Обычно это '
      + 'значит, что не загружен tokens/tokens.css с блоком @property для этой '
      + 'переменной (DS-243).',
    )
  }
  return 0
}

const clamp = (v: number, lo: number, hi: number) => Math.min(Math.max(v, lo), Math.max(lo, hi))

/**
 * Координаты плавающего узла во ВЬЮПОРТЕ, для `position: fixed`.
 *
 * ЗАЧЕМ ВООБЩЕ. Всплывающее у нас лежало `position: absolute` внутри триггера,
 * и любой прокручиваемый предок его КЛИПОВАЛ — обойти в CSS нечем: всякий
 * не-`visible` `overflow-x` вычисляет `overflow-y` в `auto`, а `clip` не
 * прокручивает. Пока это так, ни один компонент системы со всплывающим внутри
 * не может завести себе горизонтальную прокрутку, то есть закон «скроллер
 * живёт на широком ребёнке» (DS-203) для целого класса невыполним.
 * Замерено на голой геометрии: пузырёк `absolute` торчит за скроллер на 87 px,
 * а попадание в него отдаёт `HTML`; тот же пузырёк `fixed` отдаёт себя
 * (DS-240).
 *
 * ПОЧЕМУ НЕ ПОРТАЛ, хотя он надёжнее. Отказ записан в `usePopupLayer.ts` и он
 * верен: `useDismiss` слушает `document.pointerdown` и спрашивает
 * `ref.contains(e.target)` — портал превращает клик по своему же списку в
 * «клик мимо». Плюс у `Tooltip` за узлом переехал бы `aria-describedby`.
 * `fixed` не трогает ни DOM-вложенность, ни дерево доступности, ни порядок
 * фокуса, и платит только тем, что координаты приходится считать.
 *
 * ЛОВУШКА CONTAINING BLOCK, и она названа, а не замолчана — а прежняя запись
 * здесь была НЕВЕРНОЙ (DS-357, исправлено). Предок с `transform`,
 * `filter`, `backdrop-filter`, `perspective`, `will-change: transform` ИЛИ
 * `contain: layout|paint|strict|content` становится containing block для
 * `fixed` (и для `absolute` тем же механизмом): узел встаёт не туда — замерено
 * заказали 81,121, вышло 81,181. `contain: paint` — ЛОВУШКА, а не исключение:
 * перемер chromium 149.0.7827.55 на голом листе (предок `position: static` со
 * смещением через `margin: 120px`) даёт для paint/layout/strict/content те же
 * 120,120, что и для transform/filter/will-change/backdrop-filter/perspective.
 * `container-type: inline-size|size` (и голый `contain: size`) — НЕ ловушка,
 * остаётся 0,0; это отдельный ценный факт, он открывает контейнерные запросы
 * там, где их боялись (см. `Form.css`, `FormRow`).
 *
 * Прежнее «contain: paint ловушкой не оказался (расхождение 0)» — не другой
 * замер той же истины, а методологический сбой: предок пробы стоял на 0,0
 * вьюпорта, а на 0,0 ловушка и её отсутствие ДАЮТ ОДНО И ТО ЖЕ число —
 * смещаться некуда что с ловушкой, что без. Прежний замер этой пробы не
 * восстановлен по git (искали — не нашёлся), но гипотеза воспроизведена: тем
 * же скриптом на предке 0,0 ЛЮБОЕ свойство из списка выше даёт `offBy=0`.
 *
 * ЛОВУШКА КОМПЕНСИРУЕТСЯ, А НЕ СООБЩАЕТСЯ (DS-367). Прежняя редакция
 * перемеряла узел после установки и отдавала расхождение в `onTrapped` — и это
 * было мёртвым по двум причинам сразу. Первая: колбэк не передавал НИ ОДИН из
 * четырёх потребителей (`DropdownMenu`, `Popover`, `Tooltip`, `SideNav`), то
 * есть в браузере расхождение, случившись, не сообщалось никому. Вторая, хуже:
 * перемер стоял НЕ В ТОЙ ФАЗЕ. `setPos` не применяет стиль синхронно, и
 * `getBoundingClientRect()` строкой ниже читал положение ПРОШЛОГО рендера — на
 * первом показе это `0,0`, так что честный узел отдал бы `offBy = left + top`,
 * то есть «ловушка» срабатывала бы всегда и на пустом месте. Зелёным это
 * держалось только в jsdom, где прямоугольники подставлены руками и от
 * применённого стиля не зависят вовсе: проверялась арифметика `Math.abs`, а не
 * фаза. Предупреждение, которое никто не получает и которое к тому же врёт, —
 * не диагностика.
 *
 * Поэтому начало коробки предка теперь МЕРЯЕТСЯ и ВЫЧИТАЕТСЯ, а замер берётся
 * из того же прямоугольника, который и так читается ради размеров узла.
 * Механика: узел сейчас стоит по стилю, применённому в последнем коммите
 * (`applied`), а на экране он в `f` — разница и есть начало containing block
 * во вьюпорте. Без ловушки она ноль, и вычитание становится no-op. Правила CSS
 * о том, КАКОЙ край коробки ловушки берётся за начало (padding box у
 * `transform`, у `contain` — тот же), в расчёт не входят: замеряется результат,
 * а не выводится из спецификации, и поэтому счёт не протухнет от следующего
 * свойства, которое сделают ловушкой.
 *
 * ЧЕГО ЭТО ТРЕБУЕТ ОТ СРЕДЫ, и в jsdom оно НЕ ВЫПОЛНЯЕТСЯ. Вычитание верно
 * ровно пока `getBoundingClientRect` согласован с применённым стилем. В jsdom
 * раскладки нет и прямоугольник всегда нулевой, то есть согласован он только
 * на ПЕРВОМ замере, когда в стиле тоже нули; на втором (`scroll`, `resize`)
 * разница прочитается как «коробка уехала назад на всю позицию», и координаты
 * поползут. На живых компонентах это не выстреливает — их случаи событий не
 * шлют, — но случай, который их пошлёт, увидит дрейф и обвинит хук. Лечится он
 * не в хуке: в `useAnchoredPosition.test.tsx` прямоугольник плавающего узла
 * подменён ФУНКЦИЕЙ от `el.style.left/top`, то есть среда там честная, и
 * именно поэтому случаи про ловушку живут в нём, а не в тестах компонентов.
 *
 * Дополнительного рендера это не стоит и сойтись не может не с первого раза:
 * поправка не «вторая постановка», а слагаемое в той же самой. `applied`
 * обновляется в layout-эффекте, объявленном ВЫШЕ рабочего, — порядок здесь
 * часть контракта, иначе первый же замер читал бы поправку от ещё не
 * применённого стиля.
 *
 * ЧЕГО КОМПЕНСАЦИЯ НЕ ЛЕЧИТ, и это названо, а не замолчано:
 * - ОБРЕЗКА. `contain: paint` и любой не-`visible` `overflow` у предка-ловушки
 *   режут узел по своей коробке, даже когда он встал верно. Положение
 *   исправлено, видимость — нет.
 * - ШИРИНА. Плавающий узел `width: auto` ужимается по containing block, и под
 *   ловушкой это её коробка, а не вьюпорт: узкий предок переносит текст панели
 *   иначе, чем тот же узел переносил бы его у края экрана.
 * Оба чинятся только порталом, то есть ценой, от которой здесь отказались
 * выше. Оба и есть предмет `onTrapped`: колбэк остаётся, но сообщает теперь не
 * «узел уехал» (не уехал), а «над узлом ловушка, посмотрите на обрезку и
 * перенос». Он по-прежнему опционален и по-прежнему не передаётся никем:
 * предупреждать в консоли о положении, которое исправлено, значило бы приучать
 * к предупреждению, за которым обычно ничего нет.
 *
 * Оверлеи НЕ портируются в `body` (см. выше), то есть плавающий узел — ребёнок
 * корня компонента В ТОМ ЖЕ дереве, где его разместил потребитель. Отсюда:
 * ловушкой может стать любой предок между корнем и вьюпортом — свой в ДС
 * (`Card`, `Drawer`, `Modal`…) или чужой у потребителя, гейт видит только
 * первое. В самом ДС статических предков с ловушечным свойством нет (держит
 * `src/__guards__/containing-block-trap.test.ts` — запрещает
 * `contain: layout|paint|strict|content` в `src/**\/*.css`); на листах
 * компонентов только `transform: translateX(-50%)` на САМОМ позиционируемом
 * элементе (AgentTranscript.css, LogViewer.css), это не предок, а гейт по
 * `contain` его и не касается. ИСКЛЮЧЕНИЕ, вне охвата гейта и НЕ закрытое:
 * `@keyframes ds-drawer-in-*` держит `transform` на `.ds-drawer` 180мс при
 * открытии — якорный оверлей, открытый внутри `Drawer` в это окно, ловится
 * тем же механизмом.
 *
 * ЗАЗОР И ПОДЖИМ — ИЗ CSS, а не числами здесь: `--ds-anchor-gap` (от якоря) и
 * `--ds-anchor-inset` (от края экрана) объявляются на плавающем узле в его
 * листе. Так они остаются токенами и умножаются на `--ds-ui-scale`, а в JS не
 * появляется ни одного px мимо шкалы — гейт `js-px-scale` смотрит именно за
 * этим. Сами координаты на шкалу НЕ умножаются: это измеренное положение на
 * экране, оно уже в тех же единицах.
 *
 * ДВЕ ОСИ, А НЕ ОДНА (DS-242). Арифметика для `left`/`right` — та же
 * самая с переставленными осями, поэтому она и написана одной формой: сторона
 * выбирает ось, `align` всегда про ПОПЕРЕЧНУЮ. Развести их на две ветки с
 * собственными формулами значило бы завести второе место, где переворот и
 * поджим могут разойтись, — а разошлись бы они молча, потому что каждая ветка
 * поодиночке выглядит верной.
 *
 * ПЕРЕСЧЁТ, А НЕ ЗАКРЫТИЕ. `scroll` с `capture: true` на документе ловит
 * прокрутку ЛЮБОГО предка — перечислять их не нужно и нельзя надёжно.
 * Закрытие было бы дешевле, но для `Popover` это регресс: панель с формой не
 * должна исчезать оттого, что страница сдвинулась на пиксель.
 */
export function useAnchoredPosition({
  enabled, anchorRef, sideAnchorRef, floatingRef, side = 'bottom', align = 'start', onTrapped,
}: UseAnchoredPositionOptions): AnchoredPosition {
  const [pos, setPos] = useState<{ left: number, top: number, side: AnchorSide } | null>(null)
  const trapReported = useRef(false)
  const cb = useRef(onTrapped)
  useLayoutEffect(() => { cb.current = onTrapped })

  /**
   * Что стоит в стиле узла ПО СОСТОЯНИЮ НА ПОСЛЕДНИЙ КОММИТ — не то, что
   * последним заказал `measure`. Разница существенна: два замера в одном
   * задании (`scroll` и `resize` в одном кадре) React сливает в один коммит, и
   * ref, обновляемый рядом с `setPos`, ушёл бы вперёд применённого стиля — а
   * поправка ниже вычитает измеренное из применённого и обязана считать их с
   * одного момента.
   *
   * Эффект объявлен ВЫШЕ рабочего намеренно: на монтировании layout-эффекты
   * идут в порядке объявления, и `measure` обязан застать здесь `0,0` — ровно
   * то, что стоит в стиле до первой расстановки.
   */
  const applied = useRef({ left: 0, top: 0 })
  useLayoutEffect(() => {
    applied.current = pos ? { left: pos.left, top: pos.top } : { left: 0, top: 0 }
  })

  const measure = useCallback(() => {
    const anchor = anchorRef.current
    const floating = floatingRef.current
    if (!anchor || !floating) return

    const a = anchor.getBoundingClientRect()
    // Сторона — от своего якоря, если он задан; поперечная ось всегда от `a`.
    // Переворот и «влезает ли» тоже считаются по `sa`: спрашивают они про ту
    // же самую сторону.
    const sa = sideAnchorRef?.current?.getBoundingClientRect() ?? a
    const f = floating.getBoundingClientRect()
    const cs = getComputedStyle(floating)
    const gap = cssPx(cs, '--ds-anchor-gap')
    const inset = cssPx(cs, '--ds-anchor-inset')
    const vw = document.documentElement.clientWidth
    const vh = document.documentElement.clientHeight

    // Ширина и высота якоря считаются из краёв, а не берутся из `width`/
    // `height`: у прямоугольника, собранного руками (тесты хука), эти поля
    // остаются нулями, и `center` тихо считал бы от нулевого якоря.
    const aw = a.right - a.left
    const ah = a.bottom - a.top

    // Переворот — только когда заказанная сторона НЕ лезет, а противоположная
    // лезет. Иначе сторона остаётся заказанной: перевернуть в такую же тесноту
    // значит поменять дефект на такой же, но неожиданный. Правило одно на обе
    // оси; ось выбирает заказанная сторона.
    const horizontal = side === 'left' || side === 'right'
    let s = side
    let left: number
    let top: number

    // `center` — не украшение: подсказка центруется по триггеру, и через
    // `start`/`end` это не выражается. Считается ЗДЕСЬ, а не остаётся в CSS
    // через `translateX(-50%)`, потому что поджим к краю обязан работать по
    // итоговому положению, а не до сдвига.
    const cross = (near: number, far: number, size: number, extent: number) => (
      align === 'start' ? near : align === 'end' ? far - size : near + (extent - size) / 2
    )

    if (horizontal) {
      const fitsRight = sa.right + gap + f.width <= vw - inset
      const fitsLeft = sa.left - gap - f.width >= inset
      if (s === 'right' && !fitsRight && fitsLeft) s = 'left'
      else if (s === 'left' && !fitsLeft && fitsRight) s = 'right'
      left = s === 'right' ? sa.right + gap : sa.left - gap - f.width
      top = clamp(cross(a.top, a.bottom, f.height, ah), inset, vh - f.height - inset)
    } else {
      const fitsBelow = sa.bottom + gap + f.height <= vh - inset
      const fitsAbove = sa.top - gap - f.height >= inset
      if (s === 'bottom' && !fitsBelow && fitsAbove) s = 'top'
      else if (s === 'top' && !fitsAbove && fitsBelow) s = 'bottom'
      top = s === 'bottom' ? sa.bottom + gap : sa.top - gap - f.height
      left = clamp(cross(a.left, a.right, f.width, aw), inset, vw - f.width - inset)
    }

    // ЛОВУШКА CONTAINING BLOCK, компенсация. До этой строки `left`/`top` —
    // координаты ВЬЮПОРТА, и они верны. Но `fixed` отсчитывается от containing
    // block, а им мог стать предок с `transform`/`contain`/… — тогда начало
    // отсчёта не в нуле экрана. Где оно, ИЗМЕРЕНО: узел стоит по `applied`, а
    // на экране он в `f`, и разница от правил CSS не зависит. Отдельного
    // прямоугольника на это не читается — `f` уже прочитан выше ради размеров,
    // то есть замер бесплатен, а второго layout нет вовсе.
    const cbLeft = f.left - applied.current.left
    const cbTop = f.top - applied.current.top
    left -= cbLeft
    top -= cbTop

    setPos((prev) => (
      prev && prev.left === left && prev.top === top && prev.side === s ? prev : { left, top, side: s }
    ))

    // Сообщение — про то, чего вычитание НЕ чинит (обрезка ловушкой и ширина
    // по её коробке), и один раз на показ: строка на каждый кадр прокрутки —
    // это не диагностика, а шум. Порог в 1px, а не ноль: на дробной шкале
    // начало коробки без ловушки округляется не всегда в ноль.
    if (!trapReported.current && cb.current) {
      const offBy = Math.abs(cbLeft) + Math.abs(cbTop)
      if (offBy > 1) { trapReported.current = true; cb.current(offBy) }
    }
  }, [anchorRef, sideAnchorRef, floatingRef, side, align])

  useLayoutEffect(() => {
    if (!enabled) { setPos(null); trapReported.current = false; return }
    measure()
    // `capture: true` — событие `scroll` не всплывает, и без захвата документ
    // не услышит прокрутку предка, ради которой всё и затевалось.
    const onScroll = () => measure()
    const onResize = () => measure()
    document.addEventListener('scroll', onScroll, true)
    window.addEventListener('resize', onResize)

    /**
     * ResizeObserver — `scroll`/`resize` выше ловят СДВИГ, а не смену РАЗМЕРА
     * без сдвига, а таких путей несколько: догрузился шрифт и панель выросла
     * по высоте, пришло асинхронное содержимое, у предка сменился
     * `--ds-ui-scale`. Ни одно из этих событий `scroll` документа не рождает
     * и `resize` окна не рождает — окно то же самое. Живой случай: `Popover`
     * `placement=top-*` на шкале 1.15 — первый замер взял высоту панели
     * 63.8px (до применения `--ds-ui-scale` к её содержимому), реальная
     * раскладка вышла 85.5px, и низ панели, поставленный по старой высоте,
     * заехал на кнопку-якорь на 19px (гейт `matrix`, кадр
     * `Popover/placements ×1.15`).
     *
     * ПОЧЕМУ ХУК, А НЕ ВЕРСТАК. У кадра верстака `frame-app.tsx` шкала
     * ставится в `useEffect` — то есть уже ПОСЛЕ первого замера хука, и это
     * не совпадение, которое здесь чинится, а тот же класс асинхронности,
     * что у догрузки шрифта и у чужого рендера содержимого. Поправить кадр
     * значило бы спрятать дефект от гейта, а у потребителя, чей предок
     * меняет масштаб иначе, дефект остался бы как был.
     *
     * ПЕТЛЯ НЕ ЗАВОДИТСЯ, и это стоит доказать, а не предположить: колбэк —
     * `measure()`, а `measure` каждый раз пишет в состояние только `left` и
     * `top` (`setPos` выше) — РАЗМЕР наблюдаемых узлов он не меняет никогда,
     * хук не трогает ни `width`, ни `height` ни у панели, ни у якоря.
     * `ResizeObserver` реагирует на `contentRect`, а не на положение
     * (`position: fixed` из `left`/`top` в него не входит), поэтому
     * применённый `measure()` не рождает того `resize`-события, на которое
     * подписан тот же наблюдатель — цепочка обрывается на первом же шаге.
     *
     * Наблюдаются узлы, которые УЖЕ в DOM на момент эффекта: панель всегда
     * отрисована (до первого замера — с `visibility: hidden`, см. конец
     * файла), якорь и, если задан, сторонний якорь — тоже узлы потребителя,
     * а не что-то, что этот хук создаёт сам.
     *
     * Guard `typeof ResizeObserver === 'undefined'` — тот же приём, что в
     * `useChartBox.ts`: SSR и часть тестовой среды его не имеют, и
     * деградация здесь безопасна — остаются `scroll`/`resize` выше, слушатели
     * которых уже поставлены.
     */
    let ro: ResizeObserver | undefined
    if (typeof ResizeObserver !== 'undefined') {
      ro = new ResizeObserver(() => measure())
      const floating = floatingRef.current
      const anchor = anchorRef.current
      const side = sideAnchorRef?.current
      if (floating) ro.observe(floating)
      if (anchor) ro.observe(anchor)
      if (side) ro.observe(side)
    }

    return () => {
      document.removeEventListener('scroll', onScroll, true)
      window.removeEventListener('resize', onResize)
      ro?.disconnect()
    }
  }, [enabled, measure, anchorRef, sideAnchorRef, floatingRef])

  return pos
    ? { style: { position: 'fixed', left: pos.left, top: pos.top, right: 'auto', bottom: 'auto' }, side: pos.side }
    // До первого замера координат нет, а узел уже в DOM — его обязаны померить.
    // `visibility: hidden` оставляет его измеримым и убирает вспышку в углу.
    // Гашение и здесь: узел меряется ДО первой расстановки, и схлопнутая
    // высота отдала бы хуку неверный `f.height` — переворот и поджим считались
    // бы по нулю.
    : { style: { position: 'fixed', left: 0, top: 0, right: 'auto', bottom: 'auto', visibility: 'hidden' }, side }
}
