import { useCallback } from 'react'

/**
 * Один узел, две ссылки: внутренняя (компонент сам ходит в элемент) и внешняя
 * (`ref` потребителя).
 *
 * Нужен составным полям: у `DatePicker`, `Combobox`, `CodeInput`, `GlobalSearch`
 * и `FileDrop` есть свой `ref` на главный фокусируемый элемент, и отдать этот же
 * элемент наружу можно только склейкой (DS-108).
 *
 * Мемоизация обязательна, а не «на всякий случай»: ref-колбэк с новой
 * идентичностью React на каждом рендере ОТЦЕПЛЯЕТ и прицепляет заново, то есть
 * зовёт сначала с `null`, потом с узлом. Для внутреннего хранения это безобидно,
 * а `react-hook-form` на каждом таком цикле перерегистрирует поле.
 *
 * Список ссылок в зависимостях — сам массив аргументов. Он фиксированной длины
 * на каждой площадке вызова (всегда «свой плюс чужой»), поэтому правило React о
 * неизменной длине зависимостей соблюдено; передавать сюда переменное число
 * ссылок нельзя.
 */
export function useMergedRef<T>(...refs: Array<React.Ref<T> | undefined>): React.RefCallback<T> {
  return useCallback((node: T | null) => {
    for (const r of refs) {
      if (typeof r === 'function') r(node)
      else if (r) (r as React.RefObject<T | null>).current = node
    }
    // Зависимости — сами ссылки: см. оговорку о фиксированной длине выше.
  }, refs)
}
