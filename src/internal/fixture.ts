/**
 * Формат фикстуры — описания страницы компонента для верстака.
 *
 * Гибрид намеренно: шапка (`name`/`group`/`cases`/`controls`/`slots`) — обычный
 * объектный литерал, его читают `import`-ом без браузера (гейт состава,
 * будущая генерация превью). `render` — обычная функция, её просто не зовут те,
 * кому нужен только состав.
 *
 * Чисто декларативным формат быть не может: у `DataTable` опасная позиция
 * сидит внутри рендерера ячейки, а у `Modal` кейс «открыт» отличается от
 * «закрыт» структурой, а не пропсами.
 *
 * Дизайн: спека удалена из дерева на DS-351 (завершённый план, ноль
 * ссылок, пятая часть индекса CocoSearch). Живёт в истории:
 * `git log --diff-filter=D --format=%H -1 -- docs/superpowers/specs/2026-08-14-workbench-design.md`
 * и `git show <sha>^:docs/superpowers/specs/2026-08-14-workbench-design.md`.
 */
import type { ReactNode } from 'react'

/**
 * Чем компонент годится быть начинкой чужой позиции — и что позиция принимает.
 * Пара `slot.accepts` × `fixture.kind` решает совместимость вместо поимённого
 * списка разрешённых компонентов: список пришлось бы править при каждом новом
 * компоненте, и он бы соврал через месяц.
 */
export type SlotKind = 'inline' | 'block' | 'any'

/** Вид крутилки: чем её крутят. Отдельно от `prop`, потому что это про
 *  интерфейс, а `prop` — про то, что крутилка означает. */
export interface EnumControl {
  kind: 'enum'
  values: string[]
  /**
   * Значения — ЧИСЛА, а не строки. `columns` у `KeyValueList` объявлен
   * `1 | 2`; крутилка держит значения строками (так устроено хранилище
   * верстака), и сниппет печатал `columns="1"` — у потребителя это ошибка
   * типа, строка не присваивается `1 | 2`.
   *
   * ОБЪЯВЛЯЕТСЯ, А НЕ УГАДЫВАЕТСЯ ПО ВИДУ ЗНАЧЕНИЯ. `'2'` выглядит числом и у
   * крутилки, чей проп — строка; догадка напечатала бы там `size={2}` и
   * вынесла бы ошибку к потребителю вместо стенда. Ровно та же причина, по
   * которой `prop` объявляется, а не выводится.
   *
   * Вид крутилки при этом НЕ МЕНЯЕТСЯ: выбор из двух остаётся сегментным
   * переключателем, числовое поле для «1 или 2» было бы хуже. Поле про
   * значения, а не про интерфейс.
   */
  numeric?: true
}

export type ControlKind =
  | EnumControl
  | { kind: 'bool' }
  | { kind: 'number'; min: number; max: number; step?: number }
  | { kind: 'text' }

/**
 * ЧЕМУ КРУТИЛКА СООТВЕТСТВУЕТ У КОМПОНЕНТА — и это единственный источник
 * правды для сниппета (DS-128).
 *
 * `Props` фикстуры — тип ФИКСТУРЫ, а не компонента, и по нему различить
 * нельзя ничего. У `DataTable` в одном и том же `controls` лежат `dense`
 * (настоящий проп), `emptyText` (проп есть, но зовётся `emptyContent`) и
 * `widths` (пропа нет вовсе — крутилка собирает `columns` внутри фикстуры).
 * Все три объявлялись одинаково, `{ kind: 'bool' }`, поэтому сниппет печатал
 * все три подряд: `<DataTable emptyText="Данных нет" widths wrapCity />` —
 * два имени выдуманы, третье переименовано. Скопировавший получал ошибку
 * компиляции в лучшем случае и молчаливо другой компонент в худшем, а
 * виноватым выглядел компонент.
 *
 * - `true` — крутилка и есть проп, имя совпадает.
 * - строка — проп есть, но зовётся иначе (`emptyText` → `emptyContent`).
 * - `false` — пропа нет: крутилка собирает что-то внутри фикстуры. Сниппет
 *   такую не печатает и говорит, что не напечатал.
 *
 * ПОЛЕ ОБЯЗАТЕЛЬНОЕ, И ЭТО НЕ ПЕДАНТИЗМ. Дефолт здесь и есть тот механизм,
 * которым дефект въехал: любое значение по умолчанию снова делает молчание
 * законным ответом. Обязательность заставляет автора фикстуры ответить один
 * раз — и, по правилу проекта про снятый API, старая форма обязана быть
 * ОШИБКОЙ КОМПИЛЯЦИИ, а не деградацией.
 */
export type PropRef = true | string | false

/** Описание крутилки. Объявляется явно, а не выводится из типов: экстрактор
 *  `.d.ts` не перечисляет унаследованные HTML-атрибуты, а `Column<T>[]`
 *  крутилкой не выразить вовсе. */
export type Control = ControlKind & { prop: PropRef }

export type Controls<P> = { [K in keyof P]?: Control }

/** Именованная позиция, куда можно вставить другой компонент. */
export interface Slot {
  title: string
  accepts: SlotKind
  /**
   * ПОДПИСЬ для панели (`'columns[3].render'`). Ничего не адресует и на рендер
   * не влияет — начинка приходит в `render` вторым аргументом готовым узлом.
   * Использовать это поле как путь нельзя: `DataTable` первым перестанет
   * выражаться, у него позиция живёт внутри рендерера ячейки.
   */
  prop?: string
  /** Чем позиция опасна. Печатается рядом с ней. */
  note?: string
}

/** Начинка позиции: ссылка на чужую фикстуру (не вторая копия разметки) либо текст. */
export type SlotFill = { c: string; case?: string } | { text: string }

/**
 * СЛОВАРЬ РОЛЕЙ УЗЛОВ (JIG-42): база закрыта, уточнитель свободен.
 *
 * Закрыта база, а не весь словарь: опечатка в ИМЕНИ роли (`prot` вместо
 * `port`) при открытом `Record<string, string>` зелена везде — узел находится
 * (класс тот же, ошиблись в ключе), `sx`/`sy` молча не применяются («у случая
 * нет port»), `focus=port` (JIG-44) молча промахивается. Закрытая база даёт
 * ошибку компиляции (`TS2353`/`TS2561`) и, на пути `any`, ошибку
 * `validateFixtures`. Уточнитель свободен («toggle-date», «sticky-top») —
 * два поля одного вида в одном случае (`Form/overlay`: `toggle` Combobox и
 * `toggle-date` DatePicker) не нуждаются в двух строках словаря, а общий
 * смысл базы всё равно держит JIG-44/45.
 *
 * Кто читает: `jig.node`/`jig.nodes` (workbench/jig.ts), гейт ролей
 * (`scripts/case-states.mjs`), адрес оболочки `sx`/`sy` (только роль `port`),
 * `focus=<роль>` JIG-44, справочный словарь JIG-45.
 *
 * Классы (`.ds-*`) в значении РАЗРЕШЕНЫ — обратное правилу `shows`. `shows` —
 * утверждение о контракте компонента (роль/`aria-*`), `nodes` — наш АДРЕС в
 * его DOM: у порта и липкой колонки нет ни роли, ни `aria-*`, адресовать их
 * нечем, кроме класса. `aria-label`-селекторы к тому же ломаются под
 * `text=pseudo` браузерного агента (строка становится `⟦…⟧`).
 */
export const NODE_ROLES = {
  port: 'главный прокручиваемый узел случая (overflow auto|scroll); к нему применяются sx/sy адреса оболочки',
  sticky: 'липкая колонка или шапка внутри port: от её края начинается видимая область',
  cursor: 'узел текущего значения — день курсора, выбранная строка',
  toggle: 'то, что открывает панель случая',
  panel: 'открытая всплывающая панель; есть только у случая, открытого при загрузке',
  clear: 'кнопка очистки значения',
  input: 'поле ввода текста',
  label: 'подпись поля или строки',
} as const
export type NodeRole = keyof typeof NODE_ROLES
/** База или база с уточнителем через дефис: `toggle`, `toggle-date`. */
export type NodeRoleName = NodeRole | `${NodeRole}-${string}`

/** Именованное состояние компонента. Каждый кейс — свой адрес кадра. */
export interface Case<P> {
  id: string
  title: string
  /** Только отличие от `Fixture.props`, не полный набор. */
  props?: Partial<P>
  slots?: Record<string, SlotFill>
  /** Что этот случай утверждает. Печатается в шапке кадра. */
  note?: string
  /**
   * ЧТО КАДР ОБЯЗАН ПОКАЗАТЬ — селекторы, каждый из которых обязан найти в
   * кадре ВИДИМЫЙ узел. Необязательное: у случая, чьё отличие в пропсах,
   * объявлять нечего.
   *
   * Заведено на DS-134 под случай, ВЕСЬ смысл которого в состоянии:
   * раскрытый список, видимый поповер, выехавшая шторка. Такой случай сам себя
   * приводит в состояние (клик по триггеру в эффекте), и до этого поля его не
   * проверял никто. `fixtures-render` утверждает «не бросило» и одинаково зелен
   * на раскрытом списке и на схлопнувшемся; замер 30.08: снятый сторож в
   * `Combobox.fixture.tsx` — 218/218 зелёных.
   *
   * ПОЧЕМУ СЕЛЕКТОР, А НЕ РАЗМЕР КАДРА. Тот же замер в chromium: со снятым
   * сторожем `Combobox/open` даёт `aria-expanded=false` и ни одного
   * `role=listbox`, а высота кадра НЕ МЕНЯЕТСЯ — 113px и там, и там. Поповер
   * лежит поверх, из потока он вынут, и «кадр непустой» про него молчит.
   *
   * ТОЛЬКО НАЛИЧИЕ, отрицания нет и не будет. «Списка нет» зелено и тогда,
   * когда не отрисовалось ВООБЩЕ ничего, — то есть отрицательное утверждение
   * ярче всего горит зелёным ровно в тот момент, когда всё сломано.
   *
   * РОЛЬ И `aria-*`, А НЕ `.ds-*`. Класс — наше внутреннее имя, он меняется
   * вместе с починкой; роль и состояние — контракт компонента наружу
   * (`docs/writing-checks.md`, пункт 4). Классовый селектор гейт отвергает.
   * Запрет намеренно строгий: ослабить его потом можно, ужесточить — нет.
   *
   * ТЕКСТА В ОБЪЯВЛЕНИИ НЕТ, и вопрос ЗАКРЫТ: не будет. Ответила всплывающая
   * волна (DS-127, 02.09), которой он и был отложен.
   *
   * Кандидатов оказалось два на всю систему, и оба одного вида — «в списке есть
   * ОСОБАЯ строка»: предложение создать у `Combobox/create` и раздел выдачи у
   * `GlobalSearch/grouped`. Считать их мало или много бессмысленно, потому что
   * дело не в числе. У обоих особая строка — тот же `<li role="option">`, что и
   * обычная: селектор не различает их РОВНО ПОТОМУ, что их не различает и
   * скринридер. Совпадение по тексту дало бы зелёную проверку поверх дефекта
   * доступности — то есть спрятало бы его, а не измерило.
   *
   * Второе, помельче, но само по себе достаточное: текст — это КОПИЯ данных
   * фикстуры, а не контракт компонента. Утверждение «в кадре есть слово
   * „Создать“» держится и на полностью сломанном виджете, если слово
   * отрисовалось хоть где-нибудь, и рассыпается от смены формулировки в
   * `src/dictionary` — эталон текста вместо утверждения о состоянии.
   *
   * Дефект разметки заведён отдельно (DS-158). Когда особая строка
   * получит имя или группу, оба случая объявят `shows` селектором — то есть
   * закрывать надо там, а не расширением этого поля.
   *
   * Спрашивает НЕ `fixtures-render`, а `scripts/case-states.mjs` (`make
   * states`) — в настоящем chromium, на настоящем кадре. Причина: «показан» в
   * jsdom не выражается. Там нет ни раскладки, ни каскада, ни `StrictMode`
   * кадра — в том же замере jsdom со снятым сторожем показывал список
   * НАЙДЕННЫМ, то есть ответил бы «да» на сломанном случае.
   */
  shows?: string[]
  /**
   * АДРЕС узлов случая по роли, не утверждение (в отличие от `shows`).
   * `key` — роль из словаря `NODE_ROLES`, с уточнителем или без; `value` —
   * ОДНА строка-селектор (список через запятую допустим — это один селектор
   * CSS; несколько совпадений разрешает `node()`, первый с ненулевой
   * коробкой, счёт — в `matched`). Проверяет `scripts/case-states.mjs` через
   * `window.jig.nodes()` в настоящем кадре, не `fixtures-render` — там нет
   * раскладки.
   *
   * Только СОСТОЯНИЕ СЛУЧАЯ ПРИ ЗАГРУЗКЕ: роли зависят от того, что случай
   * показывает сразу (крестика нет при пустом значении, панели нет у
   * закрытого случая) — общего поля на уровне `Fixture` нет намеренно, оно
   * указало бы в пустоту в половине случаев.
   */
  nodes?: Partial<Record<NodeRoleName, string>>
  /**
   * Случай НАРОЧНО уводит документ вбок на узком кадре — и почему (DS-177).
   *
   * Строка переполнения матрицы (`scripts/case-overflow.mjs`, прогон `make
   * matrix`) утверждает, что ни один случай на вьюпорте 360 не даёт документу
   * прокрутку вбок. Бывает случай, который
   * показывает ровно это как границу системы: `PageShell/wide` — ребёнок без
   * своей прокрутки уводит страницу, и оболочка его НЕ ловит (DS-203).
   * Чинить такой случай значило бы стереть то, ради чего он заведён.
   *
   * Строка — ДОВОД, а не флаг: непустая, иначе `validateFixtures` красный.
   * И объявление проверяется НАОБОРОТ: гейт требует, чтобы такой случай
   * переполнял на каждой шкале. Иначе поле стало бы вечной индульгенцией —
   * случай перестал переполнять, объявление осталось и прикрывает следующий
   * дефект того же места.
   */
  overflows?: string
  /**
   * СЛУЧАЙ НАРОЧНО НЕСЁТ ЦЕЛЬ МЕЛЬЧЕ 24 — и почему (DS-177). Строка-довод,
   * не флаг: пустая строка красная в `validateFixtures`. Проверяется НАОБОРОТ,
   * как `overflows`: объявлено — значит такая цель обязана найтись, иначе довод
   * протух и краснеет. Снимает ТОЛЬКО мелкость — перекрытая (непопадаемая)
   * цель на объявленном случае остаётся нарушением, довод её не прощает.
   *
   * Проверка НАОБОРОТ смотрит на СЛУЧАЙ, а не на отдельную шкалу (смягчение
   * DS-177, шаг 6). Мелкая цель растёт со шкалой
   * (`calc(<n>rem * var(--ds-ui-scale))`) и на старшей законно дотягивается
   * до пола 24 — это рост по шкале, а не протухший довод. Протухшим случай
   * считается, только когда мелкой цели нет НИ НА ОДНОЙ судимой шкале
   * (0.875, 1, 1.15, 1.5); строгая форма «на каждой шкале» красила бы Prose,
   * KeyValueList и слоты EventCalendar на 1.5 ложно.
   *
   * Заводится для дизайн-исключений (декоративный крестик внутри поля,
   * плотная сетка Heatmap, шаг временной шкалы EventCalendar, ссылка внутри
   * строки текста — SC 2.5.8 «essential»/«inline»).
   * Поимённого списка в скрипте нет и не будет: имя разрешает экземпляр,
   * форма и объявленный довод описывают случай.
   */
  tinyTargets?: string
  /**
   * СЛУЧАЙ НАРОЧНО НЕСЁТ ПОЛЕ УЖЕ ОБРАЗЦОВОГО ЗНАЧЕНИЯ — и почему
   * (DS-344). Строка-довод, не флаг: пустая красная в `validateFixtures`.
   * Проверяется НАОБОРОТ, как `overflows` и `tinyTargets`: объявлено — значит
   * узкое поле обязано найтись хотя бы на одной судимой шкале, иначе довод
   * протух и краснеет.
   *
   * Поле, которое по РАЗМЕТКЕ не может принять десять знаков (`maxlength`),
   * объявлять НЕ НАДО: строка ширины поля (`scripts/case-fields.mjs`) сужает
   * образец сама — ячейка `CodeInput` судится по одному знаку. Объявление
   * остаётся для того, что формой не выражается: поле, нарочно зажатое
   * раскладкой случая.
   */
  narrowFields?: string
  /** Нужен, когда у кейса отличается структура, а не только пропсы. */
  render?: (props: P, slots: Record<string, ReactNode>) => ReactNode
}

export interface Fixture<P> {
  name: string
  group: string
  props: P
  controls: Controls<P>
  /** Наборы стресс-данных: имя → дельта пропсов. */
  data?: Record<string, Partial<P>>
  cases: Case<P>[]
  kind?: SlotKind
  slots?: Record<string, Slot>
  /**
   * ЧЕГО ЗДЕСЬ НЕТ: `frame` — ни размера кадра, ни сцены (DS-91). Поле
   * было объявлено, не читалось никем и потому молча ничего не делало — самый
   * дорогой вид ошибки: заданное и проигнорированное выглядит работающим.
   *
   * Снято, а не реализовано, по двум причинам, и обе — про предмет:
   *
   * `width`/`height` — инструмент человека, а не свойство фикстуры. Ширину
   * кадра крутят руками, а вид «Сетка» рисует ОДНУ фикстуру сразу в четырёх
   * ширинах — в нём заданная фикстурой ширина либо спорит с предметом вида,
   * либо в нём же и игнорируется. Поле, которое обязано не работать в одном
   * из двух видов, контрактом не является.
   *
   * `scene: 'fixed-overlay'` — уже сделано устройством кадра. Кадр это
   * `<iframe>`, и `position: fixed` в нём кроет КАДР, а не окно оболочки;
   * инвариант измеряется (`make measure`, «Кадр не бутафория»). Обёртке сцены
   * нечего было бы добавить: единственный претендент, `Modal`, в кадре уже
   * ведёт себя правильно.
   */
  render?: (props: P, slots: Record<string, ReactNode>) => ReactNode
}

/** Фикстура с неизвестным наперёд параметром — то, что видят реестр и гейт. */
export type AnyFixture = Fixture<any>

/** Тождественная функция: существует ради вывода типов в самих фикстурах. */
export function defineFixture<P>(f: Fixture<P>): Fixture<P> {
  return f
}
