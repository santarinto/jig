/**
 * Триггер оверлея — ОДИН ЭЛЕМЕНТ ПОТРЕБИТЕЛЯ, на который компонент вешает свои
 * пропы через `cloneElement`. Общее у `Popover` и `DropdownMenu`
 * (DS-359).
 *
 * ЗАЧЕМ ФАЙЛ. До 4.3.x на один вопрос «как отдать оверлею свой триггер» в
 * системе было два ответа: `Popover` клонировал переданный элемент, а
 * `DropdownMenu` оборачивал его в СВОЮ кнопку `.ds-dropdown__triggerwrap`.
 * Цена второго ответа была видна поимённо — `CommandBar.css` и `AppBar.css`
 * перерисовывали метрики `ds-btn--ghost.ds-btn--sm` токенами, потому что
 * надеть `.ds-btn` на обёртку можно было только вложенным узлом, то есть
 * кнопкой в кнопке. Два ответа на один вопрос — то же самое, за что в системе
 * запрещён второй каталогизированный набор цветов.
 *
 * Здесь лежит ровно то, что у двух компонентов ОДИН КОД, а не похожий:
 * возврат фокуса на триггер поиском в DOM и бросок на триггере, который
 * кнопкой не является (второй `Popover` зовёт с DS-364). Слияние
 * обработчиков осталось по месту: наборы пропов разные (`Popover` вешает
 * только `onClick`, `DropdownMenu` ещё и `onKeyDown`), и общая обёртка над
 * двумя строками была бы абстракцией ради симметрии.
 */
import { isValidElement } from 'react'

/**
 * Фокусируемое в ПОРЯДКЕ ДОКУМЕНТА. Своя копия, а не общая на репозиторий:
 * список селекторов в системе живёт в восьми местах с разными оговорками
 * (`useFocusTrap` не смотрит на `textarea`, `CommandBar` — на `[href]`), и
 * свести их одной строкой значит незаметно поменять поведение у семи соседей.
 */
const FOCUSABLE = 'a[href], button:not(:disabled), input:not(:disabled), select:not(:disabled), textarea:not(:disabled), [tabindex]:not([tabindex="-1"])'

/**
 * Вернуть фокус на триггер, НАЙДЯ его в DOM, а не удержав рефом.
 *
 * Реф пришлось бы навесить на элемент потребителя — а он не обязан его
 * пробрасывать: наш собственный `Button` на React 18 отвечает на это
 * «Function components cannot be given refs», и `triggerRef.current` остаётся
 * `null`. Возврат фокуса тогда молча не делает ничего — при том что тест на
 * голом `<button>` зелёный, потому что там реф доезжает.
 *
 * @param root корень оверлея (`.ds-popover` / `.ds-dropdown`): триггер — его
 *   первый фокусируемый потомок.
 * @param excludeId `id` всплывающего узла. На момент вызова он ЕЩЁ В DOM
 *   (React размонтирует его после), и без исключения фокус ушёл бы в него.
 */
export function focusTriggerIn(root: HTMLElement | null, excludeId: string): void {
  if (!root) return
  const popup = root.querySelector(`#${CSS.escape(excludeId)}`)
  for (const el of root.querySelectorAll<HTMLElement>(FOCUSABLE)) {
    if (!popup?.contains(el)) { el.focus(); return }
  }
}

/**
 * Теги, которые фокусируемы САМИ и принимают пропы триггера. Больше в списке
 * быть нечему, и это ЗАКРЫТЫЙ список, а не перечисление привычного: `<input
 * type="button">`, `<summary>`, `<label>`, `<my-button>` и любой другой
 * интринсик отказывают наравне со `<span>`. Разрешить их значило бы
 * утверждать про чужую модель ввода то, чего отсюда не видно: `<input>` и
 * `<select>` фокусируемы, но клик по ним принадлежит им самим, `<summary>`
 * раскрывает свой `<details>`, а что делает пользовательский элемент, не
 * знает вообще никто. Выход для них один и он есть — КОМПОНЕНТ-ОБЁРТКА:
 * своему компоненту доверие выдаётся, потому что он отвечает за то, что
 * рисует.
 */
const TRIGGER_TAGS = new Set(['button', 'a'])

/** Как починить — одной строкой, общей всем отказам. */
const HOW = 'Передайте `<Button>`, `<button>` или `<a href>` — либо свой компонент-обёртку кнопки: '
  + '`trigger={<Button variant="secondary">Действия</Button>}`.'

/**
 * Что у двух клиентов РАЗНОЕ. Лежит здесь, а не аргументом у места вызова, по
 * приземлённой причине: гейт `no-hardcoded-ui-string` считает строку в
 * `src/components` текстом интерфейса, если она не стоит прямо в `throw`, — и
 * прав: отличить оттуда текст отказа от подписи он не может.
 *
 * `task` — код задачи, с которой бросок у ЭТОГО клиента появился: по нему
 * потребитель находит пункт CHANGELOG, а пункты у клиентов разные.
 */
const SITES = {
  DropdownMenu: {
    task: 'DS-359',
    whenFalsy: 'Ложное значение больше не означает «встань встроенным кебабом» — до 4.3.0 `trigger={cond && <X/>}` '
      + 'молча давал кебаб, и отличить это от забытого триггера было нельзя. '
      + 'Нет триггера — передайте `undefined` или не передавайте проп вовсе: встанет встроенный кебаб «⋯». '
      + 'Условный триггер пишется `trigger={cond ? <Button>…</Button> : undefined}`.',
  },
  Popover: {
    task: 'DS-364',
    whenFalsy: 'У Popover триггер обязателен: встроенного у него нет, и панель без триггера открыть нечем. '
      + 'Раньше ложное значение молча рисовало корень без кнопки. '
      + 'Условный Popover — это условие СНАРУЖИ: `{cond && <Popover trigger={<Button>…</Button>}>…</Popover>}`.',
  },
} as const

/**
 * Почему элемент обязан быть кнопкой САМ. Без «больше не»: у `DropdownMenu`
 * обёртка была и снята на DS-359, у `Popover` её не было и до того, и
 * фраза про историю одного клиента врала бы второму.
 */
const WHY_ELEMENT = 'Компонент не оборачивает переданное в свою кнопку — обработчик и `aria-*` он вешает прямо на этот элемент.'

/**
 * Бросок на триггере, который кнопкой не является.
 *
 * ПОЧЕМУ БРОСОК, А НЕ ТИП. `<span>` и `<button>` неразличимы типом: оба
 * `React.ReactElement`, и сузить проп до «фокусируемого элемента» TypeScript
 * не умеет. А старая форма — ровно `<span className="ds-btn …">`: так учило
 * превью для дизайн-агента, и так это скопировано у потребителя. Без броска
 * вызов продолжил бы компилироваться и рисоваться, а триггер молча перестал бы
 * быть таб-стопом и перестал бы открываться с клавиатуры. Класс дефектов
 * эпика DS-248 — «молчаливая деградация API».
 *
 * СУДИТ ПО ТИПУ ЭЛЕМЕНТА-СТРОКИ, а не по DOM. Компонент (`<Button>`, обёртка
 * кнопки у потребителя) по типу не распознать вовсе — `typeof type ===
 * 'function'` говорит лишь, что это компонент, и что он рисует, знает только
 * он сам. Судить по DOM значило бы судить ПОСЛЕ монтирования, то есть в
 * эффекте: на сервере проверки нет, а у потребителя бросок прилетал бы не из
 * той фазы, где стоит его вызов. Поэтому правило одностороннее: интринсик не
 * из списка — отказ, компонент — доверие. Оно ловит ровно тот случай, который
 * в системе есть.
 *
 * Фрагмент (`<>…</>`) — отдельная строка отказа, и он не педантизм: `<>` не
 * принимает пропов вовсе, то есть `onClick` и `aria-expanded` уехали бы в
 * никуда, а React напечатал бы предупреждение в консоль и продолжил рисовать.
 * Так триггер и был написан в `demo/sections/button-matrix.tsx`.
 *
 * `<a>` без `href` отказывает по той же причине, что `<span>`: он не
 * фокусируем, и «ссылка» здесь только на вид.
 *
 * ЛОЖНОЕ ЗНАЧЕНИЕ (`null`, `false`, `''`) — свой отказ со своим текстом, и
 * текст этот СВОЙ У КАЖДОГО КЛИЕНТА (`SITES[…].whenFalsy`). Замена
 * у двух клиентов разная по существу: у `DropdownMenu` есть встроенный кебаб,
 * и «нет триггера» пишется `undefined`; у `Popover` встроенного триггера нет,
 * `undefined` — такой же отказ, и условие выносится наружу. Общий текст про
 * кебаб в `Popover` был бы советом, ведущим в следующий бросок
 * (DS-364). Сообщать, что пришёл `object`, нельзя ни одному: «не
 * object» верно и бесполезно.
 *
 * `undefined` сюда доходит только от клиента, у которого триггер обязателен:
 * `DropdownMenu` отсекает его до вызова — это и есть его «триггера нет».
 *
 * @param client чей это триггер. Имя компонента уходит в начало текста —
 *   потребитель обязан узнать своё место вызова, а не «где-то в
 *   дизайн-системе»; остальное, что у клиентов разное, лежит в `SITES`.
 */
export function assertTriggerElement(trigger: unknown, client: keyof typeof SITES): void {
  const site = SITES[client]
  const where = `${client}: \`trigger\``
  if (!isValidElement(trigger)) {
    if (trigger == null || trigger === false || trigger === '') {
      throw new TypeError(
        `${where}: пришло \`${trigger === '' ? "''" : String(trigger)}\` (${site.task}). ${site.whenFalsy}`,
      )
    }
    throw new TypeError(
      `${where}: триггер — ЭЛЕМЕНТ-КНОПКА, а не ${typeof trigger} (${site.task}). `
      + WHY_ELEMENT + ' ' + HOW,
    )
  }
  const type = (trigger as React.ReactElement).type
  if (typeof type === 'string') {
    if (!TRIGGER_TAGS.has(type)) {
      throw new TypeError(
        `${where}: триггер — ЭЛЕМЕНТ-КНОПКА, а пришёл \`<${type}>\` (${site.task}). `
        + WHY_ELEMENT + ' '
        + `\`<${type}>\` не фокусируется, не объявляется кнопкой и с клавиатуры оверлей не открывает. `
        + 'Список закрыт: законны только `<button>` и `<a href>`, а `<input type="button">`, `<summary>`, `<label>` '
        + 'и пользовательский элемент (`<my-button>`) отказывают наравне со `<span>` — их модель ввода принадлежит им, а не оверлею. '
        + HOW,
      )
    }
    if (type === 'a' && (trigger as React.ReactElement<{ href?: unknown }>).props.href == null) {
      throw new TypeError(
        `${where}: триггер \`<a>\` без \`href\` (${site.task}) — такая ссылка не фокусируется, то есть это тот же \`<span>\`, только на вид. `
        + HOW,
      )
    }
    return
  }
  // Компонент, `memo`, `forwardRef` — объект или функция; что он рисует, знает
  // только он, и отказывать здесь значило бы отказывать своему же `<Button>`.
  if (typeof type === 'function' || (typeof type === 'object' && type !== null)) return
  throw new TypeError(
    `${where}: триггер — ОДИН элемент-кнопка, а не фрагмент (${site.task}). `
    + '`<>…</>` пропов не принимает вовсе: `onClick` и `aria-expanded` уехали бы в никуда, а React напечатал бы предупреждение и продолжил рисовать. '
    + HOW,
  )
}
