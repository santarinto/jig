/**
 * Ступень секвенциального рампа `--ds-heat-*` по значению и порогам.
 *
 * Это ЕДИНСТВЕННОЕ место системы, где цвет кодирует величину, и потому у рампа
 * ровный шаг в L* (гейт `colour-law`). Всё остальное — категории и состояния.
 *
 * Вынесено из `Heatmap.tsx` тем же приёмом, что `Tree/model.ts`: чистая функция
 * получает прямые кейсы на границы порогов, которые через рендер календаря
 * никто не напишет (DS-117). Уровень при этом остаётся CSS-контрактом —
 * в разметке он выражен классом `ds-heat__swatch--N`, и второго представления
 * (`data-level`) у него намеренно нет.
 */

/**
 * Ступеней в рампе — столько же токенов `--ds-heat-*`. Это ПОТОЛОК числа
 * ступеней, а не само число: сколько их на конкретном ряде порогов, отвечает
 * `heatLevelCount`, и легенда спрашивает её, а не эту константу (DS-188).
 */
export const HEAT_LEVELS = 5

/**
 * Пороги теплокарты: от нуля до ЧЕТЫРЁХ, и это `HEAT_LEVELS - 1`, выраженное
 * типом (DS-208).
 *
 * Кортежем, а не `number[]`, потому что длину массива тип иначе не держит, а
 * держать её надо на стороне ВЫЗОВА: пятый порог не рисует ничего — он
 * отбрасывался молча, и компонент переставал различать то, что ему задали, не
 * говоря об этом ни строкой. Молчаливая деградация вместо отказа — ровно то,
 * что закон проекта запрещает (CLAUDE.md, Deprecated API): старая форма обязана
 * быть ошибкой КОМПИЛЯЦИИ.
 *
 * `readonly`, чтобы принимать и `as const`, и обычный литерал: компонент пороги
 * только читает, а требование мутабельности отвергало бы законный вызов.
 *
 * Цена названа: `number[]`, собранный в рантайме (квартили из данных), в такой
 * тип сам не встанет. Лечение — объявить константу этим типом
 * (`const t: HeatThresholds = [q1, q2, q3]`), а не приводить через `as`:
 * аннотация проверяет длину, приведение её выключает.
 */
export type HeatThresholds =
  | readonly []
  | readonly [number]
  | readonly [number, number]
  | readonly [number, number, number]
  | readonly [number, number, number, number]

/**
 * Порогов не больше четырёх — на пути, где типа нет (`any` у потребителя,
 * JS-вызов, данные из конфига). Бросок, а не кламп: см. `HeatThresholds`.
 *
 * Зовётся ОДИН раз за рендер, из компонента, а не из `heatLevel` — тот бежит по
 * ячейке на каждый день, и сообщение оттуда рассказывало бы про день, а ошибка
 * не в дне.
 */
export function assertHeatThresholds(thresholds: readonly number[]): void {
  if (thresholds.length > HEAT_LEVELS - 1) {
    throw new Error(
      `jig: Heatmap — порогов ${thresholds.length}, а больше ${HEAT_LEVELS - 1} `
      + `не бывает. Рамп --ds-heat-* даёт ${HEAT_LEVELS} ступеней, значит границ между `
      + 'ними ровно четыре; лишние раньше отбрасывались МОЛЧА, и компонент переставал '
      + 'различать заданное, не сообщая об этом. Оставьте не больше четырёх порогов '
      + 'или сведите шкалу (DS-208).',
    )
  }
}

/**
 * Порог ВКЛЮЧИТЕЛЬНЫЙ: значение, равное порогу, уже принадлежит верхней
 * ступени. Иначе ряд порогов `[1, 3, 6, 10]` оставлял бы единицу на нулевом
 * уровне — то есть день с одной поездкой красился бы как день без поездок.
 *
 * Уровень ограничен сверху числом ступеней рампа: лишние пороги дали бы
 * уровень, которому не соответствует ни один токен, и ячейка осталась бы вовсе
 * без цвета. Пороги ниже нуля компонент не запрещает, и клампа снизу нет —
 * при `thresholds: [-5, 0]` отрицательное значение законно попадает выше нуля.
 *
 * Кламп сверху ОСТАЁТСЯ, но перестал быть ОТВЕТОМ на ошибку потребителя
 * (DS-208): на публичном входе лишний порог теперь ошибка типа, а на
 * входе без типа — бросок `assertHeatThresholds`. Здесь он держит функцию
 * тотальной для прямого вызова из системы: `ds-heat__swatch--7` не имеет
 * токена, и ячейка без цвета хуже ячейки на верхней ступени.
 */
export function heatLevel(value: number, thresholds: readonly number[]): number {
  return Math.min(heatLevelCount(thresholds) - 1, countAbove(value, thresholds))
}

function countAbove(value: number, thresholds: readonly number[]): number {
  let n = 0
  for (const t of thresholds) if (value >= t) n++
  return n
}

/**
 * Сколько ступеней компонент РАЗЛИЧАЕТ на этом ряде порогов (DS-188).
 *
 * Одно правило на обе стороны клампа, и в этом весь смысл функции. Пять клеток
 * легенды были константой рампа, а не следствием порогов: при `thresholds:
 * [-5, 0]` компонент различает три ступени, а легенда рисовала пять — замерено
 * на 27 днях дельты, ячеек по ступеням 3/9/15/0/0 при пяти клетках легенды. Две
 * правые не встречались в сетке НИ РАЗУ.
 *
 * Дороже, чем выглядит: легенда — единственный образец шкалы, который видит
 * читатель. Сравнивая квадрат с ней, он заключает «до максимума ещё далеко»,
 * хотя максимум ЭТИХ данных — средняя клетка. Это ошибка чтения ВЕЛИЧИНЫ, то
 * есть ровно то, ради чего рамп и существует. Короткие и отрицательные ряды
 * законны намеренно (`[-5, 0]` — «стало хуже или лучше», клампа снизу нет), так
 * что случай не экзотический: он наступает у первого же, кто приложит теплокарту
 * к дельте.
 *
 * Сверху по-прежнему `HEAT_LEVELS`: порогов больше четырёх компонент не
 * различает, потому что токенов `--ds-heat-*` пять. Спрашивать об этом легенду
 * больше не приходится — до неё дело не доходит: пятый порог не компилируется
 * (`HeatThresholds`), а на пути без типа компонент бросает
 * (DS-208). Кламп здесь держит функцию тотальной, и только.
 *
 * Дефолтные `[1, 3, 6, 10]` дают те же пять — существующие календари не
 * меняются ничем.
 */
export function heatLevelCount(thresholds: readonly number[]): number {
  return Math.min(thresholds.length + 1, HEAT_LEVELS)
}
