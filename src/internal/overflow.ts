/**
 * Сколько действий остаётся в полосе, когда хвост сворачивается в «Ещё»
 * (DS-239).
 *
 * ПОЧЕМУ АРИФМЕТИКА ЗДЕСЬ, А НЕ ВО ФЛЕКСЕ. Если позволить раскладке самой
 * решать, сколько влезло, получается автоколебание: появление «Ещё» сужает
 * ряд, суженный ряд сворачивает ещё одно действие, а свернувшись до предела —
 * освобождает место, «Ещё» пропадает, и круг начинается заново. Поэтому
 * бюджет берётся от величины, которая от свёртки НЕ ЗАВИСИТ (ширина полосы
 * минус её паддинги минус хвостовой слот), а ширина кнопки «Ещё» входит в
 * расчёт числом — ровно тогда, когда что-то свёрнуто.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ТЕЛО КОМПОНЕНТА. В jsdom раскладки нет:
 * `offsetWidth` там ноль у всего, и тест через рендер панели остался бы
 * зелёным при полностью сломанном счёте. Здесь арифметика проверяется без
 * DOM, а то, что компонент подставляет в неё НАСТОЯЩИЕ числа, держит случай
 * `measure` в chromium. Пара, а не дубль: каждое утверждение переживает
 * поломку, которую не видит второе.
 */

export interface OverflowItem {
  /** Натуральная ширина действия, px. Действия не ужимаются: подпись и есть минимум. */
  width: number
  /**
   * Действие открывает новую группу — перед ним стоит разделитель.
   *
   * У НУЛЕВОГО ИНДЕКСА ИГНОРИРУЕТСЯ. Первая группа тоже группа, и потребитель
   * честно помечает её начало; но разделитель ПЕРЕД первым действием рисовать
   * нечего, и заплаченные за него пиксели свернули бы хвост на ровном месте.
   */
  startsGroup?: boolean
}

export interface OverflowMetrics {
  /** `gap` полосы, px. */
  gap: number
  /** Полная ширина разделителя вместе с его полями, px. */
  sepWidth: number
  /** Ширина кнопки «Ещё», px. */
  moreWidth: number
}

/**
 * Допуск на дробный пиксель. Ширины приезжают из `getBoundingClientRect`, а
 * `--ds-ui-scale` 1.15 у потребителя даёт дроби — без допуска полоса
 * сворачивала бы хвост от ошибки округления, и читалось бы это как «на 1.15
 * действий меньше».
 */
const EPS = 0.5

/** Сколько разделителей стоит среди первых `k` действий. */
function separators(items: readonly OverflowItem[], k: number): number {
  let n = 0
  for (let i = 1; i < k; i++) if (items[i]?.startsGroup) n++
  return n
}

/**
 * Сколько места занимают первые `k` действий вместе со своими разделителями.
 * Кнопка «Ещё» сюда НЕ входит — её резервирует вызывающий.
 */
export function overflowCost(items: readonly OverflowItem[], k: number, m: OverflowMetrics): number {
  if (k <= 0) return 0
  let sum = 0
  for (let i = 0; i < k; i++) sum += items[i]?.width ?? 0
  const seps = separators(items, k)
  // Элементов в ряду — действия плюс разделители; зазоров на один меньше.
  const elements = k + seps
  return sum + seps * m.sepWidth + (elements - 1) * m.gap
}

/**
 * Сколько действий остаётся видимыми. Остальные уходят в меню «Ещё».
 *
 * Ответ `items.length` значит «свёртки нет»; `0` — в полосе осталась одна
 * кнопка «Ещё», и это настоящий случай (кадр 360, шкала 1.5, подпись
 * «Отменить проведение»), а не вырождение: меню со всеми действиями лучше
 * полосы, из которой видно половину первого слова.
 */
export function fitCount(
  items: readonly OverflowItem[],
  o: OverflowMetrics & { available: number },
): number {
  const n = items.length
  if (n === 0) return 0
  if (overflowCost(items, n, o) <= o.available + EPS) return n
  for (let k = n - 1; k > 0; k--) {
    if (overflowCost(items, k, o) + o.gap + o.moreWidth <= o.available + EPS) return k
  }
  return 0
}
