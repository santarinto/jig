/**
 * Форматтеры `Intl`, привязанные к локали системы (DS-184).
 *
 * Зачем прослойка, а не `new Intl.DateTimeFormat(locale, …)` на месте.
 * Конструктор `Intl` — из дорогих: он разбирает тег локали и поднимает данные
 * ICU. До этой задачи компоненты платили за него ОДИН РАЗ, потому что держали
 * форматтер модульной константой; но константа знает локаль на момент загрузки
 * модуля, а не на момент рендера, — ровно поэтому локаль и оказалась нерешённой.
 * Перенести конструктор в тело компонента значило бы платить за него на каждый
 * рендер и в каждой ячейке цикла: `Heatmap` зовёт `dayFmt` на каждый день года.
 *
 * Кэш возвращает прежнее свойство: конструктор зовётся один раз на пару
 * «локаль × набор опций», а не один раз на модуль. Записей столько, сколько
 * различных пар встретилось, — то есть единицы: локаль у потребителя одна, а
 * наборы опций в коде литеральные и пересчитываются по пальцам.
 *
 * Кэш модульный, а не в React-состоянии, СОЗНАТЕЛЬНО: форматтер — чистое
 * значение от (локаль, опции), у него нет ни владельца, ни времени жизни, и
 * держать его в дереве значило бы городить провайдер ради общей константы.
 * На сервере это тоже верно и там же важнее: SSR рендерит много деревьев в
 * одном процессе, и кэш переживает их все.
 */

/**
 * Ключ кэша. Имена опций СОРТИРУЮТСЯ, а не берутся в порядке литерала: два
 * вызова с одинаковым набором полей, набранных в разном порядке, обязаны
 * получить один форматтер. Иначе кэш тихо растёт и перестаёт быть кэшем,
 * оставаясь при этом правильным, — то есть дефект не проявляется ничем, кроме
 * памяти.
 *
 * `|` разделителем, потому что он не встречается ни в теге локали, ни в имени
 * опции, ни в её значении: склейка `ru-RUmonth=long` и `ru` + `RUmonth` иначе
 * дала бы один ключ на две разные пары. Не `\u0000`, хотя он подошёл бы лучше:
 * гейт `no-nul-bytes` запрещает нулевой байт в исходниках, и запрещает по делу
 * — файл с ним выпадает из индекса поиска и не ищется grep-ом.
 */
function cacheKey(locale: string, options?: Record<string, unknown>): string {
  if (!options) return locale
  const parts: string[] = []
  for (const name of Object.keys(options).sort()) {
    parts.push(`${name}=${String(options[name])}`)
  }
  return `${locale}|${parts.join(',')}`
}

const dateCache = new Map<string, Intl.DateTimeFormat>()
const numberCache = new Map<string, Intl.NumberFormat>()

/** `Intl.DateTimeFormat` для этой локали и этих опций, один экземпляр на пару. */
export function dateFormat(
  locale: string,
  options?: Intl.DateTimeFormatOptions,
): Intl.DateTimeFormat {
  const key = cacheKey(locale, options as Record<string, unknown> | undefined)
  let fmt = dateCache.get(key)
  if (!fmt) {
    fmt = new Intl.DateTimeFormat(locale, options)
    dateCache.set(key, fmt)
  }
  return fmt
}

/** `Intl.NumberFormat` для этой локали и этих опций, один экземпляр на пару. */
export function numberFormat(
  locale: string,
  options?: Intl.NumberFormatOptions,
): Intl.NumberFormat {
  const key = cacheKey(locale, options as Record<string, unknown> | undefined)
  let fmt = numberCache.get(key)
  if (!fmt) {
    fmt = new Intl.NumberFormat(locale, options)
    numberCache.set(key, fmt)
  }
  return fmt
}

/**
 * Дата, которую не удалось разобрать, показывается СЫРОЙ строкой, а не пустотой
 * и не броском: её видно, и по ней сразу понятно, что пришло с сервера.
 *
 * Собрано сюда из `Timeline`, `AgentTranscript` и `LogViewer`, где до этой
 * задачи лежало три копии одной функции с тремя разными именами.
 */
export function safeFormatDate(ts: string, fmt: Intl.DateTimeFormat): string {
  const d = new Date(ts)
  return Number.isNaN(d.getTime()) ? ts : fmt.format(d)
}

/**
 * Первая буква заглавной — для подписи, которая стоит ЗАГОЛОВКОМ, а не внутри
 * фразы.
 *
 * Нужно потому, что `Intl` отдаёт названия месяцев и дней недели в том виде, в
 * каком язык пишет их В ТЕКСТЕ: по-русски это «сентябрь» и «пн» со строчной.
 * В шапке календаря и в столбце сетки они стоят самостоятельно, и строчная там
 * читается как опечатка. Для языков, пишущих их с прописной (английский), это
 * ничего не меняет; для языков без регистра — тоже.
 *
 * Границы приёма честные: это НЕ полноценная типографика заголовка, и в
 * подписи ВНУТРИ фразы («2 сентября 2026») её звать нельзя — там строчная
 * правильна. Поэтому функция отдельная и зовётся поимённо, а не встроена в
 * `dateFormat`.
 *
 * Локаль передаётся и в подъём регистра: в турецком `i` поднимается в `İ`, а
 * не в `I`, и взять регистр у системы значило бы завести второй источник
 * локали внутри задачи, которая ровно этот раскол и чинит.
 */
export function capitalizeFirst(s: string, locale?: string): string {
  return s.length === 0 ? s : s[0]!.toLocaleUpperCase(locale) + s.slice(1)
}
