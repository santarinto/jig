import { describe, it, expect } from 'vitest'
import { fitCount, overflowCost, type OverflowItem } from './overflow.js'

/**
 * Счёт влезающего — ЧИСТОЙ ФУНКЦИЕЙ, и это не вкусовщина (DS-239).
 * В jsdom раскладки нет вовсе: `offsetWidth` там ноль у всего, поэтому через
 * рендер панели арифметика свёртки не проверяется НИКАК — тест был бы зелёным
 * и при полностью сломанном счёте. Пара утверждений как у DS-170: здесь
 * арифметика без DOM, а в `measure` — настоящий chromium, который переживёт
 * сломанный лист.
 */

/** Однородная полоса: n действий по `w` пикселей, без групп. */
const plain = (n: number, w: number): OverflowItem[] =>
  Array.from({ length: n }, () => ({ width: w }))

/** Полоса, в которой действия по 100, а `groups` — индексы начала групп. */
const grouped = (n: number, groups: number[]): OverflowItem[] =>
  Array.from({ length: n }, (_, i) => ({ width: 100, startsGroup: groups.includes(i) }))

const O = { gap: 8, sepWidth: 17, moreWidth: 60 }

describe('fitCount: сколько действий остаётся в полосе', () => {
  it('всё влезает — «Ещё» не резервируется вовсе', () => {
    // Пять по 100 плюс четыре зазора = 532. Бюджет 532 — ровно впритык, и
    // резерв под «Ещё» здесь НЕ платится: сворачивать нечего.
    expect(fitCount(plain(5, 100), { ...O, available: 532 })).toBe(5)
  })

  it('не хватило одного пикселя — «Ещё» появляется и уносит С СОБОЙ ещё одно действие', () => {
    // Это главное утверждение функции. Наивный счёт «сколько влезло» ответил
    // бы 4 (4×100 + 3×8 = 424 ≤ 531), и панель нарисовала бы «Ещё» ПОВЕРХ
    // бюджета: 424 + 8 + 60 = 492 ≤ 531 — тут ещё влезает, а вот пятое нет.
    expect(fitCount(plain(5, 100), { ...O, available: 531 })).toBe(4)
    // Сузим так, чтобы четвёртое перестало влезать вместе с «Ещё»:
    // cost(4) + gap + more = 492, cost(3) + gap + more = 384.
    expect(fitCount(plain(5, 100), { ...O, available: 491 })).toBe(3)
  })

  it('разделитель занимает место, и из-за него сворачивается больше', () => {
    // Те же пять по 100, но группа начинается с третьего: в полосе появляется
    // разделитель (17 px) и ещё один зазор. Бюджет 532, которого хватало на
    // все пять без групп, теперь не хватает.
    expect(fitCount(grouped(5, [2]), { ...O, available: 532 })).toBe(4)
    expect(fitCount(grouped(5, [2]), { ...O, available: 557 })).toBe(5)
  })

  it('ВЕДУЩИЙ разделитель не считается никогда, даже если у первого действия своя группа', () => {
    // `startsGroup` у нулевого индекса — обычное дело: первая группа тоже
    // группа. Но рисовать разделитель ПЕРЕД первым действием нечего, и если
    // счёт заплатит за него 17 px, полоса свернёт лишнее на ровном месте.
    expect(fitCount(grouped(5, [0]), { ...O, available: 532 })).toBe(5)
    expect(overflowCost(grouped(5, [0]), 5, O)).toBe(overflowCost(plain(5, 100), 5, O))
  })

  it('свёрнутый хвост уносит свой разделитель, а не оставляет его сиротой', () => {
    // Группа начинается с четвёртого. Оставили три — разделителя нет вовсе:
    // он стоял бы ПОСЛЕ последнего видимого и означал бы «дальше другая
    // группа» там, где дальше ничего.
    const items = grouped(6, [3])
    expect(overflowCost(items, 3, O)).toBe(3 * 100 + 2 * 8)
    expect(overflowCost(items, 4, O)).toBe(4 * 100 + 4 * 8 + 17)
  })

  it('не влезает ни одно действие — в полосе остаётся одна кнопка «Ещё»', () => {
    // Вырожденный, но настоящий случай: кадр 360, шкала 1.5, подпись
    // «Отменить проведение». Меню со всеми действиями лучше полосы, из
    // которой видно половину первого слова.
    expect(fitCount(plain(3, 400), { ...O, available: 200 })).toBe(0)
  })

  it('пустой список — ноль, и «Ещё» не выводится', () => {
    expect(fitCount([], { ...O, available: 500 })).toBe(0)
    expect(overflowCost([], 0, O)).toBe(0)
  })

  it('дробный пиксель не сворачивает действие: допуск полпикселя', () => {
    // Ширины приходят из `getBoundingClientRect`, а `--ds-ui-scale` 1.15 даёт
    // дроби. Без допуска полоса сворачивала бы хвост от ошибки округления —
    // и выглядело бы это как «на 1.15 действий меньше».
    // Точная стоимость трёх — 316.6. Полпикселя НЕ ХВАТАЕТ, и дальше начинается
    // настоящая теснота, а не округление.
    expect(fitCount(plain(3, 100.2), { ...O, available: 316.2 })).toBe(3)
    expect(fitCount(plain(3, 100.2), { ...O, available: 315.9 })).toBe(2)
  })

  it('чем шире полоса, тем не меньше видимых действий — счёт монотонен', () => {
    // Немонотонный счёт даёт мигание при плавном изменении ширины: действие
    // то появляется, то исчезает, и глазами это читается как дефект отрисовки.
    const items = grouped(8, [2, 5])
    let prev = -1
    for (let avail = 0; avail <= 1400; avail += 7) {
      const k = fitCount(items, { ...O, available: avail })
      expect(k).toBeGreaterThanOrEqual(prev)
      prev = k
    }
    expect(prev).toBe(8)
  })

  it('видимое плюс резерв под «Ещё» НИКОГДА не выходит за бюджет', () => {
    // Утверждение, ради которого функция вообще существует: что бы она ни
    // ответила, нарисованное влезает. Именно этого не делала полоса до
    // DS-170 — она отдавала лишнее ДОКУМЕНТУ.
    const items = grouped(9, [3, 4, 7])
    for (let avail = 0; avail <= 1600; avail += 3) {
      const k = fitCount(items, { ...O, available: avail })
      const used = overflowCost(items, k, O) + (k < items.length ? O.gap + O.moreWidth : 0)
      if (k > 0) expect(used).toBeLessThanOrEqual(avail + 0.5)
    }
  })
})
