/**
 * Вертикаль подписи пустого поля графика («Все ряды скрыты»): середина между
 * двумя горизонтальными линиями сетки, ближайшими к центру поля.
 *
 * Найдено приёмкой глазами (DS-276, З-3). Подпись стояла ровно по центру
 * поля, и при нечётном числе тиков средняя линия сетки проходила сквозь текст —
 * на беглый взгляд подпись принадлежала тику, а не полю.
 *
 * ПОЧЕМУ ГЕОМЕТРИЯ, А НЕ ОРЕОЛ. Подложка или `paint-order: stroke` цветом
 * `--ds-surface` предполагали бы, что график лежит на поверхности. Он лежит где
 * угодно — в `Card`, на `--ds-bg-app`, на подложке потребителя, — и ореол не того
 * цвета был бы пятном. Промежуток между линиями от фона не зависит.
 *
 * Линий меньше двух — промежутка нет, остаётся центр: пересекать там нечего.
 */
export function emptyCaptionY(lines: number[], top: number, bottom: number): number {
  const center = (top + bottom) / 2
  const ys = lines.filter((y) => y >= top && y <= bottom).sort((a, b) => a - b)
  if (ys.length < 2) return center
  // Пара соседних линий, чья середина ближе всего к центру поля. При центре
  // ровно на линии обе соседние пары равноудалены — берётся первая (верхняя),
  // выбор детерминирован.
  let best = (ys[0]! + ys[1]!) / 2
  for (let i = 1; i < ys.length - 1; i++) {
    const mid = (ys[i]! + ys[i + 1]!) / 2
    if (Math.abs(mid - center) < Math.abs(best - center)) best = mid
  }
  return best
}
