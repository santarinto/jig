import { useDsText } from '../../dictionary/DsText.js'
import './AsOf.css'

export interface AsOfStale {
  /**
   * Порог в днях: подпись старше — предупреждающий тон. Приходит **с вызова**, а
   * не из компонента: у остатка счёта (стареет за две недели) и у курса валюты
   * (недельной давности — уже другой курс) свежесть измеряется разным, единого
   * числа тут нет.
   */
  afterDays: number
  /**
   * «Сегодня» — дата сервера на момент рендера, **проп, а не часы**. Дефолта нет
   * и быть не должно: отчёт потребителя детерминирован и тестируется на
   * фикстурах, а часы внутри сделали бы его тесты зависимыми от дня прогона —
   * устаревание вылезло бы в разметку и уронило проверку, которая про него не
   * была. ISO (`YYYY-MM-DD`).
   */
  today: string
}

export interface AsOfProps {
  /**
   * Дата, снятая на момент. ISO (`YYYY-MM-DD`): компонент и отображает
   * (`ДД.ММ.ГГГГ`), и — если задан `stale` — считает по ней возраст. Пустая
   * строка → компонент **молчит**: у несуществующего числа нет возраста (это
   * нужно при встраивании в `Money`, где значения может не быть). Нужна видимая
   * подпись вместо молчания — `unknownLabel`.
   *
   * Строку, не разобравшуюся как ISO, компонент показывает **как есть** и
   * возраст по ней не считает: нечитаемая дата должна быть видна на экране, а не
   * подменена пустотой — пустоту принимают за «даты и не было».
   */
  date: string
  /** Ведущее слово: «остаток на», «курс от». Default «на». */
  label?: string
  /**
   * Устаревание. Порог и «сегодня» приходят **одним объектом**, который нельзя
   * задать наполовину: иначе «задал порог, забыл дату» молча значило бы «никогда
   * не устаревает» — проп есть, а работы нет. Компонент сам считает, стар ли, и
   * на сколько дней.
   */
  stale?: AsOfStale
  /**
   * Слово-признак устаревания — показывается **словом**, а не только цветом
   * (иначе в монохромной печати и при дальтонизме предупреждение исчезает).
   * Default «устарело»; к нему компонент добавляет «, N дн.».
   */
  staleLabel?: string
  /**
   * Что сказать, когда даты нет вовсе. **Задан — подпись видима, не задан —
   * компонент молчит** (прежнее и по-прежнему умолчание).
   *
   * Две разные роли требуют разного, поэтому это опция, а не поведение. Внутри
   * `Money` дата — приложение к числу, и молчать правильно: рядом уже стоит
   * прочерк со своей причиной, а «дата неизвестна» читалась бы вторым дефектом.
   * Самостоятельной подписью — наоборот: отсутствие даты само по себе сведение,
   * и молчание делает «дату не знаем» неотличимым от «подпись забыли
   * поставить». Различить их по экрану нельзя, а починить второе можно только
   * заметив.
   */
  unknownLabel?: string
  className?: string
}

/** ISO (`YYYY-MM-DD`) → `ДД.ММ.ГГГГ` строкой, без `Date`: разбор по частям tz-safe. */
function formatIso(iso: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso)
  return m ? `${m[3]}.${m[2]}.${m[1]}` : iso
}

/**
 * Возраст числа: подпись «остаток на 07.08.2026», «курс от 05.08.2026».
 *
 * Одно правило вместо разнобоя из мелкого серого текста, набранного по-разному
 * в пяти местах. Если задан `stale`, компонент сам считает возраст и переводит
 * подпись в предупреждающий тон, помеченный **словом**, а не только цветом.
 */
export function AsOf({
  date, label, stale, staleLabel, unknownLabel, className,
}: AsOfProps) {
  const t = useDsText()
  if (!date) {
    if (!unknownLabel) return null
    return (
      <span className={['ds-asof', 'ds-asof--unknown', className].filter(Boolean).join(' ')}>
        {unknownLabel}
      </span>
    )
  }
  let isStale = false
  let ageDays = 0
  if (stale) {
    // Date.parse по ISO-датам — UTC-полночь, разница делится на сутки ровно.
    // Часов здесь нет: «сегодня» пришло пропом, результат детерминирован.
    ageDays = Math.round((Date.parse(stale.today) - Date.parse(date)) / 86_400_000)
    // Сравнение ОДНОСТОРОННЕЕ, и это решение, а не следствие записи. Устаревает
    // только прошлое: у будущей даты возраст отрицательный, и «устарело, −24 дн.»
    // было бы ложью о дате платежа, который ещё не наступил. Соблазн написать
    // здесь `Math.abs` — ровно та поломка, которую держит тест «дата в будущем
    // не устаревает».
    isStale = ageDays > stale.afterDays
  }
  return (
    <span className={['ds-asof', isStale && 'ds-asof--stale', className].filter(Boolean).join(' ')}>
      <span className="ds-asof__label">{label ?? t['asOf.at']} </span>
      <time className="ds-asof__date" dateTime={date}>{formatIso(date)}</time>
      {isStale && <span className="ds-asof__flag"> · {staleLabel ?? t['asOf.stale']}, {t['asOf.days'](ageDays)}</span>}
    </span>
  )
}
