import '../../styles/visually-hidden.css'
import { useDsText } from '../../dictionary/DsText.js'
import './EstimateMark.css'

export interface EstimateMarkProps {
  /**
   * Чем помечена величина. Уходит в дерево доступности **текстом**, а не в
   * `title`: `title` недостижим и с клавиатуры, и со скринридера — это уже
   * записано у `Money.unknownHint`, и второе решение той же беды в той же
   * системе было бы просто непоследовательностью.
   *
   * Default «оценочная величина». Переопределять стоит, когда оценочность
   * названа точнее: «ставка оценочная», «сумма по графику, не из договора».
   */
  hint?: string
  className?: string
}

/**
 * Знак оценочности — звёздочка у величины, посчитанной, а не взятой из
 * документа.
 *
 * **Отдельный компонент, а не проп `Money`,** потому что оценочными бывают не
 * только деньги: у потребителя звёздочка стоит и на суммах, и на процентных
 * ставках («43% *»). Пока знак жил внутри `Money`, второй случай приходилось
 * рисовать руками — и в одной таблице оказывались две разные звёздочки,
 * компонентная и своя. Один знак на оба случая — это и есть весь смысл.
 *
 * Звёздочка на экране декоративна (`aria-hidden`), а несёт её смысл соседний
 * скрытый текст. Обратный порядок — звёздочка в дереве доступности, пояснение
 * в `title` — как раз то, что здесь чинится: скринридер объявлял «звёздочка»
 * и замолкал.
 *
 * **Легенда страницы — работа потребителя.** Сигхтед-читателю звёздочку
 * объясняет строка внизу таблицы, а не повтор пояснения у каждого числа:
 * видимый текст на каждой строке залил бы колонку шумом.
 */
export function EstimateMark({ hint, className }: EstimateMarkProps) {
  const t = useDsText()
  return (
    <span className={['ds-estmark', className].filter(Boolean).join(' ')}>
      <span className="ds-estmark__star" aria-hidden="true">*</span>
      <span className="ds-visually-hidden">{hint ?? t['estimateMark.hint']}</span>
    </span>
  )
}
