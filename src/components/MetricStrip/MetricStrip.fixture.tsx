/**
 * Полоса заголовочных чисел. `kind: 'block'` — она идёт во всю ширину карточки
 * или шапки раздела, а не вкладывается в ячейку.
 *
 * Главная пара состояний здесь — **ноль против отсутствия**, и она из того же
 * рода, что «ноль против неизвестного» у `ProgressBar`. «0 прогонов» это ФАКТ:
 * воркер существует, запусков не было. «Данных нет» — отсутствие самого факта:
 * не считали, не дошли, не спросили. Порознь оба выглядят как «в ячейке ничего
 * содержательного», и различить их можно только рядом — поэтому случай ставит
 * их в одну полосу, а не в две.
 *
 * До DS-93 второго состояния не существовало вовсе: прочерк, положенный
 * потребителем строкой, получал `font-weight: 700` и `color:
 * var(--ds-text-primary)` от `.ds-metrics__value` — то есть был побуквенно
 * неотличим от настоящего числа (замерено: вес 700 и `rgb(38, 38, 38)` у
 * обоих). На карточке воркера без прогонов три таких прочерка читались как три
 * значения.
 *
 * Второе, что видно только парой: `tone` — про состояние САМОГО ЧИСЛА
 * (задолженность просрочена, план перевыполнен), а не про его отсутствие. Если
 * бы «данных нет» жило в `tone`, одно имя означало бы две разные вещи — та же
 * болезнь, что у слитого `ds-table__num`, который кодировал и край, и цифровую
 * типографику.
 */
import { defineFixture } from '../../internal/fixture.js'
import { MetricStrip, type Metric } from './MetricStrip.js'

