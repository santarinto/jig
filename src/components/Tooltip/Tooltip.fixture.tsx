interface Props {
  label: string
  trigger: string
}

/**
 * Наводит и ставит фокус на триггер сразу после монтирования — пузырёк
 * оказывается показан ДВУМЯ настоящими путями пользователя, а не выставленным
 * руками классом. Класс был бы враньём: кадр показал бы подсказку, ничего не
 * сказав о том, открывается ли она вообще.
 *
 * Почему обоими, а не одним фокусом — в докблоке модуля (DS-293):
 * коротко, события фокуса не приходят во вкладку, окно которой не в фокусе, и
 * случай в такой вкладке показывает пустоту.
 */
function Focused({ label, trigger }: Props) {
  const box = useRef<HTMLDivElement>(null)
  useEffect(() => {
    const btn = box.current?.querySelector<HTMLButtonElement>('button')
    if (!btn) return
    btn.focus()
    // `PointerEvent` есть не везде: в jsdom его нет, а `fixtures-render`
    // монтирует фикстуры именно там. `MouseEvent` того же типа проходит через
    // ту же делегацию React — обработчику нужен ТИП события, а не конструктор.
    const Ev = typeof PointerEvent === 'function' ? PointerEvent : MouseEvent
    btn.dispatchEvent(new Ev('pointerover', { bubbles: true }))
  }, [])
  return (
    // Триггер по ЦЕНТРУ кадра. Раньше это было вынужденно: пузырёк центрировался
    // каскадом вслепую и у левого края уезжал за него отрицательным `left`
    // (замерено до DS-167: −40 px у `shown`, −110 у `long`, срезалось
    // НАЧАЛО фразы). С DS-240 положение считает `useAnchoredPosition`, и
    // он поджимает пузырёк к краю — центр кадра больше не защита, а просто
    // самый читаемый вид случая.
    // ПРОВЕРЯТЬ ПОДЖИМ ЗДЕСЬ НЕЧЕМ: фикстура ставит триггер в одно место, а
    // утверждение о крае живёт в `useAnchoredPosition.test.tsx` («поджимается к
    // краю экрана») — там прямоугольники задаются, и оба края проверяются
    // порознь.
    <div ref={box} style={{ display: 'flex', justifyContent: 'center' }}>
      <Tooltip label={label}>
        <Button variant="ghost">{trigger}</Button>
      </Tooltip>
    </div>
  )
}

