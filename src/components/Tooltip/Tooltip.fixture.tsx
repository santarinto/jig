/**
 * Подсказка. `kind: 'inline'`.
 *
 * ПОКАЗ ДЕРЖИТ СОСТОЯНИЕ, и до DS-240 это было не так: открытость держал
 * каскад (`:hover` и `:focus-within` в `Tooltip.css`), а здесь было написано,
 * что подсказка — единственный такой компонент системы. Больше нет. Узел
 * по-прежнему ВСЕГДА в DOM вместе со своим `aria-describedby` — состояние
 * управляет показом, а не рендером, — но включают показ обработчики
 * наведения и фокуса, и позицию считает JS.
 *
 * Следствие для фикстуры: случай «показана» приводится в состояние ДВУМЯ
 * путями сразу — наведением и фокусом (DS-293). Одного фокуса мало, и
 * это не перестраховка: события фокуса не приходят во вкладку, окно которой не
 * в фокусе, а верстак смотрят именно из такой — вкладка расширения, окно за
 * чужим окном. Приёмка 16.09.2026 так и увидела: пузырёк монтируется скрытым и
 * скрытым остаётся, `innerText` кадра ровно «Итого», и случай с именем
 * «Показана» не показывает ничего. Компонент при этом здоров — настоящее
 * наведение открывает его в правильной привязке.
 *
 * Тот же изъян и у второго пути: Escape гасит показ (DS-168), а фокус с
 * кнопки не уходит — значит `.focus()` повторно ничего не включит, и случай
 * останется пустым насовсем. Замерено: после Escape `is-shown` снят, а
 * `document.activeElement` по-прежнему кнопка; один `pointerover` его
 * возвращает.
 *
 * Наведение из кода воспроизводится с DS-240: показ держит обработчик, а
 * не псевдокласс `:hover`, который `dispatchEvent` включить не может. Событие
 * `pointerover`, а не `pointerenter`: React выводит enter/leave из пары
 * over/out, делегированных на корень, и посланный напрямую `pointerenter` до
 * обработчика не доходит. `PointerEvent` берётся, только если он есть: в jsdom
 * его нет вовсе (25.0.1), а `fixtures-render` гоняет фикстуры именно там.
 *
 * Фокус ОСТАВЛЕН, а не заменён: он показывает подсказку тем же путём, которым
 * её видит клавиатура, и снимать работающее утверждение ради упрощения незачем.
 *
 * Сторож против двойного прогона эффекта здесь НЕ нужен, в отличие от
 * `Combobox` и `DatePicker`. Там эффект переключает состояние, и второй прогон
 * под `StrictMode` закрывает то, что открыл первый; здесь обе операции
 * идемпотентны — второй `.focus()` и второй `pointerover` ничего не меняют.
 *
 * ESCAPE ГАСИТ ПОКАЗ (DS-168). Проверять надо ДВУМЯ шагами, иначе
 * проверка неполна: нажали Escape — подсказка ушла; увели курсор и вернули —
 * подсказка снова здесь. Второй шаг важнее первого: гаснуть должен ПОКАЗ, а не
 * компонент, и правка, выключающая подсказку навсегда, первый шаг проходит.
 *
 * Что фикстура показать НЕ может: пузырёк, доживший до курсора. Мостик под
 * пузырьком (`::after` высотой в зазор) существует ради того, чтобы подсказка
 * не гасла, пока курсор пересекает пустоту между триггером и текстом
 * (WCAG 1.4.13). Это проверяется мышью и только мышью — ведите курсор от
 * кнопки вверх к тексту, подсказка обязана остаться.
 */
import { useEffect, useRef } from 'react'
