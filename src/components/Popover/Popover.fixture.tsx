/** Панель фильтра: то, ради чего поповер и берут вместо подсказки. */
function FilterBody() {
  const [from, setFrom] = useState('01.08.2026')
  return (
    <div style={{ display: 'grid', gap: '0.75rem', width: 'calc(16rem * var(--ds-ui-scale))' }}>
      <TextField label="Дата с" value={from} onChange={(e) => setFrom(e.target.value)} />
      <div style={{ display: 'flex', gap: '0.5rem', justifyContent: 'flex-end' }}>
        <Button variant="ghost" size="sm">Сбросить</Button>
        <Button variant="primary" size="sm">Применить</Button>
      </div>
    </div>
  )
}

