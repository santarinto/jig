/**
 * Панель у триггера. `kind: 'inline'`.
 *
 * Граница с соседями по группе, и её стоит держать в голове раньше, чем
 * смотреть на кадры: `Tooltip` — подсказка, только текст, открывается
 * наведением; `Popover` — `role="dialog"` с ЖИВЫМ содержимым, открывается
 * кликом; `Modal` — тот же диалог, но модальный, с ловушкой фокуса и
 * заблокированным фоном. Выбор между ними — про то, можно ли продолжать
 * работать с остальной страницей, а не про размер.
 *
 * Открытость здесь и управляемая, и нет: `open` + `onOpenChange` — контракт
 * потребителя, `defaultOpen` — та же открытость без чужого состояния. Кейсы
 * пользуются вторым: показывать надо панель, а не проводку фикстуры.
 */
