/**
 * Потребитель, который умеет догружать старые записи. Ради него и существует
 * `onReachTop`: компонент сам ничего не грузит, он только сообщает об упоре —
 * и ровно один раз на упор, иначе прокрутка у верха звала бы загрузку каждым
 * кадром.
 */
function Growing({ lines, ...rest }: Props) {
  const [older, setOlder] = useState<Line[]>([])
  const [rounds, setRounds] = useState(0)
  const load = useCallback(() => {
    setRounds((r) => {
      if (r >= 3) return r
      setOlder((prev) => [...build(50, -50 * (r + 1)), ...prev])
      return r + 1
    })
  }, [])
  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: '0.5rem' }}>
      <div style={{ fontSize: 'var(--ds-fs-sm)', color: 'var(--ds-text-muted)' }}>
        Догружено пачек: {rounds} из 3 — строк {older.length + lines.length}
      </div>
      <LogViewer {...rest} lines={[...older, ...lines]} getLineId={lineId} onReachTop={load} />
    </div>
  )
}

