const T0 = Date.UTC(2026, 2, 17, 6, 0, 0)

/**
 * Ряд построен формулой, а не случайными числами: счётчик совпадений в заметках
 * случаев — точное число, и оно обязано совпадать между прогонами.
 *
 * Замерено на этом ряду: 2000 строк, из них info 846, debug 554, warn 269,
 * stdout 207, error 124. Запрос «Автопарк» встречается в 501 строке; если
 * скрыть `debug` и `stdout`, видимых строк остаётся 1239, а совпадений 312.
 */
function build(count: number, offset: number): Line[] {
  const out: Line[] = []
  for (let i = offset; i < offset + count; i++) {
    const h = (i * 61 + 7) % 97
    const kind = h % 19 === 0 ? 'error'
      : h % 7 === 0 ? 'warn'
        : h % 3 === 0 ? 'debug'
          : h % 5 === 0 ? 'stdout' : 'info'
    out.push({
      id: `l${i}`,
      ts: new Date(T0 + i * 3000).toISOString(),
      kind,
      text: TEXTS[(((i * 5 + h) % TEXTS.length) + TEXTS.length) % TEXTS.length]!,
      stream: kind === 'stdout' ? 'stdout' : undefined,
    })
  }
  return out
}

