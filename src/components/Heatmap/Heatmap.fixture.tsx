/** Дельта к прошлой неделе: подпись другая — «поездок не было» тут соврало бы. */
const deltaTooltip = (date: string, value: number) =>
  value === 0 ? `${date}: без изменений`
    : `${date}: ${value > 0 ? '+' : '−'}${Math.abs(value)} к прошлой неделе`

/** Дельта к прошлой неделе: значения бывают отрицательными, и это законно. */
