const DAY = 86400000
const key = (ms: number) => new Date(ms).toISOString().slice(0, 10)
const utc = (s: string) => {
  const [y, m, d] = s.split('-').map(Number)
  return Date.UTC(y!, m! - 1, d!)
}

const FROM = '2025-09-01'
const TO = '2026-08-31'

/** Новогодние выходные: РЕДКИЙ тип, поэтому громкая пометка. */
const HOLIDAYS = new Set([
  '2026-01-01', '2026-01-02', '2026-01-05', '2026-01-06', '2026-01-07', '2026-01-08',
])

/**
 * Ряд построен ФОРМУЛОЙ, а не случайными числами: снимок случая обязан
 * совпадать между прогонами, иначе «стало другое» перестаёт быть новостью.
 *
 * Замерено на этом ряду: 365 дней, 53 колонки, по ступеням 45 / 79 / 87 / 76 /
 * 78, из них ровно 45 нулей и 29 дней с одной поездкой.
 */
function year(): HeatmapDay[] {
  const start = utc(FROM)
  const n = Math.round((utc(TO) - start) / DAY) + 1
  const days: HeatmapDay[] = []
  for (let i = 0; i < n; i++) {
    const ms = start + i * DAY
    const date = key(ms)
    const dow = new Date(ms).getUTCDay()
    const h = (i * 37 + 11) % 23
    let value: number
    if (dow === 0 || dow === 6) value = h % 4
    else if (HOLIDAYS.has(date)) value = h % 3
    else value = 2 + (h % 13)
    // Будни без единой поездки: «данных не было» — это не то же самое, что
    // «поездок не было», и различить их календарь не умеет ничем.
    if (h === 7) value = 0
    days.push({
      date,
      value,
      kind: HOLIDAYS.has(date) ? 'holiday' : undefined,
      marked: h === 3 && dow !== 0 && dow !== 6,
    })
  }
  return days
}

const YEAR = year()

