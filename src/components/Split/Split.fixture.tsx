function Live({ direction, defaultSize, min, max, collapsible, controlled, persist }: {
  direction: 'row' | 'column'
  defaultSize: number
  min: number
  max?: number
  collapsible: boolean
  controlled: boolean
  persist: boolean
}) {
  const [size, setSize] = useState(defaultSize)
  const id = 'wb-split'
  return (
    <div>
      <div id={id} style={{ height: HEIGHT, border: '1px solid var(--ds-border)', borderRadius: 'var(--ds-radius-md)', overflow: 'hidden' }}>
        <Split
          direction={direction}
          defaultSize={defaultSize}
          size={controlled ? size : undefined}
          onSizeChange={controlled ? setSize : undefined}
          min={min}
          max={max}
          collapsible={collapsible}
          storageKey={persist && !controlled ? 'wb-demo' : undefined}
          style={{ height: '100%' }}
        >
          {pane('Список документов', 6, 'a')}
          {pane('Карточка', 8, 'b')}
        </Split>
      </div>
      <Reported rootId={id} />
    </div>
  )
}
