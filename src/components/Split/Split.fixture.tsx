/** Показывает объявленные значения рядом с настоящей шириной — иначе расхождение не увидеть. */
function Reported({ rootId }: { rootId: string }) {
  const [text, setText] = useState('нажмите «замерить»')
  const measure = () => {
    const root = document.getElementById(rootId)
    const bar = root?.querySelector('[role="separator"]')
    // Через соседа разделителя, а не по `.ds-split__pane--first`: класс — наше
    // внутреннее имя и меняется вместе с починкой, а «первый пейн — тот, что
    // перед разделителем» верно по построению.
    const first = bar?.previousElementSibling
    if (!bar || !first) { setText('не найдено'); return }
    const w = Math.round((first as HTMLElement).getBoundingClientRect().width)
    setText(
      `now=${bar.getAttribute('aria-valuenow')} `
      + `min=${bar.getAttribute('aria-valuemin')} `
      + `max=${bar.getAttribute('aria-valuemax')} `
      // Единица через ПРОБЕЛ, вплотную к подстановке её писать нельзя: гейт
      // `js-px-scale` ищет подставленное значение с приклеенной единицей и не
      // отличает вывод на экран от значения стиля — отличить их он и не может,
      // форма одна и та же. Пробел здесь не обход, а принятая в заметках этого
      // репозитория запись величины («473 px», «44 px»).
      + `· настоящая ширина ${w} px`,
    )
  }
  return (
    <div style={{ display: 'flex', gap: '0.5rem', alignItems: 'center', marginTop: '0.5rem' }}>
      <Button variant="secondary" size="sm" onClick={measure}>замерить</Button>
      <output style={{
        fontFamily: 'var(--ds-font-mono)',
        fontSize: 'var(--ds-fs-sm)',
        color: 'var(--ds-text-muted)',
      }}>{text}</output>
    </div>
  )
}

