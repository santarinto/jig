import { Calendar, type CalendarMarkTone } from './Calendar.js'

/** Отгрузки: разные ВИДЫ события, а не разная их величина. */
const MARKS: Record<string, CalendarMarkTone> = {
  '2026-03-10': 'success',
  '2026-03-12': 'warning',
  '2026-03-19': 'error',
  '2026-03-26': 'accent',
}

/** Пересекается с `MARKS` на 10 марта — там побеждает `marks`. */
const MARKED = ['2026-03-03', '2026-03-10', '2026-03-24']

interface Props {
  year: number
  month: number
  selectedId?: string
  min?: string
  max?: string
  markedDates?: string[]
  marks?: Record<string, CalendarMarkTone>
  months: 1 | 2 | 3
  readOnly: boolean
  embedded: boolean
}

/**
 * Потребитель целиком: держит и выбранный день, и якорный месяц. Без него
 * `onNavigate` некуда девать — стрелки в шапке ходят не сами, а зовут
 * потребителя, и статичная фикстура выглядела бы сломанной шапкой.
 */
function Live({ year, month, selectedId, ...rest }: Props) {
  const [ym, setYm] = useState<[number, number]>([year, month])
  const [sel, setSel] = useState<string | undefined>(selectedId)
  return (
    <Calendar
      {...rest}
      year={ym[0]}
      month={ym[1]}
      selectedId={sel}
      onSelect={setSel}
      onNavigate={(y, m) => setYm([y, m])}
      // ТОЛЬКО НАВИГАЦИЯ, ВЫБОР НЕ ТРОГАЕМ. `onToday` — целиком дело
      // потребителя, компонент лишь зовёт его, и фикстура здесь пишет ПРИМЕР,
      // который скопируют. До приёмки волны 6 она делала ещё и `setSel`, то
      // есть «Сегодня» затирала выбранный пользователем день: ушёл посмотреть
      // апрель, нажал «Сегодня», чтобы вернуться, — и потерял 10 марта, о
      // котором никого не спрашивали. Вернуться к сегодняшнему месяцу и выбрать
      // сегодняшний день — два разных действия, и кнопка одна из них.
      onToday={() => setYm([2026, 2])}
    />
  )
}

