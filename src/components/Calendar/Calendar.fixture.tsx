/**
 * Сетка месяца. `kind: 'block'`.
 *
 * Календарь выглядит как таблица чисел, и почти всё, что в нём важно, числами
 * не выражается. В кадре не видно ничего из перечисленного:
 *
 *  - **Имя ячейки — полная дата, текст — число.** На экране «30», в дереве
 *    доступности «понедельник, 30 марта 2026 г.». Разница становится видимой
 *    только при `months={3}`, где трёх «15» подряд на слух не различить вовсе,
 *    — поэтому проверять это надо на случае `roving`, а не на базовом.
 *  - **Один таб-стоп на СЕТКУ, а не на календарь.** 37 кнопок марта — это один
 *    вход табом и дальше стрелки. Но сеток может быть три, и тогда таб-стопов
 *    тоже три: роуминг у каждой панели свой, и стрелка через границу месяца не
 *    переходит.
 *  - **Сетка не добивается до полной недели с конца.** Хвост предыдущего месяца
 *    рисуется (`ds-cal__day--out`), голова следующего — нет. Последний ряд
 *    марта 2026 — это два дня, а не семь. Отсюда же берётся дублирование дат в
 *    `months={3}`: см. случай `roving`, там оно посчитано.
 *  - **Недоступный день — стена, а не препятствие.** `min`/`max` гасят
 *    непрерывный префикс и суффикс, дыр посреди сетки этим API не собрать, и
 *    стрелка через погашенный день не перешагивает — она об него встаёт.
 *
 * ЦВЕТ МЕТКИ ЗДЕСЬ — КАТЕГОРИЯ, НЕ ВЕЛИЧИНА. `CalendarMarkTone` это
 * `accent | success | warning | error`, то есть четыре РАЗНЫХ вида события, а
 * не четыре ступени одного. Величину в системе несёт только `--ds-heat-*` у
 * `Heatmap`; если по календарю захочется показать «насколько загружен день»,
 * смотреть надо туда, а не сюда.
 */
import { useState } from 'react'
