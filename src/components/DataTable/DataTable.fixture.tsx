/**
 * Колонки фикстуры. `widths` включает заданные ширины — и вместе с ними
 * `table-layout: fixed` у самой таблицы: `fixedLayout` в `DataTable.tsx`
 * считается как `columns.some((c) => !!c.width)`, то есть ширина ХОТЯ БЫ ОДНОЙ
 * колонки меняет раскладку ВСЕЙ таблицы.
 *
 * Без этого ни один случай фикстуры не мог показать сокращение текста:
 * `white-space: nowrap; overflow: hidden; text-overflow: ellipsis` висит на
 * `.ds-table--fixed`, а без заданных ширин таблица остаётся `.ds-table` и
 * раздвигается под содержимое (измерено: `scrollWidth === clientWidth` во всех
 * случаях, computed `text-overflow: clip`).
 *
 * `wrapCity` вешает `wrap` на колонку «Город» — она текстовая и рядом с
 * «Водителем», у которого та же строка сокращается. Соседство и есть предмет
 * случая: одно состояние без другого ничего не доказывает.
 *
 * Ширины заданы ЧИСЛОМ, а не `'9rem'`: число едет по `--ds-ui-scale`, голый
 * rem — нет, и под `.ds-scale` колонка отставала бы от высоты строки
 * (DS-82). Фикстура — тот пример, который копируют, поэтому форма здесь
 * важнее краткости.
 *
 * Колонка действий приезжает вместе с ширинами не для красоты: DS-57 —
 * про то, что в НЕЙ то же правило рисовало ложное многоточие вплотную к
 * кнопкам (58px кнопок против 56px content-края). Пара «текст сокращается,
 * кнопки нет» в одном случае показывает и работающее сокращение, и снятое
 * там, где сокращать нечего.
 */
