/**
 * Результат `onRowClick`, видимый и СЧЁТНЫЙ (DS-341). Пустышка вместо
 * обработчика оставляла кадр неизменным, и «клик открывает строку один раз»
 * глазом не проверялся вовсе. Счётчик обязателен: «зовётся дважды» (всплытие
 * с кнопки строки на `<tr>`) без него неотличимо от «зовётся раз».
 */
function Opened({ children }: { children: (open: (id: string) => void) => ReactNode }) {
  const [last, setLast] = useState({ id: '', n: 0 })
  return (
    <div>
      {children((id) => setLast((s) => ({ id, n: s.n + 1 })))}
      <div style={{ marginTop: '1rem', color: 'var(--ds-text-muted)', fontSize: 'var(--ds-fs-sm)' }}>
        {last.id ? `открыт: ${last.id}` : 'ничего не открыто'} · вызовов: {last.n}
      </div>
    </div>
  )
}

/**
 * Живое раскрытие. Как и у `Selectable` выше и по тому же доводу: узел,
 * который нарисован и не раскрывается, — пример работающего на вид пропа,
 * а примеры копируют.
 *
 * Начальное состояние подобрано так, чтобы в одном кадре стояло СРАЗУ ТРИ
 * вещи, и ни одна из них не проверяется без него:
 *  - раскрытый узел и свёрнутый РЯДОМ. Порознь они неразличимы — и то и другое
 *    читается как «каретка», — а доступные имена у них разные («раскрыть»
 *    против «свернуть») и подменяются разными ключами словаря. Тот же довод,
 *    что у случая «Перенос в колонке»;
 *  - третий уровень ВИДЕН, то есть `--ds-row-depth` доказывается шагом, а не
 *    одним отступом: 0 → 8px, 1 → 20px, 2 → 32px, и равенство шагов и есть
 *    утверждение. На двух уровнях отступ второго не отличить от padding'а
 *    ячейки;
 *  - каретка стоит и на глубине 0 («Восточный», «Северный»), и на глубине 1
 *    («Смена ночная») — она не должна зависеть от глубины, а на одном уровне
 *    это утверждение непроверяемо.
 *
 * Модель считается на каждый рендер, без `useMemo`: `flattenTree` — чистый
 * обход десятка узлов, и мемоизация здесь спрятала бы от читателя фикстуры
 * ровно ту строку, которую он сюда и пришёл скопировать.
 */
function Tree(props: { columns: Column<Row>[]; dense: boolean }) {
  const [open, setOpen] = useState<string[]>(['p-north', 'p-north-2'])
  const toggle = (id: string) =>
    setOpen((was) => (was.includes(id) ? was.filter((x) => x !== id) : [...was, id]))
  return (
    <DataTable
      columns={props.columns}
      displayRows={flattenTree(TREE, (r) => r.id, open)}
      onToggleExpand={toggle}
      dense={props.dense}
    />
  )
}

/**
 * Живой выбор: чекбоксы обязаны переключаться. Контролируемый набор с
 * `onSelectionChange={() => {}}` дал бы колонку, которая нарисована и не
 * работает, — то есть пример, показывающий проп, который задан и молчит. Это
 * ровно тот дефект, от которого система избавляется в коде, и в примере он
 * недопустим тем более: примеры копируют.
 */
function Selectable(props: { columns: Column<Row>[]; rows: Row[]; dense: boolean; loading: boolean; emptyText: string; onRowClick?: (r: Row) => void }) {
  const [ids, setIds] = useState<string[]>([props.rows[0]?.id ?? ''].filter(Boolean))
  return (
    <DataTable
      columns={props.columns}
      rows={props.rows}
      getRowId={(r) => r.id}
      dense={props.dense}
      loading={props.loading}
      emptyContent={props.emptyText}
      selectedIds={ids}
      onSelectionChange={setIds}
      onRowClick={props.onRowClick}
    />
  )
}

