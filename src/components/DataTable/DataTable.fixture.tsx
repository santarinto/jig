/**
 * Пилотная фикстура верстака.
 *
 * `DataTable` выбран пилотом не потому, что он важнее прочих, а потому что он
 * один прогоняет обе трудные механики разом:
 *  - `@container` (два правила) — то есть проверяет, что кадр честно меряет
 *    БЛОК. Единственным компонентом с контейнерным запросом DataTable был до
 *    DS-142; у `Pagination` он теперь свой, и разница поучительна: здесь
 *    контейнер — ОБЁРТКА таблицы, а там сам корень компонента, потому что
 *    обёртку у пагинации пришлось бы требовать от потребителя;
 *  - у него есть свободная позиция для чужого содержимого, и живёт она внутри
 *    рендерера ячейки, а не в пропе — то есть проверяет, что слот выражается
 *    без поля «в какой проп подставить».
 *
 * СВОЙ ГОРИЗОНТАЛЬНЫЙ СКРОЛЛЕР, и у него есть цена (DS-169). Обёртка
 * берёт прокрутку себе, когда таблица не влезла, — иначе распор от `min-width`
 * уводил вбок ВСЮ страницу. Пока скроллер включён, ЛИПКАЯ ШАПКА ТАБЛИЦЫ НЕ
 * ЛИПНЕТ: обёртка стала контейнером прокрутки, и `sticky` считает от неё, а по
 * вертикали она не листается. Смотреть это надо на УЗКОМ кадре и НЕ на глаз:
 * прокрутите страницу вниз и сравните, где шапка при 900 и при 360. Обойти
 * нечем — разбор четырёх раскладов в `DataTable.css`.
 *
 * Разница, которую фикстура обязана показывать: `ActionColumn` типизован и сам
 * гасит всплытие клика, а `DisplayColumn.render` — свободный ReactNode, где
 * гашение на потребителе. Text-overflow здесь — общий каскад `.ds-table--fixed
 * td` (сокращает, если width задана хоть у одной колонки таблицы —
 * `DataTable.tsx`: `columns.some((c) => !!c.width)`, а не только у этой);
 * DS-57 — про другую ячейку, действий (`ds-table__actions-cell`), где то
 * же правило рисовало ложное многоточие вплотную к кнопкам (58px кнопок
 * против 56px content-края, см. DataTable.css).
 *
 * Из того же каскада растёт и `wrap`: в `fixed` ячейки однострочны, а `wrap` —
 * оговорка для колонки, где важнее прочитать значение целиком (DS-79).
 * Случай «Перенос в колонке» ставит оба состояния в один кадр: порознь они
 * схлопываются в «строка стала выше» и неотличимы.
 */
