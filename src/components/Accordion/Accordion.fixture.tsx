/**
 * Аккордеон. `kind: 'block'` — занимает ширину области, начинкой чужой ячейки
 * не бывает.
 *
 * Главное решение компонента в кадре не видно вовсе: **состоянием владеет либо
 * он сам, либо потребитель, и переключается это НАЛИЧИЕМ пропа `openIds`.**
 * Пока пропа нет, нажатие открывает секцию само; как только он появился,
 * нажатие только СООБЩАЕТ о намерении, а откроется секция или нет — решает
 * потребитель. Два случая ниже (`collapse-all` и `frozen`) отличаются друг от
 * друга ровно одной строкой у потребителя и выглядят как «работает» против
 * «сломано», хотя компонент в обоих один и тот же.
 *
 * Что здесь нельзя увидеть поодиночке:
 *  - `multiple` в снимке НЕ ОТЛИЧАЕТСЯ от одиночного режима: одна раскрытая
 *    секция выглядит одинаково в обоих. Различие появляется только вторым
 *    нажатием, поэтому случай `multiple` открыт двумя секциями сразу.
 *  - каждый заголовок — СВОЙ таб-стоп, а стрелки ↑/↓/Home/End — дополнение к
 *    табу, а не замена ему. Это противоположно `Tabs` и `ToggleGroup`, где
 *    стоп один на группу. Считает их слой «Таб-стопы», а не глаз.
 */
