/**
 * Стопка, наполненная при монтировании.
 *
 * Сторожа против двойного прогона эффекта под `StrictMode` здесь нет, и это не
 * недосмотр: у каждого вызова ЯВНЫЙ `id`, а очередь заменяет запись с тем же
 * id вместо того, чтобы добавить вторую (`toast.tsx`, `add`). Второй прогон
 * приводит очередь к тому же состоянию — то есть операция идемпотентна, и
 * стеречь нечего.
 *
 * `duration: 0` обязателен. С автоскрытием кадр показывал бы стопку первые
 * четыре секунды и пустоту потом — то есть отвечал бы разное на один и тот же
 * адрес в зависимости от того, когда на него посмотрели.
 */
function Stack() {
  useEffect(() => {
    clearToasts()
    toast.success('Документ проведён', { id: 'wb-1', duration: 0 })
    toast.error('Выписка не загружена: банк вернул 502', { id: 'wb-2', duration: 0 })
    toast.info('Справочник тарифов обновлён', { id: 'wb-3', duration: 0 })
    return clearToasts
  }, [])
  return (
    <div style={{ minHeight: '18rem' }}>
      <p style={{ color: 'var(--ds-text-muted)', fontSize: 'var(--ds-fs-sm)' }}>
        Тостер смонтирован здесь же; в приложении он стоит один раз у корня.
      </p>
      <Toaster position="bottom-right" />
    </div>
  )
}

/** Очередь, наполняемая руками: тосты бросают из обработчиков, а не из разметки. */
function Live() {
  const [n, setN] = useState(0)
  useEffect(() => clearToasts, [])
  return (
    <div style={{ minHeight: '18rem', display: 'flex', gap: '0.5rem', flexWrap: 'wrap' }}>
      {TONES.map((t) => (
        <Button key={t} variant="secondary" size="sm"
          onClick={() => { setN((v) => v + 1); toast[t](`${t}: сообщение №${n + 1}`) }}>
          {t}
        </Button>
      ))}
      <Button variant="ghost" size="sm" onClick={clearToasts}>Очистить</Button>
      <Toaster position="bottom-right" />
    </div>
  )
}

/**
 * Центр с живым `onDismiss`: строка обязана исчезать по-настоящему. Крестик,
 * подшитый к пустому обработчику, показал бы кнопку, которая ничего не делает,
 * — то есть ровно тот дефект, о котором говорит заметка случая.
 */
function Center({ items }: { items: NotificationItem[] }) {
  const [list, setList] = useState(items)
  return (
    // Высота и прокрутка — на ОБЁРТКЕ, а не в компоненте, и это решение, а не
    // оформление кадра. Центр это список; куда его поставили — в шторку, в
    // поповер, в колонку страницы, — знает тот, кто ставит, и высота его. Своя
    // `max-height` у `.ds-notifs` сделала бы список, который в шторке во весь
    // экран всё равно кончается на своих 20rem. Кадр обязан показывать место,
    // иначе он обещает, что историю можно лить бесконечно: на стресс-данных
    // `long` (12 строк) список вырастал до 826 px и выдавливал кадр в
    // прокрутку — замерено на приёмке волны 3.
    <div style={{ maxWidth: '32rem', maxHeight: '20rem', overflow: 'auto' }}>
      <NotificationCenter
        items={list}
        onDismiss={(id) => setList((l) => l.filter((n) => n.id !== id))}
      />
    </div>
  )
}

