/**
 * Уведомления. `kind: 'block'`.
 *
 * Каталог держит ТРИ разные вещи под одним именем, и путать их дорого:
 *
 * - `Toast` — карточка. Сама по себе она просто вёрстка с тоном и крестиком.
 * - `Toaster` + `toast.*` — очередь: тостер монтируется один раз у корня
 *   приложения, а сообщения бросают откуда угодно императивным вызовом.
 * - `NotificationCenter` — СПИСОК, который никуда не исчезает: история, к
 *   которой возвращаются.
 *
 * Разница не в виде, а во времени жизни. Тост исчезает сам и потому не может
 * нести ничего, что нужно прочитать позже; центр не исчезает и потому не может
 * ничего сообщить в момент события. Сообщение об ошибке, которое надо
 * скопировать, — центр, а не тост.
 *
 * Живая область — на корне тостера, не на карточке (`AGENTS.md`). Карточка
 * внутри стопки идёт с `announce={false}`: область внутри области это два
 * механизма на одном узле, и какой сработает — зависит от скринридера.
 */
