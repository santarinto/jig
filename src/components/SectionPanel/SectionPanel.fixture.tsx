/** Выключен один средний: сосед справа достижим, стрелка обязана его перешагнуть. */
const WITH_DISABLED: Section[] = SECTIONS.map((s) =>
  (s.id === 'goods' ? { ...s, disabled: true } : s))

/** Выключен АКТИВНЫЙ раздел — вырожденный случай `tabIndex`. */
const HEAD_DISABLED: Section[] = SECTIONS.map((s) =>
  (s.id === 'main' ? { ...s, disabled: true } : s))

/**
 * Полоса с собственным состоянием. Выбор ведёт фикстура: `selectedId` у
 * компонента обязателен, и без владельца состояния полоса не двигается вовсе.
 */
function Live({ sections, selectedId, orientation, silent }: {
  sections: Section[]
  selectedId: string
  orientation: 'vertical' | 'horizontal'
  silent: boolean
}) {
  const [sel, setSel] = useState(selectedId)
  return (
    <SectionPanel
      sections={sections}
      selectedId={sel}
      orientation={orientation}
      onSelect={silent ? undefined : setSel}
    />
  )
}

