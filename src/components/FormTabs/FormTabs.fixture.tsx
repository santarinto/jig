interface Props {
  tabs: FormTab[]
  closable: boolean
  home: boolean
}

/**
 * Полоса управляемая: без состояния ни переключение, ни закрытие не
 * происходят, и оба выглядят как «компонент сломан», хотя сломан пример.
 */
function Live({ tabs, closable, home, selected }: Props & { selected?: string }) {
  const [list, setList] = useState(tabs)
  const [sel, setSel] = useState(selected ?? tabs[0]!.id)
  return (
    <FormTabs
      tabs={list}
      selectedId={sel}
      onSelect={setSel}
      onHome={home ? () => {} : undefined}
      onClose={closable
        ? (id) => {
            // Выбор после закрытия — СОСЕД, а не первая форма. Решает это
            // потребитель, не компонент (полоса управляемая), но стенд обязан
            // показывать то, как ведёт себя учётная система: закрыл документ — оказался на
            // соседнем, а не улетел в начало списка. Приёмка поймала здесь
            // прыжок с третьей формы на нулевую и честно не смогла сказать, чей
            // он, — теперь видно, что стенда.
            const i = list.findIndex((t) => t.id === id)
            const rest = list.filter((t) => t.id !== id)
            setList(rest)
            if (id === sel && rest.length) setSel(rest[Math.min(i, rest.length - 1)]!.id)
          }
        : undefined}
    />
  )
}

