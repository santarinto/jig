function Live(p: Props) {
  const [collapsed, setCollapsed] = useState(false)
  const [overlayOrg, setOverlayOrg] = useState('romashka')
  const [overlayDate, setOverlayDate] = useState('2026-03-17')
  /* Тело, а не своя карточка: `overlay` подменяет ТОЛЬКО содержимое, по образцу
     `labelled` рядом. Своя `<Card>` с одним `title` молча съедала бы `tone`,
     `variant`, `dense`, `collapsible`, `withTools` и `withFooter` — крутилка
     стояла бы в панели и ничего не делала, то есть ровно та молчаливая
     деградация, которую ищет эпик DS-248. */
  const overlayBody = (
    <>
      <FormRow label="Организация">
        <Combobox options={OVERLAY_ORGS} value={overlayOrg} onChange={setOverlayOrg} />
      </FormRow>
      <FormRow label="Дата">
        <DatePicker value={overlayDate} onChange={setOverlayDate} />
      </FormRow>
      <FormRow label="Сумма" htmlFor="f-overlay-sum">
        <TextField id="f-overlay-sum" defaultValue="742,00" />
      </FormRow>
    </>
  )
  const content = p.overlay ? overlayBody : p.labelled ? body : (
    <>
      <FormRow label="Контрагент">
        <TextField defaultValue="ООО «Автопарк-Юг»" />
      </FormRow>
      <FormRow label="Договор">
        <TextField defaultValue="ТК-00417 от 17.03.2026" />
      </FormRow>
      <FormRow label="Сумма">
        <TextField defaultValue="742,00" />
      </FormRow>
    </>
  )
  const card = (
    <Card
      title={p.title || undefined}
      subtitle={p.subtitle || undefined}
      icon={p.icon ? '◆' : undefined}
      titleLines={p.titleLines}
      tone={p.tone || undefined}
      variant={p.variant}
      dense={p.dense}
      noPadding={p.noPadding}
      collapsible={p.collapsible}
      collapsed={p.collapsible ? collapsed : undefined}
      onCollapsedChange={p.collapsible ? setCollapsed : undefined}
      tools={p.withTools ? [
        { id: 'refresh', icon: '↻', label: 'Обновить', disabled: p.toolBusy || undefined, onSelect: () => {} },
        { id: 'settings', icon: '⚙', label: 'Настройки панели', onSelect: () => {} },
      ] : undefined}
      toolbar={p.withToolbar ? <>{chip('Провести')}{chip('Отменить проведение')}</> : undefined}
      footer={p.withFooter ? chip('Итого: 742,00 ₽') : undefined}
      headerAction={p.subtitle ? chip('Все документы →') : undefined}
    >
      {p.noPadding ? rows(6) : content}
    </Card>
  )
  // Случай `nameless` показывает ДВЕ карточки: со связанными подписями и без.
  // Одна карточка ничего не утверждала бы — разница только в дереве
  // доступности, и сравнивать надо с чем-то.
  if (!p.labelled) {
    return (
      <div style={{ display: 'flex', flexDirection: 'column', gap: '1rem' }}>
        <Card title="Связано через `htmlFor`">{body}</Card>
        <Card title="Без `htmlFor` — те же поля, имён нет">{content}</Card>
      </div>
    )
  }
  return card
}
