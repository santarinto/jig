/**
 * Столбчатая диаграмма. `kind: 'block'`.
 *
 * СИСТЕМНЫЙ ЗАКОН, который здесь проверяется глазами: цвет кодирует состояние
 * или категорию, НИКОГДА величину. У столбика величина живёт в высоте, а тон
 * (`barTone`) — это состояние, «прошлый период» против «текущего». Случай
 * `tone` показывает разрешённое употребление; если когда-нибудь появится
 * соблазн красить столбик по значению, смотреть надо сюда.
 *
 * Что здесь нельзя увидеть поодиночке:
 *  - **нулевая категория без `track` ИСЧЕЗАЕТ**, а не рисуется нулём: путь
 *    нулевой высоты — это ничего. Пустое место в ряду читается как «данных
 *    нет», хотя данные есть и равны нулю. Случай `zero` ставит оба варианта
 *    рядом, иначе разницу не увидеть вовсе.
 *  - **геометрия 1:1, а не масштабирование `viewBox`.** Размер холста меряется
 *    `ResizeObserver` (`useChartBox`), поэтому текст в SVG не раздувается
 *    вместе с картинкой. Обратная сторона: в СПЯЩЕЙ вкладке наблюдатель не
 *    срабатывает, и график остаётся на SSR-откате 520×height. Числа в такой
 *    вкладке внутренне согласованы и неверны — проверяйте, что кадры идут.
 *  - **легенда — переключатели**, общие с `LineChart`
 *    (`src/internal/ChartLegend.tsx`), и её нет ни в одном превью системы
 *    (DS-155).
 */
