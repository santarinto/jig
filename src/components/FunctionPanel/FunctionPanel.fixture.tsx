/** Панель не хранит выбора — обёртка нужна только затем, чтобы клик было куда деть. */
function Live({ groups }: { groups: FunctionGroup[] }) {
  const [last, setLast] = useState<string | undefined>(undefined)
  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: '0.5rem' }}>
      <FunctionPanel groups={groups} onOpen={setLast} />
      <output style={{
        padding: '0 var(--ds-space-6)',
        fontFamily: 'var(--ds-font-mono)',
        fontSize: 'var(--ds-fs-sm)',
        color: 'var(--ds-text-muted)',
      }}>
        {last == null ? 'Нажмите ссылку — здесь появится её id' : `onOpen: ${last}`}
      </output>
    </div>
  )
}
