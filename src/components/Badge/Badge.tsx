import './Badge.css'

/**
 * Каноничный словарь тонов парка: его же под своими именами носят `CardTone`,
 * `BarTone`, `TimelineTone`, `LogTone`, `HeatmapMarkTone` и тон события в
 * `AgentTranscript`. Значение, добавленное сюда, обязано иметь правило в CSS
 * КАЖДОГО из них — иначе оно протекает семи компонентам разом и рисуется
 * ничем: класс `ds-timeline__marker--<тон>` без правила оставляет маркер без
 * фона, и ни компилятор, ни гейт этого не видят.
 *
 * Так и случилось с `brand` в первой редакции DS-81: шов под чужой цвет
 * стоял седьмым тоном и молча расширял шесть чужих типов. Он здесь больше не
 * значение, а отдельный проп `brand` — см. `BadgeProps`.
 */
export type BadgeTone = 'neutral' | 'accent' | 'success' | 'warning' | 'error' | 'info'

/**
 * Хекс, и только хекс. Контракт узкий намеренно: шов существует ради значений
 * ИЗ БАЗЫ, а в базе цвет лежит хексом.
 *
 * `var(--что-то)` сюда не пускается, хотя синтаксически прошёл бы: у
 * неопределённой переменной значение невалидно на ВЫЧИСЛЕНИИ, и оба правила
 * отбрасываются уже после того, как класс проставлен, — то есть ровно в том
 * виде, от которого не спасает никакой `var()`-фолбэк. Отсекается здесь, где
 * проверка возможна.
 *
 * Альфа (8 и 4 знака) принимается и ОТБРАСЫВАЕТСЯ: прозрачностью подложки
 * распоряжается компонент (12%), потребитель отдаёт цвет. Иначе `#c026d380` из
 * базы дал бы метку в половину непрозрачности — 2.6:1 вместо обещанных 5.0, и
 * замер бы этого не увидел, потому что кормится шестизначными.
 */
const HEX = /^#(?:[0-9a-f]{3,4}|[0-9a-f]{6}|[0-9a-f]{8})$/i

/**
 * Ссылка на категориальный токен системы — `var(--ds-chart-N)`, N от 1 до 8, и
 * ничего больше. Форма строгая нарочно: `brand` несёт ЗНАЧЕНИЕ цвета, а
 * произвольный `var(--что-угодно)` открыл бы доступ к любому токену системы —
 * это уже не шов под данные потребителя, а обход через `brand` к тому, что
 * должно называться явно. Восемь — не произвольное число, а размер ЕДИНОЙ
 * категориальной палитры (закон CLAUDE.md, `--ds-chart-*`), и девятого номера
 * не существует.
 */
const TOKEN = /^var\(\s*--ds-chart-[1-8]\s*\)$/

/**
 * `tone` и `brand` — ДВА РАЗНЫХ способа покрасить бейдж, и вместе они
 * бессмысленны. Первая редакция выражала это союзом типов, и союз работал: оба
 * пропа разом падали на компиляции.
 *
 * **Союз откачен, и вот почему.** `BadgeProps` перестал быть интерфейсом, а
 * `interface Свой extends BadgeProps` — обычный способ обернуть чужой
 * компонент. Он ломался с текстом «An interface can only extend an object type
 * or intersection of object types with statically known members», и ломался
 * молча для того, кто читал в CHANGELOG «ломающего нет». Цена союза оказалась
 * выше выгоды: запрет на пару пропов, которую никто не писал, против
 * компиляции у того, кто оборачивает.
 *
 * Взаимоисключение осталось, но держится БРОСКОМ на первом рендере — тем же
 * приёмом, что `assertAlign` и `onRowClick` без `rowHeader`. Проверка позже
 * компиляции, и это названо ценой явно.
 */
export interface BadgeProps extends React.ComponentPropsWithRef<'span'> {
  tone?: BadgeTone
  dot?: boolean
  /**
   * Цвет ИЗ ДАННЫХ потребителя — свободный `#rrggbb` из его базы ИЛИ ссылка на
   * категориальный токен системы, `var(--ds-chart-N)`. Не тон системы: тон
   * называет категорию из словаря `BadgeTone`, `brand` несёт готовое значение
   * цвета.
   *
   * ```tsx
   * <Badge brand={tag.color}>{tag.name}</Badge>
   * <Badge brand="var(--ds-chart-3)">{tag.name}</Badge>
   * ```
   *
   * **Хекс или токен, и оба — ЗНАЧЕНИЕ, а не указание, что покрасить.** Токен
   * взят в довесок к хексу, а не вместо него, потому что цвет СЛЕДУЕТ ЗА ТЕМОЙ:
   * `var(--ds-chart-3)` меняется вместе с переключением темы, а хекс — значение
   * ОДНОЙ темы, у потребителя застывшее навсегда, если он сам не хранит пару на
   * тему. Из любого из двух компонент выводит ДВА цвета — подложку и метку — и
   * отвечает за их контраст. Инлайновый `background: #c026d3` у потребителя
   * отдавал бы это решение ему, а вместе с ним и читаемость. Как именно
   * выводятся оба цвета — в `Badge.css`.
   *
   * **Шов с `ToggleGroup variant="swatch"`.** `SwatchItem.swatch` документирован
   * как «ожидается `var(--ds-chart-N)`» — это ДВА КОНЦА ОДНОГО ПОТОКА:
   * потребитель выбирает цвет свотчем, показывает его бейджем. До этой правки
   * концы расходились о том, что такое цвет — свотч ждал токен, `brand` понимал
   * только хекс, — то есть выбранное свотчем нечем было показать бейджем без
   * похода в CSS за значением переменной руками.
   *
   * **Голое имя `chart-3` НЕ принимается — это отказ, а не недоделка.** `brand`
   * несёт ЗНАЧЕНИЕ цвета, а не ИМЯ токена; приняв оба, он стал бы иногда
   * значением, иногда именем, и остальной код перестал бы знать заранее, какое
   * из двух пришло. У кого в базе лежит голое имя (так хранит один из
   * потребителей), пишет `brand={`var(--ds-${tag.color})`}` — одна подстановка на его
   * стороне, а не новая ветка здесь.
   *
   * Мусор (пустая строка, `null` из базы, `c026d3` без решётки, `chart-3` без
   * обёртки, `var(--ds-chart-9)`, `var(--чужой-токен)`) → бейдж рисуется
   * `neutral`. Это не запасное правило в листе, а отсутствие класса: у мусора
   * вид штатного бейджа, а не сломанного, и держится это тем, что класс и
   * переменную по-прежнему ставит одно условие.
   *
   * Вместе с `tone` — БРОСОК: это два разных способа покрасить одно место.
   */
  brand?: string
}

export function Badge({ tone, dot = false, brand, className, style, children, ...rest }: BadgeProps) {
  // Бросок, а не молчаливый выбор одного из двух: `tone` и `brand` красят одно
  // место разными способами, и «победил такой-то» здесь было бы правилом,
  // которое надо помнить. Ошибка — у потребителя в вызове, поэтому и падает на
  // первом рендере, а не прячется в вид.
  if (tone !== undefined && brand !== undefined) {
    throw new Error(
      'jig: Badge — `tone` и `brand` вместе. Это два разных способа покрасить '
      + 'бейдж: `tone` называет КАТЕГОРИЮ из словаря системы, `brand` несёт цвет ИЗ '
      + 'ДАННЫХ. Оставьте один (DS-81).',
    )
  }
  // Класс и переменная — одно условие, а не два. Пока это так, `.ds-badge--brand`
  // не может оказаться на элементе без валидного цвета, и запасное правило в
  // листе не нужно (его отсутствие стережёт Badge.test.tsx). Хекс или токен —
  // одна и та же переменная, лист не знает, откуда пришло значение.
  const painted = brand !== undefined && (HEX.test(brand) || TOKEN.test(brand))
  return (
    <span
      className={['ds-badge', `ds-badge--${painted ? 'brand' : tone ?? 'neutral'}`, className].filter(Boolean).join(' ')}
      style={painted ? ({ ...style, '--ds-badge-brand': brand } as React.CSSProperties) : style}
      {...rest}
    >
      {dot && <span className="ds-badge__dot" aria-hidden="true" />}
      {children}
    </span>
  )
}
