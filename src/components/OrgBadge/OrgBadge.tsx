import './OrgBadge.css'

export type OrgBadgeSize = 'sm' | 'md' | 'lg'

export interface OrgBadgeProps {
  /**
   * Название организации — **доступное имя** (его объявляет скринридер).
   * В отличие от `Avatar.name`, источником буквы оно НЕ является: у организации
   * буква задаётся явно (`letter`), а не выводится из названия.
   */
  name: string
  /**
   * Монограмма, **заданная явно**: «ОЗОН Банк» → «О». `Avatar` вывел бы «ОБ»
   * (два первых слова) — он про людей, где это верно («Иванов Пётр» → «ИП»).
   * Для организации происхождение буквы другое, поэтому это отдельный проп, а
   * не общий с `Avatar` вывод.
   *
   * **Не задан и `src` тоже не задан → третье состояние, «организация не
   * опознана»:** «?» в плитке со СПЛОШНОЙ рамкой. Это не то же, что «логотип
   * ещё не приехал» (пунктир): там организация известна, не хватает картинки.
   * Записано здесь, потому что состояние было только в `AGENTS.md` и в тесте —
   * потребитель нашёл его рендером, то есть иначе найти было нельзя.
   */
  letter?: string
  /**
   * Логотип. Показывается, только если передан, и **без отката по `onError`**:
   * на статической странице (гидрации нет) обработчик не подключится, и битый
   * `src` остался бы битым навсегда. Поэтому выбор «логотип или буква» делает
   * сервер — эмитит `src` только для слагов, у которых файл реально есть.
   */
  src?: string
  /**
   * Значок **декоративен**: имя организации уже стоит рядом текстом.
   *
   * Тогда плитка уходит из дерева доступности целиком (`aria-hidden`), и
   * скринридер называет банк один раз, а не два. В самой частой связке
   * «значок + название» умолчание (значок называет себя сам) даёт именно
   * дубль — предъявлено потребителем.
   *
   * Умолчание остаётся прежним, потому что значок бывает и один в ячейке; тогда
   * молчащая плитка была бы дырой, а не чистотой.
   */
  decorative?: boolean
  size?: OrgBadgeSize
  className?: string
  id?: string
}

/**
 * Значок организации — логотип или монограмма в квадратной плитке.
 *
 * **Родня `Avatar` по поверхности** (размеры, скругление, типографика буквы),
 * но другой объект, и это видно тремя решениями: буква ЗАДаётся, а не выводится;
 * форма квадратная (человек — круг, организация — плитка); логотип без
 * `onError`-отката, потому что страница статическая.
 *
 * **Три состояния, и все три названы:** логотип (`src`), заглушка «логотип ещё
 * не приехал» (`letter` без `src`, пунктир) и «организация не опознана» (ни
 * того, ни другого — «?» со сплошной рамкой). Заглушка обязана быть **отличима
 * от настоящего логотипа** — требование про инвентаризацию: пока заглушка
 * выглядит как логотип, по экрану не видно, у каких банков логотип ещё не
 * приехал. Отсюда пунктир.
 *
 * **Фирменный цвет задаётся ЛИСТОМ ПОТРЕБИТЕЛЯ, а не пропом.** Шов — переменная
 * `--ds-orgbadge-brand`, которую читает буква заглушки:
 *
 * ```css
 * .bank-ozon { --ds-orgbadge-brand: var(--brand-ozon); }
 * ```
 * ```tsx
 * <OrgBadge name="ОЗОН Банк" letter="О" className="bank-ozon" />
 * ```
 *
 * Прежний проп `brandColor` клал значение инлайном в разметку — и был
 * единственным местом во всей системе, где произвольный цвет от потребителя
 * попадал в `style` (везде ещё цвет приходит перечислимым тоном через класс, а
 * инлайновые переменные заняты числами и раскладкой). У потребителя это вдобавок
 * запрещено правилом проекта и тестом «новых хекс-значений в разметке не
 * заводить», то есть пропом, задуманным для него, он пользоваться не мог.
 * Цвет — вопрос стилей, и место ему в листе.
 */
export function OrgBadge({ name, letter, src, decorative, size = 'md', className, id }: OrgBadgeProps) {
  const state = src ? 'logo' : letter ? 'placeholder' : 'unknown'
  return (
    <span
      id={id}
      className={['ds-orgbadge', `ds-orgbadge--${size}`,
        state === 'placeholder' && 'ds-orgbadge--placeholder',
        state === 'unknown' && 'ds-orgbadge--unknown',
        className].filter(Boolean).join(' ')}
      role={decorative ? undefined : 'img'}
      aria-label={decorative ? undefined : name}
      aria-hidden={decorative || undefined}
      title={decorative ? undefined : name}
    >
      {state === 'logo' && <img className="ds-orgbadge__img" src={src} alt="" />}
      {state === 'placeholder' && <span className="ds-orgbadge__letter" aria-hidden="true">{letter}</span>}
      {state === 'unknown' && <span className="ds-orgbadge__unknown" aria-hidden="true">?</span>}
    </span>
  )
}
