const FLAT: SearchResult[] = CATALOG.map(({ id, label }) => ({ id, label }))

/**
 * Живой поиск: фикстура фильтрует набор сама. Кадр без этого показывал бы
 * список, не отвечающий на набранное, — то есть врал бы про то, откуда
 * берётся выдача.
 */
function Live({ value, results, placeholder, label }: Props) {
  const [q, setQ] = useState(value)
  const [picked, setPicked] = useState('')
  const shown = q.trim()
    ? results.filter((r) => r.label.toLowerCase().includes(q.trim().toLowerCase()))
    : []
  return (
    // `min(...)`, а не `26rem`: 416 px шире кадра 360, и подпись «Ничего не
    // выбрано» вылезала вправо на 86 px — на узком это читалось как «поле
    // поиска ломает раскладку», хотя ломала обёртка фикстуры.
    <div style={{ width: 'min(26rem, 100%)' }}>
      <GlobalSearch
        value={q}
        onChange={setQ}
        results={shown}
        // Выбор ГАСИТ выдачу, а не только печатает строку внизу. Раскрытость
        // здесь — это «`results` непуст», и после перехода выдача обязана
        // закрыться; оставленная раскрытой, она изображала бы виджет, который
        // после Enter продолжает предлагать то, куда уже перешли.
        onSelect={(id) => {
          setPicked(results.find((r) => r.id === id)?.label ?? id)
          setQ('')
        }}
        placeholder={placeholder || undefined}
        label={label || undefined}
      />
      <div style={{ marginTop: '1rem', color: 'var(--ds-text-muted)', fontSize: 'var(--ds-fs-sm)' }}>
        {picked ? `Переход: ${picked}` : 'Ничего не выбрано'}
      </div>
    </div>
  )
}

