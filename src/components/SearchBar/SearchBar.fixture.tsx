/**
 * Единственное поле семьи, у которого обёртка `div.ds-field` появляется ТОЛЬКО
 * вместе с подписью. Это не экономия на разметке: строку поиска чаще всего
 * ставят в тулбар, где подписи нет, и лишняя обёртка меняла бы там раскладку
 * без всякой просьбы. Отсюда и главный случай — «с подписью и без».
 */

interface Props {
  label: string
  value: string
  placeholder: string
  disabled: boolean
}

function Live({ value, label, ...rest }: Props) {
  const [v, setV] = useState(value)
  return (
    <SearchBar
      {...rest}
      value={v}
      onChange={setV}
      label={label || undefined}
      aria-label={label ? undefined : 'Поиск по заказам'}
    />
  )
}

