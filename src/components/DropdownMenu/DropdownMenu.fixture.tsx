/**
 * Живое меню: действия печатают в подпись под ним. Без этого кадр показывает
 * список слов, у которых, судя по всему, ничего не происходит.
 */
function Live({ items, align, ariaLabel, ownTrigger, defaultOpen }: Props) {
  const [last, setLast] = useState('')
  // `String(it.label)`, а не `it.label`: с DS-358 подпись пункта —
  // `ReactNode`. Фикстура кладёт туда строки, и приведение здесь честное; в
  // подпись под меню печатается то же слово, что стоит в пункте.
  const wired = items.map((it) =>
    'separator' in it ? it : { ...it, onSelect: () => setLast(String(it.label)) },
  )
  return (
    <div>
      <DropdownMenu
        items={wired}
        align={align}
        ariaLabel={ariaLabel || undefined}
        defaultOpen={defaultOpen}
        // Знак раскрытия — `Caret kind="menu"`, а не текстовый треугольник. Он
        // рисуется ШРИФТОМ: вес, посадка и оптический центр приходят не от нас,
        // и рядом с шевронами системы это читается как второй знак для той же
        // мысли (DS-144). Держит гейт `inline-icons` — он же это и поймал,
        // причём во второй раз: символ, оставленный в КОММЕНТАРИИ, он тоже
        // видит, и это правильно — гейт читает исходник, а не разметку.
        // `menu` не поворачивается: раскрытие уже объявлено `aria-expanded`.
        //
        // Кнопка здесь НАСТОЯЩАЯ (DS-359). До неё стоял `<span>`, потому
        // что компонент оборачивал переданное в свою кнопку и настоящая дала бы
        // кнопку в кнопке. Фикстуру копируют — значит копировали и обход.
        trigger={ownTrigger ? <Button variant="secondary">Действия <Caret kind="menu" /></Button> : undefined}
      />
      <div style={{ marginTop: '1rem', color: 'var(--ds-text-muted)', fontSize: 'var(--ds-fs-sm)' }}>
        {last ? `Выбрано: ${last}` : 'Ничего не выбрано'}
      </div>
    </div>
  )
}

