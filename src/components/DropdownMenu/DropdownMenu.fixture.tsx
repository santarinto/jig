/**
 * Меню действий. `kind: 'inline'`.
 *
 * Открытость здесь объявляется пропом (`defaultOpen`), а не разыгрывается
 * кликом в эффекте, — и это лучший из способов, а не поблажка: клик пришлось бы
 * стеречь от двойного прогона эффекта под `StrictMode`, а проп ставит то же
 * состояние без сторожа и без единой строки, которая может сломаться молча.
 * Клик остаётся у тех, у кого пропа нет (`Combobox`, `Tooltip`).
 *
 * Чего в кадре не видно и что проверяется руками: клавиатура. Меню обещает
 * roving-фокус (`AGENTS.md`, DropdownMenu) — стрелки водят активный пункт,
 * Home/End прыгают на края, Tab закрывает меню и НЕ возвращает фокус, Escape
 * закрывает и возвращает. Выключенные пункты пропускаются стрелками, но
 * остаются в DOM: пропущенный молча означал бы, что действия просто нет.
 */
