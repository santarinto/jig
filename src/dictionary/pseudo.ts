/**
 * Псевдолокаль — словарь, в котором каждое значение называет СВОЙ КЛЮЧ
 * (DS-139, приёмка).
 *
 * Зачем. Умолчание словаря русское, и это правильно (у большинства
 * потребителей интерфейс русский). Но у правильного умолчания есть цена:
 * ГЛАЗАМИ переехавшая строка и непереехавшая выглядят ОДИНАКОВО — обе русские.
 * `wiring.test.tsx` доказывает, что переопределение доезжает, но доказывает
 * текстом: на экране этого не видно, и приёмка «а всё ли переехало» сводится к
 * чтению словаря рядом с кодом.
 *
 * Псевдолокаль делает разницу видимой: включил — и всё, что осталось русским,
 * это то, что компонент ГОВОРИТ МИМО СЛОВАРЯ. Пропущенный ключ перестаёт быть
 * находкой ревьюера и становится тем, что торчит на экране.
 *
 * Три вопроса, на которые она отвечает разом, и ни на один из них не отвечает
 * ни гейт, ни `wiring`:
 * 1. ЧТО осталось мимо словаря — русское среди скобок;
 * 2. КАКОЙ ключ где живёт — имя читается прямо с элемента, то есть приёмка
 *    имён (а они публичный API) становится взглядом, а не сверкой с таблицей;
 * 3. ЧТО ломается на длине — имена ключей длиннее русских слов, и переполнение
 *    вылезает там, где английский набор его бы не показал.
 *
 * СОБИРАЕТСЯ ИЗ `DS_TEXT_RU`, а не пишется руками. Девяносто значений,
 * набранных вторым списком, разошлись бы с первым на первом же новом ключе — и
 * разошлись бы МОЛЧА: пропущенный ключ просто остался бы русским, то есть
 * выглядел бы ровно как найденный дефект. Здесь новый ключ получает свой
 * маркер в тот же момент, когда появляется в словаре.
 *
 * Скобки `⟦⟧` (U+27E6/27E7), а не `[…]`, `{…}` или `<…>`. Довод один и
 * практический: эти знаки не встречаются ни в интерфейсном тексте, ни в
 * разметке, ни в JSON — поэтому маркер, случайно уехавший в снимок, в лог или
 * в тикет, опознаётся мгновенно и ни с чем не путается. И они одинарной
 * ширины: `[[[ключ]]]` исказил бы раскладку, то есть сломал бы ровно третий
 * вопрос из тех, ради которых псевдолокаль заведена.
 */
import { DS_TEXT_RU } from './text.js'
import type { DsTextDict } from './text.js'

export const PSEUDO_OPEN = '⟦'
export const PSEUDO_CLOSE = '⟧'

/**
 * Маркер одного ключа. Аргументы функции печатаются ПОСЛЕ двоеточия —
 * `⟦dataTable.selectRow:42⟧` — и это не украшение: так видно, что значение
 * доехало до строки. Функция, потерявшая аргумент, в псевдолокали выглядит
 * иначе, чем работающая, а в русском умолчании — так же.
 */
const mark = (key: string, args: readonly unknown[] = []): string =>
  args.length === 0
    ? `${PSEUDO_OPEN}${key}${PSEUDO_CLOSE}`
    : `${PSEUDO_OPEN}${key}:${args.map((a) => String(a)).join(',')}${PSEUDO_CLOSE}`

/**
 * Словарь псевдолокали. Полный: `DsTextDict`, а не `DsTextOverrides` — здесь
 * переопределяется ВСЁ, иначе незаданный ключ остался бы русским и был бы
 * неотличим от пропущенного, то есть инструмент врал бы ровно в том месте, для
 * которого сделан.
 *
 * ПРИВЕДЕНИЕ ЧЕРЕЗ `unknown`, и оно здесь осознанная плата. Пройти по ключам
 * `Object.entries` и сохранить при этом каждую сигнатуру по отдельности
 * система типов не умеет: у ключей разные арности (`(rowId: string)`,
 * `(nodes: number, edges: number)`), и обобщённый обход видит их как
 * объединение — `Object.fromEntries` возвращает `{[k: string]: …}`, у которого
 * с `DsTextDict` нет достаточного перекрытия, и TS требует промежуточного
 * `unknown` (TS2352). Альтернатива — те самые девяносто значений руками, то
 * есть возврат к расхождению, ради устранения которого файл и написан.
 *
 * Чем это НЕ опасно, и почему довод не «ну и ладно»: приведение снимает
 * проверку у ЭТОГО выражения, но не у результата. Что ключи те же и что
 * функции остались функциями, проверяет `pseudo.test.ts` — обходом
 * `DS_TEXT_RU`, то есть тем же источником, из которого словарь собран.
 * Приведение переносит проверку из типов в тест, а не отменяет её.
 */
export const DS_TEXT_PSEUDO: DsTextDict = Object.fromEntries(
  Object.entries(DS_TEXT_RU).map(([key, value]) => [
    key,
    typeof value === 'function' ? (...args: unknown[]) => mark(key, args) : mark(key),
  ]),
) as unknown as DsTextDict
